POLYGONS = []


def add(name, coordinates):
    values = [float(v) for v in coordinates.replace(",", " ").split()]
    assert len(values) % 2 == 0, name
    vertices = np.asarray(values, dtype=np.float64).reshape(-1, 2)
    assert len(vertices) >= 3, name
    POLYGONS.append((name, vertices))


def island(name, lon, lat, east_west_radius, north_south_radius, angle=0):
    """Small remembered islands approximated by rotated ellipses, in degrees."""
    theta = np.arange(32) * (2 * math.pi / 32)
    a = math.radians(angle)
    x = east_west_radius * np.cos(theta)
    y = north_south_radius * np.sin(theta)
    vertices = np.column_stack((
        lon + x * math.cos(a) - y * math.sin(a),
        lat + x * math.sin(a) + y * math.cos(a),
    ))
    POLYGONS.append((name, vertices))


