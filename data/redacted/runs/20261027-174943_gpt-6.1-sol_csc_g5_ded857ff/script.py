def contains_points(vertices, longitude, latitude):
    """Even/odd ray crossing with coastline boundary points assigned to land."""
    inside = np.zeros(longitude.shape, dtype=bool)
    boundary = np.zeros(longitude.shape, dtype=bool)
    previous = vertices[-1]
    for current in vertices:
        x1, y1 = previous
        x2, y2 = current
        cross = (longitude - x1) * (y2 - y1) - (latitude - y1) * (x2 - x1)
        boundary |= (
            (np.abs(cross) < 1e-11)
            & (longitude >= min(x1, x2) - 1e-11)
            & (longitude <= max(x1, x2) + 1e-11)
            & (latitude >= min(y1, y2) - 1e-11)
            & (latitude <= max(y1, y2) + 1e-11)
        )
        if y1 != y2:
            crosses = (y1 > latitude) != (y2 > latitude)
            intersection_x = x1 + (latitude - y1) * (x2 - x1) / (y2 - y1)
            inside ^= crosses & (longitude < intersection_x)
        previous = current
    return inside | boundary


def generate():
    longitudes = np.arange(495, 636, dtype=np.int64) / 5.0
    latitudes = np.arange(115, 4, -1, dtype=np.int64) / 5.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    matrix = np.zeros(longitude.shape, dtype=np.uint8)
    for name, vertices in POLYGONS:
        selected = (
            (longitude >= vertices[:, 0].min() - 1e-11)
            & (longitude <= vertices[:, 0].max() + 1e-11)
            & (latitude >= vertices[:, 1].min() - 1e-11)
            & (latitude <= vertices[:, 1].max() + 1e-11)
        )
        if np.any(selected):
            matrix[selected] |= contains_points(
                vertices, longitude[selected], latitude[selected]
            ).astype(np.uint8)
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert longitudes[0] == 99 and longitudes[-1] == 127
    assert latitudes[0] == 23 and latitudes[-1] == 1
    assert set(np.unique(matrix)).issubset({0, 1})
    return matrix


def main():
    output_directory = Path.cwd() / "outputs"
    output_directory.mkdir(parents=True, exist_ok=True)
    matrix = generate()
    csv_path = output_directory / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(output_directory / "candidate.png")
    enlarged = original.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(output_directory / "candidate_8x.png")

    # Validate the files that were actually saved, including every enlarged pixel.
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.asarray(rows, dtype=np.uint8)
    assert restored.size == 15651 and np.array_equal(restored, matrix)
    with Image.open(output_directory / "candidate.png") as saved:
        assert saved.size == (141, 111) and saved.mode == "L"
        small = np.asarray(saved).copy()
    with Image.open(output_directory / "candidate_8x.png") as saved:
        assert saved.size == (1128, 888) and saved.mode == "L"
        large = np.asarray(saved).copy()
    assert set(np.unique(small)) == {0, 255}
    assert set(np.unique(large)) == {0, 255}
    assert np.array_equal(small, pixels)
    assert np.array_equal(large, np.repeat(np.repeat(small, 8, axis=0), 8, axis=1))
    print("Validated: CSV 111x141, 15651 binary values; PNG 141x111; "
          "PNG 1128x888; only black/white; exact nearest-neighbor 8x.")


if __name__ == "__main__":
    main()
