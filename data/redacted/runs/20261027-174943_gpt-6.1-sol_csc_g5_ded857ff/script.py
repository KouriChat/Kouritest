"""South China Sea land/water reconstruction from hand-written geographic memory.

No maps, geographic datasets, network access, or land-mask libraries are used.
Coordinates below are approximate WGS84 longitude/latitude vertices, written
from prior knowledge. Classification is polygon containment at each point,
not independent language-model inference and not cell-area averaging.
Inland lakes are intentionally filled as land under the requested definition.
Only Python's standard library, numpy and Pillow are required.
Run: python outputs/generate_map.py
"""
