def polygon_contains(longitudes, latitudes, vertices):
    """Vectorized ray casting at the sample coordinates, not cell averaging."""
    inside = np.zeros(longitudes.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if by != ay:
            crossing = ((ay > latitudes) != (by > latitudes))
            intersection = ax + (latitudes - ay) * (bx - ax) / (by - ay)
            inside ^= crossing & (longitudes < intersection)
        ax, ay = bx, by
    return inside


