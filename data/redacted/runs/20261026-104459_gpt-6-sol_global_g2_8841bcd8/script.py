def contains(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing:
                inside = not inside
        j = i
    return inside


def main():
    latitudes = np.arange(89, -90, -2)
    longitudes = np.arange(-179, 180, 2)
    matrix = np.zeros((len(latitudes), len(longitudes)), dtype=np.uint8)

    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(
                any(contains(lon, lat, polygon) for polygon in POLYGONS)
                and not any(contains(lon, lat, lake) for lake in LAKES)
            )

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    np.savetxt(out / "candidate.csv", matrix, fmt="%d", delimiter=",")

    # PIL mode "1": 1 is white (land), 0 is black (water).
    raw = Image.fromarray(matrix * 255).convert("1")
    raw.save(out / "candidate.png")
    raw.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
