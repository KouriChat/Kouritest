"""Memory-only approximation; no geographic files, services, or reference maps.

Coordinates below are hand-written coastline guesses, not surveyed geometry.
Each grid point is classified by polygon membership, not independent LLM calls.
Requirements: Python 3, numpy, Pillow. Run from the desired output parent.
Inland lakes are intentionally not subtracted from land.
"""
