N = 127
lon = -131.0 + np.arange(N, dtype=np.float64) * (2.0 / 126.0)
lat = 55.0 - np.arange(N, dtype=np.float64) * (2.0 / 126.0)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((N, N), dtype=bool)

def polygon(vertices):
    """Vectorized odd/even ray crossing on the actual sample coordinates."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crossing = (y1 > Y) != (y0 > Y)
            intercept = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (X < intercept)
        x0, y0 = x1, y1
    return inside

def add(vertices):
    land[:] |= polygon(vertices)

def subtract(vertices):
    land[:] &= ~polygon(vertices)

