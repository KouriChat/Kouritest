def inside(lon, lat, poly):
    """Ray casting; boundary points are treated as land."""
    hit = False
    j = len(poly) - 1
    for i, (x1, y1) in enumerate(poly):
        x2, y2 = poly[j]
        if ((y1 > lat) != (y2 > lat)):
            cross = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < cross:
                hit = not hit
        # Include exact vertices/edges in the land classification.
        dx, dy = x2 - x1, y2 - y1
        if abs(dx * (lat - y1) - dy * (lon - x1)) < 1e-10:
            if min(x1, x2) - 1e-10 <= lon <= max(x1, x2) + 1e-10 and min(y1, y2) - 1e-10 <= lat <= max(y1, y2) + 1e-10:
                return True
        j = i
    return hit

def main():
    lats = [23.0 - 0.2 * r for r in range(111)]
    lons = [99.0 + 0.2 * c for c in range(141)]
    matrix = np.zeros((111, 141), dtype=np.uint8)
    for r, lat in enumerate(lats):
        for c, lon in enumerate(lons):
            matrix[r, c] = int(any(inside(lon, lat, p) for p in POLYGONS))
    with (OUT / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())
    image = Image.fromarray(np.where(matrix == 1, 255, 0).astype(np.uint8), mode="L")
    image.save(OUT / "candidate.png")
    image.resize((1128, 888), resample=Image.Resampling.NEAREST).save(OUT / "candidate_8x.png")

if __name__ == "__main__":
    main()
