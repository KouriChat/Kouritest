def point_on_segment(x, y, a, b):
    cross = (x - a[0]) * (b[1] - a[1]) - (y - a[1]) * (b[0] - a[0])
    if abs(cross) > 1e-10:
        return False
    return (min(a[0], b[0]) - 1e-10 <= x <= max(a[0], b[0]) + 1e-10
            and min(a[1], b[1]) - 1e-10 <= y <= max(a[1], b[1]) + 1e-10)
def point_in_polygon(x, y, polygon):
    inside = False
    j = len(polygon) - 1
    for i, current in enumerate(polygon):
        previous = polygon[j]
        if point_on_segment(x, y, previous, current):
            return True
        xi, yi = current
        xj, yj = previous
        if (yi > y) != (yj > y):
            crossing_x = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < crossing_x:
                inside = not inside
        j = i
    return inside


def main():
    rows, cols = 111, 141
    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for row in range(rows):
        latitude = 23.0 - 0.2 * row
        for col in range(cols):
            longitude = 99.0 + 0.2 * col
            matrix[row, col] = any(
                point_in_polygon(longitude, latitude, polygon)
                for polygon in LAND_POLYGONS
            )

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as f:
        for row in matrix:
            f.write(",".join(str(int(value)) for value in row) + "\n")

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")
    image.resize(
        (cols * 8, rows * 8), resample=Image.Resampling.NEAREST
    ).save(output_dir / "candidate_8x.png")


if __name__ == "__main__":
    main()
