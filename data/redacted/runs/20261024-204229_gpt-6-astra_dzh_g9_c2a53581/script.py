def outline(name, coordinates, water=False):
    points = [tuple(map(float, word.split(",")))
              for word in coordinates.split()]
    assert len(points) >= 3, name
    (WATER if water else LAND).append((name, points))


def contains_points(x, y, vertices):
    """Ray casting at the actual sampling coordinates, without raster smoothing."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-10)
                     & (x >= min(ax, bx) - 1e-10)
                     & (x <= max(ax, bx) + 1e-10)
                     & (y >= min(ay, by) - 1e-10)
                     & (y <= max(ay, by) + 1e-10))
        if dy != 0:
            hit = ((ay > y) != (by > y)) & (
                x < ax + (y - ay) * dx / dy)
            inside ^= hit
        ax, ay = bx, by
    return inside | boundary


