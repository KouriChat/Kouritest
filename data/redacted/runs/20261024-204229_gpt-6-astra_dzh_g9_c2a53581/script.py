def generate():
    lons = np.arange(-45, 186, dtype=np.int32) / 5.0
    lats = np.arange(225, 154, -1, dtype=np.int32) / 5.0
    x, y = np.meshgrid(lons, lats)
    land = np.zeros(x.shape, dtype=bool)
    for _, polygon in LAND:
        land |= contains_points(x, y, polygon)
    for _, polygon in WATER:
        land &= ~contains_points(x, y, polygon)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix)) == {0, 1}
    assert (lats[0], lats[-1], lons[0], lons[-1]) == (45, 31, -9, 37)
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    assert image.mode == "L"
    image.save(out / "candidate.png")
    large = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    large.save(out / "candidate_8x.png")

    # Validate the actual saved deliverables, including every enlarged pixel.
    with csv_path.open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(v in {"0", "1"} for row in rows for v in row)
    assert sum(map(len, rows)) == 16401
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (231, 71) and im.mode == "L"
        original = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1848, 568) and im.mode == "L"
        enlarged = np.array(im)
    assert set(np.unique(original)) == {0, 255}
    assert set(np.unique(enlarged)) == {0, 255}
    assert np.array_equal(original, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(original, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged, expected)
    report = {
        "method": "hand-written knowledge-only outlines; point-in-polygon",
        "external_geographic_data": False,
        "matrix_shape": list(matrix.shape),
        "valid_values": int(matrix.size),
        "land": int(matrix.sum()),
        "water": int(matrix.size - matrix.sum()),
        "original_size": [231, 71],
        "enlarged_size": [1848, 568],
        "black_white_only": True,
        "nearest_neighbor_verified_pixelwise": True,
        "validation": "PASS",
    }
    (out / "validation.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    generate()
