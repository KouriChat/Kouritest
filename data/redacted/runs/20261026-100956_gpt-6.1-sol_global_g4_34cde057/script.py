def inside_polygon(x, y, polygon):
    inside = np.zeros(x.shape, dtype=bool)
    vertices = polygon
    for i, (x1, y1) in enumerate(vertices):
        x2, y2 = vertices[(i + 1) % len(vertices)]
        crosses = (y1 > y) != (y2 > y)
        edge_x = (x2 - x1) * (y - y1) / (y2 - y1 + 1e-30) + x1
        inside ^= crosses & (x < edge_x)
    return inside


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2)
    longitudes = np.arange(-179, 180, 2)
    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for polygon in LAND:
        land |= inside_polygon(x, y, polygon)
    for polygon in LAKES:
        land &= ~inside_polygon(x, y, polygon)
    matrix = land.astype(np.uint8)
    if matrix.shape != (90, 180) or matrix.size != 16200:
        raise RuntimeError("Unexpected matrix shape")
    np.savetxt(out / "candidate.csv", matrix, fmt="%d", delimiter=",")
    pixels = (matrix * 255).astype(np.uint8)
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
