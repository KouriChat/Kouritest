def inside_polygon(x, y, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > y) != (yj > y):
            crossing_x = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < crossing_x:
                inside = not inside
        j = i
    return inside

def main():
    latitudes = 35.0 - np.arange(64) * (2.0 / 63.0)
    longitudes = 129.0 + np.arange(253) * (8.0 / 252.0)
    matrix = np.zeros((64, 253), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(any(
                inside_polygon(float(lon), float(lat), polygon)
                for polygon in POLYGONS
            ))

    os.makedirs("outputs", exist_ok=True)
    with open("outputs/candidate.csv", "w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L")
    image.save("outputs/candidate.png")
    image.resize((2024, 512), Image.Resampling.NEAREST).save(
        "outputs/candidate_8x.png"
    )

if __name__ == "__main__":
    main()
