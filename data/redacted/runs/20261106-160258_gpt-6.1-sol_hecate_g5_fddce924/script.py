X, Y = np.meshgrid(lon, lat)
land = np.zeros((N, N), dtype=bool)

def inside(vertices):
    """Even-odd polygon test at the actual sample coordinates."""
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > Y) != (y1 > Y))
            boundary = x0 + (Y-y0)*(x1-x0)/(y1-y0)
            result ^= crossing & (X < boundary)
        x0, y0 = x1, y1
    return result

def add(vertices):
    global land
    land |= inside(vertices)

def subtract(vertices):
    global land
    land &= ~inside(vertices)

