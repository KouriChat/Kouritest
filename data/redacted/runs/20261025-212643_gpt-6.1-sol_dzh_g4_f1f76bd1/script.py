def contains(poly, longitude, latitude):
    """Even/odd ray crossing at exact sample coordinates; boundary included."""
    xmin, ymin = poly.min(axis=0)
    xmax, ymax = poly.max(axis=0)
    eligible = ((longitude >= xmin - 1e-10) &
                (longitude <= xmax + 1e-10) &
                (latitude >= ymin - 1e-10) &
                (latitude <= ymax + 1e-10))
    result = np.zeros(longitude.shape, dtype=bool)
    if not eligible.any():
        return result
    x = longitude[eligible]
    y = latitude[eligible]
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x1, y1 = poly[-1]
    for x2, y2 in poly:
        dx, dy = x2 - x1, y2 - y1
        if dx == 0 and dy == 0:
            x1, y1 = x2, y2
            continue
        cross = (x - x1) * dy - (y - y1) * dx
        boundary |= ((np.abs(cross) <= 1e-10 * max(1, abs(dx), abs(dy))) &
                     (x >= min(x1, x2) - 1e-10) &
                     (x <= max(x1, x2) + 1e-10) &
                     (y >= min(y1, y2) - 1e-10) &
                     (y <= max(y1, y2) + 1e-10))
        if dy != 0:
            crosses = ((y1 > y) != (y2 > y))
            intersection = x1 + (y - y1) * dx / dy
            inside ^= crosses & (x < intersection)
        x1, y1 = x2, y2
    result[eligible] = inside | boundary
    return result


def main():
    # Integer fifth-degrees avoid cumulative arange drift.
    longitudes = np.arange(-45, 186, dtype=np.int64) / 5.0
    latitudes = np.arange(225, 154, -1, dtype=np.int64) / 5.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    assert longitude.shape == latitude.shape == (71, 231)
    assert (longitudes[0], longitudes[-1]) == (-9.0, 37.0)
    assert (latitudes[0], latitudes[-1]) == (45.0, 31.0)

    land = contains(EURASIA, longitude, latitude)
    land |= contains(AFRICA, longitude, latitude)
    for sea in (BLACK_SEA, MARMARA):
        land &= ~contains(sea, longitude, latitude)
    for name, outline in ISLANDS:
        land |= contains(outline, longitude, latitude)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
