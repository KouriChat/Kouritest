def coast(name, text):
    """Vertices are longitude,latitude pairs in decimal degrees."""
    vertices = [tuple(map(float, p.split(","))) for p in text.split()]
    if len(vertices) < 3:
        raise ValueError(name)
    POLYGONS.append((name, np.asarray(vertices, dtype=float)))


def island(name, lon, lat, rx, ry, angle=0):
    """An approximate, optionally rotated small-island outline."""
    ELLIPSES.append((name, lon, lat, rx, ry, angle))


