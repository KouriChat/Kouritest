"""Knowledge-only reconstruction of the Canadian Arctic, not surveyed geography.

Run: python outputs/generate_map.py
Dependencies: numpy, Pillow. No input datasets, network calls, or map libraries.
Coastlines below are hand-written approximations from geographic knowledge.
Classification uses polygon containment, not independent reasoning per point.
Inland lakes remain land; the explicitly cut inlets are marine water.
Coordinates in the rules are (degrees WEST, degrees NORTH).
"""
