matrix = np.zeros((61, 241), dtype=np.uint8)
marine_cuts = []
land_layers = []


def contains(vertices):
    """Vectorized even/odd point-in-polygon, evaluated at sample coordinates."""
    inside = np.zeros(matrix.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > NORTH) != (y1 > NORTH))
            x_cross = x0 + (NORTH - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (WEST < x_cross)
        x0, y0 = x1, y1
    return inside


def land(name, vertices):
    land_layers.append([name, contains(vertices)])


def inlet(name, vertices):
    # A fjord cuts its parent island, never a separate island in its mouth.
    marine_cuts.append((name, len(land_layers) - 1, vertices))


