def main():
    lats = np.arange(89, -90, -2, dtype=np.float64)
    lons = np.arange(-179, 180, 2, dtype=np.float64)
    lon_grid, lat_grid = np.meshgrid(lons, lats)
    land = np.zeros((90, 180), dtype=bool)
    for ring in LAND:
        land |= inside(lon_grid, lat_grid, ring)

    # Hudson Bay and connected James Bay are ocean water, not part of the continent.
    hudson_bay = [(-96,61),(-94,58),(-90,56),(-86,54),(-82,53),(-79,55),
                  (-78,58),(-79,61),(-82,63),(-87,64),(-92,63),(-96,61)]
    land &= ~inside(lon_grid, lat_grid, hudson_bay)

    matrix = land.astype(np.uint8)
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    with (output / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = np.where(matrix == 1, 255, 0).astype(np.uint8)
    original = Image.fromarray(pixels, mode="L")
    original.save(output / "candidate.png")
    enlarged = original.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    assert matrix.shape == (90, 180) and int(matrix.sum() + (matrix == 0).sum()) == 16200
    assert set(np.unique(pixels).tolist()) <= {0, 255}
    assert original.size == (180, 90) and enlarged.size == (1440, 720)
    print(f"Wrote 16,200 classifications to {output}")

if __name__ == "__main__":
    main()
