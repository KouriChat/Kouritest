def inside(lon_grid, lat_grid, ring):
    """Vectorized ray-casting membership for one hand-written polygon."""
    result = np.zeros(lon_grid.shape, dtype=bool)
    for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
        crosses = (y1 > lat_grid) != (y2 > lat_grid)
        x_cross = (x2 - x1) * (lat_grid - y1) / ((y2 - y1) or 1e-30) + x1
        result ^= crosses & (lon_grid < x_cross)
    return result
