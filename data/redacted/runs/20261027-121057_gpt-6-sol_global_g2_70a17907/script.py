X, Y = np.meshgrid(LON, LAT)
land = np.zeros((90, 180), dtype=bool)

def shape(s):
    """Coordinates are longitude,latitude pairs; no external geography is used."""
    return [(float(a), float(b)) for a, b in (item.split(",") for item in s.split())]

def inside(vertices):
    result = np.zeros_like(land)
    for offset in (-360, 0, 360):
        x = X + offset
        for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
            if ay != by:
                result ^= ((ay > Y) != (by > Y)) & (x < (bx-ax)*(Y-ay)/(by-ay)+ax)
    return result

def add(s):
    land[:] |= inside(shape(s))

def remove(s):
    land[:] &= ~inside(shape(s))

