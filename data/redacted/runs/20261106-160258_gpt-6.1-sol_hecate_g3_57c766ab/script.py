def contains(x, y, vertices):
    """Vectorized point-in-polygon; boundary points count as inside."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        on = (np.abs(cross) < 1e-12)
        on &= (x >= min(ax, bx) - 1e-12)
        on &= (x <= max(ax, bx) + 1e-12)
        on &= (y >= min(ay, by) - 1e-12)
        on &= (y <= max(ay, by) + 1e-12)
        boundary |= on
        if dy != 0:
            hit = ((ay > y) != (by > y))
            inside ^= hit & (x < ax + (y - ay) * dx / dy)
        ax, ay = bx, by
    return inside | boundary

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    # Exact 2/126-degree intervals, rather than rounded example coordinates.
    lon = -131.0 + np.arange(127, dtype=float) * (2.0 / 126)
    lat = 55.0 - np.arange(127, dtype=float) * (2.0 / 126)
    x, y = np.meshgrid(lon, lat)
    mask = np.zeros((127, 127), dtype=bool)
    for _, polygon in LAND:
        mask |= contains(x, y, polygon)
    for _, polygon in WATER:
        mask &= ~contains(x, y, polygon)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert set(np.unique(matrix)) <= {0, 1}
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    image.resize((1016, 1016), nearest).save(out / "candidate_8x.png")
    # Read only our own generated outputs to validate every delivered value.
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (127, 127)
        raw = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1016, 1016)
        enlarged = np.array(im)
    assert set(np.unique(raw)) == {0, 255}
    assert set(np.unique(enlarged)) == {0, 255}
    assert np.array_equal(raw, matrix * 255)
    assert np.array_equal(enlarged, raw.repeat(8, 0).repeat(8, 1))
    print("Validated: 127x127, 16129 binary samples; PNGs 127x127 and 1016x1016.")

if __name__ == "__main__":
    main()
