    lats = [79.0 - i * 0.1 for i in range(61)]
    lons = [-105.0 + j * 0.1 for j in range(241)]
    a = np.zeros((61, 241), dtype=np.uint8)
    for r, lat in enumerate(lats):
        for c, lon in enumerate(lons):
            a[r, c] = any(inside_polygon(lon, lat, p) for p in POLYGONS)
    return a
