def inside_polygon(x, y, poly):
    """Even/odd ray test; boundary ambiguity is consistently accepted."""
    inside = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if ((yi > y) != (yj > y)):
            crossing = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x <= crossing:
                inside = not inside
        j = i
    return inside

