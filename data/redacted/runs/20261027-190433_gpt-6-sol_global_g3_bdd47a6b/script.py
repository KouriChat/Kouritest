def points_in_polygon(lon_grid, lat_grid, polygon):
    """Vectorized ray casting for a ring of (longitude, latitude) vertices."""
    inside = np.zeros(lon_grid.shape, dtype=bool)
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        crosses = (y1 > lat_grid) != (y0 > lat_grid)
        x_cross = (x0 - x1) * (lat_grid - y1) / (y0 - y1 + 1e-300) + x1
        inside ^= crosses & (lon_grid < x_cross)
        x0, y0 = x1, y1
    return inside
