def point_in_polygon(x, y, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > y) != (yj > y):
            crossing = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < crossing:
                inside = not inside
        j = i
    return inside

def in_island(x, y, island):
    cx, cy, rx, ry, angle = island
    a = math.radians(angle)
    dx, dy = x - cx, y - cy
    u = dx * math.cos(a) + dy * math.sin(a)
    v = -dx * math.sin(a) + dy * math.cos(a)
    return (u / rx) ** 2 + (v / ry) ** 2 <= 1

def is_land(x, y):
    land = any(point_in_polygon(x, y, p) for p in LAND_POLYGONS)
    if land and any(point_in_polygon(x, y, p) for p in WATER_POLYGONS):
        land = False
    return land or any(in_island(x, y, item) for item in ISLANDS)

def main():
    rows, cols = 64, 253
    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for r in range(rows):
        lat = 35.0 - r * (2.0 / 63.0)
        for c in range(cols):
            lon = 129.0 + c * (8.0 / 252.0)
            matrix[r, c] = int(is_land(lon, lat))

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((2024, 512), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix)) <= {0, 1}
    assert image.size == (253, 64)
    assert set(image.getdata()) <= {0, 255}
    enlarged = Image.open(out / "candidate_8x.png")
    assert enlarged.size == (2024, 512)
    assert set(enlarged.getdata()) <= {0, 255}

if __name__ == "__main__":
    main()

