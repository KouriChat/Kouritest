def points_in_polygon(x, y, vertices):
    """Even/odd point containment; a point on an edge belongs to the polygon."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        if dy != 0:
            crosses = (ay > y) != (by > y)
            crossing_x = ax + (y - ay) * dx / dy
            inside ^= crosses & (x < crossing_x)
        ax, ay = bx, by
    return inside | boundary


def main():
    # Integer tenths establish exact row/column ordering without accumulated
    # floating-point increments. Samples are points, not pixel-area averages.
    longitude = np.arange(-1050, -809, dtype=np.int32) / 10.0
    latitude = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    assert len(longitude) == 241 and len(latitude) == 61
    assert (longitude[0], longitude[-1]) == (-105.0, -81.0)
    assert (latitude[0], latitude[-1]) == (79.0, 73.0)
    x, y = np.meshgrid(longitude, latitude)
    mask = np.zeros((61, 241), dtype=bool)
    for name, vertices in LAND:
        mask |= points_in_polygon(x, y, vertices)
    for name, vertices in WATER:
        mask &= ~points_in_polygon(x, y, vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert np.isin(matrix, (0, 1)).all()

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    raw_path = output / "candidate.png"
    large_path = output / "candidate_8x.png"
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    enlarged = image.resize((1928, 488), resample=nearest)
    image.save(raw_path, format="PNG")
    enlarged.save(large_path, format="PNG")

    # Check the actual written files, not merely the in-memory dimensions.
    with csv_path.open("r", encoding="utf-8", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert recovered.size == 14701 and np.array_equal(recovered, matrix)
    with Image.open(raw_path) as saved:
        assert saved.size == (241, 61) and saved.mode == "L"
        raw = np.array(saved)
    with Image.open(large_path) as saved:
        assert saved.size == (1928, 488) and saved.mode == "L"
        large = np.array(saved)
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(large).tolist()) == {0, 255}
    assert np.array_equal(raw, pixels)
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(large, expected), "Nearest-neighbor expansion failed"
    count = int(matrix.sum())
    print(
        f"Validated: 61 x 241 = 14701 binary samples; land={count}, "
        f"water={14701-count}; PNG 241x61 and 1928x488; "
        "black/white only; exact 8x nearest-neighbor blocks."
    )


if __name__ == "__main__":
    main()
