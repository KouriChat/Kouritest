def point_in_polygon(x, y, polygon):
    inside = False
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
        if abs(cross) < 1e-10 and min(x1, x2) <= x <= max(x1, x2) \
                and min(y1, y2) <= y <= max(y1, y2):
            return True
        if (y1 > y) != (y2 > y):
            if x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
                inside = not inside
    return inside
def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    latitudes = np.linspace(55.0, 53.0, 127)
    longitudes = np.linspace(-131.0, -129.0, 127)
    matrix = np.zeros((127, 127), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(any(
                point_in_polygon(float(lon), float(lat), polygon)
                for polygon in POLYGONS
            ))

    with (out / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as csv_file:
        for row in matrix:
            csv_file.write(",".join(map(str, row.tolist())) + "\n")

    rgb = np.repeat(np.where(matrix[:, :, None] == 1, 255, 0), 3, axis=2)
    image = Image.fromarray(rgb.astype(np.uint8), mode="RGB")
    image.save(out / "candidate.png")
    image.resize((1016, 1016), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert set(np.unique(matrix)) <= {0, 1}
    assert image.size == (127, 127)
    assert Image.open(out / "candidate_8x.png").size == (1016, 1016)


if __name__ == "__main__":
    main()
