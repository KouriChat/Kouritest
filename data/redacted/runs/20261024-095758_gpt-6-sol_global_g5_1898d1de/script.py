lon = np.arange(-179, 180, 2)
lat = np.arange(89, -90, -2)
xx, yy = np.meshgrid(lon, lat)
land = np.zeros((90, 180), dtype=bool)

def region(points, value=True):
    """Evaluate a remembered outline against the entire grid, not pointwise inference."""
    p = np.array(points, dtype=float)
    x, y = p[:, 0], p[:, 1]
    mask = np.zeros(land.shape, dtype=bool)
    # Even/odd crossing test with a half-open convention for vertices.
    for i in range(len(p)):
        j = (i - 1) % len(p)
        if y[i] == y[j]:
            continue
        hit = (y[i] > yy) != (y[j] > yy)
        xc = (x[j] - x[i]) * (yy - y[i]) / (y[j] - y[i]) + x[i]
        mask ^= hit & (xx < xc)
    if value:
        land[:] |= mask
    else:
        land[:] &= ~mask

