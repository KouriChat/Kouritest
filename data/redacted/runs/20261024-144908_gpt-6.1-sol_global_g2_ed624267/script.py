def inside_polygon(x, y, vertices):
    """Even-odd planar test; exact boundary points count as land."""
    inside = np.zeros(x.shape, dtype=bool)
    edge = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if dy != 0:
            inside ^= ((ay > y) != (by > y)) & (
                x < ax + (y - ay) * dx / dy)
        edge |= (
            (np.abs((x - ax) * dy - (y - ay) * dx) < 1e-9)
            & (x >= min(ax, bx)) & (x <= max(ax, bx))
            & (y >= min(ay, by)) & (y <= max(ay, by)))
        ax, ay = bx, by
    return inside | edge


