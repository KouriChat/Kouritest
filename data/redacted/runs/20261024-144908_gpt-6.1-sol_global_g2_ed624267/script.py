        mask |= inside_polygon(x, y, vertices)
        # Explicit unwrapped longitudes preserve islands crossing the date line.
        if max(p[0] for p in vertices) > 180:
            mask |= inside_polygon(x + 360, y, vertices)
        if min(p[0] for p in vertices) < -180:
            mask |= inside_polygon(x - 360, y, vertices)
