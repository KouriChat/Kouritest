ROWS, COLS = 90, 180
lats = [89 - 2 * r for r in range(ROWS)]
lons = [-179 + 2 * c for c in range(COLS)]
land_shapes = []
water_shapes = []

def land(points):
    land_shapes.append(points)

def water(points):
    water_shapes.append(points)

def inside(x, y, poly):
    hit = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y):
            cross = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < cross:
                hit = not hit
        j = i
    return hit

def add_shapes(grid, shapes, value):
    for poly in shapes:
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        for r, lat in enumerate(lats):
            if lat < min(ys) or lat > max(ys):
                continue
            for c, lon in enumerate(lons):
                if min(xs) <= lon <= max(xs) and inside(lon, lat, poly):
                    grid[r, c] = value

