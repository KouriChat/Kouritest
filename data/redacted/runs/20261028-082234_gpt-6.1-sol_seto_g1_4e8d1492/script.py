def polygon(text, target=LAND):
    target.append(np.array([tuple(map(float, p.split(",")))
                            for p in text.split()], dtype=float))

def island(x, y, rx, ry, angle=0, n=20):
    t = np.arange(n) * (2 * np.pi / n)
    a = np.deg2rad(angle)
    u, v = rx * np.cos(t), ry * np.sin(t)
    LAND.append(np.column_stack((x + u*np.cos(a)-v*np.sin(a),
                                 y + u*np.sin(a)+v*np.cos(a))))

