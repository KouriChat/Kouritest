def contains(vertices, x, y):
    """Even-odd point-in-polygon rule, evaluated on sample coordinates."""
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crosses = ((y0 > y) != (y1 > y))
            edge_x = x0 + (y-y0) * (x1-x0) / (y1-y0)
            inside ^= crosses & (x < edge_x)
        x0, y0 = x1, y1
    return inside

def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Exact requested step is 2/63 degrees in both directions.
    longitude = 129.0 + np.arange(253, dtype=float) * (2.0/63.0)
    latitude = 35.0 - np.arange(64, dtype=float) * (2.0/63.0)
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((64, 253), dtype=bool)
    for outline in LAND:
        land |= contains(outline, x, y)
    for outline in WATER:
        land &= ~contains(outline, x, y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix)) <= {0, 1}
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(out / "candidate.png")
    nearest = Image.Resampling.NEAREST
    enlarged = original.resize((2024, 512), resample=nearest)
    enlarged.save(out / "candidate_8x.png")
    # Verify serialized files, including the exact 8x8 block replication.
    with csv_path.open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (253, 64)
        pixels = np.asarray(im).copy()
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (2024, 512)
        big_pixels = np.asarray(im).copy()
    assert set(np.unique(pixels)) == {0, 255}
    assert set(np.unique(big_pixels)) == {0, 255}
    assert np.array_equal(pixels, matrix * np.uint8(255))
    assert np.array_equal(big_pixels,
                          np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1))
    print("Validated: 64x253 = 16192 binary values; PNG 253x64; "
          "nearest-neighbor PNG 2024x512; black/white only.")
    print("Method: point-in-polygon evaluation of hand-written approximations.")

if __name__ == "__main__":
    main()
