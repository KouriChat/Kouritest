def inside(x, y, vertices):
    hit = False
    x0,y0 = vertices[-1]
    for x1,y1 in vertices:
        if (y0 > y) != (y1 > y):
            crossing = x0 + (y-y0)*(x1-x0)/(y1-y0)
            if x <= crossing:
                hit = not hit
        x0,y0 = x1,y1
    return hit

def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    mask = np.array([[int(any(inside(99+0.2*j, 23-0.2*i, coast)
                              for coast in P)) for j in range(141)]
                     for i in range(111)], dtype=np.uint8)
    with (out/"candidate.csv").open("w", newline="", encoding="utf-8") as f:
        csv.writer(f).writerows(mask.tolist())
    image = Image.fromarray(mask * 255, mode="L").convert("RGB")
    image.save(out/"candidate.png")
    image.resize((1128,888), resample=Image.Resampling.NEAREST).save(out/"candidate_8x.png")
    with (out/"candidate.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    assert mask.shape == (111,141) and mask.size == 15651
    assert len(rows) == 111 and all(len(r) == 141 and set(r) <= {"0","1"} for r in rows)
    with Image.open(out/"candidate.png") as original, Image.open(out/"candidate_8x.png") as big:
        assert original.size == (141,111) and big.size == (1128,888)
        assert set(original.getdata()) <= {(0,0,0),(255,255,255)}
        assert set(big.getdata()) <= {(0,0,0),(255,255,255)}
        assert np.array_equal(np.asarray(big)[::8,::8], np.asarray(original))
        assert np.array_equal(np.asarray(big), np.repeat(np.repeat(
            np.asarray(original), 8, axis=0), 8, axis=1))
    print(f"Validated {mask.shape}, {mask.size} points, {int(mask.sum())} land points")

if __name__ == "__main__":
    main()
