def contains(vertices, x, y):
    """Vectorized planar ray casting on hand-authored lon/lat polygons."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if by != ay:
            crossing = ((ay > y) != (by > y))
            intersection_x = ax + (y - ay) * (bx - ax) / (by - ay)
            inside ^= crossing & (x < intersection_x)
        cross_product = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        boundary |= (
            (np.abs(cross_product) < 1e-9)
            & (x >= min(ax, bx)) & (x <= max(ax, bx))
            & (y >= min(ay, by)) & (y <= max(ay, by))
        )
        ax, ay = bx, by
    return inside | boundary


def main():
    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    x, y = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((90, 180), dtype=bool)
    for name, vertices in LAND:
        assert np.isfinite(vertices).all(), name
        assert (np.abs(vertices[:, 0]) <= 180).all(), name
        assert (np.abs(vertices[:, 1]) <= 90).all(), name
        mask |= contains(vertices, x, y)
    for name, vertices in WATER:
        mask &= ~contains(vertices, x, y)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (90, 180)
    assert matrix.size == 16200
    assert np.isin(matrix, [0, 1]).all()
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    original.save(output / "candidate.png")
    enlarged.save(output / "candidate_8x.png")

    # Reopen the saved artifacts, checking actual files rather than only
    # the arrays used to create them.
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    stored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(stored, matrix)
    with Image.open(output / "candidate.png") as image:
        assert image.size == (180, 90) and image.mode == "L"
        raw = np.array(image)
    with Image.open(output / "candidate_8x.png") as image:
        assert image.size == (1440, 720) and image.mode == "L"
        big = np.array(image)
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, stored * np.uint8(255))
    assert np.array_equal(big, np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1))
