def contains(points, x, y):
    """Vectorized planar ray casting at the specified lon/lat points."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = points[-1]
    for bx, by in points:
        dx, dy = bx - ax, by - ay
        if dx == 0 and dy == 0:
            ax, ay = bx, by
            continue
        if dy != 0:
            crossing = ((ay > y) != (by > y))
            intersection = ax + (y - ay) * dx / dy
            inside ^= crossing & (x < intersection)
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        ax, ay = bx, by
    return inside | boundary

def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    lons = (np.arange(231, dtype=np.int64) - 45) / 5.0
    lats = (225 - np.arange(71, dtype=np.int64)) / 5.0
    x, y = np.meshgrid(lons, lats)
    matrix = np.zeros((71, 231), dtype=np.uint8)
    for points, value in OPERATIONS:
        matrix[contains(points, x, y)] = value
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix).tolist()) == {0, 1}
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    enlarged = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert sum(map(len, rows)) == 16401
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as original:
        assert original.size == (231, 71)
        original_pixels = np.asarray(original)
        assert set(np.unique(original_pixels).tolist()) == {0, 255}
        assert np.array_equal(original_pixels, pixels)
    with Image.open(out / "candidate_8x.png") as large:
        assert large.size == (1848, 568)
        large_pixels = np.asarray(large)
        assert set(np.unique(large_pixels).tolist()) == {0, 255}
        expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(large_pixels, expected)
    assert (lats[0], lats[-1], lons[0], lons[-1]) == (45, 31, -9, 37)
    print("Validated: 71x231 = 16401 binary samples; PNG 231x71; nearest 8x 1848x568.")

