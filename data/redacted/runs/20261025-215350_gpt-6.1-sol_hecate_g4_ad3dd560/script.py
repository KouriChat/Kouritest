def contains_points(vertices, x, y):
    """Vectorized ray crossing at points, with boundary points included."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    previous = vertices[-1]
    for current in vertices:
        x0, y0 = previous
        x1, y1 = current
        dx, dy = x1 - x0, y1 - y0
        cross = (x - x0) * dy - (y - y0) * dx
        boundary |= (
            (np.abs(cross) < 1e-12)
            & (x >= min(x0, x1) - 1e-12)
            & (x <= max(x0, x1) + 1e-12)
            & (y >= min(y0, y1) - 1e-12)
            & (y <= max(y0, y1) + 1e-12)
        )
        if dy != 0:
            straddles = (y0 > y) != (y1 > y)
            crossing_x = x0 + (y - y0) * dx / dy
            inside ^= straddles & (x < crossing_x)
        previous = current
    return inside | boundary

def generate():
    # Use the exact rational spacing, not the rounded example coordinates.
    longitude = -131.0 + np.arange(127, dtype=np.float64) * (2.0 / 126.0)
    latitude = 55.0 - np.arange(127, dtype=np.float64) * (2.0 / 126.0)
    x, y = np.meshgrid(longitude, latitude)
    assert x.shape == y.shape == (127, 127)
    assert (x[0, 0], x[0, -1], y[0, 0], y[-1, 0]) == (
        -131.0, -129.0, 55.0, 53.0
    )
    result = np.zeros((127, 127), dtype=bool)
    for _, polygon in LAND:
        result |= contains_points(polygon, x, y)
    for _, polygon in WATER:
        result &= ~contains_points(polygon, x, y)
    return result.astype(np.uint8)

def validate(output, matrix):
    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()
    with (output / "candidate.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)
    with Image.open(output / "candidate.png") as im:
        assert im.size == (127, 127)
        assert im.mode == "L"
        original = np.array(im)
    with Image.open(output / "candidate_8x.png") as im:
        assert im.size == (1016, 1016)
        assert im.mode == "L"
        enlarged = np.array(im)
    assert set(np.unique(original).tolist()) == {0, 255}
    assert set(np.unique(enlarged).tolist()) == {0, 255}
    assert np.array_equal(original, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(original, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged, expected), "Not exact nearest-neighbor 8x"
    print("PASS: 127x127; 16,129 binary points; CSV round-trip verified;")
    print("PNG 127x127 and 1016x1016; black/white only; exact nearest-neighbor 8x.")
    print(f"Land points: {int(matrix.sum())}; water points: {matrix.size-int(matrix.sum())}.")

def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    matrix = generate()
    with (output / "candidate.csv").open(
        "w", newline="", encoding="utf-8"
    ) as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(output / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    original.resize((1016, 1016), resample=nearest).save(
        output / "candidate_8x.png"
    )
    validate(output, matrix)

if __name__ == "__main__":
    main()
