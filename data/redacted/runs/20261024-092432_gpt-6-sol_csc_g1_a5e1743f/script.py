LONGITUDE = 99 + np.arange(141) * .2
LATITUDE = 23 - np.arange(111) * .2
X, Y = np.meshgrid(LONGITUDE, LATITUDE)
land = np.zeros((111, 141), dtype=bool)

def polygon(text):
    """Even-odd point test on an explicitly hand-written coastline."""
    vertices = [tuple(map(float, v.split(","))) for v in text.split()]
    inside = np.zeros_like(land)
    for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
        if (ay > Y).any() or (by > Y).any():
            cross = ((ay > Y) != (by > Y)) & (
                X < (bx - ax) * (Y - ay) / (by - ay if by != ay else 1) + ax)
            inside ^= cross
    land[:] |= inside

def ellipse(cx, cy, rx, ry, tilt=0):
    """Tilt is rotation counterclockwise from the east-going longitude axis."""
    phi = np.deg2rad(tilt)
    u = (X - cx) * np.cos(phi) + (Y - cy) * np.sin(phi)
    v = -(X - cx) * np.sin(phi) + (Y - cy) * np.cos(phi)
    land[:] |= (u/rx)**2 + (v/ry)**2 <= 1

