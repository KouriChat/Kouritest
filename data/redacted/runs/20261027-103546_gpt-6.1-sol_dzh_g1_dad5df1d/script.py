def contains(points, x, y):
    """Vectorized even-odd point-in-polygon; boundary points count as inside."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        dx, dy = x1 - x0, y1 - y0
        if dx == 0 and dy == 0:
            x0, y0 = x1, y1
            continue
        cross = (x - x0) * dy - (y - y0) * dx
        boundary |= ((np.abs(cross) < 1e-10)
                     & (x >= min(x0, x1) - 1e-10)
                     & (x <= max(x0, x1) + 1e-10)
                     & (y >= min(y0, y1) - 1e-10)
                     & (y <= max(y0, y1) + 1e-10))
        if dy != 0:
            hit = ((y0 > y) != (y1 > y))
            intercept = x0 + (y - y0) * dx / dy
            inside ^= hit & (x < intercept)
        x0, y0 = x1, y1
    return inside | boundary

def main():
    output = Path.cwd() / 'outputs'
    output.mkdir(parents=True, exist_ok=True)
    longitude = np.arange(-45, 186, dtype=np.int64) / 5.0
    latitude = np.arange(225, 154, -1, dtype=np.int64) / 5.0
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((71, 231), dtype=bool)
    for shape in LAND:
        land |= contains(shape, x, y)
    for shape in WATER:
        land &= ~contains(shape, x, y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert longitude[0] == -9 and longitude[-1] == 37
    assert latitude[0] == 45 and latitude[-1] == 31
    csv_path = output / 'candidate.csv'
    with csv_path.open('w', encoding='ascii', newline='') as stream:
        csv.writer(stream, lineterminator='\n').writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
    assert original.mode == 'L'
    original.save(output / 'candidate.png')
    nearest = Image.Resampling.NEAREST if hasattr(Image, 'Resampling') else Image.NEAREST
    enlarged = original.resize((1848, 568), resample=nearest)
    enlarged.save(output / 'candidate_8x.png')
