    with csv_path.open('r', encoding='ascii', newline='') as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    reread = np.array(rows, dtype=np.uint8)
    assert np.array_equal(reread, matrix)
    with Image.open(output / 'candidate.png') as image:
        assert image.size == (231, 71) and image.mode == 'L'
        pixels = np.array(image)
    with Image.open(output / 'candidate_8x.png') as image:
        assert image.size == (1848, 568) and image.mode == 'L'
        big_pixels = np.array(image)
    assert set(np.unique(pixels).tolist()) <= {0, 255}
    assert set(np.unique(big_pixels).tolist()) <= {0, 255}
    assert np.array_equal(pixels, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(big_pixels, expected)
