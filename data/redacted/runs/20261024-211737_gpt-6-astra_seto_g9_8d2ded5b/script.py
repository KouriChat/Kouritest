def polygon(name, coordinates, water=False):
    vertices = np.array(
        [tuple(map(float, pair.split(","))) for pair in coordinates.split()],
        dtype=np.float64,
    )
    assert vertices.ndim == 2 and vertices.shape[1] == 2
    assert len(vertices) >= 3 and np.isfinite(vertices).all()
    (SEA if water else LAND).append((name, vertices))

