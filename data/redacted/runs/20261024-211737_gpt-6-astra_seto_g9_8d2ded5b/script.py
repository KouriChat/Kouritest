def contains_points(vertices, x, y):
    """Ray crossing at sample coordinates; coast-boundary points count inside."""
    result = np.zeros(x.shape, dtype=bool)
    selected = (
        (x >= vertices[:, 0].min()) & (x <= vertices[:, 0].max()) &
        (y >= vertices[:, 1].min()) & (y <= vertices[:, 1].max())
    )
    if not selected.any():
        return result
    px, py = x[selected], y[selected]
    inside = np.zeros(px.shape, dtype=bool)
    boundary = np.zeros(px.shape, dtype=bool)
    previous = vertices[-1]
    for current in vertices:
        ax, ay = previous
        bx, by = current
        dx, dy = bx - ax, by - ay
        cross = (px - ax) * dy - (py - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-12) &
            (px >= min(ax, bx) - 1e-12) &
            (px <= max(ax, bx) + 1e-12) &
            (py >= min(ay, by) - 1e-12) &
            (py <= max(ay, by) + 1e-12)
        )
        if dy != 0.0:
            crossing = ((ay > py) != (by > py))
            intersection_x = ax + (py - ay) * dx / dy
            inside ^= crossing & (px < intersection_x)
        previous = current
    result[selected] = inside | boundary
    return result


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    longitude = 129.0 + 2.0 * np.arange(253, dtype=np.float64) / 63.0
    latitude = 35.0 - 2.0 * np.arange(64, dtype=np.float64) / 63.0
    assert longitude[0] == 129.0 and longitude[-1] == 137.0
    assert latitude[0] == 35.0 and latitude[-1] == 33.0
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((64, 253), dtype=bool)
    for _, vertices in LAND:
        land |= contains_points(vertices, x, y)
    for _, vertices in SEA:
        land &= ~contains_points(vertices, x, y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix).tolist()) == {0, 1}

    csv_path = out / "candidate.csv"
    np.savetxt(csv_path, matrix, fmt="%d", delimiter=",", newline="\n")
    pixels = matrix * np.uint8(255)
    raw = Image.fromarray(pixels)
    assert raw.mode == "L"
    raw.save(out / "candidate.png", format="PNG")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = raw.resize((2024, 512), resample=nearest)
    enlarged.save(out / "candidate_8x.png", format="PNG")

    # Validate the actual written files, not just the arrays held in memory.
    with csv_path.open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    csv_matrix = np.array(rows, dtype=np.uint8)
    assert csv_matrix.size == 16192
    assert np.array_equal(csv_matrix, matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.format == "PNG" and image.size == (253, 64)
        assert image.mode == "L"
        saved_raw = np.array(image)
    with Image.open(out / "candidate_8x.png") as image:
        assert image.format == "PNG" and image.size == (2024, 512)
        assert image.mode == "L"
        saved_big = np.array(image)
    assert set(np.unique(saved_raw).tolist()) == {0, 255}
    assert set(np.unique(saved_big).tolist()) == {0, 255}
    assert np.array_equal(saved_raw, pixels)
    expected = np.repeat(np.repeat(saved_raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(saved_big, expected)
    report = {
        "method": "Memory-written polygon containment at exact sample points",
        "external_geographic_data": False,
        "shape": [64, 253], "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "raw_png_size": [253, 64], "enlarged_png_size": [2024, 512],
        "png_values": [0, 255], "nearest_neighbor_8x_verified": True,
        "validation": "passed",
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
