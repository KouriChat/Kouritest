def small_island(name, lon, lat, rx, ry, angle=0.0):
    """Hand-chosen small-island ellipse, represented as a 20-vertex polygon."""
    t = np.arange(20, dtype=np.float64) * (2.0 * np.pi / 20)
    a = np.deg2rad(angle)
    u, v = rx * np.cos(t), ry * np.sin(t)
    xy = np.column_stack((lon + u*np.cos(a) - v*np.sin(a),
                          lat + u*np.sin(a) + v*np.cos(a)))
    LAND.append((name, xy))

