def inside(x, y, vertices):
    """Even-odd crossing rule at a WGS84 sample point."""
    result = False
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if (y0 > y) != (y1 > y):
            crossing = x0 + (x1 - x0) * (y - y0) / (y1 - y0)
            if x < crossing:
                result = not result
        x0, y0 = x1, y1
    return result

def main():
    target = Path("outputs")
    target.mkdir(exist_ok=True)
    polygons = [MAINLAND, *ISLANDS]
    matrix = np.array([
        [int(any(inside(-131 + 2 * col / 126, 55 - 2 * row / 126, poly)
                 for poly in polygons)) for col in range(127)]
        for row in range(127)
    ], dtype=np.uint8)
    with (target / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(matrix.tolist())
    im = Image.fromarray(matrix * 255, mode="L")
    im.save(target / "candidate.png")
    im.resize((1016, 1016), Image.Resampling.NEAREST).save(target / "candidate_8x.png")
    assert matrix.shape == (127, 127) and set(np.unique(matrix)) <= {0, 1}
    assert Image.open(target / "candidate_8x.png").size == (1016, 1016)
    assert np.array_equal(np.asarray(Image.open(target / "candidate_8x.png")),
                          np.repeat(np.repeat(matrix * 255, 8, axis=0), 8, axis=1))

if __name__ == "__main__":
    main()
