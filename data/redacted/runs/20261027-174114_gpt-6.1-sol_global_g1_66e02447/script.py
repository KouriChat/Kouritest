def points_in_polygon(x, y, vertices):
    """Vectorized even-odd rule, including points exactly on a polygon edge."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (x - x0) * dy - (y - y0) * dx
        boundary |= (
            (np.abs(cross) < 1e-10)
            & (x >= min(x0, x1)) & (x <= max(x0, x1))
            & (y >= min(y0, y1)) & (y <= max(y0, y1))
        )
        if dy != 0:
            crossing = (y0 > y) != (y1 > y)
            intersection = x0 + (y - y0) * dx / dy
            inside ^= crossing & (x < intersection)
        x0, y0 = x1, y1
    return inside | boundary

def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    longitude = np.arange(-179, 180, 2, dtype=np.int16)
    latitude = np.arange(89, -90, -2, dtype=np.int16)
    xx, yy = np.meshgrid(longitude.astype(float), latitude.astype(float))
    mask = np.zeros((90, 180), dtype=bool)
    for _, outline in LAND:
        mask |= points_in_polygon(xx, yy, outline)
    for _, outline in WATER:
        mask &= ~points_in_polygon(xx, yy, outline)
    matrix = mask.astype(np.uint8)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * 255
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16200
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as saved:
        assert saved.size == (180, 90)
        original = np.array(saved)
        assert set(np.unique(original).tolist()) == {0, 255}
        assert np.array_equal(original, pixels)
    with Image.open(out / "candidate_8x.png") as saved:
        assert saved.size == (1440, 720)
        expanded = np.array(saved)
        assert set(np.unique(expanded).tolist()) == {0, 255}
        assert np.array_equal(expanded, original.repeat(8, 0).repeat(8, 1))
    print("Validated: 90 x 180 = 16,200 binary values; PNG 180 x 90; "
          "nearest-neighbor PNG 1440 x 720; black and white only.")
    print(f"Land: {matrix.sum()} points. Files: {out}")

if __name__ == "__main__":
    main()
