# Export without resampling geography, smoothing, or modifying classified pixels.
def export_and_validate():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    matrix = LAND.astype(np.uint8)
    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()
    assert LATS[0] == 45 and LATS[-1] == 31
    assert LONS[0] == -9 and LONS[-1] == 37
    csv_path = output / "candidate.csv"
    raw_path = output / "candidate.png"
    large_path = output / "candidate_8x.png"
    np.savetxt(csv_path, matrix, fmt="%d", delimiter=",", newline="\n")
    pixels = matrix * np.uint8(255)
    raw = Image.fromarray(pixels)
    assert raw.mode == "L"
    raw.save(raw_path)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    large = raw.resize((1848, 568), resample=nearest)
    large.save(large_path)
    with csv_path.open("r", encoding="utf-8", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.asarray(rows, dtype=np.uint8)
    assert restored.size == 16401 and np.array_equal(restored, matrix)
    with Image.open(raw_path) as image:
        assert image.size == (231, 71)
        raw_check = np.array(image)
    with Image.open(large_path) as image:
        assert image.size == (1848, 568)
        large_check = np.array(image)
    assert set(np.unique(raw_check).tolist()) == {0, 255}
    assert set(np.unique(large_check).tolist()) == {0, 255}
    assert np.array_equal(raw_check, pixels)
    expected = np.repeat(np.repeat(raw_check, 8, axis=0), 8, axis=1)
    assert np.array_equal(large_check, expected)
    print("PASS: 71 x 231 = 16401 binary CSV values; no header or missing values.")
    print("PASS: 231 x 71 PNG; black water, white land.")
    print("PASS: 1848 x 568 PNG; exact nearest-neighbor 8 x enlargement.")
    print(f"Land points: {int(matrix.sum())}; water points: {int((matrix == 0).sum())}")
    print(f"Files: {csv_path}, {raw_path}, {large_path}")

