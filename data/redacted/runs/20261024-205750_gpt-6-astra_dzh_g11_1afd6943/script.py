LONS = np.round(-9.0 + np.arange(231) * 0.2, 8)
LATS = np.round(45.0 - np.arange(71) * 0.2, 8)
X, Y = np.meshgrid(LONS, LATS)
LAND = np.zeros(X.shape, dtype=bool)

def polygon_mask(vertices):
    """Vectorized point-in-polygon, with boundary points assigned to polygon."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        dx, dy = x2 - x1, y2 - y1
        cross = (X - x1) * dy - (Y - y1) * dx
        boundary |= ((np.abs(cross) < 1e-10) &
                     (X >= min(x1, x2) - 1e-10) &
                     (X <= max(x1, x2) + 1e-10) &
                     (Y >= min(y1, y2) - 1e-10) &
                     (Y <= max(y1, y2) + 1e-10))
        if abs(dy) > 1e-14:
            inside ^= ((y1 > Y) != (y2 > Y)) & (X < x1 + (Y-y1)*dx/dy)
        x1, y1 = x2, y2
    return inside | boundary

def add(vertices):
    LAND[:] |= polygon_mask(vertices)

def subtract(vertices):
    LAND[:] &= ~polygon_mask(vertices)

