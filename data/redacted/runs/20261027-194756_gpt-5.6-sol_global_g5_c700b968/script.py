def point_in_polygon(x, y, polygon):
    inside = False
    j = len(polygon) - 1
    for i in range(len(polygon)):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        if ((yi > y) != (yj > y)):
            xinters = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < xinters:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    if lat <= -78:
        return True
    for polygon in LAND:
        if point_in_polygon(lon, lat, polygon):
            for water in WATER_HOLES:
                if point_in_polygon(lon, lat, water):
                    return False
            return True
    return False


def generate_matrix():
    rows = []
    for lat in range(89, -90, -2):
        rows.append([
            1 if is_land(lon, lat) else 0
            for lon in range(-179, 180, 2)
        ])
    matrix = np.asarray(rows, dtype=np.uint8)
    if matrix.shape != (90, 180):
        raise RuntimeError(matrix.shape)
    if not np.all((matrix == 0) | (matrix == 1)):
        raise RuntimeError("invalid matrix values")
    return matrix


def write_outputs(matrix):
    with (OUT / "candidate.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        for row in matrix:
            writer.writerow([int(v) for v in row])

    image = Image.fromarray((matrix * 255).astype(np.uint8), mode="L")
    if image.size != (180, 90):
        raise RuntimeError(image.size)
    image.save(OUT / "candidate.png")

    enlarged = image.resize((1440, 720), Image.Resampling.NEAREST)
    if enlarged.size != (1440, 720):
        raise RuntimeError(enlarged.size)
    enlarged.save(OUT / "candidate_8x.png")


if __name__ == "__main__":
    matrix = generate_matrix()
    write_outputs(matrix)
    print(matrix.shape, matrix.size, int(matrix.sum()))
