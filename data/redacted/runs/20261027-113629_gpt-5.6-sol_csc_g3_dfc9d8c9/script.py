def contains(poly, x, y):
    inside = False
    n = len(poly)
    for i, (x1, y1) in enumerate(poly):
        x2, y2 = poly[(i + 1) % n]
        cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
        if abs(cross) < 1e-10 and min(x1, x2) - 1e-10 <= x <= max(x1, x2) + 1e-10 and min(y1, y2) - 1e-10 <= y <= max(y1, y2) + 1e-10:
            return True
        if (y1 > y) != (y2 > y):
            if x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
                inside = not inside
    return inside

def main():
    matrix = np.zeros((ROWS, COLS), dtype=np.uint8)
    for r in range(ROWS):
        lat = LAT0 - STEP * r
        for c in range(COLS):
            lon = LON0 + STEP * c
            matrix[r, c] = any(contains(p, lon, lat) for p in POLYGONS)

    out = Path("outputs")
    out.mkdir(exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((COLS * 8, ROWS * 8), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
