X, Y = np.meshgrid(lon, lat)
land = np.zeros((64, 253), dtype=np.uint8)

def poly(text, value=1):
    """Ray-crossing point test on the specified handwritten polygon."""
    p = [tuple(map(float, s.split(","))) for s in text.split()]
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = p[-1]
    for x1, y1 in p:
        if y0 != y1:
            crossing = ((y0 > Y) != (y1 > Y))
            intercept = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (X < intercept)
        x0, y0 = x1, y1
    land[inside] = value

