def on_segment(x, y, a, b):
    cross = (x-a[0])*(b[1]-a[1]) - (y-a[1])*(b[0]-a[0])
    if abs(cross) > 1e-10:
        return False
    return (min(a[0],b[0])-1e-10 <= x <= max(a[0],b[0])+1e-10 and
            min(a[1],b[1])-1e-10 <= y <= max(a[1],b[1])+1e-10)


def contains(x, y, polygon):
    """Ray crossing point-in-polygon test; boundary is classified as land."""
    inside = False
    j = len(polygon) - 1
    for i, p in enumerate(polygon):
        q = polygon[j]
        if on_segment(x, y, p, q):
            return True
        if (p[1] > y) != (q[1] > y):
            cross_x = (q[0]-p[0]) * (y-p[1]) / (q[1]-p[1]) + p[0]
            if x < cross_x:
                inside = not inside
        j = i
    return inside


def main():
    matrix = np.zeros((111, 141), dtype=np.uint8)
    for row, lat in enumerate(LATS):
        for col, lon in enumerate(LONS):
            matrix[row, col] = int(any(contains(float(lon), float(lat), poly)
                                       for poly in LAND_POLYGONS))
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())
    # Matrix 1=land -> white; 0=water -> black.
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(out / "candidate.png")
    image.resize((1128, 888), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert set(np.unique(matrix)).issubset({0, 1})
    assert image.size == (141, 111)
    assert len(set(image.getdata())) == 2
    with (out / "candidate.csv").open("r", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111 and all(len(r) == 141 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    assert Image.open(out / "candidate_8x.png").size == (1128, 888)
    print("validated: 111x141, 15651 binary values; PNGs 141x111 and 1128x888")


if __name__ == "__main__":
    main()
