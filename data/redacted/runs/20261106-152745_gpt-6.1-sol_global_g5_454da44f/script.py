def polygon_mask(vertices, x, y):
    """Even/odd point-in-polygon with boundary points included."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        on_segment = (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        boundary |= on_segment
        if dy != 0:
            crossing = ((ay > y) != (by > y))
            intersection_x = ax + (y - ay) * dx / dy
            inside ^= crossing & (x < intersection_x)
        ax, ay = bx, by
    return inside | boundary


def wrapped_mask(vertices, x, y):
    result = polygon_mask(vertices, x, y)
    if vertices[:, 0].max() > 180:
        result |= polygon_mask(vertices, x + 360, y)
    if vertices[:, 0].min() < -180:
        result |= polygon_mask(vertices, x - 360, y)
    return result


def generate():
    longitudes = np.arange(-179, 180, 2, dtype=float)
    latitudes = np.arange(89, -90, -2, dtype=float)
    x, y = np.meshgrid(longitudes, latitudes)
    assert x.shape == y.shape == (90, 180)
    assert np.all(np.diff(ANTARCTIC_COAST[:, 0]) > 0)
    coast_lat = np.interp(
        longitudes, ANTARCTIC_COAST[:, 0], ANTARCTIC_COAST[:, 1]
    )
    land = y <= coast_lat[np.newaxis, :]
    for name, vertices in LAND:
        land |= wrapped_mask(vertices, x, y)
    for name, vertices in SEA:
        land &= ~wrapped_mask(vertices, x, y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert set(np.unique(matrix).tolist()) == {0, 1}

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    raw = Image.fromarray(pixels)
    raw.save(output / "candidate.png", format="PNG")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    raw.resize((1440, 720), resample=nearest).save(
        output / "candidate_8x.png", format="PNG"
    )

    # Validate the actual saved deliverables, not just in-memory dimensions.
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    loaded = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(loaded, matrix)
    with Image.open(output / "candidate.png") as im:
        assert im.size == (180, 90)
        original = np.asarray(im).copy()
    with Image.open(output / "candidate_8x.png") as im:
        assert im.size == (1440, 720)
        enlarged = np.asarray(im).copy()
    assert set(np.unique(original).tolist()) == {0, 255}
    assert set(np.unique(enlarged).tolist()) == {0, 255}
    assert np.array_equal(original, pixels)
    assert np.array_equal(enlarged, original.repeat(8, 0).repeat(8, 1))
    report = {
        "matrix_shape": [90, 180],
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "raw_image_size": [180, 90],
        "enlarged_image_size": [1440, 720],
        "pixel_values": [0, 255],
        "nearest_neighbor_8x_verified": True,
        "source": "Hand-written geographic-memory rules only; no external data.",
        "classification": "Polygon rasterization and Antarctic coast rule.",
        "validation": "PASS",
    }
    (output / "validation.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    generate()
