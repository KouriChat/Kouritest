def contains_points(vertices, x, y):
    """Ray casting on sample points, with boundary points assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    eps = 1e-10
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if abs(dy) > eps:
            crosses = (ay > y) != (by > y)
            intercept = ax + (y - ay) * dx / dy
            inside ^= crosses & (x < intercept)
        cross = (x - ax) * dy - (y - ay) * dx
        on_segment = (
            (np.abs(cross) <= eps)
            & (x >= min(ax, bx) - eps) & (x <= max(ax, bx) + eps)
            & (y >= min(ay, by) - eps) & (y <= max(ay, by) + eps)
        )
        boundary |= on_segment
        ax, ay = bx, by
    return inside | boundary


