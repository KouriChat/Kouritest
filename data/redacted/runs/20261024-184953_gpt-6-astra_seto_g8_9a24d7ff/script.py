lon = 129.0 + np.arange(253, dtype=np.float64) * (2.0 / 63.0)
lat = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((64, 253), dtype=bool)

def polygon(text):
    vertices = [tuple(map(float, p.split(","))) for p in text.split()]
    inside = np.zeros_like(land)
    boundary = np.zeros_like(land)
    for i, (ax, ay) in enumerate(vertices):
        bx, by = vertices[(i + 1) % len(vertices)]
        if ay != by:
            hit = ((ay > Y) != (by > Y))
            inside ^= hit & (X < ax + (Y - ay) * (bx - ax) / (by - ay))
        cross = (X - ax) * (by - ay) - (Y - ay) * (bx - ax)
        boundary |= ((np.abs(cross) < 1e-12)
                     & (X >= min(ax, bx)) & (X <= max(ax, bx))
                     & (Y >= min(ay, by)) & (Y <= max(ay, by)))
    return inside | boundary

def L(text):
    global land
    land |= polygon(text)

def W(text):
    global land
    land &= ~polygon(text)

def E(cx, cy, rx, ry, angle=0):
    """Hand-chosen small-island ellipse, radii in coordinate degrees."""
    global land
    a = np.deg2rad(angle)
    u = (X-cx)*np.cos(a) + (Y-cy)*np.sin(a)
    v = -(X-cx)*np.sin(a) + (Y-cy)*np.cos(a)
    land |= (u/rx)**2 + (v/ry)**2 <= 1

