lats = [45.0 - 0.2 * i for i in range(71)]
lons = [-9.0 + 0.2 * j for j in range(231)]
matrix = np.zeros((len(lats), len(lons)), dtype=np.uint8)

for r, lat in enumerate(lats):
    for c, lon in enumerate(lons):
        land = any(inside(lon, lat, p) for p in LAND)
        if land and any(inside(lon, lat, p) for p in LAKES):
            land = False
        if any(inside(lon, lat, p) for p in ISLANDS):
            land = True
        matrix[r, c] = 1 if land else 0

