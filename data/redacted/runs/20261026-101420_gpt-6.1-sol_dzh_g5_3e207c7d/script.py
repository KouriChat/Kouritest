def ring(points):
    return tuple((float(x), float(y)) for x, y in points)

def inside(x, y, poly):
    hit = False
    x1, y1 = poly[-1]
    for x2, y2 in poly:
        cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
        if abs(cross) <= 1e-10:
            if min(x1, x2) - 1e-10 <= x <= max(x1, x2) + 1e-10:
                if min(y1, y2) - 1e-10 <= y <= max(y1, y2) + 1e-10:
                    return True
        if (y1 > y) != (y2 > y):
            at_x = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < at_x:
                hit = not hit
        x1, y1 = x2, y2
    return hit

