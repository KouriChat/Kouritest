def polygon_mask(points, x, y):
    """Vectorized point-in-polygon; boundary points belong to the polygon."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    for i, (ax, ay) in enumerate(points):
        bx, by = points[(i + 1) % len(points)]
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        on_segment = (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        boundary |= on_segment
        if dy != 0:
            crossing = ((ay > y) != (by > y))
            intersection_x = ax + (y - ay) * dx / dy
            inside ^= crossing & (x < intersection_x)
    return inside | boundary


def main():
    output = Path.cwd() / 'outputs'
    output.mkdir(parents=True, exist_ok=True)
    longitudes = np.arange(-1050, -809, dtype=np.int32) / 10.0
    latitudes = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    assert len(longitudes) == 241 and len(latitudes) == 61
    assert (longitudes[0], longitudes[-1]) == (-105.0, -81.0)
    assert (latitudes[0], latitudes[-1]) == (79.0, 73.0)
    x, y = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((61, 241), dtype=bool)
    for name, points in LAND:
        mask |= polygon_mask(points, x, y)
    for name, points in WATER:
        mask &= ~polygon_mask(points, x, y)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix).tolist()) == {0, 1}

    csv_path = output / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='ascii') as stream:
        csv.writer(stream, lineterminator='\n').writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(output / 'candidate.png', format='PNG')
    nearest = getattr(Image, 'Resampling', Image).NEAREST
    enlarged = original.resize((1928, 488), resample=nearest)
