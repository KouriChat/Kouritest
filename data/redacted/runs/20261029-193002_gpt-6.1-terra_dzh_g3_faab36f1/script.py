def inside(x, y, poly):
    result = False
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if (y1 > y) != (y0 > y) and x < (x0-x1)*(y-y1)/(y0-y1)+x1:
            result = not result
        x0, y0 = x1, y1
    return result

