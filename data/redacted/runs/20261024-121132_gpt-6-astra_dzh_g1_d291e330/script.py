def polygon_mask(vertices, longitude, latitude):
    """Ray crossing at exact sample positions; coast-boundary points are land."""
    p = np.asarray(vertices, dtype=np.float64)
    assert p.ndim == 2 and p.shape[1] == 2 and len(p) >= 3
    assert np.isfinite(p).all()
    result = np.zeros(longitude.shape, dtype=bool)
    selected = (
        (longitude >= p[:, 0].min()) & (longitude <= p[:, 0].max())
        & (latitude >= p[:, 1].min()) & (latitude <= p[:, 1].max())
    )
    x, y = longitude[selected], latitude[selected]
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    eps = 1e-10
    for (x1, y1), (x2, y2) in zip(p, np.roll(p, -1, axis=0)):
        dx, dy = x2 - x1, y2 - y1
        cross = (x - x1) * dy - (y - y1) * dx
        boundary |= (
            (np.abs(cross) <= eps * max(1.0, abs(dx) + abs(dy)))
            & (x >= min(x1, x2) - eps) & (x <= max(x1, x2) + eps)
            & (y >= min(y1, y2) - eps) & (y <= max(y1, y2) + eps)
        )
        if dy != 0.0:
            inside ^= ((y1 > y) != (y2 > y)) & (
                x < x1 + (y - y1) * dx / dy
            )
    result[selected] = inside | boundary
    return result


def main():
    # Integers divided by five avoid cumulative floating-point stepping errors.
    latitudes = (225 - np.arange(71, dtype=np.int64)) / 5.0
    longitudes = (-45 + np.arange(231, dtype=np.int64)) / 5.0
    assert (latitudes[0], latitudes[-1]) == (45.0, 31.0)
    assert (longitudes[0], longitudes[-1]) == (-9.0, 37.0)
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    land = np.zeros((71, 231), dtype=bool)
    for _, vertices in POLYGONS:
        land |= polygon_mask(vertices, longitude, latitude)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix).tolist()) == {0, 1}

