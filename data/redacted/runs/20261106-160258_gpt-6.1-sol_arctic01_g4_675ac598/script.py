def contains(points, x, y):
    """Even-odd ray test, including polygon boundary points."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    for (ax, ay), (bx, by) in zip(points, points[1:] + points[:1]):
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        boundary |= ((np.abs(cross) < 1e-10)
                     & (x >= min(ax, bx) - 1e-10)
                     & (x <= max(ax, bx) + 1e-10)
                     & (y >= min(ay, by) - 1e-10)
                     & (y <= max(ay, by) + 1e-10))
        if by != ay:
            crosses = ((ay > y) != (by > y))
            inside ^= crosses & (x < ax + (y - ay) * (bx - ax) / (by - ay))
    return inside | boundary

def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    x, y = np.meshgrid(np.arange(-1050, -809) / 10.0,
                       np.arange(790, 729, -1) / 10.0)
    mask = np.zeros((61, 241), dtype=bool)
    for _, polygon in LAND:
        mask |= contains(polygon, x, y)
    for _, polygon in WATER:
        mask &= ~contains(polygon, x, y)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix)) <= {0, 1}
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    raw = Image.fromarray(matrix * np.uint8(255))
    raw.save(out / "candidate.png")
    nearest = Image.Resampling.NEAREST
    raw.resize((1928, 488), resample=nearest).save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61 and all(len(r) == 241 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (241, 61)
        pixels = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1928, 488)
        large = np.array(im)
    assert set(np.unique(pixels)) == {0, 255}
    assert set(np.unique(large)) == {0, 255}
    assert np.array_equal(large, pixels.repeat(8, axis=0).repeat(8, axis=1))
    print("Validated: 61 x 241 = 14,701 binary samples; both PNG sizes; exact 8x nearest.")

if __name__ == "__main__":
    main()
