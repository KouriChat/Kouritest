def contains(poly, x, y):
    inside = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if (yi > y) != (yj > y):
            crossing = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < crossing:
                inside = not inside
        j = i
    return inside


def generate():
    latitudes = np.round(np.arange(79.0, 72.999, -0.1), 1)
    longitudes = np.round(np.arange(-105.0, -80.999, 0.1), 1)
    matrix = np.zeros((len(latitudes), len(longitudes)), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = any(contains(poly, lon, lat) for poly in LAND)
            if matrix[row, col]:
                matrix[row, col] = not any(
                    contains(poly, lon, lat) for poly in LAKES
                )
    return matrix


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = generate()
    np.savetxt(out / "candidate.csv", matrix, fmt="%d", delimiter=",")
    image = Image.fromarray((matrix * 255).astype(np.uint8), mode="L")
    image.save(out / "candidate.png")
    image.resize((1928, 488), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
