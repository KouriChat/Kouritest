def polygon(target, name, text):
    vertices = np.array([tuple(map(float, p.split(",")))
                         for p in text.split()], dtype=np.float64)
    assert vertices.ndim == 2 and vertices.shape[1] == 2
    assert len(vertices) >= 3 and np.isfinite(vertices).all()
    target.append((name, vertices))

def land(name, text):
    polygon(LAND, name, text)

def sea(name, text):
    polygon(SEA, name, text)

