# Tiny islands use explicit, manually located rotated polygonal ovals.
# rx/ry are angular semi-axes, not cell-fill or majority-vote thresholds.
def islet(name, lon, lat, rx, ry, angle=0):
    t = np.arange(20) * (2 * np.pi / 20)
    a = np.deg2rad(angle)
    u, v = rx * np.cos(t), ry * np.sin(t)
    p = np.column_stack((lon + u*np.cos(a) - v*np.sin(a),
                         lat + u*np.sin(a) + v*np.cos(a)))
    LAND.append((name, p))

