def contains_points(vertices, x, y):
    """Even/odd horizontal ray casting at the point, with no cell averaging."""
    result = np.zeros(x.shape, dtype=bool)
    box = ((x >= vertices[:, 0].min()) & (x <= vertices[:, 0].max()) &
           (y >= vertices[:, 1].min()) & (y <= vertices[:, 1].max()))
    xx, yy = x[box], y[box]
    if xx.size == 0:
        return result
    inside = np.zeros(xx.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > yy) != (y1 > yy))
            crossing &= xx < x0 + (yy - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing
        x0, y0 = x1, y1
    result[box] = inside
    return result

