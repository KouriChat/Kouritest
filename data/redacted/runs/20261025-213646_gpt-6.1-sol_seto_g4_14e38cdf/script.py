def polygon_mask(polygon, x, y):
    """Vectorized ray crossing, with coastline points counted as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        dx, dy = x1 - x0, y1 - y0
        cross = (x - x0) * dy - (y - y0) * dx
        boundary |= (
            (np.abs(cross) <= 1e-12)
            & (x >= min(x0, x1) - 1e-12)
            & (x <= max(x0, x1) + 1e-12)
            & (y >= min(y0, y1) - 1e-12)
            & (y <= max(y0, y1) + 1e-12)
        )
        if dy != 0:
            crossing = ((y0 > y) != (y1 > y))
            x_intersection = x0 + (y - y0) * dx / dy
            inside ^= crossing & (x < x_intersection)
        x0, y0 = x1, y1
    return inside | boundary


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Use the exact specified spacing, not rounded display coordinates.
    latitudes = 35.0 - np.arange(64, dtype=float) * (2.0 / 63.0)
    longitudes = 129.0 + np.arange(253, dtype=float) * (2.0 / 63.0)
    xx, yy = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((64, 253), dtype=bool)
    for polygon in LAND:
        mask |= polygon_mask(polygon, xx, yy)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert np.isin(matrix, [0, 1]).all()
    assert latitudes[0] == 35 and latitudes[-1] == 33
    assert longitudes[0] == 129 and longitudes[-1] == 137

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    enlarged = original.resize((2024, 512), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

