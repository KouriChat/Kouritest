    with csv_path.open("r", newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert sum(len(row) for row in rows) == 16192
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array([[int(v) for v in row] for row in rows], dtype=np.uint8)
    assert np.array_equal(restored, matrix)
