ROWS, COLS = 64, 253
lons = 129.0 + np.arange(COLS) * (2.0 / 63.0)
lats = 35.0 - np.arange(ROWS) * (2.0 / 63.0)
X, Y = np.meshgrid(lons, lats)
land = np.zeros((ROWS, COLS), dtype=bool)

def poly(points):
    """Boolean point-in-polygon mask (ray crossing), including near boundary."""
    inside = np.zeros_like(X, dtype=bool)
    xj, yj = points[-1]
    for xi, yi in points:
        cross = ((yi > Y) != (yj > Y))
        xcut = (xj-xi) * (Y-yi) / ((yj-yi) if yj != yi else 1e-30) + xi
        inside ^= cross & (X < xcut)
        xj, yj = xi, yi
    return inside

def ellipse(cx, cy, rx, ry, angle=0):
    a = math.radians(angle)
    u = (X-cx)*math.cos(a) + (Y-cy)*math.sin(a)
    v = -(X-cx)*math.sin(a) + (Y-cy)*math.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1

def add_poly(p):
    global land
    land |= poly(p)

def cut_poly(p):
    global land
    land &= ~poly(p)

