def polygon(name, text, water=False):
    """Parse explicit hand-written vertices; no geographic library or data."""
    vertices = np.array(
        [[float(n) for n in pair.split(",")] for pair in text.split()],
        dtype=np.float64,
    )
    assert vertices.ndim == 2 and vertices.shape[1] == 2
    assert len(vertices) >= 3, name
    (WATER if water else LAND).append((name, vertices))


