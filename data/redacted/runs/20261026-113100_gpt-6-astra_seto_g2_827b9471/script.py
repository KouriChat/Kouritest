def inside(lon, lat, polygon):
    """Ray-casting point-in-polygon test."""
    hit = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                hit = not hit
        j = i
    return hit

def classify(lon, lat):
    land = any(inside(lon, lat, p) for p in LAND)
    if any(inside(lon, lat, p) for p in WATER):
        land = False
    if not land:
        for x, y, rx, ry in ISLANDS:
            if ((lon-x)/rx)**2 + ((lat-y)/ry)**2 <= 1.0:
                land = True
                break
    return int(land)

def main():
    matrix = [[classify(LON0 + c*STEP, LAT0 - r*STEP)
               for c in range(COLS)] for r in range(ROWS)]
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)
    pixels = np.asarray(matrix, dtype=np.uint8) * 255
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((COLS*8, ROWS*8), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")
    assert len(matrix) == 64 and all(len(row) == 253 for row in matrix)
    assert sum(map(len, matrix)) == 16192 and set(pixels.flat) <= {0, 255}
    assert Image.open(out / "candidate_8x.png").size == (2024, 512)
    print("Generated 64x253 matrix and 253x64 / 2024x512 PNGs.")

if __name__ == "__main__":
    main()
