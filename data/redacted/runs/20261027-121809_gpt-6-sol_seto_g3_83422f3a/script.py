def make_matrix():
    result = np.zeros((64, 253), dtype=np.uint8)
    for row in range(64):
        lat = 35.0 - row * 2.0 / 63.0
        for col in range(253):
            lon = 129.0 + col * 8.0 / 252.0
            land = any(inside(lon, lat, shape) for shape in POLYGONS)
            if inside(lon, lat, ISE_BAY):
                land = False
            if not land:
                land = any(((lon - cx) / rx) ** 2 +
                           ((lat - cy) / ry) ** 2 <= 1
                           for cx, cy, rx, ry in ISLANDS)
            result[row, col] = int(land)
    return result


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = make_matrix()
    assert matrix.shape == (64, 253) and set(np.unique(matrix)) <= {0, 1}
    with (out / "candidate.csv").open("w", newline="", encoding="utf-8") as file:
        csv.writer(file).writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(out / "candidate.png")
    enlarged = image.resize((2024, 512), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="utf-8") as file:
        rows = [[int(v) for v in row] for row in csv.reader(file)]
    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert sum(len(row) for row in rows) == 16192
    assert set(v for row in rows for v in row) <= {0, 1}
    assert Image.open(out / "candidate.png").size == (253, 64)
    assert Image.open(out / "candidate_8x.png").size == (2024, 512)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert list(enlarged.getdata()) == list(
        image.resize((2024, 512), Image.Resampling.NEAREST).getdata())


def inside(x, y, poly):
    """Odd-even polygon rule; each grid coordinate is tested as a point."""
    hit = False
    for i, (ax, ay) in enumerate(poly):
        bx, by = poly[i - 1]
        if (ay > y) != (by > y) and x < ax + (y - ay) * (bx - ax) / (by - ay):
            hit = not hit
    return hit


