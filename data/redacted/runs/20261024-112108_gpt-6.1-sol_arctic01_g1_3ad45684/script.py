def polygon_mask(vertices, west, north):
    """Vectorized ray casting at points, without pixel-area averaging."""
    inside = np.zeros(west.shape, dtype=bool)
    boundary = np.zeros(west.shape, dtype=bool)
    for (x1, y1), (x2, y2) in zip(vertices, vertices[1:] + vertices[:1]):
        dx, dy = x2 - x1, y2 - y1
        if dx == 0 and dy == 0:
            continue
        if dy != 0:
            crossing = (y1 > north) != (y2 > north)
            intercept = x1 + (north - y1) * dx / dy
            inside ^= crossing & (west < intercept)
        on_line = np.abs((west - x1) * dy - (north - y1) * dx) < 1e-10
        within = (
            (west >= min(x1, x2) - 1e-10)
            & (west <= max(x1, x2) + 1e-10)
            & (north >= min(y1, y2) - 1e-10)
            & (north <= max(y1, y2) + 1e-10)
        )
        boundary |= on_line & within
    return inside | boundary


def main():
    # Integer-indexed decimal-degree sampling: no accumulated float steps.
    latitude = (790 - np.arange(61)) / 10.0
    longitude = (-1050 + np.arange(241)) / 10.0
    west, north = np.meshgrid(-longitude, latitude)
    masks = {
        name: polygon_mask(points, west, north)
        for name, points in LAND
    }
    for name, points in WATER:
        owner = WATER_OWNER[name]
        masks[owner] &= ~polygon_mask(points, west, north)
    matrix = np.logical_or.reduce(list(masks.values())).astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert latitude[0] == 79 and latitude[-1] == 73
    assert longitude[0] == -105 and longitude[-1] == -81

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Reopen only our own outputs to validate the actual delivered files.
    with csv_path.open("r", encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 14701
    recovered = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(recovered, matrix)

    with Image.open(out / "candidate.png") as im:
        assert im.size == (241, 61) and im.mode == "L"
        small = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1928, 488) and im.mode == "L"
        large = np.array(im)
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(large).tolist()) == {0, 255}
    assert np.array_equal(small, pixels)
    expected = np.repeat(np.repeat(small, 8, axis=0), 8, axis=1)
    assert np.array_equal(large, expected)
    print("PASS: 61 x 241 = 14,701 binary values; CSV complete; "
          "241 x 61 and 1928 x 488 black/white PNGs; exact 8x nearest neighbor.")


