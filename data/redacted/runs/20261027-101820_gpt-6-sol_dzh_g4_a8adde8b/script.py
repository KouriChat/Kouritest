# Vertices are (east longitude, north latitude).  They are approximate
# coastline landmarks recalled from general geographic knowledge.
yy, xx = np.meshgrid(45 - .2 * np.arange(71), -9 + .2 * np.arange(231), indexing='ij')
land = np.zeros(xx.shape, dtype=bool)

def poly(vertices):
    """Union a polygon with the raster, using the sample point, not cell area."""
    global land
    p = [tuple(map(float, item.split(','))) for item in vertices.split()]
    inside = np.zeros(xx.shape, dtype=bool)
    x0, y0 = p[-1]
    for x1, y1 in p:
        if y0 != y1:
            cross = ((y0 > yy) != (y1 > yy)) & (xx < x0 + (yy-y0)*(x1-x0)/(y1-y0))
            inside ^= cross
        x0, y0 = x1, y1
    land |= inside

def ellipse(cx, cy, rx, ry, tilt=0):
    """Small islands approximated by ellipses; tilt in degrees CCW."""
    global land
    a = np.deg2rad(tilt)
    u = (xx-cx)*np.cos(a) + (yy-cy)*np.sin(a)
    v = -(xx-cx)*np.sin(a) + (yy-cy)*np.cos(a)
    land |= (u/rx)**2 + (v/ry)**2 <= 1

