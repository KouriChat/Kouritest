def points(text):
    return [tuple(map(float, pair.split(","))) for pair in text.split()]


def contains(vertices, x, y):
    """Even-odd point-in-polygon, with boundary points assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-11)
                     & (x >= min(ax, bx) - 1e-10)
                     & (x <= max(ax, bx) + 1e-10)
                     & (y >= min(ay, by) - 1e-10)
                     & (y <= max(ay, by) + 1e-10))
        if dy != 0:
            inside ^= ((ay > y) != (by > y)) & (x < ax + (y - ay) * dx / dy)
        ax, ay = bx, by
    return inside | boundary


