def inside_polygon(x, y, vertices):
    """Vectorized even/odd ray test, evaluated at the sample points only."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (x - x0) * dy - (y - y0) * dx
        on_segment = (
            (np.abs(cross) <= 1e-10)
            & (x >= min(x0, x1) - 1e-10)
            & (x <= max(x0, x1) + 1e-10)
            & (y >= min(y0, y1) - 1e-10)
            & (y <= max(y0, y1) + 1e-10)
        )
        boundary |= on_segment
        if dy != 0:
            crosses = (y0 > y) != (y1 > y)
            x_intersection = x0 + (y - y0) * dx / dy
            inside ^= crosses & (x < x_intersection)
        x0, y0 = x1, y1
    return inside | boundary


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Integer tenths avoid endpoint loss and ensure exactly the requested grid.
    north = np.arange(790, 729, -1, dtype=np.int64) / 10.0
    west = np.arange(1050, 809, -1, dtype=np.int64) / 10.0
    x, y = np.meshgrid(west, north)
    land = np.zeros((61, 241), dtype=bool)
    for vertices in LAND.values():
        land |= inside_polygon(x, y, vertices)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert north[0] == 79 and north[-1] == 73
    assert west[0] == 105 and west[-1] == 81
    assert np.isin(matrix, [0, 1]).all()

    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    assert image.mode == "L"
    image.save(out / "candidate.png")
    # Pillow's NEAREST uses no antialiasing, averaging or coast modification.
    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST
    enlarged = image.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Read back only our own outputs, never outside geographic/reference data.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    reread = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(reread, matrix)

    expected_large = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    for filename, size, expected in (
        ("candidate.png", (241, 61), pixels),
        ("candidate_8x.png", (1928, 488), expected_large),
    ):
        with Image.open(out / filename) as check:
            assert check.size == size
            assert check.mode == "L"
            actual = np.asarray(check)
            assert set(np.unique(actual).tolist()) == {0, 255}
            assert np.array_equal(actual, expected)

    report = {
        "method": "handwritten knowledge-only polygons, point-in-polygon union",
        "reference_geographic_data_used": False,
        "shape": [61, 241],
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_verified": True,
        "original_png_size": [241, 61],
        "enlarged_png_size": [1928, 488],
        "black_and_white_only": True,
        "nearest_neighbor_verified_by_exact_8x8_blocks": True,
    }
    (out / "validation.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
