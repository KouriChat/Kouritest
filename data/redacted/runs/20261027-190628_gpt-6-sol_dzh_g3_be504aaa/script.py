def inside(lon, lat, poly):
    """Even-odd point-in-ring test; sampled coastline points use boundary as land."""
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        cross = (xi - xj) * (lat - yj) - (yi - yj) * (lon - xj)
        if abs(cross) < 1e-10 and min(xi, xj) <= lon <= max(xi, xj) and min(yi, yj) <= lat <= max(yi, yj):
            return True
        if (yi > lat) != (yj > lat):
            xcross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < xcross:
                hit = not hit
        j = i
    return hit
def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for ri in range(71):
        lat = 45.0 - 0.2 * ri
        row = []
        for ci in range(231):
            lon = -9.0 + 0.2 * ci
            row.append(int(any(inside(lon, lat, p) for p in LAND)))
        rows.append(row)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(rows)
    pixels = np.asarray(rows, dtype=np.uint8) * 255
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((1848, 568), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert set(np.unique(pixels)).issubset({0, 255})
    assert Image.open(out / "candidate.png").size == (231, 71)
    assert Image.open(out / "candidate_8x.png").size == (1848, 568)
    assert all(v in (0, 1) for row in rows for v in row)
    print(f"validated: {len(rows)} x {len(rows[0])} = {sum(map(len, rows))}")


if __name__ == "__main__":
    main()
