# Vertices are hand-written (longitude, latitude) pairs. Straight lines between
# vertices are deliberate approximations, not observations at individual cells.
def inside(x, y, points):
    hit = False
    lastx, lasty = points[-1]
    for thisx, thisy in points:
        if (thisy > y) != (lasty > y):
            crossing = thisx + (y - thisy) * (lastx - thisx) / (lasty - thisy)
            if x < crossing:
                hit = not hit
        lastx, lasty = thisx, thisy
    return hit

