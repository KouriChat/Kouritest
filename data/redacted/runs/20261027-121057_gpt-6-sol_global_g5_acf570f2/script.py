# Antarctic grounded coastline, including the Antarctic Peninsula. Floating
# shelves are approximated as sea, especially in the Ross/Weddell embayments.
antarctic_edge = [
    (-180,-78),(-170,-78),(-160,-77),(-150,-76),(-140,-75),
    (-130,-74),(-120,-73),(-110,-73),(-100,-73),(-90,-73),
    (-80,-73),(-74,-72),(-70,-70),(-66,-68),(-64,-65),
    (-62,-63),(-60,-64),(-59,-68),(-55,-71),(-48,-74),
    (-36,-76),(-25,-76),(-15,-74),(0,-71),(15,-70),
    (30,-69),(45,-67),(60,-67),(75,-67),(90,-66),
    (105,-66),(120,-66),(135,-67),(150,-68),(160,-71),
    (170,-74),(180,-78)
]

def antarctic(x, y):
    for (xa, ya), (xb, yb) in zip(antarctic_edge, antarctic_edge[1:]):
        if xa <= x <= xb:
            return y <= ya + (x - xa) * (yb - ya) / (xb - xa)
    return False

def classify(lon, lat):
    return int((antarctic(lon, lat) or any(
        inside(lon, lat, polygon) for polygon in land
    )) and not any(inside(lon, lat, polygon) for polygon in sea_cutouts))

grid = np.array([[classify(lon, lat) for lon in range(-179, 180, 2)]
                 for lat in range(89, -90, -2)], dtype=np.uint8)
assert grid.shape == (90, 180) and np.isin(grid, [0, 1]).all()
