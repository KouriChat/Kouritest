def in_ellipse(lon, lat, entry):
    cx, cy, rx, ry, degrees = entry
    a = math.radians(degrees)
    dx, dy = lon - cx, lat - cy
    u = dx * math.cos(a) + dy * math.sin(a)
    v = -dx * math.sin(a) + dy * math.cos(a)
    return (u / rx) ** 2 + (v / ry) ** 2 <= 1

def make_matrix():
    result = np.zeros((111, 141), dtype=np.uint8)
    shapes = [MAINLAND] + ISLANDS
    for row in range(111):
        lat = round(23 - row * .2, 8)
        for col in range(141):
            lon = round(99 + col * .2, 8)
            result[row, col] = int(
                any(inside(lon, lat, outline) for outline in shapes)
                or any(in_ellipse(lon, lat, ell) for ell in SMALL_ISLANDS)
            )
    return result

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    matrix = make_matrix()
    assert matrix.shape == (111, 141)
    assert set(np.unique(matrix)).issubset({0, 1})
    with (OUT / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, "L").convert("RGB")
    image.save(OUT / "candidate.png")
    enlarged = image.resize((1128, 888), Image.Resampling.NEAREST)
    enlarged.save(OUT / "candidate_8x.png")
    with (OUT / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111 and all(len(r) == 141 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    assert Image.open(OUT / "candidate.png").size == (141, 111)
    assert Image.open(OUT / "candidate_8x.png").size == (1128, 888)
    assert set(image.getdata()).issubset({(0, 0, 0), (255, 255, 255)})
    assert set(enlarged.getdata()).issubset({(0, 0, 0), (255, 255, 255)})
    assert np.array_equal(np.asarray(enlarged)[::8, ::8], np.asarray(image))
    assert np.array_equal(np.asarray(enlarged), np.repeat(np.repeat(
        np.asarray(image), 8, axis=0), 8, axis=1))
    print(f"Verified {matrix.size} values; land={int(matrix.sum())}, "
          f"water={matrix.size - int(matrix.sum())}; images 141x111, 1128x888.")

if __name__ == "__main__":
    main()
