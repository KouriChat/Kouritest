def inside(lon, lat, poly):
    """Odd-even crossing test for one geographic sample point."""
    odd = False
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if (y0 > lat) != (y1 > lat):
            if lon < x0 + (lat - y0) * (x1 - x0) / (y1 - y0):
                odd = not odd
        x0, y0 = x1, y1
    return odd
