def in_poly(lon, lat, pts):
    """Ray-casting point-in-polygon for one (lon, lat) point."""
    inside = False
    j = len(pts) - 1
    for i in range(len(pts)):
        xi, yi = pts[i]
        xj, yj = pts[j]
        if ((yi > lat) != (yj > lat)):
            xcross = xi + (lat - yi) * (xj - xi) / (yj - yi)
            if lon < xcross:
                inside = not inside
        j = i
    return inside


def any_poly(lon, lat, polys):
    for p in polys:
        if in_poly(lon, lat, p):
            return True
    return False


def subtract_polys(lon, lat, polys):
    for p in polys:
        if in_poly(lon, lat, p):
            return True
    return False


def ellipse(lon, lat, cx, cy, rx, ry, n=20):
    return [(cx + rx * np.cos(2 * np.pi * i / n),
             cy + ry * np.sin(2 * np.pi * i / n)) for i in range(n)]


