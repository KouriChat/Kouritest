ellipses = [tuple(map(float, v.split())) for v in islets.replace('\n', ';').split(';') if v.strip()]

def contains(vertices, x, y):
    inside = False
    px, py = vertices[-1]
    for qx, qy in vertices:
        if (py > y) != (qy > y) and x < (qx-px)*(y-py)/(qy-py)+px:
            inside = not inside
        px, py = qx, qy
    return inside

def land(x, y):
    return int(any(contains(shape, x, y) for shape in coasts) or
               any(((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1
                   for cx, cy, rx, ry in ellipses))

def main():
    output = Path('outputs')
    output.mkdir(exist_ok=True)
    rows = [[land(-9 + col / 5, 45 - row / 5) for col in range(231)]
            for row in range(71)]
    assert len(rows) == 71 and all(len(row) == 231 and set(row) <= {0, 1} for row in rows)
    with (output / 'candidate.csv').open('w', newline='', encoding='utf-8') as file:
        csv.writer(file).writerows(rows)
    image = Image.new('L', (231, 71))
    image.putdata([255 * cell for row in rows for cell in row])
    image.save(output / 'candidate.png')
    enlarged = image.resize((1848, 568), Image.Resampling.NEAREST)
    enlarged.save(output / 'candidate_8x.png')
    assert set(image.getdata()) <= {0, 255} and set(enlarged.getdata()) <= {0, 255}
    assert enlarged.tobytes() == image.resize((1848, 568), Image.Resampling.NEAREST).tobytes()

if __name__ == '__main__':
    main()
