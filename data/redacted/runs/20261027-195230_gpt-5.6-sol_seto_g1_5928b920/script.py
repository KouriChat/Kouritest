def make_matrix():
    a = np.zeros((NY, NX), dtype=np.uint8)
    for r in range(NY):
        lat = LAT0 - r * DX
        for c in range(NX):
            lon = LON0 + c * DX
            a[r, c] = 1 if any(inside(lon, lat, p) for p in LAND) else 0
    return a

def write_all(a):
    assert a.shape == (64, 253)
    assert set(np.unique(a)).issubset({0, 1})
    with open(os.path.join(OUT, "candidate.csv"), "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        for row in a:
            w.writerow([int(v) for v in row])

    # L mode is used so the source has exactly the two byte values 0 and 255.
    src = Image.fromarray((a * 255).astype(np.uint8), mode="L")
    assert src.size == (253, 64)
    src.save(os.path.join(OUT, "candidate.png"))
    enlarged = src.resize((253 * 8, 64 * 8), Image.Resampling.NEAREST)
    assert enlarged.size == (2024, 512)
    enlarged.save(os.path.join(OUT, "candidate_8x.png"))

if __name__ == "__main__":
    matrix = make_matrix()
    write_all(matrix)
    print("generated", matrix.shape, int(matrix.sum()), "land samples")
