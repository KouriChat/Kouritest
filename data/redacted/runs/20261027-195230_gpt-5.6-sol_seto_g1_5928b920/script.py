def poly(points):
    return tuple((float(x), float(y)) for x, y in points)

def ellipse(cx, cy, rx, ry, n=24):
    import math
    return tuple((cx + rx * math.cos(2 * math.pi * k / n),
                  cy + ry * math.sin(2 * math.pi * k / n)) for k in range(n))

def inside(x, y, p):
    c = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]
        xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            xx = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < xx:
                c = not c
        j = i
    return c

