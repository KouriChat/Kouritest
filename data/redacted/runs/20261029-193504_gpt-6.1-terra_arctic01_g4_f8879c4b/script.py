lon, lat = np.meshgrid(-105.0 + np.arange(241) / 10, 79.0 - np.arange(61) / 10)
land = np.zeros(lon.shape, dtype=bool)
for poly in polygons:
    inside = np.zeros(lon.shape, dtype=bool)
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if y0 != y1:
            crossing = ((y0 > lat) != (y1 > lat)) & (lon < (x1-x0)*(lat-y0)/(y1-y0)+x0)
            inside ^= crossing
        x0, y0 = x1, y1
    land |= inside

out = Path('outputs')
out.mkdir(exist_ok=True)
with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
    csv.writer(f).writerows(land.astype(np.uint8).tolist())
image = Image.fromarray(land.astype(np.uint8) * 255, mode='L')
image.save(out / 'candidate.png')
image.resize((1928, 488), resample=Image.Resampling.NEAREST).save(out / 'candidate_8x.png')

