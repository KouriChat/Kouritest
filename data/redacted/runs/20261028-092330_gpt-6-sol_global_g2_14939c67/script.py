def classify(lon, lat):
    if any(inside(lon, lat, lake) for lake in LAKES):
        return 0
    return int(is_land(lon, lat))

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lons = range(-179, 180, 2)
    lats = range(89, -90, -2)
    matrix = np.array([[classify(lon, lat) for lon in lons] for lat in lats],
                      dtype=np.uint8)
    assert matrix.shape == (90, 180)
    assert int(matrix.sum() + (matrix == 0).sum()) == 16200

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Grayscale palette: 0 black water, 255 white land.
    image = Image.fromarray(matrix * np.uint8(255), mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")

    assert image.size == (180, 90)
    assert set(image.getdata()) <= {0, 255}
    enlarged = Image.open(out / "candidate_8x.png")
    assert enlarged.size == (1440, 720)
    assert set(enlarged.getdata()) <= {0, 255}

if __name__ == "__main__":
    main()
