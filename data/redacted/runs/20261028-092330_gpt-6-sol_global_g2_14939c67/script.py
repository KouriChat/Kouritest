def inside(lon, lat, polygon):
    hit = False
    j = len(polygon) - 1
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[j]
        crosses = ((y1 > lat) != (y2 > lat))
        if crosses:
            edge_x = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < edge_x:
                hit = not hit
        j = i
    return hit

def is_land(lon, lat):
    return any(inside(lon, lat, polygon) for polygon in LAND)
