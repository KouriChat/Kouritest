LON, LAT = np.meshgrid(-9 + np.arange(231) / 5, 45 - np.arange(71) / 5)


def inside(poly):
    result = np.zeros(LON.shape, dtype=bool)
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if y1 != y0:
            crossing = ((y0 > LAT) != (y1 > LAT))
            edge_x = x0 + (LAT - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (LON < edge_x)
        x0, y0 = x1, y1
    return result


