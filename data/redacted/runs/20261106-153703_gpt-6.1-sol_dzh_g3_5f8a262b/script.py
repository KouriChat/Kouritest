def main():
    # All tests are point-in-polygon at the exact requested grid coordinates.
    water = np.zeros(LON.shape, dtype=bool)
    for boundary in (atlantic, med, black_sea, marmara):
        water |= inside(boundary)
    land = ~water
    for boundary in islands:
        land |= inside(boundary)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert np.isin(matrix, (0, 1)).all()
    assert LON[0, 0] == -9 and LON[-1, -1] == 37
    assert LAT[0, 0] == 45 and LAT[-1, -1] == 31

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    raw = Image.fromarray(pixels)
    raw.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = raw.resize((1848, 568), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    with (out / "candidate.csv").open(encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert recovered.size == 16401 and np.array_equal(recovered, matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.size == (231, 71)
        a = np.array(image)
        assert set(np.unique(a).tolist()) == {0, 255}
        assert np.array_equal(a, pixels)
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1848, 568)
        b = np.array(image)
        assert set(np.unique(b).tolist()) == {0, 255}
        assert np.array_equal(b, np.repeat(np.repeat(a, 8, axis=0), 8, axis=1))
    print("Validated: 71x231=16401 binary points; CSV; 231x71 PNG;"
          " 1848x568 PNG; exact 8x nearest-neighbor enlargement.")


if __name__ == "__main__":
    main()
