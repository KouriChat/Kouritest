def inside_poly(x, y, p):
    """Odd/even point-in-polygon test, boundary assigned consistently."""
    hit = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]
        xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            xcut = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x <= xcut:
                hit = not hit
        j = i
    return hit


def ellipse(x, y, cx, cy, rx, ry, angle=0.0):
    a = math.radians(angle)
    dx, dy = x - cx, y - cy
    u = dx * math.cos(a) + dy * math.sin(a)
    v = -dx * math.sin(a) + dy * math.cos(a)
    return (u / rx) ** 2 + (v / ry) ** 2 <= 1.0


