def classify(lon, lat):
    land = any(inside_poly(lon, lat, p) for p in LAND)
    if not land:
        land = any(ellipse(lon, lat, *e) for e in ISLETS)
    if land and any(inside_poly(lon, lat, p) for p in WATER):
        land = False
    return 1 if land else 0


matrix = np.zeros((N, N), dtype=np.uint8)
for row, lat in enumerate(LATS):
    for col, lon in enumerate(LONS):
        matrix[row, col] = classify(float(lon), float(lat))

