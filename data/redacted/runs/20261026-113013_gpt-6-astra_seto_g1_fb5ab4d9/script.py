def point_in_polygon(lon, lat, polygon):
    """Ray crossing test; points on an outline count as land."""
    inside = False
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        cross = (lon - x1) * (y2 - y1) - (lat - y1) * (x2 - x1)
        if abs(cross) < 1e-12:
            if (min(x1, x2) - 1e-12 <= lon <= max(x1, x2) + 1e-12
                    and min(y1, y2) - 1e-12 <= lat <= max(y1, y2) + 1e-12):
                return True
        if (y1 > lat) != (y2 > lat):
            crossing_lon = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < crossing_lon:
                inside = not inside
    return inside


def is_land(lon, lat):
    return any(point_in_polygon(lon, lat, polygon)
               for polygon in LAND_POLYGONS)


def main():
    rows, cols = 64, 253
    step = 2.0 / 63.0
    latitudes = [35.0 - row * step for row in range(rows)]
    longitudes = [129.0 + col * step for col in range(cols)]
    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(is_land(lon, lat))

    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    np.savetxt(output / "candidate.csv", matrix, fmt="%d", delimiter=",")
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output / "candidate.png")
    enlarged = image.resize(
        (cols * 8, rows * 8), resample=Image.Resampling.NEAREST
    )
    enlarged.save(output / "candidate_8x.png")


if __name__ == "__main__":
    main()

