def contains_points(vertices, longitude, latitude):
    """Even-odd point-in-polygon, with exact-edge points assigned to land."""
    result = np.zeros(longitude.shape, dtype=bool)
    lower = vertices.min(axis=0)
    upper = vertices.max(axis=0)
    eligible = ((longitude >= lower[0] - 1e-10)
                & (longitude <= upper[0] + 1e-10)
                & (latitude >= lower[1] - 1e-10)
                & (latitude <= upper[1] + 1e-10))
    x, y = longitude[eligible], latitude[eligible]
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = dx * (y - y0) - dy * (x - x0)
        boundary |= ((np.abs(cross) <= 1e-10)
                     & (x >= min(x0, x1) - 1e-10)
                     & (x <= max(x0, x1) + 1e-10)
                     & (y >= min(y0, y1) - 1e-10)
                     & (y <= max(y0, y1) + 1e-10))
        if dy != 0:
            crossing = ((y0 > y) != (y1 > y))
            inside ^= crossing & (x < x0 + dx * (y - y0) / dy)
        x0, y0 = x1, y1
    result[eligible] = inside | boundary
    return result


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    longitudes = np.arange(495, 636, dtype=np.int64) / 5.0
    latitudes = np.arange(115, 4, -1, dtype=np.int64) / 5.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    land = np.zeros((111, 141), dtype=bool)
    for name, vertices in POLYGONS:
        land |= contains_points(vertices, longitude, latitude)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    image.resize((1128, 888), resample=nearest).save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111 and all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as small:
        assert small.size == (141, 111) and small.mode == "L"
        raw = np.asarray(small).copy()
    with Image.open(out / "candidate_8x.png") as large:
        assert large.size == (1128, 888) and large.mode == "L"
        enlarged = np.asarray(large).copy()
    assert set(np.unique(raw).tolist()) <= {0, 255}
    assert set(np.unique(enlarged).tolist()) <= {0, 255}
    assert np.array_equal(raw, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged, expected)
    print("Validated: 111x141 = 15651 binary values; PNG 141x111; "
          "nearest-neighbor 8x PNG 1128x888; black/white only.")
    print(f"Land: {matrix.sum()}   Water: {matrix.size - matrix.sum()}")


if __name__ == "__main__":
    main()
