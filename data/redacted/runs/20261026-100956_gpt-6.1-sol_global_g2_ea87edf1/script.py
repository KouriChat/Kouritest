def points_in_polygon(lon_grid, lat_grid, vertices):
    """Vectorized even-odd point-in-polygon test."""
    inside = np.zeros(lon_grid.shape, dtype=bool)
    previous = vertices[-1]
    for current in vertices:
        x1, y1 = previous
        x2, y2 = current
        crosses = (y1 > lat_grid) != (y2 > lat_grid)
        x_cross = (x2 - x1) * (lat_grid - y1) / ((y2 - y1) + 1e-15) + x1
        inside ^= crosses & (lon_grid < x_cross)
        previous = current
    return inside


def make_matrix():
    latitudes = np.arange(89, -90, -2, dtype=float)
    longitudes = np.arange(-179, 180, 2, dtype=float)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for polygon in POLYGONS:
        land |= points_in_polygon(lon_grid, lat_grid, polygon)

    # Inland water at coarse sample resolution: Great Lakes, Caspian, Aral,
    # Lake Baikal, Lake Victoria, and the largest North American lakes.
    lakes = [
        (-87, 47), (-85, 45), (-82, 45), (-80, 44),
        (51, 41), (59, 45), (60, 46), (52, 44),
        (59, 48), (61, 48), (105, 53), (108, 52),
        (33, -1), (34, 0), (-5, 13), (-4, 13),
    ]
    for lake_lon, lake_lat in lakes:
        land[(np.abs(lon_grid - lake_lon) <= 1) &
             (np.abs(lat_grid - lake_lat) <= 1)] = False
    return land.astype(np.uint8)


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    matrix = make_matrix()
    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Array row 0 is north; white (255) is land and black (0) is water.
    image = Image.fromarray((matrix * 255).astype(np.uint8), mode="L")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
