W, H = 253, 64
lon, lat = np.meshgrid(129 + np.arange(W) / 31.5, 35 - np.arange(H) / 31.5)
land = np.zeros((H, W), dtype=bool)

def paint(coords, value=True):
    p = np.array([(float(v.split(',')[0]), float(v.split(',')[1]))
                  for v in coords.split()], dtype=float)
    x, y = p[:, 0], p[:, 1]
    region = (lon >= min(x)) & (lon <= max(x)) & (lat >= min(y)) & (lat <= max(y))
    inside = np.zeros((H, W), dtype=bool)
    for j in range(len(p)):
        k = (j + 1) % len(p)
        if y[j] == y[k]:
            continue
        crosses = (y[j] > lat) != (y[k] > lat)
        at_x = x[j] + (lat - y[j]) * (x[k] - x[j]) / (y[k] - y[j])
        inside ^= crosses & (lon < at_x)
    land[region & inside] = value

def oval(cx, cy, rx, ry, tilt=0):
    a = np.deg2rad(tilt)
    u, v = lon - cx, lat - cy
    z = ((u*np.cos(a)+v*np.sin(a))/rx)**2 + ((-u*np.sin(a)+v*np.cos(a))/ry)**2
    land[z <= 1] = True

