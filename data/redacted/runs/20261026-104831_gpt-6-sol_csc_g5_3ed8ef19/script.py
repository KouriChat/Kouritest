def inside(x, y, poly):
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        cross = (x - xi) * (yj - yi) - (y - yi) * (xj - xi)
        if abs(cross) < 1e-10 and min(xi, xj) <= x <= max(xi, xj) \
                and min(yi, yj) <= y <= max(yi, yj):
            return True
        if (yi > y) != (yj > y):
            if x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                hit = not hit
        j = i
    return hit


def classify(lon, lat):
    land = any(inside(lon, lat, poly) for poly in LAND)
    return int(land and not any(inside(lon, lat, p) for p in WATER))


def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    latitudes = [23.0 - 0.2 * i for i in range(111)]
    longitudes = [99.0 + 0.2 * j for j in range(141)]
    grid = np.array([[classify(lon, lat) for lon in longitudes]
                     for lat in latitudes], dtype=np.uint8)
    assert grid.shape == (111, 141) and grid.size == 15651
    assert np.isin(grid, (0, 1)).all()
    with (output / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(grid.tolist())
    image = Image.fromarray(grid * 255).convert("RGB")
    image.save(output / "candidate.png")
    assert image.size == (141, 111)
    enlarged = image.resize((1128, 888), Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")
    assert enlarged.size == (1128, 888)


if __name__ == "__main__":
    main()
