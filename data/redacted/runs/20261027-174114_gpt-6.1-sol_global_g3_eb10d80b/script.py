        assert im.size == (1440, 720)
        big_pixels = np.asarray(im)
        assert set(np.unique(big_pixels).tolist()) <= {0, 255}
        assert np.array_equal(
            big_pixels, np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        )
