"""Knowledge-only, hand-drawn approximation: no geographic data are read.

Run: python outputs/generate_map.py
Dependencies: numpy, Pillow.
All vertices below are remembered/estimated (longitude, latitude), not surveyed
coastlines. Classification is polygon-rule computation, not independent model
reasoning at each point. Inland lakes are deliberately not removed from land.
"""
from pathlib import Path
