N = 127
longitude = -131.0 + np.arange(N, dtype=np.float64) * (2.0 / 126.0)
latitude = 55.0 - np.arange(N, dtype=np.float64) * (2.0 / 126.0)
X, Y = np.meshgrid(longitude, latitude)
land = np.zeros((N, N), dtype=bool)


def polygon(vertices):
    """Even-odd point containment, evaluated at the exact sample coordinates."""
    result = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if by != ay:
            crossing = ((ay > Y) != (by > Y))
            edge_x = ax + (Y - ay) * (bx - ax) / (by - ay)
            result ^= crossing & (X < edge_x)
        ax, ay = bx, by
    return result


def add(name, vertices):
    global land
    land |= polygon(vertices)


def cut(name, vertices):
    global land
    land &= ~polygon(vertices)


