POLYGONS = []
WATER = []

def polygon(name, vertices, water=False):
    """Store explicit longitude/latitude vertices; close implicitly."""
    (WATER if water else POLYGONS).append((name, vertices))

def contains(vertices):
    """Even/odd point-in-polygon, including an explicit boundary test."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
        dx, dy = bx - ax, by - ay
        cross = (X - ax) * dy - (Y - ay) * dx
        boundary |= ((np.abs(cross) <= 1e-10)
                     & (X >= min(ax, bx) - 1e-10)
                     & (X <= max(ax, bx) + 1e-10)
                     & (Y >= min(ay, by) - 1e-10)
                     & (Y <= max(ay, by) + 1e-10))
        if abs(dy) > 1e-14:
            crossing = (ay > Y) != (by > Y)
            inside ^= crossing & (X < ax + (Y - ay) * dx / dy)
    return inside | boundary

