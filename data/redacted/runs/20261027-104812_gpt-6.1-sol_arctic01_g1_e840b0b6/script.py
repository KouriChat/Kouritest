def generate():
    land = LAND.copy()
    for _, vertices in POLYGONS:
        land |= contains(vertices)
    for _, vertices in WATER:
        land &= ~contains(vertices)
    return land.astype(np.uint8)

def validate(output, expected):
    assert expected.shape == (61, 241)
    assert expected.size == 14701
    assert np.isin(expected, (0, 1)).all()
    assert np.isclose(LATITUDES[0], 79)
    assert np.isclose(LATITUDES[-1], 73)
    assert np.isclose(LONGITUDES[0], -105)
    assert np.isclose(LONGITUDES[-1], -81)

    with (output / 'candidate.csv').open('r', encoding='ascii', newline='') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert np.array_equal(recovered, expected)

    with Image.open(output / 'candidate.png') as im:
        assert im.format == 'PNG'
        assert im.mode == 'L'
        assert im.size == (241, 61)
        original = np.array(im)
    with Image.open(output / 'candidate_8x.png') as im:
        assert im.format == 'PNG'
        assert im.mode == 'L'
        assert im.size == (1928, 488)
