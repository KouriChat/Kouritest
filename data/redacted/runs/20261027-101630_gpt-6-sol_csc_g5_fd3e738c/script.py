def land(x, y):
    return int(any(inside(x, y, p) for p in POLYGONS) or any(
        ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1
        for cx, cy, rx, ry in ISLETS
    ))


def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    mask = np.array([
        [land(99 + col * .2, 23 - row * .2) for col in range(141)]
        for row in range(111)
    ], dtype=np.uint8)
    assert mask.shape == (111, 141) and mask.size == 15651
    assert set(np.unique(mask)).issubset({0, 1})

    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f).writerows(mask.tolist())
    image = Image.fromarray(mask * 255, mode='L')
    image.save(out / 'candidate.png')
    enlarged = image.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')

    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111 and all(len(r) == 141 for r in rows)
    assert all(v in ('0', '1') for r in rows for v in r)
    assert np.array_equal(np.array(rows, dtype=np.uint8), mask)
    assert image.size == (141, 111) and enlarged.size == (1128, 888)
    assert set(image.getdata()).issubset({0, 255})
    assert set(enlarged.getdata()).issubset({0, 255})
    assert np.array_equal(np.asarray(enlarged), np.repeat(np.repeat(
        np.asarray(image), 8, axis=0), 8, axis=1))
    print(f'Validated 111x141 ({mask.size} points), land={int(mask.sum())}; '
          'binary PNGs 141x111 and 1128x888 (nearest neighbor).')


if __name__ == '__main__':
    main()
