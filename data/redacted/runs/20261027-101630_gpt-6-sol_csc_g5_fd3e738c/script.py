def inside(x, y, vertices):
    """Even-odd point-in-polygon test for a hand-drawn coastline."""
    hit = False
    px, py = vertices[-1]
    for qx, qy in vertices:
        if (py > y) != (qy > y):
            crossing = px + (y - py) * (qx - px) / (qy - py)
            if x < crossing:
                hit = not hit
        px, py = qx, qy
    return hit


