def main():
    lat = LAT0 + np.arange(NROWS, dtype=float) * DLAT
    lon = LON0 + np.arange(NCOLS, dtype=float) * DLON
    lat_grid, lon_grid = np.meshgrid(lat, lon, indexing="ij")
    land = build_land(lat_grid, lon_grid).astype(np.uint8)
    assert land.shape == (NROWS, NCOLS)
    assert np.all((land == 0) | (land == 1))

    with (OUT / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        for row in land:
            writer.writerow(row.tolist())

    raw = Image.fromarray(land * 255, mode="L")
    raw.save(OUT / "candidate.png")
    enlarged = raw.resize((NCOLS * 8, NROWS * 8), resample=Image.NEAREST)
    enlarged.save(OUT / "candidate_8x.png")

    assert raw.size == (231, 71)
    assert enlarged.size == (1848, 568)
    assert set(raw.getdata()).issubset({0, 255})
    assert set(enlarged.getdata()).issubset({0, 255})

if __name__ == "__main__":
    main()
