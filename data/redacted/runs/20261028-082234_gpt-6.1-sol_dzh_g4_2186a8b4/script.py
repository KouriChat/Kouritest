def inside(points, polygon):
    """Vectorized even-odd point-in-polygon test."""
    p = np.asarray(polygon, dtype=float)
    x = points[..., 1]
    y = points[..., 0]
    px = p[:, 1]
    py = p[:, 0]
    x0 = px[:-1]
    x1 = px[1:]
    y0 = py[:-1]
    y1 = py[1:]
    hit = np.zeros(x.shape, dtype=bool)
    for a, b, c, d in zip(x0, x1, y0, y1):
        cross = ((c > y) != (d > y))
        xin = (b - a) * (y - c) / ((d - c) + 1e-30) + a
        hit ^= cross & (x < xin)
    return hit

def closed(path):
    return list(path) + [path[0]]

def add_poly(land, path, lat, lon):
    if len(path) >= 3:
        land |= inside(np.stack((lat, lon), axis=-1), closed(path))

