def inside_polygon(x, y, vertices):
    """Vectorized even/odd ray casting at the actual sample points.

    Points on a segment count as inside; no cell-area averaging is used.
    """
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        on_edge = (
            (np.abs(cross) < 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        boundary |= on_edge
        if dy != 0:
            crosses = ((ay > y) != (by > y)) & (
                x < ax + (y - ay) * dx / dy
            )
            inside ^= crosses
        ax, ay = bx, by
    return inside | boundary


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Integer tenths avoid cumulative arange floating-point step error.
    longitudes = np.arange(-1050, -809, dtype=np.int32) / 10.0
    latitudes = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((61, 241), dtype=bool)
    for _, vertices in LAND:
        land |= inside_polygon(x, y, vertices)
    for _, vertices in SEA:
        land &= ~inside_polygon(x, y, vertices)
    matrix = land.astype(np.uint8)

    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert set(np.unique(matrix)) <= {0, 1}
    assert (latitudes[0], latitudes[-1]) == (79.0, 73.0)
    assert (longitudes[0], longitudes[-1]) == (-105.0, -81.0)

    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1928, 488), resample=nearest)
    original.save(out / "candidate.png")
    enlarged.save(out / "candidate_8x.png")

    # Verify the saved outputs, not just in-memory dimensions.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    decoded = np.array(rows, dtype=np.uint8)
    assert decoded.size == 14701
    assert np.array_equal(decoded, matrix)

    with Image.open(out / "candidate.png") as im:
        assert im.size == (241, 61)
        small = np.asarray(im).copy()
        assert im.mode == "L"
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1928, 488)
        large = np.asarray(im).copy()
        assert im.mode == "L"
    assert set(np.unique(small)) <= {0, 255}
    assert set(np.unique(large)) <= {0, 255}
    assert np.array_equal(small, matrix * 255)
    expected = np.repeat(np.repeat(small, 8, axis=0), 8, axis=1)
    assert np.array_equal(large, expected), "Not an exact nearest-neighbor image"
    print("Validated: 61 x 241 = 14701 binary samples; CSV complete; "
          "PNG 241 x 61; exact nearest-neighbor PNG 1928 x 488.")


if __name__ == "__main__":
    main()
