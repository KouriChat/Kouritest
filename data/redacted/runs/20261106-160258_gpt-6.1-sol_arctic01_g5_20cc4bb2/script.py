def polygon_mask(x, y, vertices):
    """Even-odd ray test at sample coordinates (no pixel-area averaging)."""
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crosses = (y0 > y) != (y1 > y)
            intersection = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (x < intersection)
        x0, y0 = x1, y1
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    # Integer tenths avoid accumulation from repeated floating-point stepping.
    west = np.arange(1050, 809, -1, dtype=np.int32) / 10.0
    north = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    x, y = np.meshgrid(west, north)
    mask = np.zeros((61, 241), dtype=bool)
    for _, vertices in LAND:
        mask |= polygon_mask(x, y, vertices)
    for _, vertices in WATER:
        mask &= ~polygon_mask(x, y, vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix)) <= {0, 1}
    np.savetxt(out / "candidate.csv", matrix, delimiter=",", fmt="%d")
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / "candidate.png")
    enlarged = image.resize((1928, 488), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 and set(row) <= {"0", "1"} for row in rows)
    reread = np.array([[int(v) for v in row] for row in rows], dtype=np.uint8)
    assert np.array_equal(matrix, reread)
    with Image.open(out / "candidate.png") as original:
        assert original.size == (241, 61)
        a = np.asarray(original)
        assert set(np.unique(a)) == {0, 255}
        assert np.array_equal(a, matrix * 255)
    with Image.open(out / "candidate_8x.png") as large:
        assert large.size == (1928, 488)
        b = np.asarray(large)
        assert set(np.unique(b)) == {0, 255}
        assert np.array_equal(b, np.repeat(np.repeat(a, 8, axis=0), 8, axis=1))
    print("Validated: 61 x 241 = 14,701 binary points; PNGs 241x61 / 1928x488.")

if __name__ == "__main__":
    main()
