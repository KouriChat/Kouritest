def trace(text):
    return [tuple(map(float, token.split(","))) for token in text.split()]

def inside(x, y, vertices):
    """Even-odd point-in-polygon rule, including boundary points."""
    hit = False
    for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
        if (ay > y) != (by > y):
            crossing = ax + (y - ay) * (bx - ax) / (by - ay)
            if x < crossing:
                hit = not hit
    return hit

