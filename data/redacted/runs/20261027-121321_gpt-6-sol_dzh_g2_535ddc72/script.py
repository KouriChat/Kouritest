def land_at(lon, lat):
    value = inside(lon, lat, europe) or inside(lon, lat, africa)
    if inside(lon, lat, atlantic) or inside(lon, lat, black_sea):
        value = False
    if not value:
        value = any(inside(lon, lat, poly) for poly in island_polygons)
    if not value:
        value = any(((lon-cx)/rx)**2 + ((lat-cy)/ry)**2 <= 1
                    for cx,cy,rx,ry in islets)
    return int(value)

