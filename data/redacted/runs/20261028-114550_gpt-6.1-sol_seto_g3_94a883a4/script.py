lon = 129 + np.arange(253, dtype=float) * (2 / 63)
lat = 35 - np.arange(64, dtype=float) * (2 / 63)
X, Y = np.meshgrid(lon, lat)
matrix = np.zeros((64, 253), dtype=np.uint8)
for poly in polygons:
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if y1 != y0:
            cross = ((y0 > Y) != (y1 > Y))
            inside ^= cross & (X < (x1-x0)*(Y-y0)/(y1-y0) + x0)
        x0, y0 = x1, y1
    matrix |= inside.astype(np.uint8)

