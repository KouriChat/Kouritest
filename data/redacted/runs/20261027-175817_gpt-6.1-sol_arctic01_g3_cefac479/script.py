def contains_points(xs, ys, vertices):
    """Even-odd ray crossing, applied separately to each grid point."""
    inside = np.zeros(xs.shape, dtype=bool)
    xj, yj = vertices[-1]
    for xi, yi in vertices:
        if yi != yj:
            crossing = ((yi > ys) != (yj > ys))
            boundary_x = xi + (ys - yi) * (xj - xi) / (yj - yi)
            inside ^= crossing & (xs < boundary_x)
        xj, yj = xi, yi
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lons = np.arange(-1050, -809, dtype=np.int32) / 10.0
    lats = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    xs, ys = np.meshgrid(lons, lats)
    matrix = np.zeros((61, 241), dtype=np.uint8)
    for name, vertices in LAND:
        matrix[contains_points(xs, ys, vertices)] = 1
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix)) <= {0, 1}
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png")
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    loaded = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(loaded, matrix)
    with Image.open(out / "candidate.png") as original:
        assert original.size == (241, 61)
        original_pixels = np.asarray(original).copy()
        assert set(np.unique(original_pixels)) == {0, 255}
    with Image.open(out / "candidate_8x.png") as big:
        assert big.size == (1928, 488)
        big_pixels = np.asarray(big).copy()
        assert set(np.unique(big_pixels)) == {0, 255}
    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(big_pixels, expected)
    print("Validated: 61 x 241 = 14,701 binary samples; CSV complete;")
    print("PNG 241 x 61; PNG 1928 x 488; black/white; exact 8x nearest.")
    print("Method: hand-written approximate island polygons from memory.")
    print("Dependencies: Python 3, numpy, Pillow. No geographic data read.")

if __name__ == "__main__":
    main()
