def rasterize(polygons, lon_grid, lat_grid):
    result = np.zeros(lon_grid.shape, dtype=bool)
    for vertices in polygons:
        x = np.asarray([p[0] for p in vertices])
        y = np.asarray([p[1] for p in vertices])
        inside = np.zeros(lon_grid.shape, dtype=bool)
        j = len(vertices) - 1
        for i in range(len(vertices)):
            crossing = ((y[i] > lat_grid) != (y[j] > lat_grid)) & (
                lon_grid < (x[j] - x[i]) * (lat_grid - y[i]) /
                ((y[j] - y[i]) + 1e-30) + x[i])
            inside ^= crossing
            j = i
        result |= inside
    return result

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lats = np.arange(89, -90, -2, dtype=float)
    lons = np.arange(-179, 180, 2, dtype=float)
    lon_grid, lat_grid = np.meshgrid(lons, lats)
    land = rasterize(LAND + ISLANDS, lon_grid, lat_grid)
    land &= ~rasterize(LAKES, lon_grid, lat_grid)
    matrix = land.astype(np.uint8)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())
    pixels = np.where(matrix, 255, 0).astype(np.uint8)
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(out / "candidate_8x.png")
    print(f"matrix={matrix.shape}, values={matrix.size}, land={int(matrix.sum())}, water={matrix.size-int(matrix.sum())}")

if __name__ == "__main__":
    main()
