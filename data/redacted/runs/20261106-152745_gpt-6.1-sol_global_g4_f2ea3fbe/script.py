"""Memory-only world land approximation; no external geographic inputs.

All coastlines below are hand-written approximations from geographic knowledge.
The grid is classified by polygon rules, NOT independent per-point reasoning.
Inland lakes are deliberately filled as land. Ocean ice is not land.
Only the Python standard library is required.
"""
