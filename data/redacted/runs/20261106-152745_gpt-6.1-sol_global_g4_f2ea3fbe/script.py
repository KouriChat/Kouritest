def classify(longitude, latitude):
    for _, points, (west, south, east, north) in LAND:
        if not south <= latitude <= north:
            continue
        for x in (longitude, longitude + 360):
            if west <= x <= east and inside(x, latitude, points):
                return 1
    return 0


def png_chunk(kind, payload):
    crc = zlib.crc32(kind + payload) & 0xffffffff
    return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", crc)


def save_png(path, rows):
    height, width = len(rows), len(rows[0])
    assert all(len(row) == width for row in rows)
    # PNG grayscale, 8 bits; filter 0 preserves the exact binary pixel samples.
    header = struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0)
    raw = b"".join(b"\0" + bytes(row) for row in rows)
    data = (b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", header)
            + png_chunk(b"IDAT", zlib.compress(raw, 9)) + png_chunk(b"IEND", b""))
    path.write_bytes(data)


def check_png(path, expected_width, expected_height):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    offset, compressed, header, ended = 8, bytearray(), None, False
    while offset < len(data):
        size = struct.unpack(">I", data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + size]
        crc = struct.unpack(">I", data[offset + 8 + size:offset + 12 + size])[0]
        assert crc == zlib.crc32(kind + payload) & 0xffffffff
        offset += 12 + size
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", payload)
        elif kind == b"IDAT":
            compressed.extend(payload)
        elif kind == b"IEND":
            ended = True
            break
    assert ended and offset == len(data)
    assert header == (expected_width, expected_height, 8, 0, 0, 0, 0)
    raw = zlib.decompress(compressed)
    stride = expected_width + 1
    assert len(raw) == expected_height * stride
    rows = []
    for y in range(expected_height):
        assert raw[y * stride] == 0
        row = raw[y * stride + 1:(y + 1) * stride]
        assert set(row) <= {0, 255}
        rows.append(row)
    assert set(b"".join(rows)) == {0, 255}
    return rows


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    matrix = [[classify(-179 + 2 * c, 89 - 2 * r)
               for c in range(180)] for r in range(90)]
    assert len(matrix) == 90 and all(len(row) == 180 for row in matrix)
    assert sum(map(len, matrix)) == 16200
    assert all(value in (0, 1) for row in matrix for value in row)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix)
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        actual = list(csv.reader(stream))
    assert len(actual) == 90 and all(len(row) == 180 for row in actual)
    assert all(value in {"0", "1"} for row in actual for value in row)
    assert [[int(value) for value in row] for row in actual] == matrix
    pixels = [bytes(255 * value for value in row) for row in matrix]
    enlarged = []
    for row in pixels:
        wide = bytes(value for value in row for _ in range(8))
        enlarged.extend([wide] * 8)
    save_png(output / "candidate.png", pixels)
    save_png(output / "candidate_8x.png", enlarged)
    small = check_png(output / "candidate.png", 180, 90)
    large = check_png(output / "candidate_8x.png", 1440, 720)
    assert small == pixels
    for y in range(720):
        assert large[y] == bytes(value for value in small[y // 8] for _ in range(8))
    print("PASS: 90 x 180 = 16200 binary judgments; black/white PNGs; exact 8x nearest neighbor.")
    print("Rules: handwritten memory-only polygons; inland lakes filled; no external data.")
    print("Dependencies: Python standard library only.")


