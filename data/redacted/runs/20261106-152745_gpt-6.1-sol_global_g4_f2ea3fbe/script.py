LAND = []


def land(name, coordinates):
    points = [tuple(map(float, item.split(","))) for item in coordinates.split()]
    assert len(points) >= 3, name
    xs, ys = zip(*points)
    LAND.append((name, points, (min(xs), min(ys), max(xs), max(ys))))


def inside(x, y, points):
    result = False
    ax, ay = points[-1]
    for bx, by in points:
        if min(ay, by) <= y <= max(ay, by):
            cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
            if abs(cross) < 1e-10 and min(ax, bx) <= x <= max(ax, bx):
                return True
            if (ay > y) != (by > y):
                if x < ax + (y - ay) * (bx - ax) / (by - ay):
                    result = not result
        ax, ay = bx, by
    return result


