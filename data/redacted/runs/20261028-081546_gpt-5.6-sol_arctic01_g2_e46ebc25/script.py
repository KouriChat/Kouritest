def point_in_polygon(lon, lat, polygon):
    inside = False
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        cross = (lon - x1) * (y2 - y1) - (lat - y1) * (x2 - x1)
        if abs(cross) < 1e-10 and min(x1, x2) <= lon <= max(x1, x2) and min(y1, y2) <= lat <= max(y1, y2):
            return True
        if (y1 > lat) != (y2 > lat):
            if lon < x1 + (lat - y1) * (x2 - x1) / (y2 - y1):
                inside = not inside
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = np.zeros((61, 241), dtype=np.uint8)
    for r in range(61):
        lat = 79.0 - 0.1 * r
        for c in range(241):
            lon = -105.0 + 0.1 * c
            if any(point_in_polygon(lon, lat, p) for p in ISLANDS):
                matrix[r, c] = 1
    with (out / "candidate.csv").open("w", newline="", encoding="utf-8") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(out / "candidate.png")
    image.resize((1928, 488), Image.Resampling.NEAREST).save(out / "candidate_8x.png")
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix)) <= {0, 1}
    with (out / "candidate.csv").open(encoding="utf-8") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61 and all(len(row) == 241 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert image.size == (241, 61)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    print("Validated 61x241 matrix and 241x61 / 1928x488 PNGs.")

if __name__ == "__main__":
    main()



