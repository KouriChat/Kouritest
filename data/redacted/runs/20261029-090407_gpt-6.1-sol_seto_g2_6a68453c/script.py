def point_in_polygon(lon, lat, polygon):
    """Ray casting point-in-polygon test."""
    inside = False
    x, y = lon, lat
    j = len(polygon) - 1

    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        crosses = ((yi > y) != (yj > y)) and (
            x < (xj - xi) * (y - yi) / ((yj - yi) or 1e-30) + xi
        )
        if crosses:
            inside = not inside
        j = i

    return inside


def in_ellipse(lon, lat, center_lon, center_lat, radius_lon, radius_lat):
    dx = (lon - center_lon) / radius_lon
    dy = (lat - center_lat) / radius_lat
    return dx * dx + dy * dy <= 1.0


def classify(lon, lat):
    # 主体陆地
    land = any(point_in_polygon(lon, lat, poly) for poly in LAND_POLYGONS)

    # 海湾优先按水域处理
    if any(point_in_polygon(lon, lat, poly) for poly in WATER_POLYGONS):
        land = False

    # 岛屿轮廓重新计入陆地
    if any(in_ellipse(lon, lat, *island) for island in ISLANDS):
        land = True

    return 1 if land else 0


def main():
    rows, cols = 64, 253
    latitudes = [35.0 - i * (2.0 / 63.0) for i in range(rows)]
    longitudes = [129.0 + j * (8.0 / 252.0) for j in range(cols)]

    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for i, lat in enumerate(latitudes):
        for j, lon in enumerate(longitudes):
            matrix[i, j] = classify(lon, lat)

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 灰度图：陆地白色 (255)，水域黑色 (0)
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")

    enlarged = image.resize(
        (cols * 8, rows * 8),
        resample=Image.Resampling.NEAREST,
    )
    enlarged.save(output_dir / "candidate_8x.png")

    # 验证矩阵、CSV内容、颜色与最近邻放大尺寸
    assert matrix.shape == (64, 253)
    assert matrix.size == 16192
    assert set(np.unique(matrix)).issubset({0, 1})

    with (output_dir / "candidate.csv").open("r", newline="", encoding="ascii") as f:
        csv_rows = list(csv.reader(f))
    assert len(csv_rows) == 64
    assert all(len(row) == 253 for row in csv_rows)
    assert all(value in {"0", "1"} for row in csv_rows for value in row)

    assert image.size == (253, 64)
    assert set(image.getdata()).issubset({0, 255})
    assert enlarged.size == (2024, 512)

    # 每个放大像素块必须与对应原始像素完全一致。
    enlarged_array = np.asarray(enlarged)
    expected = np.repeat(np.repeat(np.asarray(image), 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged_array, expected)

    print("Generated and verified:")
    print("  outputs/candidate.csv       64 x 253")
    print("  outputs/candidate.png       253 x 64")
    print("  outputs/candidate_8x.png    2024 x 512")


if __name__ == "__main__":
    main()
