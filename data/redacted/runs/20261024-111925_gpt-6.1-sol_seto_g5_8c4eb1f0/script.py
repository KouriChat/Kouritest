    """Hand-chosen elliptical approximation for a small island."""
    t = np.linspace(0, 2 * np.pi, 24, endpoint=False)
    a = np.deg2rad(angle)
    dx, dy = rx * np.cos(t), ry * np.sin(t)
    vertices = list(zip(lon + dx*np.cos(a) - dy*np.sin(a),
                        lat + dx*np.sin(a) + dy*np.cos(a)))
    POLYGONS.append((name, vertices))


