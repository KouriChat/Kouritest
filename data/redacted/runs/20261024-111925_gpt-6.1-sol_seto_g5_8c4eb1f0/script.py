def polygon(name, coordinates):
    """Register a manually specified closed land outline."""
    vertices = [tuple(map(float, p.split(","))) for p in coordinates.split()]
    if len(vertices) < 3:
        raise ValueError(name)
    POLYGONS.append((name, vertices))


def inside(vertices):
    """Even/odd point-in-polygon rule at the sampling coordinates themselves."""
    mask = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crossing = ((ay > Y) != (by > Y))
            intercept = ax + (Y - ay) * (bx - ax) / (by - ay)
            mask ^= crossing & (X < intercept)
        ax, ay = bx, by
    return mask


