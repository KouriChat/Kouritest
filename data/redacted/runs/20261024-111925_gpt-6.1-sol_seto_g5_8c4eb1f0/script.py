def main():
    # All polygons describe land. Marine bay masks override their union.
    # Inland lakes are deliberately not subtracted.
    land = LAND.copy()
    for name, vertices in POLYGONS:
        land |= inside(vertices)
    for name, text in WATER_POLYGONS:
        vertices = [tuple(map(float, p.split(","))) for p in text.split()]
        land &= ~inside(vertices)

    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253)
    assert matrix.size == 16192
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert LON[0] == 129.0 and LON[-1] == 137.0
    assert LAT[0] == 35.0 and LAT[-1] == 33.0

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    # Direct raster conversion: one sample -> one pixel, no coast editing.
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    original_path = out / "candidate.png"
    enlarged_path = out / "candidate_8x.png"
    image.save(original_path)
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    image.resize((2024, 512), resample=nearest).save(enlarged_path)

    # Independently reopen every deliverable and check the required properties.
    with csv_path.open("r", encoding="utf-8", newline="") as f:
        records = list(csv.reader(f))
    assert len(records) == 64
    assert all(len(row) == 253 for row in records)
    assert all(value in ("0", "1") for row in records for value in row)
    assert sum(map(len, records)) == 16192
    assert np.array_equal(np.asarray(records, dtype=np.uint8), matrix)

    with Image.open(original_path) as check:
        assert check.size == (253, 64)
        assert check.mode == "L"
        raw_pixels = np.array(check)
    with Image.open(enlarged_path) as check:
        assert check.size == (2024, 512)
        assert check.mode == "L"
        large_pixels = np.array(check)
    assert set(np.unique(raw_pixels).tolist()) == {0, 255}
    assert set(np.unique(large_pixels).tolist()) == {0, 255}
    assert np.array_equal(raw_pixels, pixels)
    expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(large_pixels, expected)
    print("Validated: 64 x 253 = 16192 binary samples.")
    print("Validated: 253 x 64 black/white PNG.")
    print("Validated: 2024 x 512 PNG, exact 8x nearest-neighbor replication.")
    print(f"Land: {int(matrix.sum())}; water: {matrix.size-int(matrix.sum())}.")
    print(f"Files: {csv_path}, {original_path}, {enlarged_path}")


if __name__ == "__main__":
    main()
