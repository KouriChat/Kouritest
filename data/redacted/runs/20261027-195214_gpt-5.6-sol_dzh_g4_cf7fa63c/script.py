def on_land(lon, lat):
    """Point-in-polygon test against the hand-authored land outlines."""
    for polygon in LAND:
        inside = False
        x0, y0 = polygon[-1]
        for x1, y1 in polygon:
            cross = (lon - x0) * (y1 - y0) - (lat - y0) * (x1 - x0)
            if abs(cross) < 1e-10 and min(x0, x1) <= lon <= max(x0, x1) \
                    and min(y0, y1) <= lat <= max(y0, y1):
                return True
            if (y1 > lat) != (y0 > lat):
                crossing_lon = (x0 - x1) * (lat - y1) / (y0 - y1) + x1
                if lon < crossing_lon:
                    inside = not inside
            x0, y0 = x1, y1
        if inside:
            return True
    return False


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lons = np.round(np.arange(-9.0, 37.0 + 0.1, 0.2), 10)
    lats = np.round(np.arange(45.0, 31.0 - 0.1, -0.2), 10)
    matrix = np.array([[int(on_land(float(lon), float(lat))) for lon in lons]
                       for lat in lats], dtype=np.uint8)
    assert matrix.shape == (71, 231)
    assert matrix.size == 16401 and np.isin(matrix, (0, 1)).all()
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    enlarged = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    assert image.size == (231, 71)
    assert enlarged.size == (1848, 568)
    assert set(image.getdata()) == {0, 255}
    assert set(enlarged.getdata()) == {0, 255}


if __name__ == "__main__":
    main()
