def contains(vertices, longitude, latitude):
    """Even-odd ray casting; polygon edges are classified as land."""
    inside = np.zeros(longitude.shape, dtype=bool)
    boundary = np.zeros(longitude.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > latitude) != (y1 > latitude))
            x_cross = x0 + (latitude - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (longitude < x_cross)
        cross = (longitude - x0) * (y1 - y0)
        cross -= (latitude - y0) * (x1 - x0)
        boundary |= (
            (np.abs(cross) < 1e-10)
            & (longitude >= min(x0, x1)) & (longitude <= max(x0, x1))
            & (latitude >= min(y0, y1)) & (latitude <= max(y0, y1))
        )
        x0, y0 = x1, y1
    return inside | boundary


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2)
    longitudes = np.arange(-179, 180, 2)
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for vertices in LAND:
        land |= contains(vertices, longitude, latitude)
    for vertices in WATER:
        land &= ~contains(vertices, longitude, latitude)
    matrix = land.astype(np.uint8)
    np.savetxt(output / "candidate.csv", matrix, delimiter=",", fmt="%d")
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(output / "candidate.png")
    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    # Reopen the actual deliverables and validate their contents.
    with (output / "candidate.csv").open(newline="", encoding="utf-8") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.asarray(rows, dtype=np.uint8)
    assert restored.size == 16200 and np.array_equal(restored, matrix)
    with Image.open(output / "candidate.png") as raw:
        assert raw.size == (180, 90)
        pixels = np.asarray(raw).copy()
    with Image.open(output / "candidate_8x.png") as big:
        assert big.size == (1440, 720)
        big_pixels = np.asarray(big).copy()
    assert set(np.unique(pixels).tolist()) == {0, 255}
    assert set(np.unique(big_pixels).tolist()) == {0, 255}
    assert np.array_equal(pixels, restored * np.uint8(255))
    assert np.array_equal(big_pixels, np.repeat(np.repeat(pixels, 8, 0), 8, 1))
    print("Validated: 90 x 180 = 16,200 binary values; PNG 180 x 90; "
          "nearest-neighbor PNG 1440 x 720; black and white only.")


if __name__ == "__main__":
    main()
