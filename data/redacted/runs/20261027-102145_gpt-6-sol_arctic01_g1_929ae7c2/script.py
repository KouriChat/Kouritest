def points_in_polygon(lon, lat, vertices):
    """向量化射线判定；边界附近按浮点计算结果取舍。"""
    result = np.zeros(lon.shape, dtype=bool)
    for i, (x1, y1) in enumerate(vertices):
        x2, y2 = vertices[(i + 1) % len(vertices)]
        if y1 == y2:
            continue
        crosses_latitude = (y1 > lat) != (y2 > lat)
        crossing_lon = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
        result ^= crosses_latitude & (lon < crossing_lon)
    return result


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    # 使用整数构造采样序号，避免逐次累加 0.1 的浮点漂移。
    latitudes = 79.0 - np.arange(61) / 10.0
    longitudes = -105.0 + np.arange(241) / 10.0
    lon, lat = np.meshgrid(longitudes, latitudes)

    land = np.zeros((61, 241), dtype=bool)
    for polygon in POLYGONS:
        land |= points_in_polygon(lon, lat, polygon)

    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, (0, 1)).all()

    csv_path = output_dir / "candidate.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerows(matrix.tolist())

    pixels = matrix * 255
    original = Image.fromarray(pixels, mode="L")
    original_path = output_dir / "candidate.png"
    original.save(original_path)

    nearest = (
        Image.Resampling.NEAREST
        if hasattr(Image, "Resampling")
        else Image.NEAREST
    )
    enlarged = original.resize((1928, 488), resample=nearest)
    enlarged_path = output_dir / "candidate_8x.png"
    enlarged.save(enlarged_path)

    # 从写出的文件重新读取并验证格式与最近邻放大结果。
    with csv_path.open(newline="", encoding="utf-8") as file:
        rows = list(csv.reader(file))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(
        np.asarray(rows, dtype=np.uint8), matrix
    )

    with Image.open(original_path) as image:
        raw = np.asarray(image.convert("L"))
        assert image.size == (241, 61)
    with Image.open(enlarged_path) as image:
        big = np.asarray(image.convert("L"))
        assert image.size == (1928, 488)

    assert set(np.unique(raw).tolist()) <= {0, 255}
    assert set(np.unique(big).tolist()) <= {0, 255}
    assert np.array_equal(raw, pixels)
    assert np.array_equal(
        big,
        np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1),
    )

    print(f"已生成并验证：{csv_path}")
    print(f"已生成并验证：{original_path}")
    print(f"已生成并验证：{enlarged_path}")
    print(f"矩阵：{matrix.shape[0]} × {matrix.shape[1]}，共 {matrix.size} 点")


if __name__ == "__main__":
    main()
