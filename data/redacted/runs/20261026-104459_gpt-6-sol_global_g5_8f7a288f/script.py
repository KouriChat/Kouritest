def inside(lon, lat, polygon):
    """Even-odd point-in-polygon test."""
    hit = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                hit = not hit
        j = i
    return hit


def is_land(lon, lat):
    if lat <= -60:
        return True  # Antarctic land/ice sheet; no ocean sea ice.
    return any(inside(lon, lat, poly) for poly in POLYGONS)


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = np.zeros((90, 180), dtype=np.uint8)
    for row, lat in enumerate(range(89, -90, -2)):
        for col, lon in enumerate(range(-179, 180, 2)):
            matrix[row, col] = int(is_land(lon, lat))

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 1 maps to white land; 0 maps to black water.
    image = Image.fromarray(matrix * np.uint8(255), mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
