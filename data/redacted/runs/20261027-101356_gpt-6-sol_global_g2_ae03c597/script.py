"""Approximate world land/water raster from memory-drawn polygon rules.

No geographic files, APIs, maps, or pretrained coastline packages are used.
Large lakes, glaciers over land, and continental ice are treated as land.
"""
from pathlib import Path
import csv
import numpy as np
from PIL import Image

land_shapes = []
water_cuts = []


def shape(name, coordinates, water=False):
    """Add a hand-specified polygon in longitude,latitude notation."""
    vertices = [tuple(float(t) for t in p.split(',')) for p in coordinates.split()]
    assert len(vertices) >= 3, name
    (water_cuts if water else land_shapes).append((name, vertices))


def within(x, y, vertices):
    """Odd-even ray casting; polygon edges included approximately."""
    inside = False
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if (ay > y) != (by > y):
            crossing = ax + (y-ay)*(bx-ax)/(by-ay)
            if x < crossing:
                inside = not inside
        ax, ay = bx, by
    return inside


