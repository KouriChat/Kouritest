def generate():
    # Evaluate each WGS84 grid center against the same hand-drawn polygons.
    rows = []
    for lat in range(89, -90, -2):
        row = []
        for lon in range(-179, 180, 2):
            is_land = any(within(lon, lat, poly) for _, poly in land_shapes)
            if is_land and any(within(lon, lat, poly) for _, poly in water_cuts):
                is_land = False
            row.append(int(is_land))
        rows.append(row)
    array = np.array(rows, dtype=np.uint8)
    assert array.shape == (90, 180) and set(np.unique(array)) <= {0, 1}
    out = Path('outputs')
    out.mkdir(parents=True, exist_ok=True)
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as file:
        csv.writer(file, lineterminator='\n').writerows(rows)
    image = Image.fromarray(array * 255, mode='L').convert('RGB')
    image.save(out / 'candidate.png')
    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')
    assert image.size == (180, 90) and enlarged.size == (1440, 720)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert np.array_equal(np.asarray(enlarged)[::8, ::8], np.asarray(image))
    return array


if __name__ == '__main__':
    raster = generate()
    print(f'{raster.shape[0]}x{raster.shape[1]}, {raster.size} cells, {int(raster.sum())} land')
