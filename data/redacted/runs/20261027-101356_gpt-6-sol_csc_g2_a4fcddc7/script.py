def polygon(vertices):
    """Point-in-polygon mask, using longitude horizontally and latitude vertically."""
    vertices = np.asarray(vertices, dtype=float)
    x0, y0 = vertices[-1]
    inside = np.zeros((111, 141), dtype=bool)
    for x1, y1 in vertices:
        if y0 != y1:
            crosses = ((Y < y0) != (Y < y1))
            xi = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (X < xi)
        x0, y0 = x1, y1
    return inside


def island(coords):
    global land
    land |= polygon(coords)


def oval(cx, cy, rx, ry, angle=0):
    global land
    c, s = np.cos(np.radians(angle)), np.sin(np.radians(angle))
    dx, dy = X - cx, Y - cy
    u, v = c * dx + s * dy, -s * dx + c * dy
    land |= (u / rx) ** 2 + (v / ry) ** 2 <= 1.0


