def contains(poly, longitude, latitude):
    """Even/odd ray casting, with polygon-edge points included."""
    result = np.zeros(longitude.shape, dtype=bool)
    selection = ((longitude >= poly[:, 0].min() - 1e-10)
                 & (longitude <= poly[:, 0].max() + 1e-10)
                 & (latitude >= poly[:, 1].min() - 1e-10)
                 & (latitude <= poly[:, 1].max() + 1e-10))
    x, y = longitude[selection], latitude[selection]
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    for a, b in zip(poly, np.roll(poly, -1, axis=0)):
        ax, ay = a
        bx, by = b
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-10)
                     & (x >= min(ax, bx) - 1e-10)
                     & (x <= max(ax, bx) + 1e-10)
                     & (y >= min(ay, by) - 1e-10)
                     & (y <= max(ay, by) + 1e-10))
        if abs(dy) > 1e-14:
            inside ^= (((ay > y) != (by > y))
                       & (x < ax + (y - ay) * dx / dy))
    result[selection] = inside | boundary
    return result


def main():
    # Integers establish the requested grid without accumulated stepping error.
    longitudes = np.arange(-45, 186, dtype=np.int64) / 5.0
    latitudes = np.arange(225, 154, -1, dtype=np.int64) / 5.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    matrix = np.ones((71, 231), dtype=np.uint8)

    # Default land; carve the seas, then restore remembered islands.
    # Inland lakes are deliberately not carved, as required by the definition.
    for sea in (ATLANTIC, MEDITERRANEAN, BLACK_SEA):
        matrix[contains(sea, longitude, latitude)] = 0
    for name, outline in ISLANDS:
        matrix[contains(outline, longitude, latitude)] = 1

    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()
    assert (longitudes[0], longitudes[-1]) == (-9.0, 37.0)
    assert (latitudes[0], latitudes[-1]) == (45.0, 31.0)

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * np.uint8(255))
    assert image.mode == "L"
    image.save(output / "candidate.png")
    resampling = getattr(Image, "Resampling", Image)
    enlarged = image.resize((1848, 568), resample=resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    # Verify the actual saved artifacts rather than only the in-memory arrays.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert sum(map(len, rows)) == 16401
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)
    with Image.open(output / "candidate.png") as saved:
        assert saved.size == (231, 71) and saved.mode == "L"
        original_pixels = np.array(saved)
    with Image.open(output / "candidate_8x.png") as saved:
        assert saved.size == (1848, 568) and saved.mode == "L"
        enlarged_pixels = np.array(saved)
    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, matrix * 255)
    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged_pixels, expected)
    print("PASS: 71x231, 16401 binary values; PNG 231x71; "
          "8x nearest-neighbor PNG 1848x568; black/white only.")
    print(f"Land points: {int(matrix.sum())}; "
          f"water points: {int(matrix.size - matrix.sum())}")


if __name__ == "__main__":
    main()
