W, H = 141, 111
xs = 99.0 + np.arange(W) * 0.2
ys = 23.0 - np.arange(H) * 0.2
X, Y = np.meshgrid(xs, ys)
land = np.zeros((H, W), dtype=bool)


def polygon(vertices):
    """Point-in-polygon, evaluated on the sample points, not grid-cell areas."""
    global land
    vertices = np.asarray(vertices, dtype=float)
    inside = np.zeros((H, W), dtype=bool)
    for (x1, y1), (x2, y2) in zip(vertices, np.roll(vertices, -1, axis=0)):
        if y1 != y2:
            crossed = ((y1 > Y) != (y2 > Y)) & (
                X < (x2 - x1) * (Y - y1) / (y2 - y1) + x1
            )
            inside ^= crossed
    land |= inside


def ellipse(cx, cy, rx, ry, angle=0):
    """Small island or reef approximation; radii in longitude/latitude degrees."""
    global land
    a = np.deg2rad(angle)
    u = (X - cx) * np.cos(a) + (Y - cy) * np.sin(a)
    v = -(X - cx) * np.sin(a) + (Y - cy) * np.cos(a)
    land |= (u / rx) ** 2 + (v / ry) ** 2 <= 1


