def inside_polygon(x, y, vertices):
    """Even/odd ray test; boundary is considered land."""
    odd = False
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        # Explicit boundary test, useful for the integer-ish hand vertices.
        cross = (x-x1)*(y2-y1) - (y-y1)*(x2-x1)
        if abs(cross) < 1e-9 and min(x1,x2) <= x <= max(x1,x2) \
                and min(y1,y2) <= y <= max(y1,y2):
            return True
        if (y1 > y) != (y2 > y):
            hit = x1 + (y-y1)*(x2-x1)/(y2-y1)
            if x < hit:
                odd = not odd
        x1, y1 = x2, y2
    return odd

def is_land(lon, lat):
    if any(inside_polygon(lon, lat, q) for q in P):
        return 1
    for cx, cy, rx, ry in E:
        if ((lon-cx)/rx)**2 + ((lat-cy)/ry)**2 <= 1:
            return 1
    return 0

def main():
    lats = list(range(89, -90, -2))
    lons = list(range(-179, 180, 2))
    a = np.array([[is_land(x, y) for x in lons] for y in lats],
                 dtype=np.uint8)

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(a.tolist())

    im = Image.fromarray(a * 255, mode="L")
    im.save(out / "candidate.png")
    im.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")

    # Fail loudly if any delivery invariant is violated.
    assert a.shape == (90, 180) and a.size == 16200
    assert set(np.unique(a)).issubset({0, 1})
    assert im.size == (180, 90)
    assert set(np.unique(np.asarray(im))).issubset({0, 255})
    check = Image.open(out / "candidate_8x.png")
    assert check.size == (1440, 720)
    assert np.array_equal(np.asarray(check)[::8, ::8], np.asarray(im))
    print(f"generated {a.shape[0]}x{a.shape[1]} matrix; "
          f"land={int(a.sum())}, water={int(a.size-a.sum())}")

if __name__ == "__main__":
    main()
