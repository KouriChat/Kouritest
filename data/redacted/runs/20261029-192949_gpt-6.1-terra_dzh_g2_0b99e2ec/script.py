def contains(poly, x, y):
    inside = False
    for a, b in zip(poly, poly[1:] + poly[:1]):
        x1, y1 = a
        x2, y2 = b
        cross = (x-x1)*(y2-y1) - (y-y1)*(x2-x1)
        if abs(cross) < 1e-10 and min(x1,x2) <= x <= max(x1,x2) and min(y1,y2) <= y <= max(y1,y2):
            return True
        if (y1 > y) != (y2 > y) and x < x1 + (y-y1)*(x2-x1)/(y2-y1):
            inside = not inside
    return inside

def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    matrix = []
    for row in range(71):
        lat = (225 - row) / 5
        line = []
        for col in range(231):
            lon = (-45 + col) / 5
            line.append(int(any(contains(p, lon, lat) for p in LAND_POLYGONS)))
        matrix.append(line)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)

    image = Image.new("L", (231, 71))
    image.putdata([255 * v for line in matrix for v in line])
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    image.resize((1848, 568), nearest).save(out / "candidate_8x.png")
    validate(out, matrix)

def validate(out, matrix):
    assert len(matrix) == 71 and all(len(r) == 231 for r in matrix)
    assert all(v in (0, 1) for r in matrix for v in r)
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71 and all(len(r) == 231 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (231, 71)
        assert set(im.getdata()) <= {0, 255}
        expected = im.resize((1848, 568), getattr(Image, "Resampling", Image).NEAREST)
    with Image.open(out / "candidate_8x.png") as scaled:
        assert scaled.size == (1848, 568)
        assert set(scaled.getdata()) <= {0, 255}
        assert scaled.tobytes() == expected.tobytes()

if __name__ == "__main__":
    main()
