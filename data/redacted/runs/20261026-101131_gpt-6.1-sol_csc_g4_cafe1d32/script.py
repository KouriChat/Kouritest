lats = np.round(np.arange(23.0, 0.999, -0.2), 10)
lons = np.round(np.arange(99.0, 127.001, 0.2), 10)
X, Y = np.meshgrid(lons, lats)
land = np.zeros(X.shape, dtype=bool)


def add_polygon(points):
    inside = np.zeros(X.shape, dtype=bool)
    for i, (x1, y1) in enumerate(points):
        x2, y2 = points[(i + 1) % len(points)]
        crosses = (y1 > Y) != (y2 > Y)
        x_cross = (x2 - x1) * (Y - y1) / (y2 - y1 + 1e-30) + x1
        inside ^= crosses & (X < x_cross)
    land[:] |= inside


def add_island(lon, lat, rx, ry):
    land[:] |= ((X - lon) / rx) ** 2 + ((Y - lat) / ry) ** 2 <= 1.0


