import math

def island(cx, cy, rx, ry, n=12, phase=0.0):
    # Elliptic hand approximations; alternating radii make the outline less artificial.
    pts = []
    for i in range(n):
        a = phase + 2 * math.pi * i / n
        k = 1.0 + 0.10 * math.sin(3 * a + cx)
        pts.append((cx + rx * k * math.cos(a), cy + ry * k * math.sin(a)))
    land.append(pts)

