def inside(x, y, poly):
    # Ray crossing; boundary is treated as land for stable point classification.
    hit = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
        if abs(cross) < 1e-11 and min(x1, x2) - 1e-11 <= x <= max(x1, x2) + 1e-11 and min(y1, y2) - 1e-11 <= y <= max(y1, y2) + 1e-11:
            return True
        if (y1 > y) != (y2 > y):
            xx = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < xx:
                hit = not hit
    return hit

def is_land(lon, lat):
    if any(inside(lon, lat, p) for p in water):
        return False
    return any(inside(lon, lat, p) for p in land)

def main():
    rows = []
    for r in range(64):
        lat = 35.0 - r * (2.0 / 63.0)
        row = []
        for c in range(253):
            lon = 129.0 + c * (8.0 / 252.0)
            row.append(1 if is_land(lon, lat) else 0)
        rows.append(row)

    out = Path('outputs')
    out.mkdir(parents=True, exist_ok=True)
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerows(rows)

    # Pillow's L mode gives exactly two possible pixel values.
    im = Image.new('L', (253, 64))
    pix = im.load()
    for y, row in enumerate(rows):
        for x, value in enumerate(row):
            pix[x, y] = 255 if value else 0
    im.save(out / 'candidate.png')
    im.resize((2024, 512), Image.Resampling.NEAREST).save(out / 'candidate_8x.png')

    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert all(v in (0, 1) for row in rows for v in row)
    assert set(im.getdata()) <= {0, 255}
    assert im.size == (253, 64)
    assert Image.open(out / 'candidate_8x.png').size == (2024, 512)
    print('validated: 64 x 253 =', 64 * 253, 'cells')

