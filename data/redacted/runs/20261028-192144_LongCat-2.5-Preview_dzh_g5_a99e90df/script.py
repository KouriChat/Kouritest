GRID = np.zeros((ROWS, COLS), dtype=np.uint8)

def grid_slice(lat_min, lat_max, lon_min, lon_max):
    rl = np.where((LATS >= lat_min - 1e-6) & (LATS <= lat_max + 1e-6))[0]
    rc = np.where((LONS >= lon_min - 1e-6) & (LONS <= lon_max + 1e-6))[0]
    m = np.zeros((ROWS, COLS), dtype=bool)
    if len(rl) and len(rc):
        m[np.ix_(rl, rc)] = True
    return m

def land_box(a, b, c, d):
    GRID[grid_slice(a, b, c, d)] = 1

def sea_box(a, b, c, d):
    GRID[grid_slice(a, b, c, d)] = 0

def poly_land(pts):
    for i, la in enumerate(LATS):
        for j, lo in enumerate(LONS):
            ins = False
            n = len(pts)
            for k in range(n):
                x1, y1 = pts[k]; x2, y2 = pts[(k + 1) % n]
                if (y1 > la) != (y2 > la):
                    xin = x1 + (la - y1) * (x2 - x1) / (y2 - y1)
                    if lo < xin:
                        ins = not ins
            if ins:
                GRID[i, j] = 1

def poly_sea(pts):
    for i, la in enumerate(LATS):
        for j, lo in enumerate(LONS):
            ins = False
            n = len(pts)
            for k in range(n):
                x1, y1 = pts[k]; x2, y2 = pts[(k + 1) % n]
                if (y1 > la) != (y2 > la):
                    xin = x1 + (la - y1) * (x2 - x1) / (y2 - y1)
                    if lo < xin:
                        ins = not ins
            if ins:
                GRID[i, j] = 0

def island(lat, lon, r):
    for i, la in enumerate(LATS):
        for j, lo in enumerate(LONS):
            if (la - lat) ** 2 + ((lo - lon) * np.cos(np.radians(lat))) ** 2 <= r * r:
                GRID[i, j] = 1

