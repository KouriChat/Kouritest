def export():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    values = land.astype(np.uint8)
    assert values.shape == (111, 141)
    assert np.all((values == 0) | (values == 1))

    with (out / "candidate.csv").open(
        "w", encoding="utf-8", newline=""
    ) as stream:
        csv.writer(stream).writerows(values.tolist())

    source = Image.fromarray(values * 255, mode="L")
    source.save(out / "candidate.png")
    enlarged = source.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    with (out / "candidate.csv").open(
        "r", encoding="utf-8", newline=""
    ) as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 111 and all(len(row) == 141 for row in rows)
    assert all(v in {"0", "1"} for row in rows for v in row)
    assert source.size == (141, 111) and enlarged.size == (1128, 888)
    assert set(source.getdata()) <= {0, 255}
    assert set(enlarged.getdata()) <= {0, 255}
    assert np.array_equal(
        np.asarray(enlarged),
        np.repeat(np.repeat(np.asarray(source), 8, axis=0), 8, axis=1)
    )


if __name__ == "__main__":
    export()
