LONGITUDE, LATITUDE = np.meshgrid(
    99.0 + 0.2 * np.arange(141), 23.0 - 0.2 * np.arange(111)
)
land = np.zeros((111, 141), dtype=bool)


def polygon(vertices):
    """Fill geographic polygon via even-odd crossing at each sampling point."""
    global land
    inside = np.zeros_like(land)
    points = list(vertices)
    for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]):
        if y1 == y2:
            continue
        crossed = ((y1 > LATITUDE) != (y2 > LATITUDE))
        x_at_y = x1 + (LATITUDE - y1) * (x2 - x1) / (y2 - y1)
        inside ^= crossed & (LONGITUDE < x_at_y)
    land |= inside


def ellipse(x, y, rx, ry, tilt=0):
    """Approximate a small island or reef; tilt is in degrees."""
    a = np.deg2rad(tilt)
    dx, dy = LONGITUDE - x, LATITUDE - y
    u = (dx * np.cos(a) + dy * np.sin(a)) / rx
    v = (-dx * np.sin(a) + dy * np.cos(a)) / ry
    land[:] |= u * u + v * v <= 1


