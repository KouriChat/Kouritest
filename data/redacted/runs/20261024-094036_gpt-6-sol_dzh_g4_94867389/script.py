LON = -9 + .2 * np.arange(231)
LAT = 45 - .2 * np.arange(71)
X, Y = np.meshgrid(LON, LAT)
land = np.zeros((71, 231), dtype=bool)


def polygon(vertices):
    """Point-in-polygon, not a cell-coverage/multisample test."""
    global land
    inside = np.zeros_like(land)
    for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
        if ay == by:
            continue
        cross = ((ay > Y) != (by > Y)) & (
            X < ax + (Y - ay) * (bx - ax) / (by - ay))
        inside ^= cross
    land |= inside


def ellipse(x, y, rx, ry, angle=0):
    """Small island/reef approximated by rotated elliptical shoreline."""
    global land
    a = math.radians(angle)
    dx, dy = X-x, Y-y
    u = dx * math.cos(a) + dy * math.sin(a)
    v = -dx * math.sin(a) + dy * math.cos(a)
    land |= (u/rx)**2 + (v/ry)**2 <= 1


