def generate():
    for name, vertices in polygons:
        if not np.isfinite(vertices).all():
            raise ValueError("Invalid manually specified polygon: " + name)
        matrix[contains(vertices)] = 1

    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert LONS[0] == 99 and LONS[-1] == 127
    assert LATS[0] == 23 and LATS[-1] == 1

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    resampling = getattr(Image, "Resampling", Image)
    enlarged = original.resize((1128, 888), resampling.NEAREST)
    original.save(output / "candidate.png")
    enlarged.save(output / "candidate_8x.png")

    # Read back only our own generated outputs, never external map data.
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert restored.size == 15651
    assert np.array_equal(restored, matrix)
    with Image.open(output / "candidate.png") as image:
        assert image.size == (141, 111) and image.mode == "L"
        small = np.array(image)
    with Image.open(output / "candidate_8x.png") as image:
        assert image.size == (1128, 888) and image.mode == "L"
        large = np.array(image)
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(large).tolist()) == {0, 255}
    assert np.array_equal(small, matrix * 255)
    expected = np.repeat(np.repeat(small, 8, axis=0), 8, axis=1)
    assert np.array_equal(large, expected), "Nearest-neighbor check failed"
    print("PASS: 111x141 = 15651 binary samples; CSV complete; "
          "141x111 and 1128x888 black/white PNGs; exact 8x nearest neighbor.")
    print("Land:", int(matrix.sum()), "Water:", int(matrix.size - matrix.sum()))


if __name__ == "__main__":
    generate()
