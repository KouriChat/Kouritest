def land(name, coordinates):
    """Register a handwritten polygon, with longitude preceding latitude."""
    values = np.fromstring(coordinates, sep=" ")
    assert len(values) >= 6 and len(values) % 2 == 0, name
    polygons.append((name, values.reshape(-1, 2)))


def contains(vertices):
    """Even-odd point-in-polygon test; boundary points count as land."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (X - ax) * dy - (Y - ay) * dx
        boundary |= (
            (np.abs(cross) < 1e-10)
            & (X >= min(ax, bx) - 1e-10)
            & (X <= max(ax, bx) + 1e-10)
            & (Y >= min(ay, by) - 1e-10)
            & (Y <= max(ay, by) + 1e-10)
        )
        if dy != 0:
            inside ^= ((ay > Y) != (by > Y)) & (
                X < ax + (Y - ay) * dx / dy
            )
        ax, ay = bx, by
    return inside | boundary


