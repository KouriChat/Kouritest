"""Memory-only coastline reconstruction; no geographic files or services.

Coordinates below are hand-written approximations, not surveyed outlines.
Every sample is classified by polygon containment, not independent inference.
Dependencies: Python 3, numpy, Pillow. Run from the desired working directory.
"""
from pathlib import Path
