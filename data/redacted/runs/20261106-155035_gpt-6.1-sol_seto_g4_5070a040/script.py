from PIL import Image

LAND = []
WATER = []

def polygon(text, water=False):
    values = [float(v) for v in text.replace(",", " ").split()]
    assert len(values) % 2 == 0
    p = np.asarray(values, dtype=float).reshape(-1, 2)
    (WATER if water else LAND).append(p)

def ellipse(x, y, rx, ry, angle=0, n=24):
    t = np.arange(n) * (2 * np.pi / n)
    a = np.deg2rad(angle)
    u, v = rx * np.cos(t), ry * np.sin(t)
    LAND.append(np.column_stack((x+u*np.cos(a)-v*np.sin(a),
                                 y+u*np.sin(a)+v*np.cos(a))))

