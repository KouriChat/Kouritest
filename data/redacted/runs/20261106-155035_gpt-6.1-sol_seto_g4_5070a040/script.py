def inside(x, y, vertices):
    """Vectorized even-odd point-in-polygon test on exact sample positions."""
    result = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crossing = ((y0 > y) != (y1 > y))
            edge_x = x0 + (y-y0) * (x1-x0) / (y1-y0)
            result ^= crossing & (x < edge_x)
        x0, y0 = x1, y1
    return result

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    longitude = 129.0 + np.arange(253) * (2.0 / 63.0)
    latitude = 35.0 - np.arange(64) * (2.0 / 63.0)
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((64, 253), dtype=bool)
    for vertices in LAND:
        land |= inside(x, y, vertices)
    for vertices in WATER:
        land &= ~inside(x, y, vertices)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix)) == {0, 1}
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    enlarged = image.resize((2024, 512), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as a:
        assert a.size == (253, 64)
        assert np.array_equal(np.asarray(a), pixels)
    with Image.open(out / "candidate_8x.png") as b:
        assert b.size == (2024, 512) and set(np.unique(b)) == {0, 255}
        expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(np.asarray(b), expected)
    print("Validated: 64x253=16192; CSV binary; PNG 253x64 and nearest 2024x512.")

if __name__ == "__main__":
    main()
