def contains(lon, lat, polygon):
    """Even-odd point-in-polygon test for the hand-drawn rings."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                inside = not inside
        j = i
    return inside


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lats = range(89, -90, -2)
    lons = range(-179, 180, 2)
    matrix = np.zeros((90, 180), dtype=np.uint8)
    for row, lat in enumerate(lats):
        for col, lon in enumerate(lons):
            matrix[row, col] = any(contains(lon, lat, p) for p in POLYGONS)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = (matrix * 255).astype(np.uint8)
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
