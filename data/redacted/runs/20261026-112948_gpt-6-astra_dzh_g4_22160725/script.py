def inside_polygon(lon_grid, lat_grid, polygon):
    inside = np.zeros(lon_grid.shape, dtype=bool)
    eps = 1e-10
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        cross = (lon_grid - x1) * (y2 - y1) - (lat_grid - y1) * (x2 - x1)
        inside |= (
            (np.abs(cross) <= eps)
            & (lon_grid >= min(x1, x2) - eps)
            & (lon_grid <= max(x1, x2) + eps)
            & (lat_grid >= min(y1, y2) - eps)
            & (lat_grid <= max(y1, y2) + eps)
        )
        crosses = (y1 > lat_grid) != (y2 > lat_grid)
        xhit = x1 + (lat_grid - y1) * (x2 - x1) / (
            (y2 - y1) if y2 != y1 else 1.0
        )
        inside ^= crosses & (lon_grid < xhit)
    return inside


def main():
    latitudes = np.round(np.arange(45.0, 30.999, -0.2), 1)
    longitudes = np.round(np.arange(-9.0, 37.001, 0.2), 1)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((71, 231), dtype=bool)
    for polygon in MAINLAND + ISLANDS:
        land |= inside_polygon(lon_grid, lat_grid, polygon)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231)
    assert matrix.size == 16401

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((1848, 568), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert image.size == (231, 71)
    assert set(image.getdata()) <= {0, 255}
    assert Image.open(out / "candidate_8x.png").size == (1848, 568)


if __name__ == "__main__":
    main()
