def inside_polygon(x, y, vertices):
    """Vectorized ray crossing for the sample points themselves."""
    inside = np.zeros(x.shape, dtype=bool)
    previous_x, previous_y = vertices[-1]
    for current_x, current_y in vertices:
        if current_y != previous_y:
            crosses_y = (current_y > y) != (previous_y > y)
            crossing_x = (
                (previous_x - current_x) * (y - current_y)
                / (previous_y - current_y) + current_x
            )
            inside ^= crosses_y & (x < crossing_x)
        previous_x, previous_y = current_x, current_y
    return inside


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    # Integer tenths avoid cumulative error from floating point arange.
    latitudes = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    longitudes = np.arange(-1050, -809, dtype=np.int32) / 10.0
    x, y = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((61, 241), dtype=bool)
    for _, vertices in LAND:
        mask |= inside_polygon(x, y, vertices)
    for _, vertices in SEA:
        mask &= ~inside_polygon(x, y, vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, [0, 1]).all()
    assert (latitudes[0], latitudes[-1]) == (79, 73)
    assert (longitudes[0], longitudes[-1]) == (-105, -81)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(output / "candidate.png")
    enlarged = original.resize((1928, 488), resample=Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    # Verify the saved artifacts, including every replicated image pixel.
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    loaded = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(loaded, matrix)
    with Image.open(output / "candidate.png") as image:
        assert image.size == (241, 61)
        original_pixels = np.array(image)
    with Image.open(output / "candidate_8x.png") as image:
        assert image.size == (1928, 488)
        enlarged_pixels = np.array(image)
    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, pixels)
    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged_pixels, expected)
    print(json.dumps({
        "shape": list(matrix.shape),
        "valid_values": int(matrix.size),
        "land": int(matrix.sum()),
        "water": int(matrix.size - matrix.sum()),
        "original_pixels": [241, 61],
        "enlarged_pixels": [1928, 488],
        "nearest_neighbor_verified": True,
        "saved_files_verified": True,
        "method": "Handwritten approximate polygons and point-in-polygon rules",
        "dependencies": ["numpy", "Pillow"],
    }, indent=2))


if __name__ == "__main__":
    main()
