def inside(vertices):
    """Even-odd rule applied to the actual sample points, not pixel areas."""
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > Y) != (y1 > Y))
            edge_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (X < edge_x)
        x0, y0 = x1, y1
    return result


