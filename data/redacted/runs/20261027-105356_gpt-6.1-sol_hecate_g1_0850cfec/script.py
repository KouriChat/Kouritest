def generate():
    land = np.zeros((N, N), dtype=bool)
    for polygon in LAND:
        land |= inside(polygon)
    for polygon in WATER:
        land &= ~inside(polygon)
    return land.astype(np.uint8)


def main():
    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    matrix = generate()
    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert np.all((matrix == 0) | (matrix == 1))
    assert np.isclose(lon[0], -131) and np.isclose(lon[-1], -129)
    assert np.isclose(lat[0], 55) and np.isclose(lat[-1], 53)

    csv_path = out / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='ascii') as f:
        writer = csv.writer(f, lineterminator='\n')
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / 'candidate.png')
    nearest = Image.Resampling.NEAREST if hasattr(Image, 'Resampling') else Image.NEAREST
    enlarged = image.resize((1016, 1016), resample=nearest)
    enlarged.save(out / 'candidate_8x.png')

    # Independently reload all deliverables and validate the saved bytes.
    with csv_path.open('r', newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    reloaded = np.array(rows, dtype=np.uint8)
    assert reloaded.size == 16129
    assert np.array_equal(reloaded, matrix)

    with Image.open(out / 'candidate.png') as saved:
        saved.load()
        assert saved.size == (127, 127) and saved.mode == 'L'
        raw = np.array(saved)
    with Image.open(out / 'candidate_8x.png') as saved:
        saved.load()
        assert saved.size == (1016, 1016) and saved.mode == 'L'
        big = np.array(saved)
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, reloaded * np.uint8(255))
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected), 'Not exact 8x nearest-neighbor'
