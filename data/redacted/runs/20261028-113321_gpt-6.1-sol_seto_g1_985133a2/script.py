def inside(points, X, Y):
    result = np.zeros(X.shape, dtype=bool)
    ax, ay = points[-1]
    for bx, by in points:
        if by != ay:
            result ^= ((ay > Y) != (by > Y)) & (
                X < (bx-ax)*(Y-ay)/(by-ay)+ax)
        ax, ay = bx, by
    return result

def main():
    os.makedirs("outputs", exist_ok=True)
    xs = 129 + np.arange(253)*2/63
    ys = 35 - np.arange(64)*2/63
    X,Y = np.meshgrid(xs, ys)
    mask = np.zeros((64,253), dtype=bool)
    for p in polygons:
        mask |= inside(p, X, Y)
    # Explicit water indentation of Mikawa Bay; lakes remain land by definition.
    bay = [(137.00,34.78),(137.04,34.83),(137.11,34.84),
           (137.17,34.81),(137.23,34.82),(137.28,34.81),
           (137.31,34.78),(137.27,34.73),(137.21,34.70),
           (137.12,34.66),(137.06,34.64),(137.02,34.68)]
    mask &= ~inside(bay,X,Y)
    a = mask.astype(np.uint8)
    with open("outputs/candidate.csv","w",newline="",encoding="ascii") as f:
        csv.writer(f).writerows(a.tolist())
    image = Image.fromarray(a*255)
    image.save("outputs/candidate.png")
    big = image.resize((2024,512), Image.Resampling.NEAREST)
    big.save("outputs/candidate_8x.png")
    with open("outputs/candidate.csv",newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows)==64 and all(len(r)==253 for r in rows)
    assert all(v in ("0","1") for r in rows for v in r)
    assert a.size==16192
    raw = np.asarray(Image.open("outputs/candidate.png"))
    enlarged = np.asarray(Image.open("outputs/candidate_8x.png"))
    assert raw.shape==(64,253) and enlarged.shape==(512,2024)
    assert set(np.unique(raw)).issubset({0,255})
    assert set(np.unique(enlarged)).issubset({0,255})
    assert np.array_equal(enlarged,np.repeat(np.repeat(raw,8,0),8,1))
    print("Validated: 64 x 253 = 16192 binary points; PNGs 253x64 and 2024x512.")

if __name__ == "__main__":
    main()
