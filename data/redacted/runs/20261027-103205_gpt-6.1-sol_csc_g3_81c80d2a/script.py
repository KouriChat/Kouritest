LONS = 99.0 + np.arange(141, dtype=np.float64) / 5
LATS = 23.0 - np.arange(111, dtype=np.float64) / 5
X, Y = np.meshgrid(LONS, LATS)
LAND = np.zeros(X.shape, dtype=bool)


def polygon(points):
    """Point-in-polygon, including boundary, without pixel-area voting."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        dx, dy = x1 - x0, y1 - y0
        cross = (X - x0) * dy - (Y - y0) * dx
        boundary |= ((np.abs(cross) <= 1e-10)
                     & (X >= min(x0, x1) - 1e-10)
                     & (X <= max(x0, x1) + 1e-10)
                     & (Y >= min(y0, y1) - 1e-10)
                     & (Y <= max(y0, y1) + 1e-10))
        if abs(dy) > 1e-15:
            crosses = ((y0 > Y) != (y1 > Y))
            inside ^= crosses & (X < x0 + (Y - y0) * dx / dy)
        x0, y0 = x1, y1
    return inside | boundary


def add(points):
    LAND[:] |= polygon(points)


def remove(points):
    LAND[:] &= ~polygon(points)


