def contains(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                inside = not inside
        j = i
    return inside
def classify(lon, lat):
    return int(any(contains(lon, lat, polygon) for polygon in POLYGONS))


def main():
    os.makedirs("outputs", exist_ok=True)
    lats = list(range(89, -90, -2))
    lons = list(range(-179, 180, 2))
    matrix = np.array([[classify(lon, lat) for lon in lons] for lat in lats], dtype=np.uint8)

    if matrix.shape != (90, 180) or matrix.size != 16200:
        raise RuntimeError("unexpected matrix dimensions")
    if not np.isin(matrix, (0, 1)).all():
        raise RuntimeError("matrix contains values other than 0 and 1")

    with open("outputs/candidate.csv", "w", newline="", encoding="ascii") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Array values 1/0 become white/black directly; no interpolation is applied.
    image = Image.fromarray(matrix * 255, mode="L")
    image.save("outputs/candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        "outputs/candidate_8x.png"
    )

    if image.size != (180, 90):
        raise RuntimeError("unexpected source image size")
    if Image.open("outputs/candidate_8x.png").size != (1440, 720):
        raise RuntimeError("unexpected enlarged image size")
    if set(image.getdata()) - {0, 255}:
        raise RuntimeError("source image contains non-binary pixels")


if __name__ == "__main__":
    main()
