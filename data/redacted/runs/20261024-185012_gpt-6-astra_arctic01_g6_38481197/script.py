LAT = (790 - np.arange(61)) / 10.0
LON = (-1050 + np.arange(241)) / 10.0
X, Y = np.meshgrid(LON, LAT)
LAND = np.zeros((61, 241), dtype=bool)
RULES = []


def polygon_mask(vertices):
    """Ray casting at sample POINTS; coastline ties are assigned to land."""
    vertices = [(-float(w), float(n)) for w, n in vertices]
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        cross = (X - ax) * (by - ay) - (Y - ay) * (bx - ax)
        boundary |= ((np.abs(cross) < 1e-10)
                     & (X >= min(ax, bx) - 1e-10)
                     & (X <= max(ax, bx) + 1e-10)
                     & (Y >= min(ay, by) - 1e-10)
                     & (Y <= max(ay, by) + 1e-10))
        if ay != by:
            crossing = ((ay > Y) != (by > Y))
            edge_x = ax + (Y - ay) * (bx - ax) / (by - ay)
            inside ^= crossing & (X < edge_x)
        ax, ay = bx, by
    return inside | boundary


def island(name, vertices):
    RULES.append((name, vertices))
    LAND[:] |= polygon_mask(vertices)


