"""Memory-only Canadian Arctic land/water reconstruction.

Dependencies: Python 3, numpy, Pillow.
Run from any working directory; results go into ./outputs/.
Coastlines below are handwritten approximations from prior geographic
knowledge, not downloaded or read from any map or geographic database.
All samples are classified by the same point-in-polygon rules, NOT by
independent language-model reasoning. Inland lakes remain classified land;
marine channels and floating ice remain water. Vertices use (degrees W, N).
"""
