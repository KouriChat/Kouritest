def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    matrix = LAND.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix)) <= {0, 1}
    assert (LAT[0], LAT[-1], LON[0], LON[-1]) == (79, 73, -105, -81)
    assert np.allclose(np.diff(LAT), -0.1)
    assert np.allclose(np.diff(LON), 0.1)

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    resampling = getattr(Image, "Resampling", Image)
    enlarged = original.resize((1928, 488), resample=resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    # Validate the actual exported files, not merely the source arrays.
    with csv_path.open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 14701
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)

    with Image.open(out / "candidate.png") as img:
        assert img.size == (241, 61) and img.mode == "L"
        actual = np.array(img)
    with Image.open(out / "candidate_8x.png") as img:
        assert img.size == (1928, 488) and img.mode == "L"
        actual_large = np.array(img)
    assert set(np.unique(actual)) == {0, 255}
    assert set(np.unique(actual_large)) == {0, 255}
    assert np.array_equal(actual, pixels)
    expected = np.repeat(np.repeat(actual, 8, axis=0), 8, axis=1)
    assert np.array_equal(actual_large, expected)
    report = {
        "valid": True, "rows": 61, "columns": 241, "samples": 14701,
        "land": int(matrix.sum()), "water": int((matrix == 0).sum()),
        "original_pixels": [241, 61], "enlarged_pixels": [1928, 488],
        "binary_csv": True, "black_white_only": True,
        "nearest_neighbor_verified": True,
        "method": "Memory-written polygons; point-in-polygon classification",
        "geographic_accuracy_verified": False,
    }
    (out / "validation.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=True))


if __name__ == "__main__":
    main()
