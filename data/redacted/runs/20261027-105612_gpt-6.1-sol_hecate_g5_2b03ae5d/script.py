"""Knowledge-only, approximate Hecate Strait land/water reconstruction.

No map, geographic database, network request, or external input is used.
Coordinates below are hand-written estimates from geographic knowledge, not
surveyed coastlines. Classification is vectorized point-in-polygon testing,
not separate language-model reasoning for each of the 16,129 sample points.
Inland lakes remain land; only explicitly drawn marine channels remove land.
Run from the desired working directory with Python, numpy and Pillow.
"""
