def main():
    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f, lineterminator='\n').writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / 'candidate.png')
    enlarged = original.resize((1016, 1016), resample=Image.Resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')

    # Verify the serialized artifacts, not just the in-memory source arrays.
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / 'candidate.png') as im:
        assert im.size == (127, 127) and im.mode == 'L'
        small = np.array(im)
    with Image.open(out / 'candidate_8x.png') as im:
        assert im.size == (1016, 1016) and im.mode == 'L'
        large = np.array(im)
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(large).tolist()) == {0, 255}
    assert np.array_equal(small, pixels)
    assert np.array_equal(large, np.repeat(np.repeat(small, 8, axis=0), 8, axis=1))
    assert LONGITUDES[0] == -131 and LONGITUDES[-1] == -129
    assert LATITUDES[0] == 55 and LATITUDES[-1] == 53
    print(json.dumps({'shape': list(matrix.shape), 'valid_values': int(matrix.size),
                      'land_points': int(matrix.sum()), 'csv_valid': True,
                      'png_sizes': [[127, 127], [1016, 1016]],
                      'black_white_only': True, 'nearest_neighbor_verified': True,
                      'method': 'knowledge-only hand-written polygons; point tests'},
                     ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
