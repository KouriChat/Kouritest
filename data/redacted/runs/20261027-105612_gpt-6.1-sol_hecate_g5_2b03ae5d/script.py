N = 127
LONGITUDES = -131.0 + np.arange(N, dtype=np.float64) * (2.0 / 126)
LATITUDES = 55.0 - np.arange(N, dtype=np.float64) * (2.0 / 126)
X, Y = np.meshgrid(LONGITUDES, LATITUDES)
land = np.zeros((N, N), dtype=bool)


def polygon(vertices):
    """Even-odd ray casting at the actual longitude/latitude sample points."""
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crosses = (y0 > Y) != (y1 > Y)
            edge_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crosses & (X < edge_x)
        x0, y0 = x1, y1
    return result


def add(vertices):
    land[:] |= polygon(vertices)


def sea(vertices):
    land[:] &= ~polygon(vertices)


