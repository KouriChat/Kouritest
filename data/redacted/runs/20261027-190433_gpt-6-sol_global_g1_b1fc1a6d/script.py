def classify(lon, lat):
    on_land = any(inside(lon, lat, shape) for shape in LAND)
    if not on_land:
        return 0
    if any(inside(lon, lat, lake) for lake in WATER_HOLES):
        return 0
    return 1


def main():
    lats = list(range(89, -90, -2))
    lons = list(range(-179, 180, 2))
    matrix = [[classify(lon, lat) for lon in lons] for lat in lats]

    if len(matrix) != 90 or any(len(row) != 180 for row in matrix):
        raise RuntimeError("Unexpected matrix dimensions")
    if any(value not in (0, 1) for row in matrix for value in row):
        raise RuntimeError("Matrix contains a value other than 0 or 1")

    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    with (output_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as handle:
        for row in matrix:
            handle.write(",".join(str(value) for value in row))
            handle.write("\n")

    pixels = np.asarray(matrix, dtype=np.uint8) * 255
    original = Image.fromarray(pixels, mode="L")
    original.save(output_dir / "candidate.png")

    enlarged = original.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(output_dir / "candidate_8x.png")

    if original.size != (180, 90):
        raise RuntimeError("Unexpected original image dimensions")
    if enlarged.size != (1440, 720):
        raise RuntimeError("Unexpected enlarged image dimensions")
    if not set(int(value) for value in np.asarray(original).ravel()).issubset({0, 255}):
        raise RuntimeError("Original image contains non-black/non-white pixels")


if __name__ == "__main__":
    main()
