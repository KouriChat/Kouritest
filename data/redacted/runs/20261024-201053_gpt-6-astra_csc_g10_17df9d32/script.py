def ellipse(name, x, y, rx, ry, angle=0):
    t = np.arange(48) * (2 * np.pi / 48)
    a = np.deg2rad(angle)
    dx, dy = rx * np.cos(t), ry * np.sin(t)
    add(name, list(zip(x + dx*np.cos(a) - dy*np.sin(a),
                       y + dx*np.sin(a) + dy*np.cos(a))))

def contains(xs, ys, vertices):
    inside = np.zeros(xs.shape, dtype=bool)
    boundary = np.zeros(xs.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1-x0, y1-y0
        cross = (xs-x0)*dy - (ys-y0)*dx
        on = np.abs(cross) < 1e-10
        on &= (xs >= min(x0,x1)-1e-10)
        on &= (xs <= max(x0,x1)+1e-10)
        on &= (ys >= min(y0,y1)-1e-10)
        on &= (ys <= max(y0,y1)+1e-10)
        boundary |= on
        if dy != 0:
            cut = ((y0 > ys) != (y1 > ys))
            inside ^= cut & (xs < x0 + (ys-y0)*dx/dy)
        x0, y0 = x1, y1
    return inside | boundary

