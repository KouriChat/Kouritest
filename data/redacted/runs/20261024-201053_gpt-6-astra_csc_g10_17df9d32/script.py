def main():
    # Exact 0.2-degree grid, north to south and west to east.
    latitudes = (230 - 2*np.arange(111)) / 10.0
    longitudes = (990 + 2*np.arange(141)) / 10.0
    xs, ys = np.meshgrid(longitudes, latitudes)
    land = np.zeros((111,141), dtype=bool)
    for name, vertices in POLYGONS:
        assert len(vertices) >= 3, name
        land |= contains(xs, ys, vertices)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (111,141) and matrix.size == 15651
    assert set(np.unique(matrix).tolist()) == {0,1}
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    with (out/"candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    raw = Image.fromarray(matrix * np.uint8(255))
    raw.save(out/"candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    large = raw.resize((1128,888), resample=nearest)
    large.save(out/"candidate_8x.png")
    # Validate saved files, including every enlarged pixel, not just metadata.
    with (out/"candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(v in ("0","1") for row in rows for v in row)
    saved_matrix = np.array(rows, dtype=np.uint8)
    assert saved_matrix.size == 15651
    assert np.array_equal(saved_matrix, matrix)
    with Image.open(out/"candidate.png") as im:
        assert im.size == (141,111) and im.mode == "L"
        a = np.array(im)
    with Image.open(out/"candidate_8x.png") as im:
        assert im.size == (1128,888) and im.mode == "L"
        b = np.array(im)
    assert set(np.unique(a).tolist()) == {0,255}
    assert set(np.unique(b).tolist()) == {0,255}
    assert np.array_equal(a, matrix*255)
    expected = np.repeat(np.repeat(a, 8, axis=0), 8, axis=1)
    assert np.array_equal(b, expected), "Not exact nearest-neighbor enlargement"
    print("PASS: 111x141 = 15651 binary values; no missing CSV fields.")
    print("PASS: black/white PNGs 141x111 and exact nearest 8x 1128x888.")
    print(f"Land={int(matrix.sum())}, water={int(matrix.size-matrix.sum())}.")

if __name__ == "__main__":
    main()
