def main():
    matrix_land = LAND.copy()
    for name, vertices in POLYGONS:
        matrix_land |= polygon_mask(vertices)
    for vertices in SEA_CUTOUTS:
        matrix_land &= ~polygon_mask(vertices)
    matrix = matrix_land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix)) == {0, 1}
    assert LONGITUDES[0] == -9 and LONGITUDES[-1] == 37
    assert LATITUDES[0] == 45 and LATITUDES[-1] == 31

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(output / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1848, 568), resample=nearest)
    enlarged.save(output / "candidate_8x.png")

    # Verify saved files, including every replicated 8x8 pixel block.
    with csv_path.open("r", newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16401
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(output / "candidate.png") as image:
        assert image.size == (231, 71)
        raw = np.array(image)
    with Image.open(output / "candidate_8x.png") as image:
        assert image.size == (1848, 568)
        big = np.array(image)
    assert set(np.unique(raw)) == {0, 255}
    assert set(np.unique(big)) == {0, 255}
    assert np.array_equal(raw, pixels)
    assert np.array_equal(big, np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1))
    print("Validated: 71x231, 16401 binary values; PNG 231x71; nearest 8x 1848x568.")


if __name__ == "__main__":
    main()
