LONGITUDES = (np.arange(231, dtype=np.float64) - 45) / 5
LATITUDES = (225 - np.arange(71, dtype=np.float64)) / 5
X, Y = np.meshgrid(LONGITUDES, LATITUDES)
LAND = np.zeros(X.shape, dtype=bool)
POLYGONS = []


def land(name, coordinates):
    numbers = list(map(float, coordinates.split()))
    assert len(numbers) % 2 == 0, name
    vertices = list(zip(numbers[::2], numbers[1::2]))
    assert len(vertices) >= 3, name
    POLYGONS.append((name, vertices))


def polygon_mask(vertices):
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        if dy != 0:
            crossing = ((y0 > Y) != (y1 > Y))
            inside ^= crossing & (X < x0 + (Y - y0) * dx / dy)
        cross = (X - x0) * dy - (Y - y0) * dx
        boundary |= (
            (np.abs(cross) < 1e-10)
            & (X >= min(x0, x1) - 1e-10)
            & (X <= max(x0, x1) + 1e-10)
            & (Y >= min(y0, y1) - 1e-10)
            & (Y <= max(y0, y1) + 1e-10)
        )
        x0, y0 = x1, y1
    return inside | boundary


