"""Knowledge-only Mediterranean reconstruction; no map/data inputs.

All coordinates below are manually estimated from remembered geography.
Point classification is a union of handwritten coastline polygons, not
independent language-model inference for each point. Inland lakes stay land.
Dependencies: Python 3, numpy, Pillow. Run from the desired working directory.
"""
