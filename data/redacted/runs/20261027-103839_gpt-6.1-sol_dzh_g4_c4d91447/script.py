def contains_points(vertices, x, y):
    """Even-odd point-in-polygon test; points on an edge count as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    eps = 1e-10
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if abs(dy) > 1e-14:
            crossing = ((ay > y) != (by > y))
            x_intersection = ax + (y - ay) * dx / dy
            inside ^= crossing & (x < x_intersection)
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= eps)
            & (x >= min(ax, bx) - eps) & (x <= max(ax, bx) + eps)
            & (y >= min(ay, by) - eps) & (y <= max(ay, by) + eps)
        )
        ax, ay = bx, by
    return inside | boundary


def make_matrix():
    # Integer tenths avoid cumulative floating-point arange endpoint errors.
    latitudes = (450 - 2 * np.arange(71, dtype=np.int64)) / 10.0
    longitudes = (-90 + 2 * np.arange(231, dtype=np.int64)) / 10.0
    assert (latitudes[0], latitudes[-1]) == (45.0, 31.0)
    assert (longitudes[0], longitudes[-1]) == (-9.0, 37.0)
    lon, lat = np.meshgrid(longitudes, latitudes)
    x, y = lon.ravel(), lat.ravel()
    land = np.zeros(x.shape, dtype=bool)
    for name, vertices in POLYGONS.items():
        assert np.isfinite(vertices).all(), name
        lo, hi = vertices.min(axis=0), vertices.max(axis=0)
        selected = np.flatnonzero(
            (x >= lo[0] - 1e-10) & (x <= hi[0] + 1e-10)
            & (y >= lo[1] - 1e-10) & (y <= hi[1] + 1e-10)
        )
        if selected.size:
            land[selected] |= contains_points(vertices, x[selected], y[selected])
    return land.reshape(71, 231).astype(np.uint8)


def main():
    output = Path.cwd() / 'outputs'
    output.mkdir(parents=True, exist_ok=True)
    matrix = make_matrix()
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()
    csv_path = output / 'candidate.csv'
    with csv_path.open('w', encoding='ascii', newline='') as f:
        csv.writer(f, lineterminator='\n').writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    assert image.mode == 'L'
    image.save(output / 'candidate.png')
    nearest = Image.Resampling.NEAREST if hasattr(Image, 'Resampling') else Image.NEAREST
    enlarged = image.resize((1848, 568), resample=nearest)
    enlarged.save(output / 'candidate_8x.png')

    # Reopen only our own output files; never read geographic reference data.
    with csv_path.open('r', encoding='ascii', newline='') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(v in ('0', '1') for row in rows for v in row)
    assert sum(map(len, rows)) == 16401
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(output / 'candidate.png') as raw:
        assert raw.size == (231, 71) and raw.mode == 'L'
        raw_pixels = np.array(raw)
        assert np.array_equal(raw_pixels, pixels)
        assert set(np.unique(raw_pixels).tolist()) == {0, 255}
    with Image.open(output / 'candidate_8x.png') as big:
        assert big.size == (1848, 568) and big.mode == 'L'
        big_pixels = np.array(big)
        assert set(np.unique(big_pixels).tolist()) == {0, 255}
        expected = np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(big_pixels, expected)
    print(json.dumps({
        'matrix_shape': list(matrix.shape), 'valid_values': int(matrix.size),
        'csv_rows': len(rows), 'csv_columns': 231, 'csv_values': [0, 1],
        'raw_png_size': [231, 71], 'enlarged_png_size': [1848, 568],
        'png_colors': [0, 255], 'nearest_neighbor_verified': True,
        'land_points': int(matrix.sum()), 'water_points': int(matrix.size - matrix.sum()),
        'method': 'handwritten memory-only polygons, vectorized point-in-polygon',
        'dependencies': ['numpy', 'Pillow'], 'validation': 'passed'
    }, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
