def in_polygon(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing_x = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing_x:
                inside = not inside
        j = i
    return inside

def is_land(lon, lat):
    if any(in_polygon(lon, lat, poly) for poly in LAND):
        return True
    for cx, cy, rx, ry in ISLANDS:
        if ((lon-cx)/rx)**2 + ((lat-cy)/ry)**2 <= 1:
            return True
    return False
