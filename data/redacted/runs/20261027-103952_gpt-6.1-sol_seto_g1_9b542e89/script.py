def inside_polygon(x, y, vertices):
    """Even-odd point test; a point exactly on an edge is included."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if dy != 0:
            crosses = (ay > y) != (by > y)
            cut_x = ax + (y - ay) * dx / dy
            inside ^= crosses & (x < cut_x)
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-11)
            & (x >= min(ax, bx) - 1e-11)
            & (x <= max(ax, bx) + 1e-11)
            & (y >= min(ay, by) - 1e-11)
            & (y <= max(ay, by) + 1e-11)
        )
        ax, ay = bx, by
    return inside | boundary

def generate():
    # Full-precision common spacing, not the rounded examples in the prompt.
    latitudes = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
    longitudes = 129.0 + np.arange(253, dtype=np.float64) * (2.0 / 63.0)
    assert latitudes[0] == 35 and latitudes[-1] == 33
    assert longitudes[0] == 129 and longitudes[-1] == 137
    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((64, 253), dtype=bool)
    for _, vertices in LAND:
        land |= inside_polygon(x, y, vertices)
    for _, vertices in WATER:
        land &= ~inside_polygon(x, y, vertices)
    return land.astype(np.uint8)

