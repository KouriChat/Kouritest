def point_value(lon, lat):
    result = any(inside(lon, lat, p) for p in land)
    if result and any(inside(lon, lat, p) for p in water):
        result = False
    return int(result)

def build_matrix():
    return [
        [point_value(LON0 + c * STEP, LAT0 - r * STEP)
         for c in range(W)]
        for r in range(H)
    ]

def main():
    matrix = build_matrix()
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix)

    array = np.asarray(matrix, dtype=np.uint8)
    image = Image.fromarray(array * 255, mode="L")
    image.save(out / "candidate.png")
    enlarged = image.resize((W * 8, H * 8), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    assert array.shape == (71, 231)
    assert array.size == 16401
    assert set(np.unique(array)).issubset({0, 1})
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(v in {"0", "1"} for row in rows for v in row)
    assert Image.open(out / "candidate.png").size == (231, 71)
    assert Image.open(out / "candidate_8x.png").size == (1848, 568)
    assert set(Image.open(out / "candidate.png").getdata()).issubset({0, 255})
    assert set(Image.open(out / "candidate_8x.png").getdata()).issubset({0, 255})
    print("validated: 71x231 matrix, 16401 values, binary CSV, binary PNGs")

if __name__ == "__main__":
    main()

