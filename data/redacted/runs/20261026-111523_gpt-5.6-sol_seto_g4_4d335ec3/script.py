def point_in_polygon(x, y, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > y) != (yj > y):
            crossing_x = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < crossing_x:
                inside = not inside
        j = i
    return inside
def classify(lon, lat):
    land = any(point_in_polygon(lon, lat, poly) for poly in LAND_POLYGONS)
    if any(point_in_polygon(lon, lat, poly) for poly in WATER_POLYGONS):
        land = False
    if any(
        ((lon - x) / rx) ** 2 + ((lat - y) / ry) ** 2 <= 1.0
        for x, y, rx, ry in ISLANDS
    ):
        land = True
    return int(land)


def main():
    out_dir = Path("outputs")
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for row in range(64):
        lat = 35.0 - row * (2.0 / 63.0)
        rows.append([
            classify(129.0 + col * (8.0 / 252.0), lat)
            for col in range(253)
        ])

    with (out_dir / "candidate.csv").open(
        "w", newline="", encoding="ascii"
    ) as f:
        csv.writer(f, lineterminator="\n").writerows(rows)

    matrix = np.asarray(rows, dtype=np.uint8)
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out_dir / "candidate.png")
    image.resize((2024, 512), Image.Resampling.NEAREST).save(
        out_dir / "candidate_8x.png"
    )
    assert matrix.shape == (64, 253)
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert image.size == (253, 64)
    assert set(image.getdata()) <= {0, 255}


if __name__ == "__main__":
    main()
