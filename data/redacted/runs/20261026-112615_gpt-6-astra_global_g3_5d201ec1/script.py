def contains(lon, lat, ring):
    """Vectorized even-odd point-in-polygon test."""
    inside = np.zeros(lon.shape, dtype=bool)
    x0, y0 = ring[-1]
    for x1, y1 in ring:
        crosses = (y1 > lat) != (y0 > lat)
        edge_x = (x0 - x1) * (lat - y1) / ((y0 - y1) or 1e-30) + x1
        inside ^= crosses & (lon < edge_x)
        x0, y0 = x1, y1
    return inside


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    lon, lat = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for ring in LAND:
        land |= contains(lon, lat, ring)

    matrix = land.astype(np.uint8)
    np.savetxt(OUT / "candidate.csv", matrix, fmt="%d", delimiter=",")
    pixels = np.where(land, 255, 0).astype(np.uint8)
    Image.fromarray(pixels, mode="L").save(OUT / "candidate.png")
    Image.fromarray(pixels, mode="L").resize((1440, 720), Image.Resampling.NEAREST).save(
        OUT / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
