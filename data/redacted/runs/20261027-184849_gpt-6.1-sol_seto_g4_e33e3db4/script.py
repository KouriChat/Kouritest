longitudes = 129.0 + np.arange(COLS, dtype=np.float64) * (8.0 / 252.0)
lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)

matrix = np.zeros((ROWS, COLS), dtype=np.uint8)
for polygon in LAND:
    matrix |= inside_polygon(lon_grid, lat_grid, polygon).astype(np.uint8)
for polygon in WATER:
    matrix[inside_polygon(lon_grid, lat_grid, polygon)] = 0

