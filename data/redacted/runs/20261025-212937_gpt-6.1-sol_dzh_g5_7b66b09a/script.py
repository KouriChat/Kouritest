def inside(vertices):
    """Vectorized even-odd point-in-polygon test; boundary counts as inside."""
    result = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    previous = vertices[-1]
    for current in vertices:
        ax, ay = previous
        bx, by = current
        cross = (X - ax) * (by - ay) - (Y - ay) * (bx - ax)
        boundary |= ((np.abs(cross) < 1e-10)
                     & (X >= min(ax, bx) - 1e-10)
                     & (X <= max(ax, bx) + 1e-10)
                     & (Y >= min(ay, by) - 1e-10)
                     & (Y <= max(ay, by) + 1e-10))
        if by != ay:
            intersection = ax + (Y - ay) * (bx - ax) / (by - ay)
            result ^= ((ay > Y) != (by > Y)) & (X < intersection)
        previous = current
    return result | boundary


