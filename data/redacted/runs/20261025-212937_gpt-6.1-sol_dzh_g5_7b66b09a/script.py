def generate():
    # Each entry is a single coordinate, not a cell-area estimate.
    water = inside(OCEAN) | inside(BLACK_SEA) | inside(MARMARA)
    land = ~water
    for vertices in ISLANDS.values():
        land |= inside(vertices)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert set(np.unique(matrix)).issubset({0, 1})
    assert (LATS[0], LATS[-1], LONS[0], LONS[-1]) == (45, 31, -9, 37)

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    png_path = output / "candidate.png"
    enlarged_path = output / "candidate_8x.png"

    with csv_path.open("w", newline="", encoding="ascii") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(png_path, format="PNG")
    enlarged = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(enlarged_path, format="PNG")

    # Validate the serialized files, not just the in-memory objects.
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert sum(map(len, rows)) == 16401
    assert all(value in ("0", "1") for row in rows for value in row)
    reloaded = np.array(rows, dtype=np.uint8)
    assert np.array_equal(matrix, reloaded)

    with Image.open(png_path) as raw_image:
        assert raw_image.size == (231, 71)
        assert raw_image.mode == "L"
        raw_pixels = np.array(raw_image)
    with Image.open(enlarged_path) as large_image:
        assert large_image.size == (1848, 568)
        assert large_image.mode == "L"
        large_pixels = np.array(large_image)
    assert set(np.unique(raw_pixels)) == {0, 255}
    assert set(np.unique(large_pixels)) == {0, 255}
    assert np.array_equal(raw_pixels, reloaded * np.uint8(255))
    expected_large = np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(large_pixels, expected_large)

    report = {
        "method": "Handwritten remembered coast polygons; vectorized point-in-polygon.",
        "geographic_data_sources": "None: no network, map files, or geodata libraries.",
        "independent_point_reasoning": False,
        "matrix_shape": list(matrix.shape),
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_valid": True,
        "original_png_size": [231, 71],
        "enlarged_png_size": [1848, 568],
        "black_and_white_only": True,
        "nearest_neighbor_exactly_verified": True,
        "geographic_accuracy_verified": False,
    }
    (output / "validation.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    generate()
