LON, LAT = np.meshgrid(129.0 + np.arange(253) * (2.0 / 63.0),
                       35.0 - np.arange(64) * (2.0 / 63.0))
LAND = np.zeros((64, 253), dtype=bool)


def polygon(points, value=True):
    """Ray casting at the sample coordinates, not area rasterization."""
    inside = np.zeros(LAND.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y0 != y1:
            crosses = (y0 > LAT) != (y1 > LAT)
            cut = x0 + (LAT - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (LON < cut)
        x0, y0 = x1, y1
    LAND[inside] = value


def ellipse(x, y, rx, ry, angle=0):
    """Hand-estimated outlines for small islands (degrees, rotation degrees)."""
    a = np.deg2rad(angle)
    dx, dy = LON - x, LAT - y
    u, v = dx * np.cos(a) + dy * np.sin(a), -dx * np.sin(a) + dy * np.cos(a)
    LAND[(u / rx) ** 2 + (v / ry) ** 2 <= 1] = True


