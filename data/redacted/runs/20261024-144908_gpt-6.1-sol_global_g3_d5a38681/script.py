def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    assert latitude.shape == longitude.shape == (90, 180)
    assert (latitude[0, 0], latitude[-1, 0]) == (89, -89)
    assert (longitude[0, 0], longitude[0, -1]) == (-179, 179)
    land = np.zeros((90, 180), dtype=bool)
    for name, vertices in LAND:
        land |= polygon_mask(vertices, longitude, latitude)
    for name, vertices in SEA:
        land &= ~polygon_mask(vertices, longitude, latitude)
    matrix = land.astype(np.uint8)
    assert matrix.size == 16200
    assert set(np.unique(matrix).tolist()) == {0, 1}

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    assert original.mode == "L"
    original.save(out / "candidate.png", format="PNG")
    resampling = getattr(Image, "Resampling", Image)
    enlarged = original.resize((1440, 720), resample=resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png", format="PNG")

    # Reopen the actual deliverables, rather than only checking in-memory data.
    with csv_path.open("r", newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert restored.size == 16200 and np.array_equal(restored, matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.format == "PNG" and image.size == (180, 90)
        raw = np.array(image)
        assert set(np.unique(raw).tolist()) == {0, 255}
        assert np.array_equal(raw, restored * np.uint8(255))
    with Image.open(out / "candidate_8x.png") as image:
        assert image.format == "PNG" and image.size == (1440, 720)
        large = np.array(image)
        assert set(np.unique(large).tolist()) == {0, 255}
        expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
        assert np.array_equal(large, expected), "Not exact nearest-neighbor 8x"
