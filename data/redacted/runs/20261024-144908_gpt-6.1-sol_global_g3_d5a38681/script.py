def add(name, coordinates, water=False):
    values = [float(v) for v in coordinates.replace(";", " ").split()]
    assert len(values) % 2 == 0, name
    vertices = np.array(values, dtype=np.float64).reshape(-1, 2)
    assert len(vertices) >= 3, name
    (SEA if water else LAND).append((name, vertices))


# Longitudes can exceed 180 for polygons crossing the date line.
# Each polygon is tested at equivalent longitudes, without wrapping its edges.
def polygon_mask(vertices, longitude, latitude):
    result = np.zeros(longitude.shape, dtype=bool)
    low = vertices.min(axis=0)
    high = vertices.max(axis=0)
    for shift in (-360.0, 0.0, 360.0):
        x = longitude + shift
        possible = ((x >= low[0]) & (x <= high[0]) &
                    (latitude >= low[1]) & (latitude <= high[1]))
        if not possible.any():
            continue
        px, py = x[possible], latitude[possible]
        inside = np.zeros(px.shape, dtype=bool)
        boundary = np.zeros(px.shape, dtype=bool)
        ax, ay = vertices[-1]
        for bx, by in vertices:
            dx, dy = bx - ax, by - ay
            cross = (px - ax) * dy - (py - ay) * dx
            boundary |= ((np.abs(cross) < 1e-10) &
                         (px >= min(ax, bx)) & (px <= max(ax, bx)) &
                         (py >= min(ay, by)) & (py <= max(ay, by)))
            if dy != 0:
                intersects = ((ay > py) != (by > py))
                x_crossing = ax + (py - ay) * dx / dy
                inside ^= intersects & (px < x_crossing)
            ax, ay = bx, by
        result[possible] |= inside | boundary
    return result


