LON, LAT = np.meshgrid(-9 + np.arange(231) / 5,
                      45 - np.arange(71) / 5)
land = np.zeros((71, 231), dtype=bool)

def polygon(text):
    numbers = [float(x) for x in text.replace(",", " ").split()]
    assert len(numbers) % 2 == 0
    points = np.array(numbers).reshape(-1, 2)
    inside = np.zeros(LON.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y0 != y1:
            crossing = ((y0 > LAT) != (y1 > LAT))
            edge_x = x0 + (LAT-y0) * (x1-x0) / (y1-y0)
            inside ^= crossing & (LON < edge_x)
        x0, y0 = x1, y1
    return inside

def add(name, text):
    global land
    land |= polygon(text)

def remove(name, text):
    global land
    land &= ~polygon(text)

