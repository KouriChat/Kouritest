def polygon_mask(spec, longitude, latitude):
    pts = [tuple(map(float, p.split(','))) for p in spec.split()]
    inside = np.zeros(longitude.shape, dtype=bool)
    for (x1, y1), (x2, y2) in zip(pts, pts[1:] + pts[:1]):
        crossing = ((y1 > latitude) != (y2 > latitude)) & (longitude < (x2-x1) * (latitude-y1) / (y2-y1 if y2 != y1 else 1) + x1)
        inside ^= crossing
    return inside

def land_mask():
    lons = np.arange(-179, 180, 2, dtype=np.float64)
    lats = np.arange(89, -90, -2, dtype=np.float64)
    longitude, latitude = np.meshgrid(lons, lats)
    land = np.zeros((90, 180), dtype=bool)
    for spec in (N_AMERICA, S_AMERICA, AFRICA, EURASIA, AUSTRALIA, GREENLAND):
        land |= polygon_mask(spec, longitude, latitude)
    for spec in ISLANDS.strip().splitlines():
        land |= polygon_mask(spec, longitude, latitude)
    for spec in SEA_HOLES.strip().splitlines():
        land &= ~polygon_mask(spec, longitude, latitude)
    # Approximate Antarctic coast by longitude, including peninsula and oceanic embayments.
    coast = np.array([
        (-179,-77),(-170,-78),(-160,-76),(-150,-75),(-140,-73),(-125,-73),(-110,-74),
        (-95,-72),(-80,-72),(-70,-69),(-66,-66),(-64,-63),(-62,-65),(-62,-69),
        (-55,-74),(-45,-77),(-30,-78),(-20,-76),(-10,-72),(0,-70),(15,-70),
        (30,-70),(40,-68),(55,-67),(70,-68),(85,-67),(100,-65),(115,-65),
        (130,-66),(145,-68),(160,-70),(170,-73),(179,-76)], dtype=float)
    land |= latitude <= np.interp(longitude, coast[:,0], coast[:,1])
    return land.astype(np.uint8)

def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    grid = land_mask()
    assert grid.shape == (90, 180) and np.isin(grid, [0, 1]).all()
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f).writerows(grid.tolist())
    original = Image.fromarray(grid * np.uint8(255), mode='L').convert('RGB')
    original.save(out / 'candidate.png')
    enlarged = original.resize((1440, 720), Image.Resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90 and all(len(row) == 180 and set(row) <= {'0','1'} for row in rows)
    with Image.open(out / 'candidate.png') as src, Image.open(out / 'candidate_8x.png') as big:
        assert src.size == (180,90) and big.size == (1440,720)
        assert set(src.getdata()) <= {(0,0,0),(255,255,255)}
        assert set(big.getdata()) <= {(0,0,0),(255,255,255)}
        assert np.array_equal(np.asarray(big), np.repeat(np.repeat(np.asarray(src),8,axis=0),8,axis=1))
    print(f'Validated {grid.size} points: {int(grid.sum())} land; files in {out.resolve()}')

if __name__ == '__main__':
    main()
