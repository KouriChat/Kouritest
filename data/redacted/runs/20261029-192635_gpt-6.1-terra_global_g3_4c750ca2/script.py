def polygon_mask(vertices, lon_grid, lat_grid):
    """Vectorized even-odd polygon test, with boundary points on land."""
    inside = np.zeros(lon_grid.shape, dtype=bool)
    on_edge = np.zeros(lon_grid.shape, dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        dx, dy = x2 - x1, y2 - y1
        cross = (lon_grid - x1) * dy - (lat_grid - y1) * dx
        on_edge |= (
            (np.abs(cross) < 1e-9)
            & (lon_grid >= min(x1, x2))
            & (lon_grid <= max(x1, x2))
            & (lat_grid >= min(y1, y2))
            & (lat_grid <= max(y1, y2))
        )
        if dy:
            crossing = (y1 > lat_grid) != (y2 > lat_grid)
            edge_x = x1 + (lat_grid - y1) * dx / dy
            inside ^= crossing & (lon_grid < edge_x)
        x1, y1 = x2, y2
    return inside | on_edge


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2)
    longitudes = np.arange(-179, 180, 2)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for polygon in POLYGONS:
        land |= polygon_mask(polygon, lon_grid, lat_grid)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert set(np.unique(matrix)) <= {0, 1}
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * 255
    original = Image.fromarray(pixels)
    original.save(output / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    enlarged.save(output / "candidate_8x.png")

    # Validate the actual serialized files, including every enlarged pixel.
    with csv_path.open(newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)
    with Image.open(output / "candidate.png") as image:
        assert image.size == (180, 90) and image.mode == "L"
        small = np.array(image)
        assert set(np.unique(small)) == {0, 255}
        assert np.array_equal(small, restored * 255)
    with Image.open(output / "candidate_8x.png") as image:
        assert image.size == (1440, 720) and image.mode == "L"
        large = np.array(image)
        assert set(np.unique(large)) == {0, 255}
        expected = np.repeat(np.repeat(small, 8, axis=0), 8, axis=1)
        assert np.array_equal(large, expected)
    print("Validated 90 x 180 matrix: 16,200 binary classifications.")
    print("Validated black/white PNGs: 180 x 90 and 1440 x 720.")
    print("Validated exact 8x nearest-neighbor enlargement.")
    print(f"Land: {matrix.sum()}; water: {matrix.size - matrix.sum()}")
    print("Outputs:", output)


if __name__ == "__main__":
    main()
