def contains_points(longitude, latitude, polygon):
    """Even/odd ray casting at each coordinate, with coast-edge inclusion."""
    inside = np.zeros(longitude.shape, dtype=bool)
    boundary = np.zeros(longitude.shape, dtype=bool)
    previous = polygon[-1]
    for current in polygon:
        x1, y1 = previous
        x2, y2 = current
        dx, dy = x2 - x1, y2 - y1
        cross = (longitude - x1) * dy - (latitude - y1) * dx
        on_segment = (
            (np.abs(cross) < 1e-10)
            & (longitude >= min(x1, x2) - 1e-10)
            & (longitude <= max(x1, x2) + 1e-10)
            & (latitude >= min(y1, y2) - 1e-10)
            & (latitude <= max(y1, y2) + 1e-10)
        )
        boundary |= on_segment
        if dy != 0:
            crosses = (y1 > latitude) != (y2 > latitude)
            intersection = x1 + (latitude - y1) * dx / dy
            inside ^= crosses & (longitude < intersection)
        previous = current
    return inside | boundary


def main():
    # Integer arithmetic defines the requested decimal-degree grid exactly
    # before conversion to floating point; rows run north to south.
    latitudes = (230 - 2 * np.arange(111)) / 10.0
    longitudes = (990 + 2 * np.arange(141)) / 10.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    land = np.zeros((111, 141), dtype=bool)
    for polygon in POLYGONS:
        land |= contains_points(longitude, latitude, polygon)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert set(np.unique(matrix)).issubset({0, 1})
    assert latitudes[0] == 23 and latitudes[-1] == 1
    assert longitudes[0] == 99 and longitudes[-1] == 127

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    enlarged = image.resize((1128, 888), resample=Image.Resampling.NEAREST)
    image.save(output / "candidate.png")
    enlarged.save(output / "candidate_8x.png")

    # Validate the actual files after reloading.
    with csv_path.open("r", newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert np.array_equal(recovered, matrix)
    with Image.open(output / "candidate.png") as saved:
        assert saved.size == (141, 111)
        original_pixels = np.array(saved)
        assert set(np.unique(original_pixels)).issubset({0, 255})
        assert np.array_equal(original_pixels, pixels)
    with Image.open(output / "candidate_8x.png") as saved:
        assert saved.size == (1128, 888)
        large_pixels = np.array(saved)
        assert set(np.unique(large_pixels)).issubset({0, 255})
        expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(large_pixels, expected)
    print("Validated: 111 x 141 = 15651 binary values; PNG 141 x 111; "
          "nearest-neighbor PNG 1128 x 888.")
    print(f"Land samples: {int(matrix.sum())}; water samples: "
          f"{int(matrix.size - matrix.sum())}")


if __name__ == "__main__":
    main()
