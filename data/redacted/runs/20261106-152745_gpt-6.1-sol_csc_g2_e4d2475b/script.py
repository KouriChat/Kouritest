def contains_points(x, y, vertices):
    """Even-odd rule on lon/lat coordinates; coastline points count as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        if dy != 0:
            crosses = (ay > y) != (by > y)
            edge_x = ax + (y - ay) * dx / dy
            inside ^= crosses & (x < edge_x)
        ax, ay = bx, by
    return inside | boundary

def main():
    # Only the requested points are classified. No cell-area averaging.
    longitude = 99.0 + np.arange(141, dtype=np.float64) / 5.0
    latitude = 23.0 - np.arange(111, dtype=np.float64) / 5.0
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((111, 141), dtype=bool)
    for name, outline in POLYGONS:
        land |= contains_points(x, y, outline)
    matrix = land.astype(np.uint8)
    assert longitude[0] == 99 and longitude[-1] == 127
    assert latitude[0] == 23 and latitude[-1] == 1
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert np.isin(matrix, (0, 1)).all()
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1128, 888), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Validate the actual serialized files, including every enlarged pixel.
    with (out / "candidate.csv").open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert restored.size == 15651 and np.array_equal(restored, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.format == "PNG" and im.mode == "L"
        assert im.size == (141, 111)
        saved_original = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.format == "PNG" and im.mode == "L"
        assert im.size == (1128, 888)
        saved_enlarged = np.array(im)
    assert set(np.unique(saved_original).tolist()) == {0, 255}
    assert set(np.unique(saved_enlarged).tolist()) == {0, 255}
    assert np.array_equal(saved_original, restored * np.uint8(255))
    expected = np.repeat(np.repeat(saved_original, 8, axis=0), 8, axis=1)
    assert np.array_equal(saved_enlarged, expected)
    digest = hashlib.sha256((out / "candidate.csv").read_bytes()).hexdigest()
    print(f"PASS: 111x141 = {matrix.size} binary values; PNG 141x111; "
          f"nearest-neighbor PNG 1128x888; land={int(matrix.sum())}; "
          f"CSV SHA256={digest}")

if __name__ == "__main__":
    main()
