def smoothstep(e0, e1, x):
    t = max(0.0, min(1.0, (x - e0) / (e1 - e0)))
    return t * t * (3 - 2 * t)

def ang(poly, lon, lat):
    x, y = lon, lat
    inside = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (y1 > y) != (y2 > y):
            xin = x1 + (y - y1) / (y2 - y1) * (x2 - x1)
            if x < xin:
                inside = not inside
    return inside

def field(poly, lon, lat):
    inside = ang(poly, lon, lat)
    best = 1e9
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        dx, dy = x2 - x1, y2 - y1
        L2 = dx * dx + dy * dy
        if L2 == 0:
            d = math.hypot(lon - x1, lat - y1)
        else:
            t = max(0.0, min(1.0, ((lon - x1) * dx + (lat - y1) * dy) / L2))
            d = math.hypot(lon - (x1 + t * dx), lat - (y1 + t * dy))
        best = min(best, d)
    return -(best + 0.03) if inside else best
