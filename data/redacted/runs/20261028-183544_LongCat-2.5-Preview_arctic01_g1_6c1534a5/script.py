def continent(lat, lon):
    yb = 73.0
    if 95.0 <= lon <= 105.0:
        yb = 73.0 - 0.45 * (lon - 95.0)
    ym = 70.0
    if 85.0 <= lon <= 95.0:
        ym = 70.0 - 0.5 * (lon - 85.0)
    yw = 67.5
    if 81.0 <= lon <= 85.0:
        yw = 67.5 - 0.4 * (lon - 81.0)
    if 95.0 <= lon <= 105.0 and lat > yb:
        return True
    if 85.0 <= lon <= 95.0 and lat > ym:
        return True
    if 81.0 <= lon <= 85.0 and lat > yw:
        return True
    if lon < 81.0 and lat > 66.0:
        return True
    if lon > 105.0 and lat > 68.0:
        return True
    return False

def inland_lake(lat, lon):
    if -122.0 <= lon <= -118.0 and 65.0 <= lat <= 67.0:
        if -121.5 <= lon <= -120.5 and 66.0 <= lat <= 67.0:
            return True
        if -120.5 <= lon <= -119.0 and 65.5 <= lat <= 66.5:
            return True
    if -116.0 <= lon <= -113.0 and 61.0 <= lat <= 62.5:
        return True
    if -72.0 <= lon <= -70.0 and 81.5 <= lat <= 82.5:
        return True
    if -71.0 <= lon <= -69.0 and 66.0 <= lat <= 67.0:
        return True
    return False

def is_land(lat, lon):
    if lat < 73.0 or lat > 79.0 or lon < -105.0 or lon > -81.0:
        return False
    for p in ISLAND_POLYS:
        if field(p, lon, lat) < 0.0:
            return True
    if continent(lat, lon):
        return True
    if inland_lake(lat, lon):
        return True
    if -88.0 <= lon <= -81.0 and 64.0 <= lat <= 66.0:
        return False
    return False

def build_matrix():
    M = np.zeros((61, 241), dtype=np.uint8)
    for i, lat in enumerate(LATS):
        for j, lon in enumerate(LONS):
            M[i, j] = 1 if is_land(lat, lon) else 0
    return M
