"""Approximate Mediterranean land mask from manually remembered coastlines.

No map, geographic database, network access, or reference answer is used.
Classification is vectorized point-in-polygon, not independent LLM inference.
Coordinates below are deliberately approximate longitude/latitude vertices.
Inland lakes count as land; only marine water polygons are subtracted.
Run: python outputs/generate_map.py ; dependencies: numpy, Pillow.
"""
from pathlib import Path
