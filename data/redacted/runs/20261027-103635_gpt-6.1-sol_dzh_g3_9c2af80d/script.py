LANDS = []
WATERS = []


def polygon(text):
    return [tuple(map(float, item.split(','))) for item in text.split()]


def land(text):
    LANDS.append(polygon(text))


def water(text):
    WATERS.append(polygon(text))


def inside(x, y, vertices):
    result = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if dy != 0:
            crossing_x = ax + (y - ay) * dx / dy
            result ^= ((ay > y) != (by > y)) & (x < crossing_x)
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-10)
                     & (x >= min(ax, bx) - 1e-10)
                     & (x <= max(ax, bx) + 1e-10)
                     & (y >= min(ay, by) - 1e-10)
                     & (y <= max(ay, by) + 1e-10))
        ax, ay = bx, by
    return result | boundary


