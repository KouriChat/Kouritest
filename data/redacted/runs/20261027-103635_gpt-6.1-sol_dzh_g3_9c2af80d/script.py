def main():
    # Integer ticks avoid accumulated floating-point steps and endpoint drift.
    latitudes = np.arange(225, 154, -1, dtype=np.int64) / 5.0
    longitudes = np.arange(-45, 186, dtype=np.int64) / 5.0
    x, y = np.meshgrid(longitudes, latitudes)
    mask = np.zeros(x.shape, dtype=bool)
    for outline in LANDS[:MAINLAND_COUNT]:
        mask |= inside(x, y, outline)
    for outline in WATERS:
        mask &= ~inside(x, y, outline)
    # Islands override the broad sea outlines, including Marmara islands.
    for outline in LANDS[MAINLAND_COUNT:]:
        mask |= inside(x, y, outline)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert latitudes[0] == 45 and latitudes[-1] == 31
    assert longitudes[0] == -9 and longitudes[-1] == 37
    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / 'candidate.csv'
    with csv_path.open('w', encoding='ascii', newline='') as stream:
        csv.writer(stream, lineterminator='\n').writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / 'candidate.png')
    nearest = getattr(Image, 'Resampling', Image).NEAREST
    image.resize((1848, 568), resample=nearest).save(
        out / 'candidate_8x.png')
    validate(out, matrix)


def validate(out, expected):
    with (out / 'candidate.csv').open(encoding='ascii', newline='') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert recovered.size == 16401
    assert np.array_equal(recovered, expected)
    with Image.open(out / 'candidate.png') as source:
        source.load()
        assert source.size == (231, 71) and source.mode == 'L'
        small = np.array(source)
    with Image.open(out / 'candidate_8x.png') as enlarged:
        enlarged.load()
        assert enlarged.size == (1848, 568) and enlarged.mode == 'L'
        big = np.array(enlarged)
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(small, expected * np.uint8(255))
    exact_nearest = np.repeat(np.repeat(small, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, exact_nearest)
    print(json.dumps({
        'shape': list(recovered.shape), 'valid_values': int(recovered.size),
        'land': int(recovered.sum()),
        'water': int(recovered.size - recovered.sum()),
        'original_png': [231, 71], 'enlarged_png': [1848, 568],
        'black_white_only': True, 'nearest_neighbor_verified': True,
        'method': 'handwritten approximate polygons; vectorized point tests',
        'external_geographic_data_used': False,
    }, ensure_ascii=False))


if __name__ == '__main__':
    main()
