def polygon_mask(vertices):
    """Vectorized point-in-polygon classification on the sample points."""
    inside = np.zeros((N, N), dtype=bool)
    xj, yj = vertices[-1]
    for xi, yi in vertices:
        crossing = ((yi > Y) != (yj > Y))
        denominator = yj - yi
        if denominator == 0:
            denominator = 1.0e-15
        edge_x = (xj - xi) * (Y - yi) / denominator + xi
        inside ^= crossing & (X < edge_x)
        xj, yj = xi, yi
    return inside


def ellipse_mask(lon, lat, rx, ry, angle_degrees=0.0):
    """Point mask for a hand-placed small island or islet cluster."""
    angle = np.deg2rad(angle_degrees)
    dx = X - lon
    dy = Y - lat
    u = dx * np.cos(angle) + dy * np.sin(angle)
    v = -dx * np.sin(angle) + dy * np.cos(angle)
    return (u / rx) ** 2 + (v / ry) ** 2 <= 1.0


