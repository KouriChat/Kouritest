def point_in_polygon(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                inside = not inside
        j = i
    return inside

def build_matrix():
    matrix = []
    for lat in range(89, -90, -2):
        row = []
        for lon in range(-179, 180, 2):
            row.append(int(any(point_in_polygon(lon, lat, p) for p in POLYGONS)))
        matrix.append(row)
    return matrix
def main():
    output_dir = "outputs"
    os.makedirs(output_dir, exist_ok=True)
    matrix = build_matrix()
    with open(os.path.join(output_dir, "candidate.csv"), "w", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix)
    # Pillow's mode "1" gives exactly black water and white land.
    pixels = np.asarray(matrix, dtype=np.uint8) * 255
    image = Image.fromarray(pixels, mode="L").convert("1")
    image.save(os.path.join(output_dir, "candidate.png"))
    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(os.path.join(output_dir, "candidate_8x.png"))

if __name__ == "__main__":
    main()
