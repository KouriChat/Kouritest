def inside(x, y, poly):
    """Vectorized even-odd test for points in a hand-written polygon."""
    p = np.asarray(poly, dtype=float)
    result = np.zeros(x.shape, dtype=bool)
    j = len(p) - 1
    for i, (xi, yi) in enumerate(p):
        xj, yj = p[j]
        cross = ((yi > y) != (yj > y)) & (
            x < (xj-xi) * (y-yi) / ((yj-yi) or 1e-30) + xi)
        result ^= cross
        j = i
    return result

def main():
    os.makedirs("outputs", exist_ok=True)
    lat = 35.0 - np.arange(64) * (2.0 / 63.0)
    lon = 129.0 + np.arange(253) * (8.0 / 252.0)
    xx, yy = np.meshgrid(lon, lat)
    land = np.zeros((64, 253), dtype=bool)
    for poly in POLYGONS:
        land |= inside(xx, yy, poly)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    with open("outputs/candidate.csv", "w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L")
    image.save("outputs/candidate.png")
    image.resize((2024, 512), Image.Resampling.NEAREST).save(
        "outputs/candidate_8x.png")
    with open("outputs/candidate.csv", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64 and all(len(r) == 253 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    original = np.asarray(Image.open("outputs/candidate.png"))
    assert original.shape == (64, 253) and set(np.unique(original)) <= {0, 255}
    assert Image.open("outputs/candidate_8x.png").size == (2024, 512)

if __name__ == "__main__":
    main()

