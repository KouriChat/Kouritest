def inside_polygon(x, y, polygon):
    inside = np.zeros(x.shape, dtype=bool)
    vertices = np.asarray(polygon, dtype=float)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        crosses = (y1 > y) != (y2 > y)
        x_cross = (x2 - x1) * (y - y1) / ((y2 - y1) + 1e-30) + x1
        inside ^= crosses & (x < x_cross)
        x1, y1 = x2, y2
    return inside


def main():
    latitudes = 23.0 - 0.2 * np.arange(111)
    longitudes = 99.0 + 0.2 * np.arange(141)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((111, 141), dtype=bool)
    for polygon in POLYGONS:
        land |= inside_polygon(lon_grid, lat_grid, polygon)
    for lon, lat, rx, ry in REEFS:
        land |= ((lon_grid - lon) / rx) ** 2 + ((lat_grid - lat) / ry) ** 2 <= 1
    matrix = land.astype(np.uint8)

    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    with (output / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        for row in matrix:
            f.write(",".join(map(str, row.tolist())) + "\n")

    image = Image.fromarray(np.where(matrix, 255, 0).astype(np.uint8), mode="L")
    image.save(output / "candidate.png")
    image.resize((1128, 888), resample=Image.Resampling.NEAREST).save(
        output / "candidate_8x.png"
    )
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert image.size == (141, 111) and set(image.getdata()) <= {0, 255}
    assert Image.open(output / "candidate_8x.png").size == (1128, 888)


if __name__ == "__main__":
    main()
