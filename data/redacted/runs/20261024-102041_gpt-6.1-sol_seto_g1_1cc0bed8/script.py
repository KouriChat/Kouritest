LAND = []
SEA = []


def polygon(name, text, water=False):
    vertices = [tuple(map(float, p.split(","))) for p in text.split()]
    assert len(vertices) >= 3, name
    (SEA if water else LAND).append((name, vertices))


def oval(name, lon, lat, rx, ry, angle=0):
    """A handwritten small-island approximation, axes in coordinate degrees."""
    a = math.radians(angle)
    vertices = []
    for t in np.linspace(0, 2 * math.pi, 20, endpoint=False):
        u, v = rx * math.cos(t), ry * math.sin(t)
        vertices.append((lon + u * math.cos(a) - v * math.sin(a),
                         lat + u * math.sin(a) + v * math.cos(a)))
    LAND.append((name, vertices))


