latitude = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
X, Y = np.meshgrid(longitude, latitude)
land = np.zeros((64, 253), dtype=bool)
rules = []

def polygon(name, text, value=True):
    """Ray casting at each sampling coordinate; no external geometry library."""
    vertices = [tuple(map(float, t.split(','))) for t in text.split()]
    inside = np.zeros_like(land)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crossing_x = ax + (Y - ay) * (bx - ax) / (by - ay)
            inside ^= ((ay > Y) != (by > Y)) & (X < crossing_x)
        ax, ay = bx, by
    land[inside] = value
    rules.append({'name': name, 'kind': 'polygon', 'vertices': vertices,
                  'land': bool(value)})

def ellipse(name, lon, lat, east_radius, north_radius, angle=0.0):
    """Small-island approximation; angle in degrees in lon/lat coordinates."""
    theta = np.deg2rad(angle)
    dx, dy = X - lon, Y - lat
    u = dx * np.cos(theta) + dy * np.sin(theta)
    v = -dx * np.sin(theta) + dy * np.cos(theta)
    land[(u / east_radius)**2 + (v / north_radius)**2 <= 1.0] = True
    rules.append({'name': name, 'kind': 'ellipse', 'center': [lon, lat],
                  'radii': [east_radius, north_radius], 'angle': angle})
