    # Only the requested 16,129 points are classified. Polygon vertices may
    # extend beyond the frame to avoid treating the frame as a coastline.
    # Haida Gwaii's coastline at these latitudes is west of this longitude box.
    mask = np.zeros((N, N), dtype=bool)
    for _, vertices in LAND:
        mask |= inside(vertices)
    for _, vertices in WATER:
        mask &= ~inside(vertices)
    for _, half_width, vertices in CHANNELS:
        mask &= ~channel_mask(vertices, half_width)
    matrix = mask.astype(np.uint8)

    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    enlarged = original.resize((1016, 1016), resample=nearest)
    original.save(out / "candidate.png", format="PNG")
    enlarged.save(out / "candidate_8x.png", format="PNG")

    # Validate the actual saved files, not just the arrays before writing.
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert np.isin(matrix, (0, 1)).all()
    assert latitude[0] == 55.0 and latitude[-1] == 53.0
    assert longitude[0] == -131.0 and longitude[-1] == -129.0
    assert np.all(np.diff(latitude) < 0) and np.all(np.diff(longitude) > 0)
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    loaded_csv = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(loaded_csv, matrix)

    with Image.open(out / "candidate.png") as image:
        assert image.size == (127, 127) and image.mode == "L"
        saved_original = np.asarray(image).copy()
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1016, 1016) and image.mode == "L"
        saved_enlarged = np.asarray(image).copy()
    assert set(np.unique(saved_original).tolist()) == {0, 255}
    assert set(np.unique(saved_enlarged).tolist()) == {0, 255}
    assert np.array_equal(saved_original, loaded_csv * np.uint8(255))
    expected_8x = np.repeat(np.repeat(saved_original, 8, axis=0), 8, axis=1)
    assert np.array_equal(saved_enlarged, expected_8x)
    assert np.array_equal(saved_enlarged[::8, ::8], saved_original)

    report = {
        "method": "Handwritten knowledge-only polygons and marine channel rules;"
                  " vectorized point classification, no external geography.",
        "matrix_shape": [127, 127],
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_no_header_binary_complete": True,
        "original_image_size": [127, 127],
        "enlarged_image_size": [1016, 1016],
        "image_values": [0, 255],
        "nearest_neighbor_8x_verified": True,
        "geographic_accuracy": "Unverified approximation; not a surveyed map.",
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print("VALIDATED: 127x127 = 16129 binary points; PNG 127x127;"
          " PNG 1016x1016; exact 8x nearest-neighbor.")


