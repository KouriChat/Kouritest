latitude = 55.0 - np.arange(N, dtype=np.float64) * (2.0 / 126.0)
X, Y = np.meshgrid(longitude, latitude)
LAND = []
WATER = []
CHANNELS = []


def points(text):
    return [tuple(map(float, pair.split(","))) for pair in text.split()]


def land(name, text):
    LAND.append((name, points(text)))


def water(name, text):
    WATER.append((name, points(text)))


def channel(name, half_width_km, text):
    CHANNELS.append((name, half_width_km, points(text)))


def inside(vertices):
    """Ray crossing at the actual grid points; no cell averaging."""
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crossing_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= ((y0 > Y) != (y1 > Y)) & (X < crossing_x)
        x0, y0 = x1, y1
    return result


def channel_mask(vertices, half_width_km):
    """Distance to a handwritten channel centreline in a local km plane."""
    result = np.zeros(X.shape, dtype=bool)
    px, py = X * 65.4, Y * 111.2
    for (x0, y0), (x1, y1) in zip(vertices[:-1], vertices[1:]):
        ax, ay, bx, by = x0 * 65.4, y0 * 111.2, x1 * 65.4, y1 * 111.2
        dx, dy = bx - ax, by - ay
        t = np.clip(((px - ax) * dx + (py - ay) * dy) / (dx*dx + dy*dy),
                    0.0, 1.0)
        result |= (px - ax - t*dx)**2 + (py - ay - t*dy)**2 <= half_width_km**2
    return result


