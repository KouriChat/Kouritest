"""Knowledge-only, hand-drawn approximation of the northern BC coast.

Run from the desired working directory: python outputs/generate_map.py
Dependencies: numpy, Pillow. No geographic data files or network are used.
Classification is vectorized point-in-polygon plus hand-specified marine
channels, NOT independent language-model reasoning for the 16,129 points.
All coordinates below are approximate recollections, not surveyed coastlines.
Inland lakes are deliberately not removed from land.
"""
