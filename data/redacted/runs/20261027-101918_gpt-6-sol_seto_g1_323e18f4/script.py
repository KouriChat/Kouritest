def parse_poly(line):
    label, coords = line.split('|', 1)
    verts = [tuple(map(float, p.split(','))) for p in coords.split()]
    assert len(verts) >= 3, label
    xs, ys = zip(*verts)
    return (min(xs), max(xs), min(ys), max(ys)), verts


POLYS = [parse_poly(s.strip()) for s in SHORES.strip().splitlines()]
OVALS = [tuple(map(float, s.split(','))) for s in ISLETS.split()]


def inside_polygon(x, y, vertices):
    """Even-odd point rule; not grid cell coverage or independent LLM calls."""
    contained = False
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if (y0 > y) != (y1 > y):
            if x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
                contained = not contained
        x0, y0 = x1, y1
    return contained


def is_land(x, y):
    for (xmin, xmax, ymin, ymax), vertices in POLYS:
        if xmin <= x <= xmax and ymin <= y <= ymax:
            if inside_polygon(x, y, vertices):
                return 1
    for cx, cy, rx, ry in OVALS:
        if abs(x - cx) <= rx and abs(y - cy) <= ry:
            if ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1:
                return 1
    return 0


def main():
    target = Path('outputs')
    target.mkdir(exist_ok=True)
    # Both intervals equal 2/63 degrees. Endpoints are included exactly.
    rows = [[is_land(129 + j * 2 / 63, 35 - i * 2 / 63)
             for j in range(253)] for i in range(64)]
    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert all(value in (0, 1) for row in rows for value in row)
    with (target / 'candidate.csv').open('w', encoding='ascii', newline='') as f:
        csv.writer(f).writerows(rows)
    image = Image.new('L', (253, 64))
    image.putdata([v * 255 for row in rows for v in row])
    large = image.resize((2024, 512), Image.Resampling.NEAREST)
    image.save(target / 'candidate.png')
    large.save(target / 'candidate_8x.png')
    with (target / 'candidate.csv').open(newline='', encoding='ascii') as f:
        saved = [[int(cell) for cell in row] for row in csv.reader(f)]
    assert saved == rows and set(image.getdata()) <= {0, 255}
    assert large.size == (2024, 512) and set(large.getdata()) <= {0, 255}
    assert all(large.getpixel((x, y)) == image.getpixel((x // 8, y // 8))
               for y in range(512) for x in range(2024))
    print(f'Validated: {len(rows)} x {len(rows[0])}, '
          f'{sum(map(sum, rows))} land points, 2 binary PNGs')


if __name__ == '__main__':
    main()
