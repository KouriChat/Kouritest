def inside_polygon(lon, lat, vertices):
    """Ray-casting point-in-polygon classification over the sample grid."""
    result = np.zeros(lon.shape, dtype=bool)
    count = len(vertices)
    for index in range(count):
        x1, y1 = vertices[index]
        x2, y2 = vertices[(index + 1) % count]
        if y1 == y2:
            continue
        crosses = (y1 > lat) != (y2 > lat)
        intersection_x = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
        result ^= crosses & (lon < intersection_x)
    return result


def main():
    longitude = 99.0 + np.arange(141, dtype=np.float64) * .2
    latitude = 23.0 - np.arange(111, dtype=np.float64) * .2
    lon, lat = np.meshgrid(longitude, latitude)
    land = np.zeros((111, 141), dtype=bool)
    for vertices in POLYGONS:
        land |= inside_polygon(lon, lat, vertices)
    for center_lon, center_lat, radius_lon, radius_lat in ELLIPSES:
        distance = (((lon - center_lon) / radius_lon) ** 2
                    + ((lat - center_lat) / radius_lat) ** 2)
        land |= distance <= 1.0
    matrix = land.astype(np.uint8)
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as file:
        writer = csv.writer(file, lineterminator="\n")
        writer.writerows(matrix.tolist())
    original = Image.fromarray(matrix * 255, mode="L")
    original.save(output / "candidate.png")
    enlarged = original.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    # Check the output files, not merely their in-memory inputs.
    with csv_path.open("r", encoding="ascii", newline="") as file:
        rows = list(csv.reader(file))
    assert matrix.shape == (111, 141)
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 15651
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(output / "candidate.png") as image:
        actual_original = np.asarray(image.convert("L"))
        assert image.size == (141, 111)
    with Image.open(output / "candidate_8x.png") as image:
        actual_enlarged = np.asarray(image.convert("L"))
        assert image.size == (1128, 888)
    assert set(np.unique(actual_original).tolist()) <= {0, 255}
    assert set(np.unique(actual_enlarged).tolist()) <= {0, 255}
    expected = np.repeat(np.repeat(actual_original, 8, axis=0), 8, axis=1)
    assert np.array_equal(actual_enlarged, expected)
    print("Generated and validated all three output files.")


if __name__ == "__main__":
    main()
