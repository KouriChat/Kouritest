def polygon_membership(lon_grid, lat_grid, coordinates):
    """Vectorized ray crossing with coast/boundary points assigned to land."""
    inside = np.zeros(lon_grid.shape, dtype=bool)
    boundary = np.zeros(lon_grid.shape, dtype=bool)
    eps = 1e-10
    x1, y1 = coordinates[-1]
    for x2, y2 in coordinates:
        dx, dy = x2 - x1, y2 - y1
        if dx != 0 or dy != 0:
            cross = (lon_grid - x1) * dy - (lat_grid - y1) * dx
            on_segment = (
                (np.abs(cross) <= eps)
                & (lon_grid >= min(x1, x2) - eps)
                & (lon_grid <= max(x1, x2) + eps)
                & (lat_grid >= min(y1, y2) - eps)
                & (lat_grid <= max(y1, y2) + eps)
            )
            boundary |= on_segment
        if dy != 0:
            cuts_row = (y1 > lat_grid) != (y2 > lat_grid)
            intersection = x1 + (lat_grid - y1) * dx / dy
            inside ^= cuts_row & (lon_grid < intersection)
        x1, y1 = x2, y2
    return inside | boundary


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Integer-derived coordinates avoid accumulation from repeated +/-0.2.
    longitudes = np.arange(495, 636, dtype=np.int64) / 5.0
    latitudes = np.arange(115, 4, -1, dtype=np.int64) / 5.0
    assert len(latitudes) == 111 and len(longitudes) == 141
    assert (latitudes[0], latitudes[-1]) == (23.0, 1.0)
    assert (longitudes[0], longitudes[-1]) == (99.0, 127.0)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((111, 141), dtype=bool)
    for name, coordinates in POLYGONS:
        assert len(coordinates) >= 3, name
        mask |= polygon_membership(lon_grid, lat_grid, coordinates)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert set(np.unique(matrix).tolist()) == {0, 1}

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    assert original.mode == "L"
    original.save(out / "candidate.png")
    # Pillow's NEAREST never averages or interpolates the classified samples.
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1128, 888), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Read back only our own generated artifacts, never any map/reference data.
    with csv_path.open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    reread = np.array(rows, dtype=np.uint8)
    assert reread.size == 15651 and np.array_equal(reread, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (141, 111) and im.mode == "L"
        raw = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1128, 888) and im.mode == "L"
        big = np.array(im)
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, matrix * 255)
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected), "Not exact nearest-neighbor scaling"
    checks = {
        "method": "Hand-written memory-only polygons; vectorized point membership",
        "external_geographic_data": False,
        "shape": list(matrix.shape),
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_no_header_no_missing_binary_only": True,
        "original_png_size": [141, 111],
        "enlarged_png_size": [1128, 888],
        "png_pixel_values": [0, 255],
        "exact_nearest_neighbor_8x": True,
        "dependencies": ["numpy", "Pillow"],
        "accuracy_note": "Approximation from prior knowledge, not a reference map",
    }
    (out / "validation.json").write_text(
        json.dumps(checks, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(checks, ensure_ascii=False))


