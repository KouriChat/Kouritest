# Hand-drawn geographic reconstruction: no files, maps, APIs, or geographic
# libraries are read.  Coordinates below are remembered approximate outlines.
def in_poly(x, y, p):
    inside = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]; xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            cut = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x <= cut:
                inside = not inside
        j = i
    return inside

def ellipse(x, y, cx, cy, rx, ry, angle=0):
    a = math.radians(angle)
    dx, dy = x-cx, y-cy
    u = dx*math.cos(a) + dy*math.sin(a)
    v = -dx*math.sin(a) + dy*math.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1

