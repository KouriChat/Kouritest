def is_land(x, y):
    if any(in_poly(x, y, p) for p in POLYS):
        return 1
    if any(ellipse(x, y, *q) for q in ISLANDS):
        return 1
    key = (round(x,1), round(y,1))
    return int(key in REEF_POINTS)

def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    lats = np.round(np.arange(23.0, 0.99, -0.2), 1)
    lons = np.round(np.arange(99.0, 127.01, 0.2), 1)
    a = np.array([[is_land(float(x), float(y)) for x in lons]
                  for y in lats], dtype=np.uint8)
    assert a.shape == (111, 141) and a.size == 15651
    assert set(np.unique(a)).issubset({0, 1})

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(a.tolist())

    raw = Image.fromarray(a * 255, mode="L")
    raw.save(out / "candidate.png")
    big = raw.resize((1128, 888), resample=Image.Resampling.NEAREST)
    big.save(out / "candidate_8x.png")

    # Re-open and verify delivered encodings and exact nearest-neighbour blocks.
    rows = list(csv.reader((out / "candidate.csv").open(encoding="ascii")))
    assert len(rows) == 111 and all(len(r) == 141 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    r = np.array(Image.open(out / "candidate.png"))
    b = np.array(Image.open(out / "candidate_8x.png"))
    assert r.shape == (111,141) and b.shape == (888,1128)
    assert set(np.unique(r)) <= {0,255} and set(np.unique(b)) <= {0,255}
    assert np.array_equal(b, np.repeat(np.repeat(r,8,axis=0),8,axis=1))
    print("validated:", a.shape, a.size, "land points:", int(a.sum()))

if __name__ == "__main__":
    main()
