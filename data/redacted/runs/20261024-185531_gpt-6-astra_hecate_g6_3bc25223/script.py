N = 127
longitude = -131.0 + np.arange(N, dtype=float) * (2.0 / 126.0)
latitude = 55.0 - np.arange(N, dtype=float) * (2.0 / 126.0)
X, Y = np.meshgrid(longitude, latitude)
land = np.zeros((N, N), dtype=bool)


def polygon(text, value=True):
    """Apply a manually drawn polygon using point-in-polygon ray crossing."""
    vertices = np.array([tuple(map(float, p.split(",")))
                         for p in text.split()], dtype=float)
    inside = np.zeros_like(land)
    boundary = np.zeros_like(land)
    for i in range(len(vertices)):
        ax, ay = vertices[i - 1]
        bx, by = vertices[i]
        dx, dy = bx - ax, by - ay
        if dy != 0.0:
            cross_x = ax + (Y - ay) * dx / dy
            inside ^= ((ay > Y) != (by > Y)) & (X < cross_x)
        cross = (X - ax) * dy - (Y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-12)
                     & (X >= min(ax, bx)) & (X <= max(ax, bx))
                     & (Y >= min(ay, by)) & (Y <= max(ay, by)))
    land[inside | boundary] = value


