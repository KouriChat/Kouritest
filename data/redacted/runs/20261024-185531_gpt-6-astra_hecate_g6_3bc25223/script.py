"""Knowledge-only approximate reconstruction; no external geographic data.

Handwritten WGS84 coastline polygons are evaluated at the exact sample
coordinates, not independently inferred at each point. Inland lakes remain
land. Shapes deliberately approximate uncertain islands and tidal inlets.
Run from any working directory: python outputs/generate_map.py
Dependencies: Python 3, numpy, Pillow.
"""
