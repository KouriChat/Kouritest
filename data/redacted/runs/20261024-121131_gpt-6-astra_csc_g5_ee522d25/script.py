LONGITUDES = (990 + 2 * np.arange(141)) / 10.0
LATITUDES = (230 - 2 * np.arange(111)) / 10.0
X, Y = np.meshgrid(LONGITUDES, LATITUDES)
LAND = np.zeros(X.shape, dtype=bool)
OUTLINES = {}


def polygon(name, vertices):
    """Union a memorized outline into the mask, using point containment."""
    OUTLINES[name] = vertices
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        cross = (X - ax) * (by - ay) - (Y - ay) * (bx - ax)
        boundary |= ((np.abs(cross) < 1e-10) &
                     (X >= min(ax, bx) - 1e-10) &
                     (X <= max(ax, bx) + 1e-10) &
                     (Y >= min(ay, by) - 1e-10) &
                     (Y <= max(ay, by) + 1e-10))
        if ay != by:
            inside ^= (((ay > Y) != (by > Y)) &
                       (X < ax + (Y - ay) * (bx - ax) / (by - ay)))
        ax, ay = bx, by
    LAND[:] |= inside | boundary


