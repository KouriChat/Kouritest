def base_land(lon, lat):
    return any_poly(lon, lat, [
        NORTH_AMERICA, SOUTH_AMERICA, EURASIA, AFRICA, AUSTRALIA, ANTARCTICA
    ])

def island_land(lon, lat):
    if any_poly(lon, lat, ISLAND_POLYS):
        return True
    return any(ellipse(lon, lat, *e) for e in ISLAND_ELLIPSES)
