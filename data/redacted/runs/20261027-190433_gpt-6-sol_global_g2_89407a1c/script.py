def land_at(lon, lat):
    land = base_land(lon, lat) or island_land(lon, lat)
    if not land:
        return False
    if any_poly(lon, lat, WATER_HOLES):
        return False
    # The Mediterranean boundary also removes the overlap between Africa
    # and Eurasia in this deliberately coarse construction.
    return True

def make_matrix():
    rows = []
    for lat in range(89, -90, -2):
        rows.append([1 if land_at(lon, lat) else 0
                     for lon in range(-179, 180, 2)])
    return np.asarray(rows, dtype=np.uint8)

def write_outputs(matrix):
    with (OUT / "candidate.csv").open("w", newline="", encoding="ascii") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerows(matrix.tolist())
    raw = np.where(matrix == 1, 255, 0).astype(np.uint8)
    image = Image.fromarray(raw, mode="L")
    image.save(OUT / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        OUT / "candidate_8x.png"
    )

if __name__ == "__main__":
    matrix = make_matrix()
    if matrix.shape != (90, 180):
        raise ValueError(matrix.shape)
    if not np.isin(matrix, (0, 1)).all():
        raise ValueError("matrix contains values other than 0 and 1")
    write_outputs(matrix)
