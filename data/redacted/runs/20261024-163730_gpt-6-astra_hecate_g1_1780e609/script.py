def inside(x, y, vertices):
    """Even-odd point-in-polygon test on the exact sampling coordinates."""
    hit = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crossing = (ay > y) != (by > y)
            edge_x = ax + (y - ay) * (bx - ax) / (by - ay)
            hit ^= crossing & (x < edge_x)
        ax, ay = bx, by
    return hit

