def small_island(name, lon, lat, rx, ry, angle=0.0):
    """Manually positioned oval approximation; radii are degrees."""
    t = np.linspace(0.0, 2.0 * np.pi, 32, endpoint=False)
    a = np.deg2rad(angle)
    u, v = rx * np.cos(t), ry * np.sin(t)
    polygon(name, list(zip(lon + u*np.cos(a) - v*np.sin(a),
                           lat + u*np.sin(a) + v*np.cos(a))))


