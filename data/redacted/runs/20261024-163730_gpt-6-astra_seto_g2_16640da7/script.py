def contains(vertices, longitude, latitude):
    """Vectorized odd/even ray crossing at the actual sample coordinates."""
    result = np.zeros(longitude.shape, dtype=bool)
    xmin, ymin = vertices.min(axis=0)
    xmax, ymax = vertices.max(axis=0)
    eligible = ((longitude >= xmin) & (longitude <= xmax)
                & (latitude >= ymin) & (latitude <= ymax))
    if not eligible.any():
        return result
    x, y = longitude[eligible], latitude[eligible]
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crosses = ((y0 > y) != (y1 > y))
            crossing_x = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (x < crossing_x)
        x0, y0 = x1, y1
    result[eligible] = inside
    return result


def generate():
    # Use the exact 2/63 degree interval, not the rounded example labels.
    latitudes = 35.0 - (2.0 / 63.0) * np.arange(64, dtype=np.float64)
    longitudes = 129.0 + (2.0 / 63.0) * np.arange(253, dtype=np.float64)
    assert latitudes[0] == 35.0 and latitudes[-1] == 33.0
    assert longitudes[0] == 129.0 and longitudes[-1] == 137.0
    xx, yy = np.meshgrid(longitudes, latitudes)
    land = np.zeros((64, 253), dtype=bool)
    for name, vertices in LAND:
        land |= contains(vertices, xx, yy)
    for name, vertices in WATER:
        land &= ~contains(vertices, xx, yy)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert np.isin(matrix, [0, 1]).all()
    return matrix


def save_and_validate(matrix):
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    png_path = output / "candidate.png"
    big_path = output / "candidate_8x.png"

    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = (matrix * 255).astype(np.uint8)
    original = Image.fromarray(pixels)
    original.save(png_path, format="PNG")
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    enlarged = original.resize((2024, 512), resample=nearest)
    enlarged.save(big_path, format="PNG")

    # Re-open the actual delivered files; do not only check in-memory objects.
    with csv_path.open("r", newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    loaded = np.array(rows, dtype=np.uint8)
    assert loaded.size == 16192
    assert np.array_equal(loaded, matrix)

    with Image.open(png_path) as im:
        assert im.size == (253, 64) and im.mode == "L"
        original_pixels = np.array(im)
    with Image.open(big_path) as im:
        assert im.size == (2024, 512) and im.mode == "L"
        enlarged_pixels = np.array(im)
    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, pixels)
    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged_pixels, expected)

    report = {
        "method": "Memory-written polygons; vectorized point-in-polygon rules.",
        "external_geographic_data_used": False,
        "shape": [64, 253],
        "valid_values": int(matrix.size),
        "land_values": int(matrix.sum()),
        "water_values": int(matrix.size - matrix.sum()),
        "csv_no_header_no_gaps_binary": True,
        "original_png_size": [253, 64],
        "enlarged_png_size": [2024, 512],
        "png_colors": [0, 255],
        "nearest_neighbor_exactly_verified": True,
        "manual_land_outlines": len(LAND),
        "verification_passed": True,
    }
    with (output / "validation.json").open("w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    print(json.dumps(report, ensure_ascii=False))


