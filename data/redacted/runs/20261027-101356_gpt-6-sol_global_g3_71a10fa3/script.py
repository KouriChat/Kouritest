def inside_polygon(x, y, points):
    hit = False
    j = len(points) - 1
    for i, (xi, yi) in enumerate(points):
        xj, yj = points[j]
        if (yi > y) != (yj > y):
            boundary = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < boundary:
                hit = not hit
        j = i
    return hit


# Approximate mainland Antarctic coastline; floating ice shelves are water.
ANTARCTIC_COAST = [
    (-180, -74), (-165, -76), (-150, -78), (-135, -77),
    (-120, -76), (-100, -75), (-80, -73), (-72, -70),
    (-69, -67), (-64, -64), (-60, -63), (-56, -65),
    (-50, -73), (-30, -76), (-15, -73), (0, -70),
    (20, -69), (40, -68), (60, -66), (80, -67),
    (100, -66), (120, -66), (140, -67), (160, -69),
    (180, -74),
]
def antarctica(lon, lat):
    for (x0, y0), (x1, y1) in zip(
        ANTARCTIC_COAST, ANTARCTIC_COAST[1:]
    ):
        if x0 <= lon <= x1:
            coast_lat = y0 + (y1 - y0) * (lon - x0) / (x1 - x0)
            return lat <= coast_lat
    return False


def land_at(lon, lat):
    if antarctica(lon, lat):
        return 1
    return int(any(inside_polygon(lon, lat, p) for p in LAND_POLYGONS))


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)

    matrix = np.array(
        [[land_at(lon, lat) for lon in range(-179, 180, 2)]
         for lat in range(89, -90, -2)],
        dtype=np.uint8,
    )
    assert matrix.shape == (90, 180)
    assert matrix.size == 16200
    assert set(np.unique(matrix).tolist()) <= {0, 1}

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file, lineterminator="\n")
        writer.writerows(matrix.tolist())

    original = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    enlarged = original.resize((1440, 720), Image.Resampling.NEAREST)
    original.save(out / "candidate.png")
    enlarged.save(out / "candidate_8x.png")

    with csv_path.open(newline="", encoding="utf-8") as file:
        rows = list(csv.reader(file))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)

    with Image.open(out / "candidate.png") as image:
        assert image.size == (180, 90)
        pixels = np.asarray(image.convert("RGB"))
    assert set(map(tuple, pixels.reshape(-1, 3))) <= {
        (0, 0, 0), (255, 255, 255)
    }
    assert np.array_equal(pixels[:, :, 0] // 255, matrix)

    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1440, 720)
        scaled = np.asarray(image.convert("RGB"))
    assert set(map(tuple, scaled.reshape(-1, 3))) <= {
        (0, 0, 0), (255, 255, 255)
    }
    assert np.array_equal(
        scaled, np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    )
    print("Validated: 90x180 CSV, 180x90 PNG, 1440x720 nearest-neighbor PNG")


if __name__ == "__main__":
    main()
