# A ray-crossing point test.  Polygons follow remembered coastlines, rather
# than being fitted to, or obtained from, a geographic data set.
def inside(x, y, p):
    hit = False
    xj, yj = p[-1]
    for xi, yi in p:
        if ((yi > y) != (yj > y)):
            xx = (xj-xi)*(y-yi)/(yj-yi)+xi
            if x <= xx:
                hit = not hit
        xj, yj = xi, yi
    return hit

