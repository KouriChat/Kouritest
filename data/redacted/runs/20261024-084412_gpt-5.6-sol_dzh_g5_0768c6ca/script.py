def is_land(x,y):
    land=any(inside(x,y,p) for p in polys)
    if not land:
        land=any(((x-a)/rx)**2+((y-b)/ry)**2 <= 1
                 for a,b,rx,ry in isles)
    # Remembered narrow sea channels that coarse adjoining polygons can cover.
    if 40.82 <= y <= 41.25 and abs(x-(29.02-.10*(y-41.0))) < .075:
        land=False
    if 39.92 <= y <= 40.48 and abs(x-(26.18+1.00*(y-39.92))) < .075:
        land=False
    return int(land)

lons=[-9+i*.2 for i in range(231)]
lats=[45-i*.2 for i in range(71)]
matrix=np.array([[is_land(x,y) for x in lons] for y in lats],dtype=np.uint8)
out=Path("outputs"); out.mkdir(exist_ok=True)
