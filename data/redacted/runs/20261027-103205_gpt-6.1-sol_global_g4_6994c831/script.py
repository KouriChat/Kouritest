def points_in_polygon(lon, lat, vertices):
    """Even-odd ray casting on lon/lat; outlines are coarse by design."""
    x1 = vertices[:, 0]
    y1 = vertices[:, 1]
    x2 = np.roll(x1, -1)
    y2 = np.roll(y1, -1)
    inside = np.zeros(lon.shape, dtype=bool)
    for ax, ay, bx, by in zip(x1, y1, x2, y2):
        crosses = (ay > lat) != (by > lat)
        crossing_x = (bx - ax) * (lat - ay) / (by - ay + 1e-300) + ax
        inside ^= crosses & (lon < crossing_x)
    return inside


def main():
    out = Path('outputs')
    out.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for _name, outline in LAND:
        land |= points_in_polygon(lon_grid, lat_grid, outline)

    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        writer = csv.writer(f, lineterminator='\n')
        writer.writerows(land.astype(np.uint8))

    # Pillow mode 1 with white land and black water, without interpolation.
    image = Image.fromarray(np.where(land, 255, 0).astype(np.uint8), mode='L')
    image.save(out / 'candidate.png')
    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')

    assert land.shape == (90, 180) and int(land.size) == 16200
    assert set(np.unique(np.asarray(image)).tolist()) <= {0, 255}
    assert image.size == (180, 90) and enlarged.size == (1440, 720)
    print(json.dumps({'matrix': [90, 180], 'values': int(land.size),
                      'land': int(land.sum()), 'water': int((~land).sum()),
                      'polygons': len(LAND), 'files': [
                          'outputs/candidate.csv', 'outputs/candidate.png',
                          'outputs/candidate_8x.png']}, indent=2))


if __name__ == '__main__':
    main()
