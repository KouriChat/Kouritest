"""Memory-only, hand-drawn world land mask; no geographical files or services.

Coordinates below are approximate outlines written from geographical knowledge.
Classification is vectorized point-in-polygon, NOT independent model judgments.
Lakes are deliberately not subtracted. Sea ice is never added as land.
Run: python outputs/generate_map.py   (requires numpy and Pillow)
"""
