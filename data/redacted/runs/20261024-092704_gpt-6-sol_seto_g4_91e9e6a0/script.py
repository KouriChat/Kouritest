def xy(p):
    return ((p[0] - 129.0) * 31.5, (35.0 - p[1]) * 31.5)


def land(points):
    d.polygon([xy(p) for p in points], fill=255)


def water(points):
    d.polygon([xy(p) for p in points], fill=0)


def oval(lon, lat, east, north, angle=0, n=16):
    """Hand-placed island, size in degrees; angle counterclockwise from east."""
    ca, sa = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    p = []
    for k in range(n):
        t = 2 * math.pi * k / n
        a, b = east * math.cos(t), north * math.sin(t)
        p.append((lon + a * ca - b * sa, lat + a * sa + b * ca))
    land(p)


