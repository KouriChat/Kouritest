def point_in_polygon(lon, lat, polygon):
    inside = False
    eps = 1e-12
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        cross = (lon - x1) * (y2 - y1) - (lat - y1) * (x2 - x1)
        if abs(cross) <= eps and (
            min(x1, x2) - eps <= lon <= max(x1, x2) + eps
            and min(y1, y2) - eps <= lat <= max(y1, y2) + eps
        ):
            return True
        if (y1 > lat) != (y2 > lat):
            x_intersect = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < x_intersect:
                inside = not inside
    return inside


def is_land(lon, lat):
    if any(point_in_polygon(lon, lat, p) for p in POLYGONS):
        return 1
    for cx, cy, rx, ry in ELLIPSES:
        if ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2 <= 1:
            return 1
    return 0


def build_matrix():
    matrix = np.zeros((111, 141), dtype=np.uint8)
    for row in range(111):
        lat = 23.0 - 0.2 * row
        for col in range(141):
            lon = 99.0 + 0.2 * col
            matrix[row, col] = is_land(lon, lat)
    return matrix


def main():
    matrix = build_matrix()
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert np.all((matrix == 0) | (matrix == 1))

    np.savetxt(
        os.path.join(OUT_DIR, "candidate.csv"),
        matrix,
        fmt="%d",
        delimiter=",",
    )

    image = Image.fromarray((matrix * 255).astype(np.uint8), mode="L")
    assert image.size == (141, 111)
    assert set(image.getdata()).issubset({0, 255})
    image.save(os.path.join(OUT_DIR, "candidate.png"))

    enlarged = image.resize(
        (1128, 888),
        resample=Image.Resampling.NEAREST,
    )
    assert enlarged.size == (1128, 888)
    assert set(enlarged.getdata()).issubset({0, 255})
    enlarged.save(os.path.join(OUT_DIR, "candidate_8x.png"))


if __name__ == "__main__":
    main()
