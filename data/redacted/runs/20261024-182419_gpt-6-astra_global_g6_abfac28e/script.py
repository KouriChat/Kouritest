def contains_points(vertices, x, y):
    """Even/odd ray crossing; points on the hand-written boundary are land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-9)
            & (x >= min(ax, bx) - 1e-9)
            & (x <= max(ax, bx) + 1e-9)
            & (y >= min(ay, by) - 1e-9)
            & (y <= max(ay, by) + 1e-9)
        )
        if dy != 0:
            hit = ((ay > y) != (by > y)) & (
                x < ax + (y - ay) * dx / dy
            )
            inside ^= hit
        ax, ay = bx, by
    return inside | boundary


def polygon_mask(vertices, longitude, latitude):
    """Longitude shifts handle hand-drawn polygons crossing the date line."""
    result = np.zeros(longitude.shape, dtype=bool)
    xmin, ymin = vertices.min(axis=0)
    xmax, ymax = vertices.max(axis=0)
    for shift in (-360.0, 0.0, 360.0):
        x = longitude + shift
        select = (
            (x >= xmin) & (x <= xmax)
            & (latitude >= ymin) & (latitude <= ymax)
        )
        if np.any(select):
            result[select] |= contains_points(
                vertices, x[select], latitude[select]
            )
    return result


def generate():
    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    longitude, latitude = np.meshgrid(
        longitudes.astype(float), latitudes.astype(float)
    )
    matrix = np.zeros((90, 180), dtype=np.uint8)
    for name, vertices in LAND:
        matrix[polygon_mask(vertices, longitude, latitude)] = 1
    for name, vertices in SEA:
        matrix[polygon_mask(vertices, longitude, latitude)] = 0

    # No filtering, resampling of geography, coastline repair, or smoothing.
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert np.isin(matrix, (0, 1)).all()
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    original.save(out / "candidate.png")
    enlarged.save(out / "candidate_8x.png")

    # Validate the serialized products, not merely in-memory dimensions.
    with (out / "candidate.csv").open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    recovered = np.asarray(rows, dtype=np.uint8)
    assert recovered.size == 16200 and np.array_equal(recovered, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (180, 90) and im.mode == "L"
        raw = np.asarray(im).copy()
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1440, 720) and im.mode == "L"
        big = np.asarray(im).copy()
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, recovered * np.uint8(255))
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected)
    land_count = int(matrix.sum())
    print(
        "PASS: 90x180 = 16200 binary values; "
        "180x90 and 1440x720 black/white PNGs; exact 8x nearest-neighbor."
    )
    print(f"Land={land_count}; water={matrix.size - land_count}")
    print(f"Files: {out / 'candidate.csv'}, "
          f"{out / 'candidate.png'}, {out / 'candidate_8x.png'}")


if __name__ == "__main__":
    generate()
