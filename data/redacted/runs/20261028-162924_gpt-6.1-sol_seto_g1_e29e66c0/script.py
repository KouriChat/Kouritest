def on_segment(x, y, a, b):
    cross = (x-a[0])*(b[1]-a[1]) - (y-a[1])*(b[0]-a[0])
    return (abs(cross) <= 1e-12 and
            min(a[0],b[0])-1e-12 <= x <= max(a[0],b[0])+1e-12 and
            min(a[1],b[1])-1e-12 <= y <= max(a[1],b[1])+1e-12)


def inside_polygon(x, y, poly):
    inside = False
    j = len(poly)-1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if on_segment(x, y, (xi, yi), (xj, yj)):
            return True
        if (yi > y) != (yj > y):
            crossing = (xj-xi)*(y-yi)/(yj-yi)+xi
            if x < crossing:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    if any(inside_polygon(lon, lat, p) for p in POLYGONS):
        return True
    return any(((lon-cx)/rx)**2 + ((lat-cy)/ry)**2 <= 1
               for cx, cy, rx, ry in ISLANDS)


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = np.array([
        [int(is_land(129+c*(8/252), 35-r*(2/63))) for c in range(253)]
        for r in range(64)
    ], dtype=np.uint8)
    with (out/"candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix*255, mode="L")
    image.save(out/"candidate.png")
    image.resize((2024, 512), resample=Image.Resampling.NEAREST).save(
        out/"candidate_8x.png")
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix).tolist()) <= {0, 1}


if __name__ == "__main__":
    main()
