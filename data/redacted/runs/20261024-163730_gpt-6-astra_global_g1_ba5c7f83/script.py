def contains_grid(points, longitude, latitude):
    """Planar lon/lat ray casting; boundary points count as land.

    This is an approximate geographic rule, not a geodesic coastline model.
    Testing three longitude copies handles the +/-180-degree discontinuity.
    """
    points = np.asarray(points, dtype=np.float64)
    xmin, ymin = points.min(axis=0)
    xmax, ymax = points.max(axis=0)
    result = np.zeros(longitude.shape, dtype=bool)
    for shift in (-360.0, 0.0, 360.0):
        xx = longitude + shift
        selected = ((xx >= xmin) & (xx <= xmax) &
                    (latitude >= ymin) & (latitude <= ymax))
        if not selected.any():
            continue
        x, y = xx[selected], latitude[selected]
        inside = np.zeros(x.shape, dtype=bool)
        boundary = np.zeros(x.shape, dtype=bool)
        ax, ay = points[-1]
        for bx, by in points:
            dx, dy = bx - ax, by - ay
            if abs(dx) + abs(dy) > 0:
                boundary |= (
                    (np.abs((x - ax) * dy - (y - ay) * dx) < 1e-9)
                    & (x >= min(ax, bx)) & (x <= max(ax, bx))
                    & (y >= min(ay, by)) & (y <= max(ay, by))
                )
            if dy != 0:
                crosses = (ay > y) != (by > y)
                inside ^= crosses & (x < ax + (y - ay) * dx / dy)
            ax, ay = bx, by
        result[selected] |= inside | boundary
    return result


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    assert longitude.shape == latitude.shape == (90, 180)

    land = np.zeros((90, 180), dtype=bool)
    for name, points in LAND:
        land |= contains_grid(points, longitude, latitude)
    for name, points in WATER:
        land &= ~contains_grid(points, longitude, latitude)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert set(np.unique(matrix)) == {0, 1}

    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())

    # Direct matrix-to-pixel conversion: no drawing, smoothing or retouching.
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    assert original.mode == "L" and original.size == (180, 90)
    original.save(output / "candidate.png", format="PNG")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    enlarged.save(output / "candidate_8x.png", format="PNG")

    # Read back only files generated by this script, never external map data.
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16200
    restored = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)

    with Image.open(output / "candidate.png") as image:
        assert image.format == "PNG" and image.mode == "L"
        assert image.size == (180, 90)
        raw = np.asarray(image).copy()
    with Image.open(output / "candidate_8x.png") as image:
        assert image.format == "PNG" and image.mode == "L"
        assert image.size == (1440, 720)
        large = np.asarray(image).copy()
    assert set(np.unique(raw)) == {0, 255}
    assert set(np.unique(large)) == {0, 255}
    assert np.array_equal(raw, restored * np.uint8(255))
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(large, expected), "Not exact nearest-neighbor 8x"
    assert np.array_equal(large[::8, ::8], raw)
    assert latitudes[0] == 89 and latitudes[-1] == -89
    assert longitudes[0] == -179 and longitudes[-1] == 179

    report = (
        "Method: handwritten knowledge-only polygons; automatic ray casting.\n"
        "No external geographic data, network, reference mask or image model.\n"
        "Inland lakes are land; ocean ice is water; shelves approximated as water.\n"
        f"Handwritten land polygons: {len(LAND)}\n"
        "CSV: 90 rows x 180 columns; 16200 valid binary values; no header.\n"
        f"Land points: {int(matrix.sum())}; water points: {int((matrix == 0).sum())}\n"
        "Original PNG: 180 x 90; grayscale values exactly {0, 255}.\n"
        "Enlarged PNG: 1440 x 720; grayscale values exactly {0, 255}.\n"
        "8x nearest-neighbor enlargement: verified pixel-for-pixel.\n"
        "Orientation: north to south, west to east.\n"
        "All structural checks passed; geographic accuracy is NOT validated.\n"
    )
    (output / "validation.txt").write_text(report, encoding="utf-8")
    print(report, end="")


if __name__ == "__main__":
    main()
