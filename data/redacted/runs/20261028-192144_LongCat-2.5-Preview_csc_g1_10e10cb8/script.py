LAND_POLYS = [ASIA_MAIN, HAINAN, TAIWAN, LUZON, MINDORO, PANAY, NEGROS, CEBU,
              BOHOL, SAMAR, LEYTE, MINDANAO, PALAWAN, BORNEO, SUMATRA, JAVA,
              SULAWESI] + SMALL_ISLANDS

def is_land(lon, lat):
    for p in LAND_POLYS:
        if in_poly(lon, lat, p):
            return 1
    return 0

def build_matrix():
    M = np.zeros((111, 141), dtype=np.uint8)
    for i, lat in enumerate(LATS):
        for j, lon in enumerate(LONS):
            M[i, j] = is_land(lon, lat)
    return M

def write_csv(M, path):
    with open(path, "w", newline="") as f:
        for i in range(M.shape[0]):
            f.write(",".join(str(int(v)) for v in M[i]) + "\n")

def main():
    os.makedirs("outputs", exist_ok=True)
    M = build_matrix()
    assert M.shape == (111, 141), M.shape
    assert set(np.unique(M).tolist()) <= {0, 1}
    write_csv(M, "outputs/candidate.csv")
    img = Image.fromarray((M * 255).astype(np.uint8), mode="L")
    img.save("outputs/candidate.png")
    big = img.resize((141 * 8, 111 * 8), resample=Image.NEAREST)
    big.save("outputs/candidate_8x.png")
    print("matrix", M.shape, "land", int(M.sum()))

if __name__ == "__main__":
    main()
