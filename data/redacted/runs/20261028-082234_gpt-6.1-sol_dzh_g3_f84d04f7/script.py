def inside(points, x, y):
    """Ray crossing test for one point and one closed polygon."""
    hit = False
    j = len(points) - 1
    for i in range(len(points)):
        xi, yi = points[i]
        xj, yj = points[j]
        crosses = ((yi > y) != (yj > y))
        if crosses and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def make_mask():
    longitudes = np.array([ -9.0 + 0.2 * i for i in range(231) ])
    latitudes = np.array([ 45.0 - 0.2 * i for i in range(71) ])
    mask = np.zeros((len(latitudes), len(longitudes)), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            mask[row, col] = any(inside(p, lon, lat) for p in POLYGONS)
    return mask


def write_outputs(mask):
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerows(mask.tolist())

    # The array is directly mapped: 0 -> black water, 1 -> white land.
    raw = Image.fromarray(mask * 255, mode="L")
    raw.save(out / "candidate.png")
    enlarged = raw.resize((231 * 8, 71 * 8), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")


if __name__ == "__main__":
    result = make_mask()
    write_outputs(result)
    assert result.shape == (71, 231)
    assert set(np.unique(result)).issubset({0, 1})
    print("generated", result.shape, "values", int(result.sum()), "land points")
