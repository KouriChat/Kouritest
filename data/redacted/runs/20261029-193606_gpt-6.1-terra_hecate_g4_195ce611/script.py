from pathlib import Path
import csv

from PIL import Image


N = 127
SCALE = 8
WEST = -131.0
EAST = -129.0
NORTH = 55.0
SOUTH = 53.0


def inside(poly, x, y):
    """Odd-even point-in-polygon test for a hand-written outline."""
    hit = False
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if (y1 > y) != (y0 > y):
            cross = (x0 - x1) * (y - y1) / (y0 - y1) + x1
            if x < cross:
                hit = not hit
        x0, y0 = x1, y1
    return hit


def point(row, col):
    lat = NORTH + (SOUTH - NORTH) * row / (N - 1)
    lon = WEST + (EAST - WEST) * col / (N - 1)
    return lon, lat


def write_outputs(matrix):
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)
    img = Image.new("L", (N, N))
    img.putdata([255 * v for row in matrix for v in row])
    img.save(out / "candidate.png")
    img.resize((N * SCALE, N * SCALE), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


