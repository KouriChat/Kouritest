def make_matrix():
    result = []
    for row in range(N):
        line = []
        for col in range(N):
            lon, lat = point(row, col)
            land = any(inside(poly, lon, lat) for poly in LAND)
            cut = any(inside(poly, lon, lat) for poly in WATER)
            line.append(int(land and not cut))
        result.append(line)
    return result


def validate(matrix):
    assert len(matrix) == N
    assert all(len(row) == N for row in matrix)
    assert all(v in (0, 1) for row in matrix for v in row)
    assert sum(len(row) for row in matrix) == 16129
    out = Path("outputs")
    with (out / "candidate.csv").open(encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == N and all(len(row) == N for row in rows)
    assert all(v in {"0", "1"} for row in rows for v in row)
    with Image.open(out / "candidate.png") as img:
        assert img.size == (N, N)
        assert img.mode == "L"
        assert set(img.getdata()) <= {0, 255}
    with Image.open(out / "candidate_8x.png") as img:
        assert img.size == (N * SCALE, N * SCALE)
        assert img.mode == "L"
        assert set(img.getdata()) <= {0, 255}


def main():
    matrix = make_matrix()
    write_outputs(matrix)
    validate(matrix)
    print("validated", N, "x", N, "matrix and PNG outputs")


if __name__ == "__main__":
    main()
