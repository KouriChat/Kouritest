def inside_poly(x, y, p):
    """Boundary-inclusive even/odd point-in-polygon test."""
    hit = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]
        xj, yj = p[j]
        dx, dy = xj - xi, yj - yi
        cross = (x - xi) * dy - (y - yi) * dx
        if abs(cross) < 1e-10 and min(xi, xj)-1e-10 <= x <= max(xi, xj)+1e-10 \
                and min(yi, yj)-1e-10 <= y <= max(yi, yj)+1e-10:
            return True
        if ((yi > y) != (yj > y)):
            xx = xi + (y - yi) * dx / dy
            if x < xx:
                hit = not hit
        j = i
    return hit


def ellipse(cx, cy, rx, ry, angle=0.0, n=18):
    a = math.radians(angle)
    ca, sa = math.cos(a), math.sin(a)
    return [(cx + rx*math.cos(t)*ca - ry*math.sin(t)*sa,
             cy + rx*math.cos(t)*sa + ry*math.sin(t)*ca)
            for t in np.linspace(0, 2*math.pi, n, endpoint=False)]


