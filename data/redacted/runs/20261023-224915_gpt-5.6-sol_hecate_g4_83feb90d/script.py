def classify():
    out = np.zeros((N, N), dtype=np.uint8)
    for r, lat in enumerate(LATS):
        for c, lon in enumerate(LONS):
            if any(inside_poly(lon, lat, p) for p in land):
                out[r, c] = 1
            if out[r, c] and any(inside_poly(lon, lat, p)
                                 for p in water_cuts):
                out[r, c] = 0
    return out


def main():
    outdir = Path("outputs")
    outdir.mkdir(parents=True, exist_ok=True)
    matrix = classify()
    assert matrix.shape == (127, 127)
    assert set(np.unique(matrix)).issubset({0, 1})
    with (outdir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels, mode="L")
    image.save(outdir / "candidate.png")
    enlarged = image.resize((1016, 1016), resample=Image.Resampling.NEAREST)
    enlarged.save(outdir / "candidate_8x.png")

    # Self-check dimensions, palette, row lengths, and exact nearest-neighbour.
    rows = list(csv.reader((outdir / "candidate.csv").open(encoding="ascii")))
    assert len(rows) == 127 and all(len(row) == 127 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert image.size == (127, 127) and enlarged.size == (1016, 1016)
    assert set(image.getdata()).issubset({0, 255})
    assert np.array_equal(np.asarray(enlarged),
                          np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1))


if __name__ == "__main__":
    main()
