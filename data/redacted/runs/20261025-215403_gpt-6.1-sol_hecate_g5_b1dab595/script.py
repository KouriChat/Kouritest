N = 127
lon = -131.0 + np.arange(N, dtype=float) * (2.0 / 126.0)
lat = 55.0 - np.arange(N, dtype=float) * (2.0 / 126.0)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((N, N), dtype=bool)
outlines = {}


def inside(vertices):
    """Even-odd point test; samples, not cell areas, determine classifications."""
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crossing = ((y0 > Y) != (y1 > Y))
            edge_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (X < edge_x)
        x0, y0 = x1, y1
    return result


def add(name, vertices):
    outlines[name] = {"kind": "land", "vertices": vertices}
    land[:] |= inside(vertices)


def water(name, vertices):
    outlines[name] = {"kind": "water", "vertices": vertices}
    land[:] &= ~inside(vertices)


