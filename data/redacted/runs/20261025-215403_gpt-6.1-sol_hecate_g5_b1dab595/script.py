"""Memory-only reconstruction; no map, geographic dataset, or network access.

Coordinates below are hand-written approximate longitude/latitude outlines.
The calculation is a point-in-polygon rasterization, NOT independent reasoning
for each point. Inland lakes remain land. All coordinates use WGS84 degrees.
Run: python outputs/generate_map.py
Dependencies: numpy, Pillow.
"""
from pathlib import Path
