def polygon_mask(vertices, longitude, latitude):
    """Vectorized even/odd ray crossing; polygon edges count as land."""
    inside = np.zeros(longitude.shape, dtype=bool)
    on_edge = np.zeros(longitude.shape, dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        dx, dy = x2 - x1, y2 - y1
        cross = (longitude - x1) * dy - (latitude - y1) * dx
        on_edge |= (
            (np.abs(cross) < 1e-10)
            & (longitude >= min(x1, x2) - 1e-10)
            & (longitude <= max(x1, x2) + 1e-10)
            & (latitude >= min(y1, y2) - 1e-10)
            & (latitude <= max(y1, y2) + 1e-10)
        )
        if dy != 0:
            intersect_x = x1 + (latitude - y1) * dx / dy
            inside ^= ((y1 > latitude) != (y2 > latitude)) & (
                longitude < intersect_x
            )
        x1, y1 = x2, y2
    return inside | on_edge

def main():
    destination = Path("outputs")
    destination.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    xx, yy = np.meshgrid(longitudes.astype(float), latitudes.astype(float))
    result = np.zeros((90, 180), dtype=bool)
    for name, vertices in LAND:
        assert len(vertices) >= 3, name
        assert all(-180 <= x <= 180 and -90 <= y <= 90 for x, y in vertices), name
        result |= polygon_mask(vertices, xx, yy)
    for name, vertices in WATER:
        result &= ~polygon_mask(vertices, xx, yy)
    matrix = result.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert np.isin(matrix, (0, 1)).all()
    with (destination / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    assert image.mode == "L"
    image.save(destination / "candidate.png")
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    image.resize((1440, 720), resample=nearest).save(
        destination / "candidate_8x.png"
    )

    # Validate the actual files, including every individual CSV entry and pixel.
    with (destination / "candidate.csv").open(encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    reread = np.array(rows, dtype=np.uint8)
    assert reread.size == 16200 and np.array_equal(reread, matrix)
    with Image.open(destination / "candidate.png") as original:
        assert original.size == (180, 90) and original.mode == "L"
        small = np.array(original)
    with Image.open(destination / "candidate_8x.png") as enlarged:
        assert enlarged.size == (1440, 720) and enlarged.mode == "L"
        big = np.array(enlarged)
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(small, pixels)
    assert np.array_equal(big, small.repeat(8, axis=0).repeat(8, axis=1))
    report = {
        "method": "Hand-written memory-only polygons; automatic point-in-polygon",
        "external_geographic_data": False,
        "matrix_shape": list(matrix.shape),
        "valid_entries": int(matrix.size),
        "land_entries": int(matrix.sum()),
        "water_entries": int(matrix.size - matrix.sum()),
        "original_size": [180, 90],
        "enlarged_size": [1440, 720],
        "colors": [0, 255],
        "exact_nearest_neighbor_8x_verified": True,
        "land_polygons": len(LAND),
        "water_polygons": len(WATER),
    }
    (destination / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))

