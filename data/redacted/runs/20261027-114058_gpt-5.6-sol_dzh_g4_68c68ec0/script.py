# Rasterize the common rules once for every requested sample point.
mask = np.zeros((len(LATS), len(LONS)), dtype=np.uint8)
for row, lat in enumerate(LATS):
    for col, lon in enumerate(LONS):
        is_land = any(inside(lon, lat, p) for p in land_polys)
        if not is_land:
            is_land = any(ellipse(lon, lat, *e) for e in land_ellipses)
        mask[row, col] = int(is_land)

out = Path("outputs")
out.mkdir(parents=True, exist_ok=True)
with (out / "candidate.csv").open("w", newline="", encoding="utf-8") as f:
    csv.writer(f).writerows(mask.tolist())

raw = Image.fromarray(mask * 255, mode="L")
