def inside(x, y, poly):
    """Even/odd point-in-polygon test; boundary points are treated as land."""
    hit = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        cross = (x-x1)*(y2-y1) - (y-y1)*(x2-x1)
        if abs(cross) < 1e-10 and min(x1,x2)-1e-10 <= x <= max(x1,x2)+1e-10 \
                and min(y1,y2)-1e-10 <= y <= max(y1,y2)+1e-10:
            return True
        if (y1 > y) != (y2 > y):
            xi = x1 + (y-y1) * (x2-x1) / (y2-y1)
            if x < xi:
                hit = not hit
    return hit

def ellipse(x, y, cx, cy, rx, ry, angle=0.0):
    a = np.deg2rad(angle)
    u = (x-cx)*np.cos(a) + (y-cy)*np.sin(a)
    v = -(x-cx)*np.sin(a) + (y-cy)*np.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1.0

