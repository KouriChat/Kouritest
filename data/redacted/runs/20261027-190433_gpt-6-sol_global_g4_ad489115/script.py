# Coordinates are (longitude, latitude), in degrees.  These are deliberately
# hand-drawn recognition rules, rather than data imported from a map.
POLYGONS = []

def add(points):
    POLYGONS.append(points)

def inside(lon, lat, poly):
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        crosses = ((yi > lat) != (yj > lat))
        if crosses:
            edge_x = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < edge_x:
                hit = not hit
        j = i
    return hit

def land(lon, lat):
    return any(inside(lon, lat, p) for p in POLYGONS)

