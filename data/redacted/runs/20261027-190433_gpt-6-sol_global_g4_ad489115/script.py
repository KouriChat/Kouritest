def make_matrix():
    lats = list(range(89, -90, -2))
    lons = list(range(-179, 180, 2))
    matrix = [[1 if land(lon, lat) else 0 for lon in lons] for lat in lats]
    return matrix

def write_csv(matrix):
    with (OUT / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)

def write_images(matrix):
    # The requested display convention is white land and black water.
    raw = np.asarray(matrix, dtype=np.uint8) * 255
    image = Image.fromarray(raw, mode="L")
    image.save(OUT / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        OUT / "candidate_8x.png"
    )

def main():
    matrix = make_matrix()
    if len(matrix) != 90 or any(len(row) != 180 for row in matrix):
        raise RuntimeError("matrix dimensions are not 90 by 180")
    if any(value not in (0, 1) for row in matrix for value in row):
        raise RuntimeError("matrix contains a value other than 0 or 1")
    write_csv(matrix)
    write_images(matrix)
    print("wrote 90x180 matrix and 180x90 / 1440x720 PNG files")

if __name__ == "__main__":
    main()
