def in_polygon(x, y, vertices):
    """Even/odd ray test at sample coordinates; boundary is assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-12)
                     & (x >= min(ax, bx) - 1e-12)
                     & (x <= max(ax, bx) + 1e-12)
                     & (y >= min(ay, by) - 1e-12)
                     & (y <= max(ay, by) + 1e-12))
        if dy != 0:
            intersects = ((ay > y) != (by > y))
            inside ^= intersects & (x < ax + (y - ay) * dx / dy)
        ax, ay = bx, by
    return inside | boundary


def near_line(x, y, vertices, half_width):
    # Fixed local scale is only a hand-rule distance approximation, not GIS data.
    sx, sy = 65.4, 111.2
    px, py = x * sx, y * sy
    mask = np.zeros(x.shape, dtype=bool)
    for (a, b), (c, d) in zip(vertices[:-1], vertices[1:]):
        ax, ay, bx, by = a * sx, b * sy, c * sx, d * sy
        dx, dy = bx - ax, by - ay
        t = np.clip(((px - ax)*dx + (py - ay)*dy)/(dx*dx + dy*dy), 0, 1)
        mask |= (px - ax - t*dx)**2 + (py - ay - t*dy)**2 <= half_width**2
    return mask


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    # Exact prescribed spacing, not rounded displayed coordinates.
    lon = -131.0 + np.arange(127, dtype=float) * (2.0 / 126.0)
    lat = 55.0 - np.arange(127, dtype=float) * (2.0 / 126.0)
    x, y = np.meshgrid(lon, lat)
    land = np.zeros((127, 127), dtype=bool)
    for name, polygon in LAND:
        land |= in_polygon(x, y, polygon)
    for half_width, line in CHANNELS:
        land &= ~near_line(x, y, line, half_width)
    matrix = land.astype(np.uint8)
    np.savetxt(out / "candidate.csv", matrix, fmt="%d", delimiter=",")
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    enlarged = original.resize((1016, 1016), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    # Validate the saved files, including every pixel of all 8x8 blocks.
    with (out / "candidate.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127 and all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    saved = np.asarray([[int(value) for value in row] for row in rows])
    assert saved.size == 16129 and np.array_equal(saved, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (127, 127)
        small = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1016, 1016)
        big = np.array(im)
    assert set(np.unique(small)) <= {0, 255}
    assert set(np.unique(big)) <= {0, 255}
    assert np.array_equal(small, pixels)
    assert np.array_equal(big, np.repeat(np.repeat(small, 8, axis=0), 8, axis=1))
    print("PASS: 127x127; 16129 binary samples; black/white PNGs; exact 8x nearest.")


if __name__ == "__main__":
    main()
