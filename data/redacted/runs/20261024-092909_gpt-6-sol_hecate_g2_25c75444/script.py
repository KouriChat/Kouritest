land = np.zeros((N, N), dtype=bool)


def poly(points):
    """Ray-crossing test at the sample POINT, not area coverage."""
    inside = np.zeros_like(land)
    for (ax, ay), (bx, by) in zip(points, points[1:] + points[:1]):
        if ay == by:
            continue
        cross = ((ay > Y) != (by > Y)) & (
            X < (bx - ax) * (Y - ay) / (by - ay) + ax
        )
        inside ^= cross
    return inside


def add(*outlines):
    global land
    for outline in outlines:
        land |= poly(outline)


def subtract(*outlines):
    global land
    for outline in outlines:
        land &= ~poly(outline)


