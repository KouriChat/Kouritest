N = 127
longitude = np.linspace(-131.0, -129.0, N)
latitude = np.linspace(55.0, 53.0, N)
X, Y = np.meshgrid(longitude, latitude)


def polygon(vertices):
    """Even-odd point-in-polygon (the boundary is assigned arbitrarily)."""
    inside = np.zeros((N, N), dtype=bool)
    for (x1, y1), (x2, y2) in zip(vertices, vertices[1:] + vertices[:1]):
        if y1 == y2:
            continue
        cut = ((y1 > Y) != (y2 > Y))
        x_intersection = x1 + (Y - y1) * (x2 - x1) / (y2 - y1)
        inside ^= cut & (X < x_intersection)
    return inside


land = np.zeros((N, N), dtype=bool)


def add(points):
    global land
    land |= polygon(points)


def subtract(points):
    global land
    land &= ~polygon(points)


