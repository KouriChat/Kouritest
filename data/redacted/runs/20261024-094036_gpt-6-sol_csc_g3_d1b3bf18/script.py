LONS = 99.0 + np.arange(141) * 0.2
LATS = 23.0 - np.arange(111) * 0.2
X, Y = np.meshgrid(LONS, LATS)
land = np.zeros((111, 141), dtype=bool)


def polygon(points):
    """Rasterize point-in-polygon at sample centers (lon,lat)."""
    global land
    inside = np.zeros_like(land)
    for (ax, ay), (bx, by) in zip(points, points[1:] + points[:1]):
        if ay == by:
            continue
        inside ^= ((ay > Y) != (by > Y)) & (
            X < ax + (Y - ay) * (bx - ax) / (by - ay)
        )
    land |= inside


def island(lon, lat, ew, ns, angle=0):
    """Oval island, radii in degrees; angle rotates its long axis CCW."""
    global land
    a = np.deg2rad(angle)
    dx = X - lon
    dy = Y - lat
    u = dx * np.cos(a) + dy * np.sin(a)
    v = -dx * np.sin(a) + dy * np.cos(a)
    land |= (u / ew) ** 2 + (v / ns) ** 2 <= 1


