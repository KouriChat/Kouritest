def polygon_contains(xx, yy, vertices):
    """Vectorized point-in-polygon; no cell averaging or map lookup."""
    inside = np.zeros(xx.shape, dtype=bool)
    boundary = np.zeros(xx.shape, dtype=bool)
    eps = 1e-10
    for index, (x1, y1) in enumerate(vertices):
        x2, y2 = vertices[(index + 1) % len(vertices)]
        cross = (xx - x1) * (y2 - y1) - (yy - y1) * (x2 - x1)
        on_segment = (
            (np.abs(cross) <= eps)
            & (xx >= min(x1, x2) - eps)
            & (xx <= max(x1, x2) + eps)
            & (yy >= min(y1, y2) - eps)
            & (yy <= max(y1, y2) + eps)
        )
        boundary |= on_segment
        if y1 != y2:
            intersects = ((y1 > yy) != (y2 > yy))
            intersection_x = x1 + (yy - y1) * (x2 - x1) / (y2 - y1)
            inside ^= intersects & (xx < intersection_x)
    return inside | boundary


def generate():
    # Integer tenths avoid cumulative stepping errors and include all borders.
    latitudes = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    longitudes = np.arange(-1050, -809, dtype=np.int32) / 10.0
    xx, yy = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((61, 241), dtype=bool)
    for _name, vertices in LAND:
        mask |= polygon_contains(xx, yy, vertices)
    for _name, vertices in SEA:
        mask &= ~polygon_contains(xx, yy, vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, [0, 1]).all()
    assert latitudes[0] == 79 and latitudes[-1] == 73
    assert longitudes[0] == -105 and longitudes[-1] == -81

    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    original_path = output / "candidate.png"
    enlarged_path = output / "candidate_8x.png"
    with csv_path.open("w", encoding="ascii", newline="") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(original_path)
    nearest = Image.Resampling.NEAREST
    enlarged = original.resize((1928, 488), resample=nearest)
    enlarged.save(enlarged_path)

    # Re-read only our own outputs, never external geographical information.
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert np.array_equal(recovered, matrix)
    with Image.open(original_path) as image:
        assert image.size == (241, 61) and image.mode == "L"
        actual_original = np.array(image)
    with Image.open(enlarged_path) as image:
        assert image.size == (1928, 488) and image.mode == "L"
        actual_enlarged = np.array(image)
    assert set(np.unique(actual_original).tolist()) == {0, 255}
    assert set(np.unique(actual_enlarged).tolist()) == {0, 255}
    assert np.array_equal(actual_original, pixels)
    expected_enlarged = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(actual_enlarged, expected_enlarged)
    print("PASS: CSV 61x241 = 14701 binary values; PNG 241x61; "
          "8x nearest-neighbor PNG 1928x488; black/white only.")


if __name__ == "__main__":
    generate()
