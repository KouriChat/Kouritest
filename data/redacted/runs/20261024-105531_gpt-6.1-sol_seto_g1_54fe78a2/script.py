lon = 129.0 + np.arange(253, dtype=float) * (2.0 / 63.0)
lat = 35.0 - np.arange(64, dtype=float) * (2.0 / 63.0)
X, Y = np.meshgrid(lon, lat)
M = np.zeros((64, 253), dtype=bool)

def polygon(text, value=True):
    pts = [tuple(map(float, p.split(","))) for p in text.split()]
    inside = np.zeros_like(M)
    ax, ay = pts[-1]
    for bx, by in pts:
        if by != ay:
            crossing = ((ay > Y) != (by > Y))
            edge_x = ax + (Y - ay) * (bx - ax) / (by - ay)
            inside ^= crossing & (X < edge_x)
        ax, ay = bx, by
    M[inside] = value

def ellipse(cx, cy, rx, ry, angle=0, value=True):
    a = np.deg2rad(angle)
    dx, dy = X-cx, Y-cy
    u = dx*np.cos(a) + dy*np.sin(a)
    v = -dx*np.sin(a) + dy*np.cos(a)
    M[(u/rx)**2 + (v/ry)**2 <= 1] = value

