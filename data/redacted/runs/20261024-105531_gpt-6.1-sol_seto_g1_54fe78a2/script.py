"""Memory-only approximation of Japanese coasts; no map/data input.

Dependencies: numpy, Pillow. Run from the desired working directory.
All geographic coordinates below were hand-written from geographic knowledge.
The classifications are polygon/ellipse calculations, not independent LLM
judgments for the 16192 individual points. Inland lakes remain land.
"""
