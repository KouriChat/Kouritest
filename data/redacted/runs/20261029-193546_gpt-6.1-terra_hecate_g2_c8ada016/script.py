def inside(x, y, polygon):
    hit = False
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        if (y0 > y) != (y1 > y) and x < (x1-x0)*(y-y0)/(y1-y0)+x0:
            hit = not hit
        x0, y0 = x1, y1
    return hit

def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    matrix = [[int(any(inside(-131 + 2*c/126, 55 - 2*r/126, p)
                       for p in polygons)) for c in range(127)] for r in range(127)]
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f).writerows(matrix)
    image = Image.new('L', (127, 127))
    image.putdata([255*v for row in matrix for v in row])
    image.save(out / 'candidate.png')
    image.resize((1016, 1016), Image.Resampling.NEAREST).save(out / 'candidate_8x.png')
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127 and all(len(r) == 127 and set(r) <= {'0','1'} for r in rows)
    raw = Image.open(out / 'candidate.png')
    large = Image.open(out / 'candidate_8x.png')
    assert raw.size == (127,127) and large.size == (1016,1016)
    assert set(raw.getdata()) <= {0,255} and set(large.getdata()) <= {0,255}
    assert list(large.getdata()) == list(raw.resize(large.size, Image.Resampling.NEAREST).getdata())
    print('Verified 16129 values, binary PNGs and nearest-neighbor scaling.')

if __name__ == '__main__':
    main()
