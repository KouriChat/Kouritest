def contains_points(x, y, vertices):
    """Even-odd polygon membership; an exact boundary point counts as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        dx, dy = x2 - x1, y2 - y1
        cross = (x - x1) * dy - (y - y1) * dx
        boundary |= (
            (np.abs(cross) <= 1e-9)
            & (x >= min(x1, x2) - 1e-10)
            & (x <= max(x1, x2) + 1e-10)
            & (y >= min(y1, y2) - 1e-10)
            & (y <= max(y1, y2) + 1e-10)
        )
        if dy != 0:
            inside ^= (
                ((y1 > y) != (y2 > y))
                & (x < x1 + (y - y1) * dx / dy)
            )
        x1, y1 = x2, y2
    return inside | boundary


def generate_matrix():
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    lon, lat = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for name, vertices in POLYGONS:
        xmin, ymin = vertices.min(axis=0)
        xmax, ymax = vertices.max(axis=0)
        # Periodic longitude: e.g. 181 E and -179 W are the same meridian.
        for shift in (-360.0, 0.0, 360.0):
            x = lon + shift
            candidate = (
                (x >= xmin) & (x <= xmax)
                & (lat >= ymin) & (lat <= ymax)
            )
            if candidate.any():
                land[candidate] |= contains_points(
                    x[candidate], lat[candidate], vertices
                )
    return land.astype(np.uint8)


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    matrix = generate_matrix()
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert np.isin(matrix, (0, 1)).all()

    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        csv.writer(handle).writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    original.save(out / "candidate.png")
    enlarged.save(out / "candidate_8x.png")

    # Validate files actually written, including all 16,200 CSV entries.
    with csv_path.open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert sum(len(row) for row in rows) == 16200
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.size == (180, 90) and image.mode == "L"
        raw = np.asarray(image).copy()
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1440, 720) and image.mode == "L"
        big = np.asarray(image).copy()
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, pixels)
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected), "Not an exact nearest-neighbor 8x image"
    print(
        f"Validated: 90x180 = {matrix.size} binary entries; "
        f"land={int(matrix.sum())}, water={int(matrix.size - matrix.sum())}; "
        "180x90 and 1440x720 PNGs; black/white only; exact nearest-neighbor 8x."
    )


if __name__ == "__main__":
    main()
