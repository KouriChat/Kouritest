def inside(x, y, ring):
    """Odd-even point-in-polygon, including a negligible boundary ambiguity."""
    parity = False
    px, py = ring[-1]
    for qx, qy in ring:
        if ((qy > y) != (py > y)) and (
            x < (px - qx) * (y - qy) / (py - qy) + qx
        ):
            parity = not parity
        px, py = qx, qy
    return parity


