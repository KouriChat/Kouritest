def land_at(lon, lat):
    if inside(lon, lat, alaska):
        return 1
    if inside(lon, lat, mainland):
        if not any(inside(lon, lat, inlet) for inlet in mainland_water):
            return 1
    if any(inside(lon, lat, island) for island in islands):
        if not any(inside(lon, lat, inlet) for inlet in island_channels):
            return 1
    for cx, cy, rx, ry in small_islands:
        if ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2 <= 1:
            return 1
    return 0


def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    matrix = np.array(
        [
            [land_at(-131.0 + 2.0 * col / 126, 55.0 - 2.0 * row / 126)
             for col in range(127)]
            for row in range(127)
        ],
        dtype=np.uint8,
    )

    with (output / "candidate.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    img = Image.fromarray(matrix * 255, mode="L")
    img.save(output / "candidate.png")
    enlarged = img.resize((1016, 1016), resample=Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    with (output / "candidate.csv").open(newline="", encoding="utf-8") as f:
        check_rows = list(csv.reader(f))
    assert len(check_rows) == 127
    assert all(len(row) == 127 and all(x in ("0", "1") for x in row)
               for row in check_rows)
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert set(np.unique(np.asarray(img))).issubset({0, 255})
    assert enlarged.size == (1016, 1016)
    assert set(np.unique(np.asarray(enlarged))).issubset({0, 255})
    assert np.array_equal(np.asarray(enlarged),
                          np.repeat(np.repeat(np.asarray(img), 8, axis=0),
                                    8, axis=1))
    print("Verified: 127x127 binary CSV and PNG, 1016x1016 nearest-neighbor PNG.")


if __name__ == "__main__":
    main()
