LAND = []


def poly(points):
    LAND.append(np.asarray(points, dtype=np.float64))


def ellipse(lon, lat, rx, ry, angle=0.0, vertices=24):
    t = np.linspace(0, 2 * np.pi, vertices, endpoint=False)
    a = np.deg2rad(angle)
    x, y = rx * np.cos(t), ry * np.sin(t)
    poly(list(zip(lon + x * np.cos(a) - y * np.sin(a),
                  lat + x * np.sin(a) + y * np.cos(a))))


