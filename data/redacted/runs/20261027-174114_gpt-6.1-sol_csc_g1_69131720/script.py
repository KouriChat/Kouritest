def build_matrix():
    """Evaluate the hand-written polygon union at the exact grid points."""
    longitudes = (990 + 2 * np.arange(141)) / 10.0
    latitudes = (230 - 2 * np.arange(111)) / 10.0
    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros(x.shape, dtype=bool)
    for outline in LAND:
        # Bounding boxes only skip polygons that cannot contain the point.
        possible = ((x >= outline[:, 0].min()) &
                    (x <= outline[:, 0].max()) &
                    (y >= outline[:, 1].min()) &
                    (y <= outline[:, 1].max()))
        if not possible.any():
            continue
        px, py = x[possible], y[possible]
        inside = np.zeros(px.shape, dtype=bool)
        on_edge = np.zeros(px.shape, dtype=bool)
        ax, ay = outline[-1]
        for bx, by in outline:
            cross = (px - ax) * (by - ay) - (py - ay) * (bx - ax)
            on_edge |= ((np.abs(cross) <= 1e-11) &
                        (px >= min(ax, bx) - 1e-12) &
                        (px <= max(ax, bx) + 1e-12) &
                        (py >= min(ay, by) - 1e-12) &
                        (py <= max(ay, by) + 1e-12))
            if by != ay:
                intersection = ax + (py - ay) * (bx - ax) / (by - ay)
                inside ^= ((ay > py) != (by > py)) & (px < intersection)
            ax, ay = bx, by
        land[possible] |= inside | on_edge
    return land.astype(np.uint8)


def main():
    matrix = build_matrix()
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert np.isin(matrix, (0, 1)).all()
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(output / "candidate.png")
    enlarged = image.resize((1128, 888), Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    # Validate the actual saved files, including every output CSV value and
    # every pixel in every 8-by-8 block of the enlarged image.
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    recovered = np.asarray(rows, dtype=np.uint8)
    assert recovered.size == 15651
