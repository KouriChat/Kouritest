def ellipse(lon, lat, rx, ry, angle=0):
    t = np.linspace(0, 2 * np.pi, 33)[:-1]
    a = np.deg2rad(angle)
    x, y = rx * np.cos(t), ry * np.sin(t)
    LAND.append(np.column_stack((lon + x*np.cos(a) - y*np.sin(a),
                                 lat + x*np.sin(a) + y*np.cos(a))))


