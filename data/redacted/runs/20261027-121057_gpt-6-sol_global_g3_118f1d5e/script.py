def polygons(text):
    for line in text.strip().splitlines():
        values = [float(v) for v in line.split()]
        assert len(values) % 2 == 0 and len(values) >= 6
        yield list(zip(values[::2], values[1::2]))

def contains(xs, ys, vertices):
    inside = np.zeros(xs.shape, dtype=bool)
    previous_x, previous_y = vertices[-1]
    for current_x, current_y in vertices:
        if (current_y > ys).any() or (previous_y > ys).any():
            crosses = ((current_y > ys) != (previous_y > ys))
            at_x = previous_x + (ys - previous_y) * (current_x - previous_x) / (current_y - previous_y) if current_y != previous_y else 0
            inside ^= crosses & (xs < at_x)
        previous_x, previous_y = current_x, current_y
    return inside

def main():
    xs, ys = np.meshgrid(np.arange(-179, 180, 2), np.arange(89, -90, -2))
    land = np.zeros((90, 180), dtype=bool)
    for polygon in polygons(LAND):
        land |= contains(xs, ys, polygon)
    for polygon in polygons(WATER):
        land &= ~contains(xs, ys, polygon)
    # A few isolated islands too small for detailed polygons at this resolution.
    for x, y, rx, ry in [
        (-157, 21, 1.2, 1.2), (-155, 19, 1.4, 1.8), (-150, 60, 2, 1),
        (-167, 53, 2, 1), (-173, 52, 2, 1), (-179, 52, 1.5, 1),
        (-80, 25, 2, 1), (-77, 25, 1.2, 1), (-61, 16, 1.3, 1.5),
        (-62, 17, 1, 1), (-78, 18, 1.2, 1.1), (-91, 0, 1, 1),
        (-6, 50, 1, 1), (1, 39, 1.3, 1.2), (3, 39, 1, 1),
        (15, 38, 1, 1), (56, -4, 1, 1), (73, 4, 1, 1),
        (118, 10, 1.5, 2), (119, 12, 1, 2), (125, 0, 1, 1),
        (127, -4, 1, 1), (128, -7, 1, 1), (130, -3, 1.5, 1),
        (136, -1, 1, 1), (152, -4, 1, 1), (155, -6, 1, 1),
        (159, -9, 1, 1), (167, -16, 1, 2), (177, -18, 1.3, 1.3),
        (48, -12, 1, 1), (59, -20, 1, 1), (69, -49, 1, 1),
        (25, 78, 2, 1.5), (54, 73, 2, 1.5), (59, 81, 1.2, 1),
        (-98, 76, 4, 2), (-110, 77, 3, 2), (-120, 75, 3, 2),
        (-90, 74, 4, 2), (-83, 73, 3, 2), (-70, 72, 3, 2),
    ]:
        land |= ((xs - x) / rx) ** 2 + ((ys - y) / ry) ** 2 <= 1
    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180) and np.isin(matrix, [0, 1]).all()
    destination = Path("outputs")
    destination.mkdir(exist_ok=True)
    with (destination / "candidate.csv").open("w", newline="", encoding="utf-8") as file:
        csv.writer(file).writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(destination / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(destination / "candidate_8x.png")
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}

if __name__ == "__main__":
    main()
