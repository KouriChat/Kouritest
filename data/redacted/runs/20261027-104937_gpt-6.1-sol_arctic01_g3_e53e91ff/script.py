def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    mask = np.zeros((61, 241), dtype=bool)
    for _, vertices in LAND:
        mask |= contains(vertices)
    for _, vertices in SEA:
        mask &= ~contains(vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, (0, 1)).all()
    assert LAT[0] == 79.0 and LAT[-1] == 73.0
    assert LON[0] == -105.0 and LON[-1] == -81.0

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    raw_pixels = matrix * np.uint8(255)
    image = Image.fromarray(raw_pixels)
    assert image.mode == "L"
    image.save(out / "candidate.png", format="PNG")
    nearest = (Image.Resampling.NEAREST if hasattr(Image, "Resampling")
               else Image.NEAREST)
    enlarged = image.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png", format="PNG")

    # Read back only our generated artifacts, never any source map/data.
    with csv_path.open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    roundtrip = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(roundtrip, matrix)
    with Image.open(out / "candidate.png") as small:
        assert small.size == (241, 61) and small.mode == "L"
        small_array = np.array(small)
    with Image.open(out / "candidate_8x.png") as big:
        assert big.size == (1928, 488) and big.mode == "L"
        big_array = np.array(big)
    assert set(np.unique(small_array).tolist()) == {0, 255}
    assert set(np.unique(big_array).tolist()) == {0, 255}
    assert np.array_equal(small_array, raw_pixels)
    expected = np.repeat(np.repeat(small_array, 8, axis=0), 8, axis=1)
    assert np.array_equal(big_array, expected)

    report = {
        "method": "memory-only hand-authored polygons; grid-point tests",
        "external_geographic_data_used": False,
        "shape_rows_columns": [61, 241],
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - int(matrix.sum())),
        "csv": "61 rows, 241 binary values per row, no header or blanks",
        "original_png_width_height": [241, 61],
        "enlarged_png_width_height": [1928, 488],
        "pixel_values": [0, 255],
        "nearest_neighbor_exact_8x_verified": True,
        "geographic_accuracy": "approximate; not checked against a real map",
        "all_checks_passed": True,
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
