def contains(vertices):
    """Vectorized point test; boundary points are assigned to the polygon."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (X - ax) * dy - (Y - ay) * dx
        boundary |= ((np.abs(cross) < 1e-10)
                     & (X >= min(ax, bx) - 1e-10)
                     & (X <= max(ax, bx) + 1e-10)
                     & (Y >= min(ay, by) - 1e-10)
                     & (Y <= max(ay, by) + 1e-10))
        if abs(dy) > 1e-15:
            inside ^= ((ay > Y) != (by > Y)) & (
                X < ax + (Y - ay) * dx / dy)
        ax, ay = bx, by
    return inside | boundary


