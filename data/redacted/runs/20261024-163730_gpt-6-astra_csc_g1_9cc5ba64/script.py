def contains_points(x, y, vertices):
    """Even-odd point membership, with coastline points assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    for i, (ax, ay) in enumerate(vertices):
        bx, by = vertices[(i + 1) % len(vertices)]
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        if ay != by:
            intersects = ((ay > y) != (by > y))
            crossing_x = ax + (y - ay) * (bx - ax) / (by - ay)
            inside ^= intersects & (x < crossing_x)
    return inside | boundary


