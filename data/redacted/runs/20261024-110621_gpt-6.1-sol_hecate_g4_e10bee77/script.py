"""Knowledge-only approximation of the northern British Columbia coast.

No maps, GIS datasets, network requests, or external inputs are used.
All vertices below are handwritten estimates from geographic knowledge.
Point-in-polygon rules, not independent model judgments, classify the grid.
Requires Python 3, numpy, and Pillow. Run from the desired working directory.
"""
from pathlib import Path
import csv
import numpy as np
from PIL import Image

N = 127
lon = np.linspace(-131.0, -129.0, N)
lat = np.linspace(55.0, 53.0, N)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((N, N), dtype=bool)


def polygon(vertices):
    """Point membership; input longitudes are positive degrees west."""
    vertices = [(-w, n) for w, n in vertices]
    inside = np.zeros(X.shape, dtype=bool)
    xj, yj = vertices[-1]
    for xi, yi in vertices:
        if yi != yj:
            crosses = ((yi > Y) != (yj > Y))
            edge_x = xi + (Y - yi) * (xj - xi) / (yj - yi)
            inside ^= crosses & (X < edge_x)
        xj, yj = xi, yi
    return inside


def island(vertices):
    land[:] |= polygon(vertices)


def water(vertices):
    land[:] &= ~polygon(vertices)


