def save_and_validate():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()
    assert lon[0] == -131 and lon[-1] == -129
    assert lat[0] == 55 and lat[-1] == 53
    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    small = Image.fromarray(pixels)
    assert small.mode == "L"
    small.save(out / "candidate.png")
    big = small.resize((1016, 1016), resample=Image.Resampling.NEAREST)
    big.save(out / "candidate_8x.png")

    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert sum(map(len, rows)) == 16129
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.size == (127, 127)
        original = np.array(image)
        assert image.mode == "L"
        assert set(np.unique(original).tolist()) == {0, 255}
        assert np.array_equal(original, pixels)
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1016, 1016)
        enlarged = np.array(image)
        assert image.mode == "L"
        assert set(np.unique(enlarged).tolist()) == {0, 255}
        expected = np.repeat(np.repeat(original, 8, axis=0), 8, axis=1)
        assert np.array_equal(enlarged, expected)
    print("Validated: 127x127 = 16,129 binary points; "
          "127x127 PNG; exact 8x nearest-neighbor 1016x1016 PNG.")


if __name__ == "__main__":
    save_and_validate()
