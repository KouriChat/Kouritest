def oval(w, n, rx, ry, tilt=0.0, count=40):
    """Small islands, angular orientation in degrees."""
    import math
    a = math.radians(tilt)
    p = []
    for j in range(count):
        t = 2 * math.pi * j / count
        x, y = rx * math.cos(t), ry * math.sin(t)
        p.append((w + x * math.cos(a) - y * math.sin(a),
                  n + x * math.sin(a) + y * math.cos(a)))
    island(*p)

