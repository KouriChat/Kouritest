def contains(x, y, vertices):
    """Vectorized even-odd point-in-polygon, no external geographic data."""
    inside = np.zeros(x.shape, dtype=bool)
    a = vertices[-1]
    for b in vertices:
        x1, y1 = a
        x2, y2 = b
        if y1 != y2:
            cross = ((y1 > y) != (y2 > y)) & (
                x < x1 + (y - y1) * (x2 - x1) / (y2 - y1))
            inside ^= cross
        a = b
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    west = 105.0 - np.arange(241)[None, :] / 10.0
    north = 79.0 - np.arange(61)[:, None] / 10.0
    # Broadcast coordinates to the precise grid of 14,701 sampling points.
    west, north = np.broadcast_arrays(west, north)
    land = np.zeros((61, 241), dtype=bool)
    for coastline in islands:
        land |= contains(west, north, coastline)
    for inlet in inlets:
        land &= ~contains(west, north, inlet)
    matrix = land.astype(np.uint8)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    large = image.resize((1928, 488), resample=Image.Resampling.NEAREST)
    large.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61 and all(
        len(row) == 241 and set(row) <= {"0", "1"} for row in rows)
    assert sum(map(len, rows)) == 14701
    assert image.size == (241, 61) and large.size == (1928, 488)
    assert set(image.getdata()) <= {0, 255} and set(large.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(large), np.repeat(
        np.repeat(np.asarray(image), 8, axis=0), 8, axis=1))
    print("Verified: 61x241 = 14701 points; binary PNGs; 8x nearest neighbor.")

if __name__ == "__main__":
    main()
