"""Memory-only Mediterranean land mask; no external geographic data.

All coastlines below are hand-written approximations from geographic knowledge.
The entire grid is classified by polygon membership, not independent LLM calls.
Inland lakes are left as land. Only numpy and Pillow are required.
Run: python outputs/generate_map.py
"""
from pathlib import Path
