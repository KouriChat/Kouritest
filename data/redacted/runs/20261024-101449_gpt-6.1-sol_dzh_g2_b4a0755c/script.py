LONS = np.arange(-90, 371, 2, dtype=np.int32) / 10.0
LATS = np.arange(450, 309, -2, dtype=np.int32) / 10.0
X, Y = np.meshgrid(LONS, LATS)
land = np.zeros(X.shape, dtype=bool)


def points(text):
    a = [float(v) for v in text.replace(",", " ").split()]
    assert len(a) % 2 == 0
    return list(zip(a[::2], a[1::2]))


def inside(vertices):
    """Even/odd point test; points on an edge belong to the polygon."""
    result = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (X - x0) * dy - (Y - y0) * dx
        boundary |= (
            (np.abs(cross) < 1e-10)
            & (X >= min(x0, x1) - 1e-10)
            & (X <= max(x0, x1) + 1e-10)
            & (Y >= min(y0, y1) - 1e-10)
            & (Y <= max(y0, y1) + 1e-10)
        )
        if dy != 0:
            hit = ((y0 > Y) != (y1 > Y))
            result ^= hit & (X < x0 + (Y - y0) * dx / dy)
        x0, y0 = x1, y1
    return result | boundary


def add(text):
    global land
    land |= inside(points(text))


def subtract(text):
    global land
    land &= ~inside(points(text))


