def contains(x, y, vertices):
    """Ray crossing at each sampled coordinate; no cell-area averaging."""
    result = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crossing = ((ay > y) != (by > y))
            edge_x = ax + (y - ay) * (bx - ax) / (by - ay)
            result ^= crossing & (x < edge_x)
        ax, ay = bx, by
    return result

def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    # Integer tenths fix both endpoint inclusion and row/column order.
    west = np.arange(1050, 809, -1, dtype=np.int64) / 10.0
    north = np.arange(790, 729, -1, dtype=np.int64) / 10.0
    x, y = np.meshgrid(west, north)
    land = np.zeros((61, 241), dtype=bool)
    for name, outline in LAND:
        land |= contains(x, y, outline)
    for name, outline in SEA:
        land &= ~contains(x, y, outline)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert np.isin(matrix, [0, 1]).all()
    assert (west[0], west[-1], north[0], north[-1]) == (105, 81, 79, 73)

    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)

    raw = Image.fromarray(matrix * np.uint8(255))
    raw_path = output / "candidate.png"
    enlarged_path = output / "candidate_8x.png"
    raw.save(raw_path)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    raw.resize((1928, 488), resample=nearest).save(enlarged_path)
    with Image.open(raw_path) as image:
        assert image.size == (241, 61)
        raw_pixels = np.array(image)
    with Image.open(enlarged_path) as image:
        assert image.size == (1928, 488)
        enlarged_pixels = np.array(image)
    assert set(np.unique(raw_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(raw_pixels, matrix * np.uint8(255))
    assert np.array_equal(
        enlarged_pixels, np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
    )
    print("Validated: 61 x 241 = 14,701 binary values; CSV has no gaps.")
    print("Validated: black/white PNGs; 241 x 61 and exact 8x nearest-neighbor.")
    print("Output directory:", output.resolve())

if __name__ == "__main__":
    main()
