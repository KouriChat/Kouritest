def inside(x, y, p):
    hit = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]; xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            xx = (xj-xi) * (y-yi) / (yj-yi) + xi
            if x <= xx:
                hit = not hit
        j = i
    return hit

