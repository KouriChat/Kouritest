def antarctic_coast(lon):
    anchors = [
        (-180, -85), (-150, -85), (-140, -75), (-120, -73),
        (-90, -72), (-65, -71), (-60, -63), (-55, -66),
        (-50, -72), (-45, -83), (-30, -83), (-20, -72),
        (0, -70), (30, -69), (60, -68), (90, -67),
        (120, -66), (150, -67), (160, -85), (180, -85),
    ]
    for i in range(len(anchors) - 1):
        x1, y1 = anchors[i]
        x2, y2 = anchors[i + 1]
        if x1 <= lon <= x2:
            t = (lon - x1) / (x2 - x1)
            return y1 + t * (y2 - y1)
    return -70.0


