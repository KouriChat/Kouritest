def is_land(lon, lat):
    if lat <= antarctic_coast(lon):
        return True
    hit = False
    for pts in LAND_POLYGONS:
        if in_polygon(lon, lat, pts):
            hit = True
            break
    if not hit:
        for pts in ISLAND_POLYGONS:
            if in_polygon(lon, lat, pts):
                hit = True
                break
    if not hit:
        for cx, cy, rx, ry, angle in ISLAND_ELLIPSES:
            if ellipse(lon, lat, cx, cy, rx, ry, angle):
                hit = True
                break
    if hit:
        for pts in WATER_MASKS:
            if in_polygon(lon, lat, pts):
                return False
    return hit


def build_matrix():
    lats = [89 - 2 * i for i in range(90)]
    lons = [-179 + 2 * j for j in range(180)]
    arr = np.zeros((90, 180), dtype=np.uint8)
    for i, lat in enumerate(lats):
        for j, lon in enumerate(lons):
            arr[i, j] = 1 if is_land(lon, lat) else 0
    return arr


def main():
    os.makedirs("outputs", exist_ok=True)
    arr = build_matrix()
    assert arr.shape == (90, 180), arr.shape
    assert np.isin(arr, [0, 1]).all()
    with open("outputs/candidate.csv", "w", encoding="ascii", newline="") as f:
        for row in arr:
            f.write(",".join("1" if v else "0" for v in row) + "\n")
    img = Image.fromarray((arr * 255).astype(np.uint8), mode="L")
