def polygon(points):
    return [tuple(p) for p in points]


def in_polygon(lon, lat, pts):
    """Ray casting; a point exactly on an edge is treated as land."""
    inside = False
    n = len(pts)
    for i in range(n):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % n]
        cross = (x2 - x1) * (lat - y1) - (y2 - y1) * (lon - x1)
        if abs(cross) < 1e-9 and min(x1, x2) - 1e-9 <= lon <= max(x1, x2) + 1e-9 \
                and min(y1, y2) - 1e-9 <= lat <= max(y1, y2) + 1e-9:
            return True
        if (y1 > lat) != (y2 > lat):
            xin = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < xin:
                inside = not inside
    return inside


def ellipse(lon, lat, cx, cy, rx, ry, angle=0.0):
    a = math.radians(angle)
    dx, dy = lon - cx, lat - cy
    x = dx * math.cos(a) + dy * math.sin(a)
    y = -dx * math.sin(a) + dy * math.cos(a)
    return (x / rx) ** 2 + (y / ry) ** 2 <= 1.0


def capsule(lon, lat, x1, y1, x2, y2, width):
    vx, vy = x2 - x1, y2 - y1
    wx, wy = lon - x1, lat - y1
    t = (wx * vx + wy * vy) / (vx * vx + vy * vy)
    t = max(0.0, min(1.0, t))
    px, py = x1 + t * vx, y1 + t * vy
    return (lon - px) ** 2 + (lat - py) ** 2 <= width ** 2


