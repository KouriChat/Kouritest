def points_in_polygon(lon_grid, lat_grid, polygon):
    """Vectorized ray-casting point-in-polygon test."""
    inside = np.zeros(lon_grid.shape, dtype=bool)
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        crosses = (yi > lat_grid) != (yj > lat_grid)
        edge_x = (xj - xi) * (lat_grid - yi) / ((yj - yi) + 1e-30) + xi
        inside ^= crosses & (lon_grid < edge_x)
        j = i
    return inside


def build_matrix():
    latitudes = 23.0 - 0.2 * np.arange(111)
    longitudes = 99.0 + 0.2 * np.arange(141)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((111, 141), dtype=bool)
    for polygon in POLYGONS:
        land |= points_in_polygon(lon_grid, lat_grid, polygon)
    return land.astype(np.uint8)


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    matrix = build_matrix()
    if matrix.shape != (111, 141):
        raise RuntimeError(f"Unexpected matrix shape: {matrix.shape}")

    with (output_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as csv_file:
        for row in matrix:
            csv_file.write(",".join(str(int(value)) for value in row) + "\n")

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")
    enlarged = image.resize(
        (1128, 888), resample=Image.Resampling.NEAREST
    )
    enlarged.save(output_dir / "candidate_8x.png")

    rows = (output_dir / "candidate.csv").read_text(
        encoding="ascii"
    ).splitlines()
    if len(rows) != 111 or any(
        len(row.split(",")) != 141
        or any(value not in {"0", "1"} for value in row.split(","))
        for row in rows
    ):
        raise RuntimeError("CSV validation failed")
    if set(np.unique(np.asarray(image))) != {0, 255}:
        raise RuntimeError("Image must contain only black and white")
    if Image.open(output_dir / "candidate_8x.png").size != (1128, 888):
        raise RuntimeError("Enlarged image size validation failed")


if __name__ == "__main__":
    main()
