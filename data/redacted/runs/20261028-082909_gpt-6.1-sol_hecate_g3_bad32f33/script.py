ALL_POLYGONS = [MAINLAND, ALASKA, *ISLANDS, *HAIDA, *SMALL_ISLANDS]


def is_land(lon, lat):
    return any(inside(lon, lat, poly) for poly in ALL_POLYGONS)


def make_matrix():
    # Exact requested endpoints, with 2/126 degree increments.
    return [
        [1 if is_land(-131.0 + 2.0 * col / 126.0,
                      55.0 - 2.0 * row / 126.0) else 0
         for col in range(127)]
        for row in range(127)
    ]


def write_outputs(matrix):
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)

    raw = Image.new("1", (127, 127))
    raw.putdata([255 if value else 0 for row in matrix for value in row])
    raw.save(out / "candidate.png")

    enlarged = raw.resize((1016, 1016), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")


if __name__ == "__main__":
    matrix = make_matrix()
    write_outputs(matrix)
