def inside(x, y, polygon):
    """Even/odd ray crossing using only manually supplied vertices."""
    result = False
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        if (y0 > y) != (y1 > y):
            cross_x = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            if x < cross_x:
                result = not result
        x0, y0 = x1, y1
    return result


def main():
    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    matrix = []
    for lat in range(89, -90, -2):
        row = []
        for lon in range(-179, 180, 2):
            land = any(inside(lon, lat, p) for p in polygons)
            if land and any(inside(lon, lat, p) for p in water_polygons):
                land = False
            row.append(int(land))
        matrix.append(row)
    assert len(matrix) == 90 and all(len(row) == 180 for row in matrix)
    assert sum(map(len, matrix)) == 16200
    assert {v for row in matrix for v in row} <= {0, 1}
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f, lineterminator='\n').writerows(matrix)
    image = Image.new('L', (180, 90))
    image.putdata([v * 255 for row in matrix for v in row])
    image.save(out / 'candidate.png')
    large = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    large.save(out / 'candidate_8x.png')
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        saved = list(csv.reader(f))
    assert len(saved) == 90 and all(len(row) == 180 for row in saved)
    assert all(v in ('0', '1') for row in saved for v in row)
    with Image.open(out / 'candidate.png') as raw, Image.open(out / 'candidate_8x.png') as big:
        assert raw.size == (180, 90) and big.size == (1440, 720)
        assert set(raw.getdata()) == {0, 255}
        assert set(big.getdata()) == {0, 255}
        assert list(raw.getdata()) == [int(v) * 255 for row in saved for v in row]
        pixels, small = big.load(), raw.load()
        assert all(pixels[x, y] == small[x // 8, y // 8]
                   for y in range(720) for x in range(1440))
    print('Verified: 90 x 180 = 16200 binary entries; PNG 180 x 90; '
          'PNG 1440 x 720, exact nearest-neighbor 8x; black and white only.')


if __name__ == '__main__':
    main()
