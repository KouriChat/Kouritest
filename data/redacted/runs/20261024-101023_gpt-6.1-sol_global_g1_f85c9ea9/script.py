POLYGONS = []

def polygon(name, text):
    points = [tuple(map(float, token.split(","))) for token in text.split()]
    assert len(points) >= 3 and all(len(p) == 2 for p in points), name
    POLYGONS.append((name, points))

def ellipse(name, lon, lat, rx, ry, angle=0):
    t = np.linspace(0, 2*np.pi, 49)[:-1]
    a = np.deg2rad(angle)
    x, y = rx*np.cos(t), ry*np.sin(t)
    points = list(zip(lon+x*np.cos(a)-y*np.sin(a),
                      lat+x*np.sin(a)+y*np.cos(a)))
    POLYGONS.append((name, points))

