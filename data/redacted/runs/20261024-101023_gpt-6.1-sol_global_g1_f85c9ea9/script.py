def polygon_mask(points, longitude, latitude):
    """Even-odd ray casting, with boundaries land and periodic longitude."""
    result = np.zeros(longitude.shape, dtype=bool)
    vertices = np.asarray(points, dtype=np.float64)
    xmin, ymin = vertices.min(axis=0)
    xmax, ymax = vertices.max(axis=0)
    for offset in (-360.0, 0.0, 360.0):
        xx = longitude + offset
        eligible = ((xx >= xmin) & (xx <= xmax) &
                    (latitude >= ymin) & (latitude <= ymax))
        if not eligible.any():
            continue
        x, y = xx[eligible], latitude[eligible]
        inside = np.zeros(x.shape, dtype=bool)
        boundary = np.zeros(x.shape, dtype=bool)
        ax, ay = vertices[-1]
        for bx, by in vertices:
            dx, dy = bx-ax, by-ay
            if dy != 0:
                crossing = ((ay > y) != (by > y))
                inside ^= crossing & (x < ax + dx*(y-ay)/dy)
            cross_product = (x-ax)*dy - (y-ay)*dx
            on_segment = (
                (np.abs(cross_product) < 1e-10) &
                (x >= min(ax, bx)-1e-10) & (x <= max(ax, bx)+1e-10) &
                (y >= min(ay, by)-1e-10) & (y <= max(ay, by)+1e-10)
            )
            boundary |= on_segment
            ax, ay = bx, by
        result[eligible] |= inside | boundary
    return result

def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for name, points in POLYGONS:
        land |= polygon_mask(points, longitude, latitude)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert set(np.unique(matrix).tolist()) == {0, 1}
    with (output / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(output / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    image.resize((1440, 720), resample=nearest).save(output / "candidate_8x.png")

    # Reopen only the files just generated, never any external geographic data.
    with (output / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(output / "candidate.png") as original:
        assert original.size == (180, 90) and original.mode == "L"
        original_pixels = np.array(original)
    with Image.open(output / "candidate_8x.png") as enlarged:
        assert enlarged.size == (1440, 720) and enlarged.mode == "L"
        enlarged_pixels = np.array(enlarged)
    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, pixels)
    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged_pixels, expected)
    report = {
        "matrix_shape": list(matrix.shape),
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "matrix_values": [0, 1],
        "png_values": [0, 255],
        "original_size": [180, 90],
        "enlarged_size": [1440, 720],
        "nearest_neighbor_8x_verified": True,
        "handwritten_polygon_count": len(POLYGONS),
        "external_geographic_data_used": False,
    }
    (output / "validation.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))

