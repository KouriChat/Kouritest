X, Y = np.meshgrid(LON, LAT)
LAND = np.zeros((64, 253), dtype=bool)
POLYGONS = []

def polygon(name, text):
    """Union a hand-estimated land polygon into the point classification."""
    points = [tuple(map(float, token.split(','))) for token in text.split()]
    if len(points) < 3:
        raise ValueError(name)
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y0 != y1:
            crosses = ((y0 > Y) != (y1 > Y))
            xcross = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (X < xcross)
        x0, y0 = x1, y1
    LAND[:] |= inside
    POLYGONS.append({'name': name, 'vertices': len(points)})

