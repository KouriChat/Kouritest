NY, NX = 64, 253
LON = np.linspace(129., 137., NX)
LAT = np.linspace(35., 33., NY)
X, Y = np.meshgrid(LON, LAT)
land = np.zeros((NY, NX), dtype=bool)


def polygon(vertices):
    """Use an even-odd point-in-polygon test at sample centers (not cells)."""
    global land
    v = np.asarray(vertices, dtype=float)
    inside = np.zeros_like(land)
    for a, b in zip(v, np.roll(v, -1, axis=0)):
        xa, ya = a
        xb, yb = b
        if ya == yb:
            continue
        crossing = ((ya > Y) != (yb > Y)) & (X < (xb - xa) * (Y - ya) / (yb - ya) + xa)
        inside ^= crossing
    land |= inside


def island(cx, cy, rx, ry, tilt=0):
    """Approximate a small island with a rotated, point-tested ellipse."""
    global land
    theta = np.deg2rad(tilt)
    u = (X-cx)*np.cos(theta)+(Y-cy)*np.sin(theta)
    v = -(X-cx)*np.sin(theta)+(Y-cy)*np.cos(theta)
    land |= (u/rx)**2+(v/ry)**2 <= 1


