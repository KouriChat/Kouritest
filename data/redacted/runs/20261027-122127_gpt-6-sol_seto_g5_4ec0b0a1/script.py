def contains(x, y, ring):
    """Ray crossing rule on a hand-drawn coastal polygon."""
    inside = np.zeros_like(x, dtype=bool)
    for (a, b), (c, d) in zip(ring, ring[1:] + ring[:1]):
        if b == d:
            continue
        cross = (a + (y - b) * (c - a) / (d - b))
        inside ^= ((b > y) != (d > y)) & (x < cross)
    return inside


def polygon(ring):
    global land
    land |= contains(lons, lats, ring)


def oval(cx, cy, rx, ry, tilt=0):
    """Hand-estimated island extents; tilt is lon offset per degree latitude."""
    global land
    dx = (lons - cx - tilt * (lats - cy)) / rx
    dy = (lats - cy) / ry
    land |= dx * dx + dy * dy <= 1


def water_oval(cx, cy, rx, ry, tilt=0):
    global land
    dx = (lons - cx - tilt * (lats - cy)) / rx
    dy = (lats - cy) / ry
    land &= dx * dx + dy * dy > 1


