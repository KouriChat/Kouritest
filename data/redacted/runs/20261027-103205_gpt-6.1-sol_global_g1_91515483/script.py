def build_matrix():
    rows = []
    for lat in range(89, -90, -2):
        row = []
        for lon in range(-179, 180, 2):
            row.append(int(any(contains(lon, lat, poly) for _, poly in LAND)))
        rows.append(row)
    return rows


def png_bytes(rows, scale=1):
    """Write a standards-compliant grayscale PNG, with nearest-neighbor scaling."""
    width, height = len(rows[0]), len(rows)
    scanlines = []
    for row in rows:
        pixels = bytes(255 if cell else 0 for cell in row)
        pixels = b'\0' + pixels
        scanlines.extend([pixels] * scale)
    if scale > 1:
        scanlines = [b'\0' + bytes(255 if rows[y // scale][x // scale] else 0
                     for x in range(width * scale)) for y in range(height * scale)]
    raw = b''.join(scanlines)

    def chunk(kind, data):
        body = kind + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xffffffff)

    return (b'\x89PNG\r\n\x1a\n' +
            chunk(b'IHDR', struct.pack('>2I5B', width*scale, height*scale, 8, 0, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def main():
    output = Path('outputs')
    output.mkdir(parents=True, exist_ok=True)
    matrix = build_matrix()
    with (output / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        writer = csv.writer(f, lineterminator='\n')
        writer.writerows(matrix)
    (output / 'candidate.png').write_bytes(png_bytes(matrix))
    (output / 'candidate_8x.png').write_bytes(png_bytes(matrix, 8))
    assert len(matrix) == 90 and all(len(row) == 180 for row in matrix)
    assert all(cell in (0, 1) for row in matrix for cell in row)
    print('Wrote 90x180 matrix (16200 values) and 180x90 / 1440x720 PNGs.')


if __name__ == '__main__':
    main()
