LAND = []


def land(name, points):
    if len(points) < 3:
        raise ValueError(name)
    LAND.append((name, tuple(points)))


def contains(x, y, polygon):
    """Even-odd rule; polygon coordinates must not jump across the dateline."""
    inside = False
    ax, ay = polygon[-1]
    for bx, by in polygon:
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        if abs(cross) < 1e-10 and min(ax, bx) <= x <= max(ax, bx) and min(ay, by) <= y <= max(ay, by):
            return True
        if (ay > y) != (by > y):
            if x < ax + (y - ay) * (bx - ax) / (by - ay):
                inside = not inside
        ax, ay = bx, by
    return inside


