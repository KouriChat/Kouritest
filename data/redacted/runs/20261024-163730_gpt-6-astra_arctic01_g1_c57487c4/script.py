def contains_points(vertices, x, y):
    """Even/odd ray test on points, with boundary points included.

    Straight segments in longitude/latitude are an approximation rule, not
    imported coastlines. No cell areas or subpixel majority votes are used.
    """
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    eps = 1e-10
    for i, (ax, ay) in enumerate(vertices):
        bx, by = vertices[(i + 1) % len(vertices)]
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= eps)
            & (x >= min(ax, bx) - eps) & (x <= max(ax, bx) + eps)
            & (y >= min(ay, by) - eps) & (y <= max(ay, by) + eps)
        )
        if abs(dy) > eps:
            straddles = (ay > y) != (by > y)
            crossing_x = ax + (y - ay) * dx / dy
            inside ^= straddles & (x < crossing_x)
    return inside | boundary


def generate():
    longitude = np.arange(-1050, -809, dtype=np.int64) / 10.0
    latitude = np.arange(790, 729, -1, dtype=np.int64) / 10.0
    x, y = np.meshgrid(longitude, latitude)
    assert x.shape == y.shape == (61, 241)
    assert latitude[0] == 79 and latitude[-1] == 73
    assert longitude[0] == -105 and longitude[-1] == -81
    mask = np.zeros((61, 241), dtype=bool)
    for _, vertices in LAND:
        mask |= contains_points(vertices, x, y)
    for _, vertices in WATER:
        mask &= ~contains_points(vertices, x, y)
    # These islands are within/near the broad fjord-mouth approximations.
    # Their own land outlines take precedence over those water cutouts.
    protected_islands = {
        "Stor Island", "Eureka Sound small island", "Beechey Island"
    }
    for name, vertices in LAND:
        if name in protected_islands:
            mask |= contains_points(vertices, x, y)
    return mask.astype(np.uint8)


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = generate()
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, [0, 1]).all()
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    assert image.mode == "L"
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Reopen and validate the actual written files, not just in-memory arrays.
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 14701
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as saved:
        assert saved.size == (241, 61)
        assert saved.mode == "L"
        original_pixels = np.array(saved)
    with Image.open(out / "candidate_8x.png") as saved:
        assert saved.size == (1928, 488)
        assert saved.mode == "L"
        enlarged_pixels = np.array(saved)
    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, pixels)
    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged_pixels, expected)
    print("Validated: 61x241 = 14,701 binary point samples; CSV complete; "
          "241x61 PNG and exact 8x nearest-neighbor 1928x488 PNG; black/white only.")


if __name__ == "__main__":
    main()
