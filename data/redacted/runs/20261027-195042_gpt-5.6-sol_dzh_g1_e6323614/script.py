def point_in_ring(lon, lat, ring):
    inside = False
    x1, y1 = ring[-1]
    for x2, y2 in ring:
        if (y1 > lat) != (y2 > lat):
            crossing = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < crossing:
                inside = not inside
        x1, y1 = x2, y2
    return inside


def island_contains(lon, lat, island):
    cx, cy, rx, ry, rotation = island
    angle = math.radians(rotation)
    dx, dy = lon - cx, lat - cy
    u = (dx * math.cos(angle) + dy * math.sin(angle)) / rx
    v = (-dx * math.sin(angle) + dy * math.cos(angle)) / ry
    return u * u + v * v <= 1.0


def is_land(lon, lat):
    return any(point_in_ring(lon, lat, ring) for ring in LAND_RINGS) or any(
        island_contains(lon, lat, island) for island in ISLANDS
    )


def main():
    rows, cols = 71, 231
    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for row in range(rows):
        lat = LAT_NORTH - row * LAT_STEP
        for col in range(cols):
            lon = LON_WEST + col * LON_STEP
            matrix[row, col] = int(is_land(lon, lat))

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((cols * 8, rows * 8), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        saved = list(csv.reader(f))
    assert len(saved) == rows and all(len(r) == cols for r in saved)
    assert all(value in ("0", "1") for r in saved for value in r)
    assert int(matrix.sum()) + int((matrix == 0).sum()) == rows * cols
    raw = Image.open(out / "candidate.png")
    enlarged = Image.open(out / "candidate_8x.png")
    assert raw.size == (231, 71) and enlarged.size == (1848, 568)
    assert set(raw.getdata()) == {0, 255}
    expected = raw.resize(enlarged.size, resample=Image.Resampling.NEAREST)
    assert list(expected.getdata()) == list(enlarged.getdata())
    print(f"validated {rows}x{cols} matrix; land points: {int(matrix.sum())}")


if __name__ == "__main__":
    main()
