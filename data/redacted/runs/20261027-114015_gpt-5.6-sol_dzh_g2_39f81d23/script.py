# All vertices below are a hand-drawn, from-memory approximation in lon/lat.
def inside(x, y, p):
    c = False
    j = len(p)-1
    for i in range(len(p)):
        xi,yi=p[i]; xj,yj=p[j]
        if ((yi>y)!=(yj>y)) and x < (xj-xi)*(y-yi)/(yj-yi)+xi: c=not c
        j=i
    return c

def ellipse(x,y,cx,cy,rx,ry,ang=0):
    a=math.radians(ang); u=x-cx; v=y-cy
    q=u*math.cos(a)+v*math.sin(a); r=-u*math.sin(a)+v*math.cos(a)
    return (q/rx)**2+(r/ry)**2 <= 1

