def build_map():
    land = Image.new("1", (180, 90), 0)
    draw = ImageDraw.Draw(land)
    for polygon in POLYGONS:
        points = [((lon + 179) / 2, (89 - lat) / 2) for lon, lat in polygon]
        draw.polygon(points, fill=1)
    return np.asarray(land, dtype=np.uint8)


def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    matrix = build_map()
    if matrix.shape != (90, 180):
        raise ValueError(f"unexpected matrix shape: {matrix.shape}")
    np.savetxt(output / "candidate.csv", matrix, fmt="%d", delimiter=",")
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        output / "candidate_8x.png"
    )
    print(f"wrote {matrix.shape[0]}x{matrix.shape[1]} matrix ({matrix.size} values)")



