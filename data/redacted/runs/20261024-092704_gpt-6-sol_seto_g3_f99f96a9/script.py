LON = 129.0 + np.arange(253) * (8.0 / 252)
LAT = 35.0 - np.arange(64) * (2.0 / 63)
X, Y = np.meshgrid(LON, LAT)
land = np.zeros((64, 253), dtype=bool)

def polygon(vertices):
    """Vectorized even-odd test on sampling POINTS, not cell areas."""
    inside = np.zeros(X.shape, dtype=bool)
    for (x1, y1), (x2, y2) in zip(vertices, vertices[1:] + vertices[:1]):
        if y1 == y2:
            continue
        crossing = ((y1 > Y) != (y2 > Y))
        xcross = x1 + (Y - y1) * (x2 - x1) / (y2 - y1)
        inside ^= crossing & (X < xcross)
    land[:] |= inside

def oval(x, y, rx, ry, angle=0):
    """One small manually positioned island: rotated ellipse in lon/lat."""
    a = np.deg2rad(angle)
    dx, dy = X - x, Y - y
    u = dx * np.cos(a) + dy * np.sin(a)
    v = -dx * np.sin(a) + dy * np.cos(a)
    land[:] |= (u / rx) ** 2 + (v / ry) ** 2 <= 1

