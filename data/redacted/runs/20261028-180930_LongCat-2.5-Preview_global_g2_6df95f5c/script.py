def build_mask():
    mask = np.zeros((len(LATS), len(LONS)), dtype=np.uint8)
    for poly in LAND_POLYS:
        fill_poly(mask, poly, 1)
    for poly in WATER_POLYS:
        fill_poly(mask, poly, 0)
    for poly in ISLAND_POLYS:
        fill_poly(mask, poly, 1)
    return mask

def main():
    os.makedirs("outputs", exist_ok=True)
    mask = build_mask()
    assert mask.shape == (90, 180)
    assert int(mask.sum()) > 0 and int(mask.sum()) < mask.size
    np.savetxt("outputs/candidate.csv", mask, fmt="%d", delimiter=",")
    image = Image.fromarray((mask * 255).astype(np.uint8), mode="L")
    image.save("outputs/candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save("outputs/candidate_8x.png")
    print("shape", mask.shape, "land", int(mask.sum()), "water", int(mask.size - mask.sum()))

if __name__ == "__main__":
    main()
