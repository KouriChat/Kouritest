def pip(lon, lat, poly):
    inside = False
    n = len(poly)
    for k in range(n):
        x1, y1 = poly[k]
        x2, y2 = poly[(k + 1) % n]
        if (y1 > lat) != (y2 > lat):
            xin = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < xin:
                inside = not inside
    return inside

def in_poly(lon, lat, poly):
    for shift in (-360.0, 0.0, 360.0):
        if pip(lon + shift, lat, poly):
            return True
    return False

def fill_poly(mask, poly, value):
    for i, lat in enumerate(LATS):
        for j, lon in enumerate(LONS):
            if in_poly(float(lon), float(lat), poly):
                mask[i, j] = value

