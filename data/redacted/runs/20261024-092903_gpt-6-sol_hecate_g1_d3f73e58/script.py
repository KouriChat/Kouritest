def land_at(lon, lat):
    on_mainland = in_poly(lon, lat, mainland)
    if on_mainland and not any(in_poly(lon, lat, c) for c in inlets):
        return 1
    if any(in_poly(lon, lat, island) for island in islands):
        return 1
    if any(ellipse(lon, lat, *reef) for reef in rocks):
        return 1
    return 0


def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    rows = [
        [land_at(WEST + 2 * j / (N - 1), NORTH - 2 * i / (N - 1))
         for j in range(N)]
        for i in range(N)
    ]
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(rows)

    img = Image.new("L", (N, N))
    img.putdata([v * 255 for row in rows for v in row])
    img.save(out / "candidate.png")
    enlarged = img.resize((N * 8, N * 8), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        checked = [list(map(int, row)) for row in csv.reader(f)]
    assert len(checked) == N and all(len(row) == N for row in checked)
    assert all(value in (0, 1) for row in checked for value in row)
    assert checked == rows
    with Image.open(out / "candidate.png") as source:
        assert source.size == (127, 127)
        assert set(source.getdata()) <= {0, 255}
        expected = source.resize((1016, 1016), Image.Resampling.NEAREST)
        with Image.open(out / "candidate_8x.png") as scaled:
            assert scaled.size == (1016, 1016)
            assert set(scaled.getdata()) <= {0, 255}
            assert list(scaled.getdata()) == list(expected.getdata())
    print("Validated: 127x127, 16129 binary points, 1016x1016 nearest-neighbor.")


if __name__ == "__main__":
    main()
