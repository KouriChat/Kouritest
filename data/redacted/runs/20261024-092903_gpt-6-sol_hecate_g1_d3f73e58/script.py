def in_poly(x, y, vertices):
    inside = False
    j = len(vertices) - 1
    for i, (xi, yi) in enumerate(vertices):
        xj, yj = vertices[j]
        if (yi > y) != (yj > y):
            cross = xi + (y - yi) * (xj - xi) / (yj - yi)
            if x < cross:
                inside = not inside
        j = i
    return inside


def ellipse(x, y, cx, cy, rx, ry, angle=0):
    # Orientation angle is counter-clockwise in degrees.
    import math
    a = math.radians(angle)
    u, v = x - cx, y - cy
    t = (u * math.cos(a) + v * math.sin(a)) / rx
    s = (-u * math.sin(a) + v * math.cos(a)) / ry
    return t * t + s * s <= 1


