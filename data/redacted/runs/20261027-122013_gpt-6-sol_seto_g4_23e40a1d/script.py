def contains_polygon(lon, lat, polygon):
    inside = False
    previous_x, previous_y = polygon[-1]
    for current_x, current_y in polygon:
        if (current_y > lat) != (previous_y > lat):
            crossing_x = current_x + (
                (lat - current_y) * (previous_x - current_x)
                / (previous_y - current_y)
            )
            if lon < crossing_x:
                inside = not inside
        previous_x, previous_y = current_x, current_y
    return inside


def make_ellipse(spec):
    cx, cy, rx, ry, degrees = map(float, spec.split())
    theta = math.radians(degrees)
    return cx, cy, rx, ry, math.cos(theta), math.sin(theta)


def contains_ellipse(lon, lat, ellipse):
    cx, cy, rx, ry, cosine, sine = ellipse
    dx, dy = lon - cx, lat - cy
    local_x = dx * cosine + dy * sine
    local_y = -dx * sine + dy * cosine
    return (local_x / rx) ** 2 + (local_y / ry) ** 2 <= 1.0


def main():
    polygons = MAINLANDS + ISLAND_POLYGONS
    ellipses = [
        make_ellipse(line)
        for line in ISLAND_ELLIPSES_TEXT.strip().splitlines()
    ]
    matrix = np.zeros((64, 253), dtype=np.uint8)
    for row in range(64):
        lat = 35.0 - row * (2.0 / 63.0)
        for col in range(253):
            lon = 129.0 + col * (8.0 / 252.0)
            land = any(
                contains_polygon(lon, lat, polygon)
                for polygon in polygons
            )
            if not land:
                land = any(
                    contains_ellipse(lon, lat, ellipse)
                    for ellipse in ellipses
                )
            matrix[row, col] = int(land)

    output_dir = Path("outputs")
    output_dir.mkdir(exist_ok=True)
    csv_path = output_dir / "candidate.csv"
    original_path = output_dir / "candidate.png"
    enlarged_path = output_dir / "candidate_8x.png"

    with csv_path.open("w", encoding="utf-8", newline="") as file:
        csv.writer(file).writerows(matrix.tolist())

    original = Image.fromarray(matrix * np.uint8(255), mode="L")
    enlarged = original.resize((2024, 512), Image.Resampling.NEAREST)
    original.save(original_path)
    enlarged.save(enlarged_path)

    with csv_path.open("r", encoding="utf-8", newline="") as file:
        rows = list(csv.reader(file))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    assert sum(map(len, rows)) == 16192
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)

    with Image.open(original_path) as saved_original:
        original_pixels = np.asarray(saved_original.convert("L"))
        assert saved_original.size == (253, 64)
        assert set(np.unique(original_pixels).tolist()) <= {0, 255}
    with Image.open(enlarged_path) as saved_enlarged:
        enlarged_pixels = np.asarray(saved_enlarged.convert("L"))
        assert saved_enlarged.size == (2024, 512)
        assert set(np.unique(enlarged_pixels).tolist()) <= {0, 255}
        assert np.array_equal(
            enlarged_pixels,
            np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1),
        )
    print(f"Validated: {csv_path}, {original_path}, {enlarged_path}")


if __name__ == "__main__":
    main()
