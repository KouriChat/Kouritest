def inside(lon, lat, polygon):
    """Even-odd point-in-polygon test for non-dateline-crossing rings."""
    hit = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                hit = not hit
        j = i
    return hit

def build():
    latitudes = np.arange(89, -90, -2, dtype=int)
    longitudes = np.arange(-179, 180, 2, dtype=int)
    matrix = np.zeros((len(latitudes), len(longitudes)), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            land = any(inside(lon, lat, ring) for ring in LAND)
            if land and any(west <= lon <= east and south <= lat <= north
                            for west, south, east, north in LAKES):
                land = False
            matrix[row, col] = int(land)
    return matrix


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = build()
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())
    # Image convention: white land (1), black water (0), north at top.
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")


if __name__ == "__main__":
    main()
