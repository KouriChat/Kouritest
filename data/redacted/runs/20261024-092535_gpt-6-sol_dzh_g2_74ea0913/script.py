XS = np.linspace(-9, 37, 231)
YS = np.linspace(45, 31, 71)
X, Y = np.meshgrid(XS, YS)
land = np.zeros(X.shape, dtype=bool)

def polygon(points):
    """Point-in-polygon test on the sampling points (not pixel area)."""
    inside = np.zeros(X.shape, dtype=bool)
    for (ax, ay), (bx, by) in zip(points, points[1:] + points[:1]):
        if ay != by:
            inside ^= ((ay > Y) != (by > Y)) & (
                X < (bx - ax) * (Y - ay) / (by - ay) + ax
            )
    return inside

def add(points):
    land[:] |= polygon(points)

def remove(points):
    land[:] &= ~polygon(points)

def oval(lon, lat, rx, ry, angle=0):
    a = np.deg2rad(angle)
    u = (X-lon)*np.cos(a) + (Y-lat)*np.sin(a)
    v = -(X-lon)*np.sin(a) + (Y-lat)*np.cos(a)
    land[:] |= (u/rx)**2 + (v/ry)**2 <= 1

