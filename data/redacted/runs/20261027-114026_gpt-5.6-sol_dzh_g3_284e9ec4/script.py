LONS=np.round(np.arange(-9,37.0001,.2),10); LATS=np.round(np.arange(45,30.9999,-.2),10)
A=np.zeros((len(LATS),len(LONS)),dtype=np.uint8)
def pip(x,y,p):
    c=False; j=len(p)-1
    for i,(xi,yi) in enumerate(p):
        xj,yj=p[j]
        if ((yi>y)!=(yj>y)) and x < (xj-xi)*(y-yi)/(yj-yi)+xi: c=not c
        j=i
    return c
def poly(p,v=1):
    for r,y in enumerate(LATS):
        for c,x in enumerate(LONS):
            if pip(x,y,p): A[r,c]=v
def oval(x,y,rx,ry):
    A[:]=np.maximum(A,(((LONS[None,:]-x)/rx)**2+((LATS[:,None]-y)/ry)**2<=1).astype(np.uint8))

