def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lat = np.arange(89, -90, -2, dtype=float)
    lon = np.arange(-179, 180, 2, dtype=float)
    xx, yy = np.meshgrid(lon, lat)
    land = np.zeros(xx.shape, dtype=bool)
    for vertices in LAND:
        land |= poly_mask(xx, yy, vertices)
    matrix = land.astype(np.uint8)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Pillow uses RGB to ensure precisely two colors with no palette artifacts.
    pixels = np.where(land, 255, 0).astype(np.uint8)
    rgb = np.repeat(pixels[:, :, None], 3, axis=2)
    image = Image.fromarray(rgb, mode="RGB")
    image.save(out / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(out / "candidate_8x.png")


if __name__ == "__main__":
    main()
