def poly_mask(x, y, vertices):
    """Vectorized even/odd polygon test; wrapped longitudes support the dateline."""
    verts = np.asarray(vertices, dtype=float)
    a, b = verts[:, 0], verts[:, 1]
    answer = np.zeros(x.shape, dtype=bool)
    for shift in (-360, 0, 360):
        xx = x + shift
        hit = np.zeros(x.shape, dtype=bool)
        j = len(a) - 1
        for i in range(len(a)):
            cross = ((b[i] > y) != (b[j] > y)) & (
                xx < (a[j] - a[i]) * (y - b[i]) / (b[j] - b[i] + 1e-100) + a[i]
            )
            hit ^= cross
            j = i
        answer |= hit
    return answer


