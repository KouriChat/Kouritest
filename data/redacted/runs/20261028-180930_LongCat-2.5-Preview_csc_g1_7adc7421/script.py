"""Rebuild a land/sea map of the South China Sea region from hand-written
geographic rules only. No network, no external data, no image models.

Grid: lat 23..1 (N) step 0.2 -> 111 rows (north->south)
      lon 99..127 (E) step 0.2 -> 141 cols (west->east)
1 = land, 0 = water. Point criterion: each sample point is judged alone.
"""
