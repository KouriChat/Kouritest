NLAT = 111
NLON = 141
LAT0, LAT1 = 23.0, 1.0
LON0, LON1 = 99.0, 127.0


def grid_lats():
    return [LAT0 - i * 0.2 for i in range(NLAT)]


def grid_lons():
    return [LON0 + j * 0.2 for j in range(NLON)]


def in_ring(lon, lat, ring):
    n = len(ring)
    inside = False
    j = n - 1
    for i in range(n):
        xi, yi = ring[i]
        xj, yj = ring[j]
        if (yi > lat) != (yj > lat):
            xin = xi + (lat - yi) * (xj - xi) / (yj - yi)
            if lon < xin:
                inside = not inside
        j = i
    return inside


def in_poly(lon, lat, polys):
    if not polys:
        return False
    if not in_ring(lon, lat, polys[0]):
        return False
    for hole in polys[1:]:
        if in_ring(lon, lat, hole):
            return False
    return True


def in_ell(lon, lat, cx, cy, rx, ry):
    dx = (lon - cx) / rx
    dy = (lat - cy) / ry
    return dx * dx + dy * dy <= 1.0

