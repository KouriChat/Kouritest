def contains_points(lons, lats, polygon):
    inside = np.zeros(lons.shape, dtype=bool)
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        crosses = (y1 > lats) != (y2 > lats)
        crossing_x = (x2 - x1) * (lats - y1) / (y2 - y1 + 1e-15) + x1
        inside ^= crosses & (lons < crossing_x)
    return inside


def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=float)
    longitudes = np.arange(-179, 180, 2, dtype=float)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)
    for polygon in POLYGONS:
        land |= contains_points(lon_grid, lat_grid, polygon)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    with (output_dir / "candidate.csv").open(
        "w", newline="", encoding="ascii"
    ) as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(np.where(land, 255, 0).astype(np.uint8), mode="L")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )
    assert image.size == (180, 90)
    assert set(image.getdata()) <= {0, 255}


if __name__ == "__main__":
    main()
