    bounded = [
        (shape, min(p[0] for p in shape), max(p[0] for p in shape),
         min(p[1] for p in shape), max(p[1] for p in shape))
        for shape in POLYGONS
    ]
    mask = np.zeros((111, 141), dtype=np.uint8)
    for row in range(111):
        lat = round(23.0 - 0.2 * row, 10)
        for col in range(141):
            lon = round(99.0 + 0.2 * col, 10)
            for vertices, x0, x1, y0, y1 in bounded:
                if x0 <= lon <= x1 and y0 <= lat <= y1:
                    if inside(lon, lat, vertices):
                        mask[row, col] = 1
                        break
            if mask[row, col] == 0:
                for cx, cy, rx, ry, theta in SMALL_ISLANDS:
                    if (abs(lon - cx) <= max(rx, ry) * 1.45 and
                            abs(lat - cy) <= max(rx, ry) * 1.45 and
                            ellipse(lon, lat, cx, cy, rx, ry, theta)):
                        mask[row, col] = 1
                        break
    return mask


