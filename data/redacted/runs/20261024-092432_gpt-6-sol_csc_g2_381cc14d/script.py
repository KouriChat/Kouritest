def inside(x, y, vertices):
    """Odd-even ray crossing on a hand-drawn coastline / island polygon."""
    state = False
    px, py = vertices[-1]
    for qx, qy in vertices:
        if (qy > y) != (py > y):
            cut = (px - qx) * (y - qy) / (py - qy) + qx
            if x < cut:
                state = not state
        px, py = qx, qy
    return state


def ellipse(x, y, cx, cy, rx, ry, angle=0.0):
    """Approximation to a small island, optionally rotated (degrees)."""
    from math import cos, sin, radians
    t = radians(angle)
    dx, dy = x - cx, y - cy
    a = dx * cos(t) + dy * sin(t)
    b = -dx * sin(t) + dy * cos(t)
    return (a / rx) ** 2 + (b / ry) ** 2 <= 1.0


