def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, (0, 1)).all()
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / "candidate.png")
    # Explicit nearest-neighbor replication; no interpolation or retouching.
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Validate the actual saved artifacts rather than only in-memory data.
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    reread = np.array(rows, dtype=np.uint8)
    assert np.array_equal(matrix, reread)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (241, 61)
        original = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1928, 488)
        zoomed = np.array(im)
    assert set(np.unique(original)) == {0, 255}
    assert set(np.unique(zoomed)) == {0, 255}
    assert np.array_equal(original, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(original, 8, axis=0), 8, axis=1)
    assert np.array_equal(zoomed, expected)
    print("Validated: 61 x 241 = 14,701 binary point classifications.")
    print("CSV: 61 rows, 241 entries per row; no missing values.")
    print("PNG: 241 x 61; enlarged PNG: 1928 x 488; black/white only.")
    print("Nearest-neighbor enlargement verified pixel-for-pixel.")
    print(f"Land: {int(matrix.sum())}; water: {int(matrix.size-matrix.sum())}.")


if __name__ == "__main__":
    main()
