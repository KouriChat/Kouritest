LON, LAT = np.meshgrid(-105 + np.arange(241) / 10,
                      79 - np.arange(61) / 10)
land = np.zeros((61, 241), dtype=bool)


def inside(points):
    """Even-odd point-in-polygon test, applied directly to sample locations."""
    result = np.zeros(LON.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y0 != y1:
            cross = ((y0 > LAT) != (y1 > LAT))
            xhit = x0 + (LAT - y0) * (x1 - x0) / (y1 - y0)
            result ^= cross & (LON < xhit)
        x0, y0 = x1, y1
    return result


def island(points, bays=()):
    global land
    mask = inside(points)
    for bay in bays:
        mask &= ~inside(bay)
    land |= mask


