def land(x, y):
    for polygon in P:
        inside = False
        for i, (x1, y1) in enumerate(polygon):
            x2, y2 = polygon[(i + 1) % len(polygon)]
            if (y1 > y) != (y2 > y):
                if x < x1 + (y-y1)*(x2-x1)/(y2-y1):
                    inside = not inside
        if inside:
            return 1
    return 0


def main():
    ys = 45.0 - 0.2 * np.arange(71)
    xs = -9.0 + 0.2 * np.arange(231)
    a = np.array([[land(float(x), float(y)) for x in xs] for y in ys],
                 dtype=np.uint8)
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(a.tolist())
    image = Image.fromarray(a * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((1848, 568), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")
    assert a.shape == (71, 231) and a.size == 16401


if __name__ == "__main__":
    main()
