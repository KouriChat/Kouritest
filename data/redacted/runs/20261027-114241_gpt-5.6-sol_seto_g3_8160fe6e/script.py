def inside(x,y,p):
    c=False; j=len(p)-1
    for i in range(len(p)):
        xi,yi=p[i]; xj,yj=p[j]
        if ((yi>y)!=(yj>y)) and x < (xj-xi)*(y-yi)/(yj-yi)+xi: c=not c
        j=i
    return c

def poly(a,p,v=1):
    x0,x1=min(q[0] for q in p),max(q[0] for q in p); y0,y1=min(q[1] for q in p),max(q[1] for q in p)
    for r,y in enumerate(ys):
        if y0<=y<=y1:
            for c,x in enumerate(xs):
                if x0<=x<=x1 and inside(x,y,p): a[r,c]=v

def ell(a,x,y,rx,ry,ang=0,v=1):
    ca,sa=math.cos(math.radians(ang)),math.sin(math.radians(ang))
    for r,Y in enumerate(ys):
        for c,X in enumerate(xs):
            u=(X-x)*ca+(Y-y)*sa; w=-(X-x)*sa+(Y-y)*ca
            if (u/rx)**2+(w/ry)**2<=1: a[r,c]=v

