longitude = -131.0 + np.arange(N, dtype=float) * (2.0 / 126.0)
latitude = 55.0 - np.arange(N, dtype=float) * (2.0 / 126.0)
X, Y = np.meshgrid(longitude, latitude)
land = np.zeros((N, N), dtype=np.uint8)
rules = []


def paint(name, points, value=1):
    """Even/odd point-in-polygon classification at the actual sample points."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y0 != y1:
            crosses = (y0 > Y) != (y1 > Y)
            intercept = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (X < intercept)
        x0, y0 = x1, y1
    land[inside] = value
    rules.append({"name": name, "value": value, "vertices": len(points)})


