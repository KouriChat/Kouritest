"""Knowledge-only, approximate coast reconstruction; no geographic input files.

Run: python outputs/generate_map.py
Requires: numpy and Pillow. All coordinates below are hand-estimated lon/lat.
The grid is evaluated against polygons, not by independent model inference.
This reconstruction is not suitable for navigation.
"""
