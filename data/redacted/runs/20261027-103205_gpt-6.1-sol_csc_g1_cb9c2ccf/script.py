def point_mask(vertices, x, y):
    """Even-odd point test, including the boundary; no raster-cell averaging."""
    v = np.asarray(vertices, dtype=np.float64)
    eps = 1e-10
    selected = ((x >= v[:, 0].min() - eps) & (x <= v[:, 0].max() + eps)
                & (y >= v[:, 1].min() - eps) & (y <= v[:, 1].max() + eps))
    result = np.zeros(x.shape, dtype=bool)
    if not selected.any():
        return result
    px, py = x[selected], y[selected]
    inside = np.zeros(px.shape, dtype=bool)
    boundary = np.zeros(px.shape, dtype=bool)
    for i in range(len(v)):
        x0, y0 = v[i - 1]
        x1, y1 = v[i]
        dx, dy = x1 - x0, y1 - y0
        cross = (px - x0) * dy - (py - y0) * dx
        boundary |= ((np.abs(cross) <= eps)
                     & (px >= min(x0, x1) - eps)
                     & (px <= max(x0, x1) + eps)
                     & (py >= min(y0, y1) - eps)
                     & (py <= max(y0, y1) + eps))
        if dy != 0:
            crosses = (y0 > py) != (y1 > py)
            inside ^= crosses & (px < x0 + (py - y0) * dx / dy)
    result[selected] = inside | boundary
    return result


def main():
    # Integer fifth-degree indexing gives exact row/column counts and ordering.
    lats = np.arange(115, 4, -1, dtype=np.int64) / 5.0
    lons = np.arange(495, 636, dtype=np.int64) / 5.0
    assert len(lats) == 111 and len(lons) == 141
    assert (lats[0], lats[-1], lons[0], lons[-1]) == (23, 1, 99, 127)
    xx, yy = np.meshgrid(lons, lats)
    x, y = xx.ravel(), yy.ravel()
    mask = np.zeros(x.shape, dtype=bool)
    for name, vertices in POLYGONS:
        mask |= point_mask(vertices, x, y)
    matrix = mask.reshape(111, 141).astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert np.isin(matrix, (0, 1)).all()

    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='ascii') as f:
        csv.writer(f, lineterminator='\n').writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / 'candidate.png')
    resampling = getattr(Image, 'Resampling', Image)
    enlarged = original.resize((1128, 888), resample=resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')

    # Read back ONLY the outputs just generated, never any reference map/data.
    with csv_path.open('r', newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    expected_large = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    for filename, size, expected in [
        ('candidate.png', (141, 111), pixels),
        ('candidate_8x.png', (1128, 888), expected_large),
    ]:
        with Image.open(out / filename) as im:
            assert im.mode == 'L' and im.size == size
            actual = np.asarray(im)
            assert set(np.unique(actual).tolist()) == {0, 255}
            assert np.array_equal(actual, expected)
