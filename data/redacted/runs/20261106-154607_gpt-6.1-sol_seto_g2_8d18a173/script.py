LAND = []

def polygon(text):
    LAND.append(np.array([tuple(map(float, p.split(",")))
                          for p in text.split()], dtype=float))

def ellipse(x, y, rx, ry, angle=0):
    t = np.arange(48) * (2 * np.pi / 48)
    a = np.deg2rad(angle)
    u, v = rx*np.cos(t), ry*np.sin(t)
    LAND.append(np.column_stack((x+u*np.cos(a)-v*np.sin(a),
                                y+u*np.sin(a)+v*np.cos(a))))

