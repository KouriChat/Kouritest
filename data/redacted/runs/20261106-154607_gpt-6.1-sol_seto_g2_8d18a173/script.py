def contains(poly, x, y):
    """Ray crossing evaluated at the sample points, not pixel areas."""
    inside = np.zeros(x.shape, dtype=bool)
    ax, ay = poly[-1]
    for bx, by in poly:
        if by != ay:
            crosses = ((ay > y) != (by > y))
            boundary_x = ax + (y-ay) * (bx-ax) / (by-ay)
            inside ^= crosses & (x < boundary_x)
        ax, ay = bx, by
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    longitude = 129.0 + np.arange(253, dtype=float) * (2.0/63.0)
    latitude = 35.0 - np.arange(64, dtype=float) * (2.0/63.0)
    x, y = np.meshgrid(longitude, latitude)
    matrix = np.zeros((64, 253), dtype=np.uint8)
    for coast in LAND:
        matrix |= contains(coast, x, y).astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert np.isin(matrix, (0, 1)).all()
    np.savetxt(out/"candidate.csv", matrix, fmt="%d", delimiter=",")
    raw = Image.fromarray(matrix * np.uint8(255))
    raw.save(out/"candidate.png")
    large = raw.resize((2024, 512), resample=Image.Resampling.NEAREST)
    large.save(out/"candidate_8x.png")
    with (out/"candidate.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out/"candidate.png") as im:
        a = np.asarray(im)
        assert im.size == (253, 64)
        assert set(np.unique(a)) == {0, 255}
        assert np.array_equal(a, matrix*255)
    with Image.open(out/"candidate_8x.png") as im:
        b = np.asarray(im)
        assert im.size == (2024, 512)
        assert set(np.unique(b)) == {0, 255}
        assert np.array_equal(b, np.repeat(np.repeat(a, 8, 0), 8, 1))
    print("Validated: 64x253 = 16192 binary samples; PNG 253x64; "
          "nearest-neighbor PNG 2024x512.")

