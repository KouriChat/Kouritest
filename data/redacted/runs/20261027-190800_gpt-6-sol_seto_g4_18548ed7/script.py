def build():
    # linspace gives exactly the stated 2/63 degree spacing.
    lats = np.linspace(35.0, 33.0, 64)
    lons = np.linspace(129.0, 137.0, 253)
    a = np.zeros((64, 253), dtype=np.uint8)
    for r, lat in enumerate(lats):
        for c, lon in enumerate(lons):
            a[r, c] = 1 if is_land(float(lon), float(lat)) else 0
    return a

