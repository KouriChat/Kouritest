def inside(x, y, poly):
    """Ray crossing point-in-polygon test, including boundary by convention."""
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        # Treat a point on an edge as land.
        cross = (x-xi)*(yj-yi) - (y-yi)*(xj-xi)
        if abs(cross) < 1e-10 and min(xi,xj)-1e-10 <= x <= max(xi,xj)+1e-10 and \
                min(yi,yj)-1e-10 <= y <= max(yi,yj)+1e-10:
            return True
        if ((yi > y) != (yj > y)):
            at_x = (xj-xi)*(y-yi)/(yj-yi) + xi
            if x < at_x:
                hit = not hit
        j = i
    return hit

LAND = []

def add(*points):
    LAND.append(tuple(points))

def is_land(lon, lat):
    for p in LAND:
        if inside(lon, lat, p):
            return True
    return False
