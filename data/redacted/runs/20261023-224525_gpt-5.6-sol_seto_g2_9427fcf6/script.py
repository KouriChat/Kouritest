YS = np.linspace(35.0, 33.0, H)

def inside_poly(x, y, p):
    """Even/odd point-in-polygon test (boundary choice is immaterial here)."""
    c = False
    j = len(p) - 1
    for i, (xi, yi) in enumerate(p):
        xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            xx = (xj-xi) * (y-yi) / (yj-yi) + xi
            if x <= xx:
                c = not c
        j = i
    return c

def poly_mask(p):
    return np.array([[inside_poly(x, y, p) for x in XS] for y in YS])

def ellipse_mask(cx, cy, rx, ry, angle=0.0):
    xx, yy = np.meshgrid(XS-cx, YS-cy)
    a = math.radians(angle)
    u = xx*math.cos(a) + yy*math.sin(a)
    v = -xx*math.sin(a) + yy*math.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1

