def point_in_polygon(x, y, polygon):
    """Ray-casting point test; boundary points count as land."""
    inside = False
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        dx, dy = x2 - x1, y2 - y1
        cross = (x - x1) * dy - (y - y1) * dx
        if abs(cross) < 1e-10:
            if (min(x1, x2) - 1e-10 <= x <= max(x1, x2) + 1e-10
                    and min(y1, y2) - 1e-10 <= y <= max(y1, y2) + 1e-10):
                return True
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * dx / dy:
            inside = not inside
    return inside


def main():
    longitudes = 99.0 + 0.2 * np.arange(141)
    latitudes = 23.0 - 0.2 * np.arange(111)
    matrix = np.zeros((111, 141), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(any(
                point_in_polygon(float(lon), float(lat), polygon)
                for polygon in LAND
            ))

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    enlarged = image.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    assert matrix.shape == (111, 141)
    assert matrix.size == 15651 and set(np.unique(matrix)) <= {0, 1}
    assert image.size == (141, 111)
    assert enlarged.size == (1128, 888)
    assert set(image.getdata()) <= {0, 255}


if __name__ == "__main__":
    main()
