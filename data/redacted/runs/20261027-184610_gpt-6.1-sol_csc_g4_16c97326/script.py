def on_land(lon, lat):
    """Test a sample point against the hand-written polygons."""
    for polygon in [MAINLAND, *ISLANDS]:
        inside = False
        j = len(polygon) - 1
        for i, (xi, yi) in enumerate(polygon):
            xj, yj = polygon[j]
            if (yi > lat) != (yj > lat):
                crossing_x = (xj - xi) * (lat - yi) / (yj - yi) + xi
                if lon < crossing_x:
                    inside = not inside
            j = i
        if inside:
            return True
    return False


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lats = 23.0 - 0.2 * np.arange(111)
    lons = 99.0 + 0.2 * np.arange(141)
    matrix = np.array(
        [[int(on_land(float(lon), float(lat))) for lon in lons] for lat in lats],
        dtype=np.uint8,
    )

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(out / "candidate.png")
    image.resize((1128, 888), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
