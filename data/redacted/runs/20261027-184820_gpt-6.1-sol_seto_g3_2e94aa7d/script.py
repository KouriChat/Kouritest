STEP = 2 / 63
ROWS = 64
COLS = 253


def build_matrix():
    matrix = np.zeros((ROWS, COLS), dtype=np.uint8)
    for row in range(ROWS):
        lat = 35.0 - row * STEP
        for col in range(COLS):
            lon = 129.0 + col * STEP
            on_land = any(inside(lon, lat, polygon) for polygon in LAND)
            if any(inside(lon, lat, polygon) for polygon in WATER):
                on_land = False
            matrix[row, col] = int(on_land)
    return matrix


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    matrix = build_matrix()

    with (output / "candidate.csv").open("w", newline="", encoding="ascii") as file:
        writer = csv.writer(file, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output / "candidate.png")
    image.resize((COLS * 8, ROWS * 8), resample=Image.Resampling.NEAREST).save(
        output / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
