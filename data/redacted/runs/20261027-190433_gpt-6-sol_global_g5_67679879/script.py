def inside(lon, lat, polygon):
    """Ray-casting test; vertices are deliberately approximate."""
    hit = False
    j = len(polygon) - 1
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[j]
        crosses = (y1 > lat) != (y2 > lat)
        if crosses:
            x_at_lat = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < x_at_lat:
                hit = not hit
        j = i
    return hit


def is_land(lon, lat):
    if any(inside(lon, lat, shape) for shape in POLYGONS + ISLANDS):
        return not any(inside(lon, lat, lake) for lake in LAKES)
    return False

def main():
    latitudes = range(89, -90, -2)
    longitudes = range(-179, 180, 2)
    matrix = np.zeros((90, 180), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(is_land(lon, lat))

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Black water, white land; array row zero is the northernmost latitude.
    image = Image.fromarray((matrix * 255).astype(np.uint8), mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    with (out / "candidate.csv").open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    assert sum(map(len, rows)) == 16200
    assert image.size == (180, 90)
    assert set(image.getdata()) <= {0, 255}
    enlarged = Image.open(out / "candidate_8x.png")
    assert enlarged.size == (1440, 720)
    assert set(enlarged.getdata()) <= {0, 255}
    assert enlarged.resize((180, 90), Image.Resampling.NEAREST).tobytes() == image.tobytes()


if __name__ == "__main__":
    main()
