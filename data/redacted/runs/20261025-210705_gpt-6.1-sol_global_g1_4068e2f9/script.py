def polygon_hits(x, y, points):
    """Ray crossing, with points on the hand-drawn boundary counted as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = points[-1]
    for bx, by in points:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        on = (
            (np.abs(cross) <= 1e-9)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        boundary |= on
        if dy != 0:
            straddles = (ay > y) != (by > y)
            crossing_x = ax + (y - ay) * dx / dy
            inside ^= straddles & (x < crossing_x)
        ax, ay = bx, by
    return inside | boundary


def build_matrix():
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    xx, yy = np.meshgrid(longitudes, latitudes)
    x, y = xx.ravel(), yy.ravel()
    result = np.zeros(x.size, dtype=np.uint8)
    for name, points in POLYGONS:
        vertices = np.array(points)
        min_x, min_y = vertices.min(axis=0)
        max_x, max_y = vertices.max(axis=0)
        # Some manually drawn islands/peninsulas use longitudes over 180.
        for shift in (-360, 0, 360):
            shifted_x = x + shift
            eligible = (
                (shifted_x >= min_x) & (shifted_x <= max_x)
                & (y >= min_y) & (y <= max_y) & (result == 0)
            )
            indices = np.flatnonzero(eligible)
            if indices.size:
                hit = polygon_hits(shifted_x[indices], y[indices], points)
                result[indices[hit]] = 1
    return result.reshape(90, 180)


