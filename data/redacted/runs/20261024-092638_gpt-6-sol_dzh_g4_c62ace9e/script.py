def polygon(points, x, y):
    """Even/odd ray crossing, with a consistent half-open edge convention."""
    hit = False
    px, py = points[-1]
    for qx, qy in points:
        if (py > y) != (qy > y):
            at_x = px + (y - py) * (qx - px) / (qy - py)
            if x < at_x:
                hit = not hit
        px, py = qx, qy
    return hit

