def polygon(points, group=land):
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    group.append((points, (min(xs), min(ys), max(xs), max(ys))))


def inside(x, y, shape):
    pts, (xl, yb, xr, yt) = shape
    if not (xl <= x <= xr and yb <= y <= yt):
        return False
    result = False
    x0, y0 = pts[-1]
    for x1, y1 in pts:
        if (y0 > y) != (y1 > y):
            if x < x0 + (y-y0)*(x1-x0)/(y1-y0):
                result = not result
        x0, y0 = x1, y1
    return result


def island_centreline(stations):
    """North-to-south stations: latitude, west shore, east shore."""
    polygon([(west, lat) for lat, west, east in stations] +
            [(east, lat) for lat, west, east in reversed(stations)])


