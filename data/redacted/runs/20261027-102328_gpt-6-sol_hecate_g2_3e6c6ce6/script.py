# Evaluate the hand-drawn contours at the exact 127 x 127 WGS84 point grid.
# No area averaging or independent per-point geographical reasoning is used.
SIZE = 127
SCALE = 8


def classify(lon, lat):
    return int(any(inside(lon, lat, feature) for feature in land) and
               not any(inside(lon, lat, feature) for feature in water))


def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    grid = [[classify(-131.0 + 2.0*col/(SIZE-1),
                      55.0 - 2.0*row/(SIZE-1))
             for col in range(SIZE)] for row in range(SIZE)]

    csv_path = out / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='ascii') as stream:
        csv.writer(stream, lineterminator='\n').writerows(grid)

    image = Image.new('L', (SIZE, SIZE))
    image.putdata([255*value for row in grid for value in row])
    original = out / 'candidate.png'
    enlarged = out / 'candidate_8x.png'
    image.save(original)
    nearest = (Image.Resampling.NEAREST if hasattr(Image, 'Resampling')
               else Image.NEAREST)
    image.resize((SIZE*SCALE, SIZE*SCALE), nearest).save(enlarged)

    with csv_path.open(newline='', encoding='ascii') as stream:
        check = list(csv.reader(stream))
    assert len(check) == SIZE
    assert all(len(row) == SIZE and set(row) <= {'0', '1'} for row in check)
    assert sum(len(row) for row in check) == 16129
    with Image.open(original) as raw, Image.open(enlarged) as zoom:
        assert raw.size == (127, 127) and zoom.size == (1016, 1016)
        assert set(raw.getdata()) <= {0, 255}
        assert set(zoom.getdata()) <= {0, 255}
        assert all(zoom.getpixel((x, y)) == raw.getpixel((x//SCALE, y//SCALE))
                   for y in range(1016) for x in range(1016))
    print('Checked 16129 binary point values; 127x127 PNG and 1016x1016 nearest-neighbor PNG.')


if __name__ == '__main__':
    main()
