def in_polygon(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    if any(in_polygon(lon, lat, polygon) for polygon in POLYGONS):
        return True
    return any(
        ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2 <= 1
        for cx, cy, rx, ry in ISLANDS
    )


matrix = []
for row_index in range(64):
    latitude = 35.0 - (2.0 / 63.0) * row_index
    row = []
    for column_index in range(253):
        longitude = 129.0 + (8.0 / 252.0) * column_index
        row.append(int(is_land(longitude, latitude)))
    matrix.append(row)

assert len(matrix) == 64 and all(len(row) == 253 for row in matrix)
