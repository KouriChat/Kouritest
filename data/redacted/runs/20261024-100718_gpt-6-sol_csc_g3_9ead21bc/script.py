LAT = 23.0 - np.arange(111, dtype=float)[:, None] * 0.2
LON = 99.0 + np.arange(141, dtype=float)[None, :] * 0.2
land = np.zeros((111, 141), dtype=bool)


def polygon(vertices):
    """Rasterize a hand-entered lon/lat coastline by point-in-polygon parity."""
    global land
    inside = np.zeros_like(land)
    for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
        if ay == by:
            continue
        inside ^= ((ay > LAT) != (by > LAT)) & (
            LON < (bx - ax) * (LAT - ay) / (by - ay) + ax
        )
    land |= inside


def isle(x, y, rx, ry):
    """Small hand-located island / emergent reef, with approximate extent."""
    global land
    land |= ((LON - x) / rx) ** 2 + ((LAT - y) / ry) ** 2 <= 1


