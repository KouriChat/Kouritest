def polygon(lon, lat, vertices):
    """Even-odd point-in-polygon, including points on polygon edges."""
    inside = False
    px, py = vertices[-1]
    for qx, qy in vertices:
        cross = (qx-px)*(lat-py) - (qy-py)*(lon-px)
        if abs(cross) < 1e-9 and min(px,qx)-1e-9 <= lon <= max(px,qx)+1e-9 \
                and min(py,qy)-1e-9 <= lat <= max(py,qy)+1e-9:
            return True
        if (py > lat) != (qy > lat):
            if lon < px + (lat-py)*(qx-px)/(qy-py):
                inside = not inside
        px, py = qx, qy
    return inside


