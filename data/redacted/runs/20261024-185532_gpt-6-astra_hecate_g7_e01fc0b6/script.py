N = 127
longitude = -131.0 + np.arange(N, dtype=np.float64) * (2.0 / 126.0)
latitude = 55.0 - np.arange(N, dtype=np.float64) * (2.0 / 126.0)
X, Y = np.meshgrid(longitude, latitude)
land = np.zeros((N, N), dtype=bool)
features = []


def polygon_mask(vertices):
    """Vectorized even-odd point-in-polygon test; no geographic library."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > Y) != (y1 > Y))
            x_cross = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (X < x_cross)
        x0, y0 = x1, y1
    return inside


def island(name, vertices):
    features.append((name, "land", vertices))
    land[:] |= polygon_mask(vertices)


def water(name, vertices):
    features.append((name, "water", vertices))
    land[:] &= ~polygon_mask(vertices)


