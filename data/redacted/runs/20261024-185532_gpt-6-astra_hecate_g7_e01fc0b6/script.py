"""Knowledge-only, hand-drawn approximation of the northern BC coast.

No geographic files, network access, databases, or reference maps are used.
All vertices below are remembered/estimated WGS84 longitude, latitude pairs.
Each sampling POINT is classified by polygon membership, not cell coverage.
This is a rule-based reconstruction, not 16,129 independent model judgments.
Inland lakes are intentionally not removed from land.
Run: python outputs/generate_map.py
Dependencies: numpy, Pillow. Outputs are relative to the working directory.
"""
