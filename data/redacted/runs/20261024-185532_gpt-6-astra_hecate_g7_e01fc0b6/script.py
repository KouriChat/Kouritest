    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert sum(len(row) for row in rows) == 16129
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)

    with Image.open(out / "candidate.png") as image:
        assert image.size == (127, 127)
        assert image.mode == "L"
        raw_pixels = np.asarray(image).copy()
