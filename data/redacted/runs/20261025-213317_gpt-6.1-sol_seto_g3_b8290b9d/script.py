LAND, WATER = [], []

def polygon(text, water=False):
    pts = [tuple(map(float, p.split(","))) for p in text.split()]
    (WATER if water else LAND).append(np.asarray(pts, dtype=np.float64))

def island(x, y, rx, ry, angle=0):
    # Small islands with poorly remembered outlines use an explicit 16-gon.
    a = np.arange(16) * np.pi / 8
    t = np.deg2rad(angle)
    dx, dy = rx * np.cos(a), ry * np.sin(a)
    LAND.append(np.column_stack((x+dx*np.cos(t)-dy*np.sin(t),
                                 y+dx*np.sin(t)+dy*np.cos(t))))

