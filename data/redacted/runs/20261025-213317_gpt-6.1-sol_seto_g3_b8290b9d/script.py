def contains(vertices, x, y):
    """Even-odd polygon containment evaluated at each coordinate, vectorized."""
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        crosses = (y0 > y) != (y1 > y)
        if y1 != y0:
            intersection = x0 + (y-y0) * (x1-x0)/(y1-y0)
            inside ^= crosses & (x < intersection)
        x0, y0 = x1, y1
    return inside

def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Exact stated spacing, not the rounded illustrative coordinate labels.
    lons = 129.0 + np.arange(253, dtype=np.float64) * (2.0/63.0)
    lats = 35.0 - np.arange(64, dtype=np.float64) * (2.0/63.0)
    x, y = np.meshgrid(lons, lats)
    land = np.zeros((64, 253), dtype=bool)
    for vertices in LAND:
        land |= contains(vertices, x, y)
    for vertices in WATER:
        land &= ~contains(vertices, x, y)
    land |= contains(HARIO, x, y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert np.isin(matrix, (0, 1)).all()
    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    enlarged = image.resize((2024, 512), resample=nearest)
    enlarged.save(out / "candidate_8x.png")
    # Re-read every delivered artifact, including the exact 8x8 pixel blocks.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (253, 64)
        original = np.asarray(im)
        assert set(np.unique(original)).issubset({0, 255})
        assert np.array_equal(original, pixels)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (2024, 512)
        large = np.asarray(im)
        assert set(np.unique(large)).issubset({0, 255})
        assert np.array_equal(large, original.repeat(8, axis=0).repeat(8, axis=1))
    print("Validated: 64x253 = 16192 binary values; 253x64 PNG; exact nearest 8x PNG 2024x512.")
    print("Method: hand-written memory-only polygons, vectorized point-in-polygon.")

