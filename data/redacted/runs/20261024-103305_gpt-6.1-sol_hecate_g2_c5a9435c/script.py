def inside_polygon(vertices):
    """Vectorized even/odd ray casting at the actual sampling coordinates."""
    result = np.zeros((N, N), dtype=bool)
    x, y = LONGITUDE, LATITUDE
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > y) != (y1 > y))
            intersection = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (x < intersection)
        x0, y0 = x1, y1
    return result


def generate():
    # One shared, handwritten coastline model is evaluated for every point.
    # There is no cell-area averaging and no subsequent image modification.
    result = np.zeros((N, N), dtype=bool)
    for _, vertices in LAND:
        result |= inside_polygon(vertices)
    for _, vertices in SEA:
        result &= ~inside_polygon(vertices)
    return result.astype(np.uint8)


def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    matrix = generate()
    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()
    assert LATITUDE[0, 0] == 55.0 and LATITUDE[-1, 0] == 53.0
    assert LONGITUDE[0, 0] == -131.0 and LONGITUDE[0, -1] == -129.0

    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())

    image = Image.fromarray(matrix * np.uint8(255))
    image.save(output / "candidate.png")
    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST
    enlarged = image.resize((1016, 1016), resample=nearest)
    enlarged.save(output / "candidate_8x.png")

    # Validate the files after writing, rather than just the memory objects.
    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    reread = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(reread, matrix)
    with Image.open(output / "candidate.png") as saved:
        assert saved.size == (127, 127)
        raw = np.asarray(saved).copy()
    with Image.open(output / "candidate_8x.png") as saved:
        assert saved.size == (1016, 1016)
        big = np.asarray(saved).copy()
    assert set(np.unique(raw).tolist()) <= {0, 255}
    assert set(np.unique(big).tolist()) <= {0, 255}
    assert np.array_equal(raw, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected)
    print("Validated: 127x127, 16129 binary values; PNG 127x127; "
          "nearest-neighbor PNG 1016x1016.")


if __name__ == "__main__":
    main()
