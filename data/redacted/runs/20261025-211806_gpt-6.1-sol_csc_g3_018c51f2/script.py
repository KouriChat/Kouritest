def points_in_polygon(x, y, vertices):
    """Vectorized point test with boundary points assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        cross = (x-x1)*(y2-y1) - (y-y1)*(x2-x1)
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(x1,x2)-1e-10) & (x <= max(x1,x2)+1e-10)
            & (y >= min(y1,y2)-1e-10) & (y <= max(y1,y2)+1e-10)
        )
        if y1 != y2:
            crossing = ((y1 > y) != (y2 > y))
            inside ^= crossing & (x < x1+(y-y1)*(x2-x1)/(y2-y1))
        x1, y1 = x2, y2
    return inside | boundary

