    result = np.zeros((111,141), dtype=bool)
    for name, vertices in POLYGONS:
        result |= points_in_polygon(x, y, vertices)
    for name, cx, cy, ax, ay, ix, iy in REEFS:
        outer = ((x-cx)/ax)**2 + ((y-cy)/ay)**2 <= 1.0
        lagoon = ((x-cx)/ix)**2 + ((y-cy)/iy)**2 < 1.0
        result |= outer & ~lagoon
    matrix = result.astype(np.uint8)
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1128,888), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Validate the actual files written, not just the in-memory arrays.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0","1") for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert recovered.shape == (111,141) and recovered.size == 15651
    assert np.array_equal(recovered, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (141,111) and im.mode == "L"
        raw = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1128,888) and im.mode == "L"
        big = np.array(im)
    assert set(np.unique(raw).tolist()) == {0,255}
    assert set(np.unique(big).tolist()) == {0,255}
    assert np.array_equal(raw, recovered*255)
    assert np.array_equal(big, np.repeat(np.repeat(raw,8,axis=0),8,axis=1))
    assert (latitudes[0],latitudes[-1]) == (23.0,1.0)
    assert (longitudes[0],longitudes[-1]) == (99.0,127.0)
    print("Validated: 111 x 141 = 15651 binary point classifications.")
    print("PNG: 141 x 111; nearest-neighbor 8x: 1128 x 888; black/white only.")
    print(f"Land: {int(matrix.sum())}; water: {matrix.size-int(matrix.sum())}.")
    print(f"Files: {out}")

