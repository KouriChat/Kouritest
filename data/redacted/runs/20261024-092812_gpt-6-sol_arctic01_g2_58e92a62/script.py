LAT = np.arange(61, dtype=np.float64)[:, None]
LON = np.arange(241, dtype=np.float64)[None, :]
lat = np.broadcast_to(79.0 - LAT / 10.0, (61, 241))
west = np.broadcast_to(105.0 - LON / 10.0, (61, 241))
land = np.zeros((61, 241), dtype=bool)

def island(points):
    """Set all sampled points inside one hand-sketched island to land."""
    polygon = np.asarray(points, dtype=float)
    # Bounding box pruning; parity crossing uses sample POINTS, not grid cells.
    box = ((west >= polygon[:, 0].min()) & (west <= polygon[:, 0].max()) &
           (lat >= polygon[:, 1].min()) & (lat <= polygon[:, 1].max()))
    yy, xx = np.where(box)
    x, y = west[yy, xx], lat[yy, xx]
    inside = np.zeros(len(x), dtype=bool)
    for i, (a, b) in enumerate(polygon):
        c, d = polygon[(i + 1) % len(polygon)]
        if b == d:
            continue
        inside ^= ((b > y) != (d > y)) & (x < a + (y - b) * (c - a) / (d - b))
    land[yy, xx] |= inside

