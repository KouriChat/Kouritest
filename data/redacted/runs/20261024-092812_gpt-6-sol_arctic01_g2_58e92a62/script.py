"""Hand-sketched point-in-polygon reconstruction of the Canadian Arctic Archipelago.

Coordinates in every outline are (degrees WEST, degrees NORTH).  These outlines
are approximate, written from geographic recollection, not traced from data.
"""
from pathlib import Path
