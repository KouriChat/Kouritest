POLYGONS = []

def polygon(name, text):
    numbers = [float(x) for x in text.replace(",", " ").split()]
    assert len(numbers) % 2 == 0, name
    POLYGONS.append((name, np.array(numbers).reshape(-1, 2)))

def ellipse(name, x, y, rx, ry, angle=0):
    t = np.linspace(0, 2*np.pi, 49)[:-1]
    a = np.deg2rad(angle)
    dx, dy = rx*np.cos(t), ry*np.sin(t)
    points = np.column_stack((x+dx*np.cos(a)-dy*np.sin(a),
                              y+dx*np.sin(a)+dy*np.cos(a)))
    POLYGONS.append((name, points))

