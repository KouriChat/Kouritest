def contains_points(vertices, xx, yy):
    """Ray crossing plus an explicit, land-inclusive boundary convention."""
    inside = np.zeros(xx.shape, dtype=bool)
    boundary = np.zeros(xx.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1-x0, y1-y0
        cross = (xx-x0)*dy-(yy-y0)*dx
        boundary |= ((np.abs(cross) < 1e-10)
                     & (xx >= min(x0,x1)-1e-10)
                     & (xx <= max(x0,x1)+1e-10)
                     & (yy >= min(y0,y1)-1e-10)
                     & (yy <= max(y0,y1)+1e-10))
        if abs(dy) > 1e-14:
            crossing = ((y0 > yy) != (y1 > yy))
            intersect_x = x0 + (yy-y0)*dx/dy
            inside ^= crossing & (xx < intersect_x)
        x0, y0 = x1, y1
    return inside | boundary

def main():
    # Integer fifth-degrees avoid accumulating 0.2-degree rounding errors.
    longitude = np.arange(495,636,dtype=np.int64)/5.0
    latitude = np.arange(115,4,-1,dtype=np.int64)/5.0
    xx, yy = np.meshgrid(longitude,latitude)
    land = np.zeros((111,141),dtype=bool)
    for name, vertices in POLYGONS:
        land |= contains_points(vertices,xx,yy)
    matrix = land.astype(np.uint8)
    out = Path.cwd() / "outputs"
