land = np.zeros((N, N), dtype=bool)


def polygon(vertices):
    """Ray crossing evaluated at the sampling coordinates, not cell areas."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            cross = ((y0 > Y) != (y1 > Y))
            xx = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= cross & (X < xx)
        x0, y0 = x1, y1
    return inside


def add(name, vertices):
    land[:] |= polygon(vertices)


def subtract(name, vertices):
    land[:] &= ~polygon(vertices)


