def marine_channel(name, points, widths):
    """Subtract a hand-positioned marine inlet, with full widths in km."""
    xx, yy = X * 65.4, Y * 111.2
    wet = np.zeros(X.shape, dtype=bool)
    for i in range(len(points) - 1):
        ax, ay = points[i][0] * 65.4, points[i][1] * 111.2
        bx, by = points[i+1][0] * 65.4, points[i+1][1] * 111.2
        dx, dy = bx - ax, by - ay
        t = np.clip(((xx-ax)*dx + (yy-ay)*dy) / (dx*dx+dy*dy), 0, 1)
        radius = (widths[i] + t*(widths[i+1]-widths[i])) * 0.5
        wet |= (xx-ax-t*dx)**2 + (yy-ay-t*dy)**2 <= radius**2
    land[:] &= ~wet


