def polygon_mask(x, y, vertices):
    """Even-odd ray casting at the points themselves; include polygon edges."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if abs(dy) > 1e-14:
            crossing = (ay > y) != (by > y)
            intersection_x = ax + dx * (y - ay) / dy
            inside ^= crossing & (x < intersection_x)
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        ax, ay = bx, by
    return inside | boundary


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Integer tenths prevent accumulation of floating-point stepping error.
    latitudes = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    longitudes = np.arange(-1050, -809, dtype=np.int32) / 10.0
    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((61, 241), dtype=bool)
    for vertices in LAND.values():
        land |= polygon_mask(x, y, vertices)
    for vertices in WATER.values():
        land &= ~polygon_mask(x, y, vertices)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert (latitudes[0], latitudes[-1]) == (79.0, 73.0)
    assert (longitudes[0], longitudes[-1]) == (-105.0, -81.0)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
