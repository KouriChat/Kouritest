def generate():
    """Evaluate every sample with the same hand-drawn polygon rules."""
    land_shapes = prepare(LAND)
    water_shapes = prepare(WATER)
    matrix = []
    for row in range(90):
        lat = 89 - 2 * row
        matrix.append([
            int(in_any(-179 + 2 * col, lat, land_shapes)
                and not in_any(-179 + 2 * col, lat, water_shapes))
            for col in range(180)
        ])

    directory = Path("outputs")
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)

    image = Image.new("L", (180, 90))
    image.putdata([255 * cell for row in matrix for cell in row])
    image.convert("RGB").save(directory / "candidate.png")
    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.convert("RGB").save(directory / "candidate_8x.png")

    assert len(matrix) == 90 and all(len(row) == 180 for row in matrix)
    assert all(v in (0, 1) for row in matrix for v in row)
    assert image.size == (180, 90)
    assert enlarged.size == (1440, 720)
    assert set(enlarged.getdata()) <= {0, 255}
    assert all(enlarged.getpixel((8 * x + dx, 8 * y + dy)) == image.getpixel((x, y))
               for y in range(90) for x in range(180)
               for dx in (0, 7) for dy in (0, 7))


if __name__ == "__main__":
    generate()
