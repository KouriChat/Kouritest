def inside(x, y, poly):
    result = False
    px, py = poly[-1]
    for qx, qy in poly:
        if ((qy > y) != (py > y)):
            ix = qx + (y - qy) * (px - qx) / (py - qy)
            if x < ix:
                result = not result
        px, py = qx, qy
    return result


def prepare(polys):
    return [(min(p[0] for p in poly), max(p[0] for p in poly),
             min(p[1] for p in poly), max(p[1] for p in poly), poly)
            for poly in polys]


def in_any(lon, lat, prepared):
    return any(a <= lon <= b and c <= lat <= d and inside(lon, lat, p)
               for a, b, c, d, p in prepared)


