def polygon_mask(x, y, vertices):
    """Even/odd point-in-polygon rule evaluated at points, not pixel areas."""
    inside = np.zeros(x.shape, dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        if y2 != y1:
            crosses = (y1 > y) != (y2 > y)
            intersection = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            inside ^= crosses & (x < intersection)
        x1, y1 = x2, y2
    return inside

def main():
    # Exact requested spacing, rather than the rounded coordinate examples.
    longitude = -131.0 + np.arange(127, dtype=np.float64) * (2.0 / 126)
    latitude = 55.0 - np.arange(127, dtype=np.float64) * (2.0 / 126)
    x, y = np.meshgrid(longitude, latitude)
    mask = np.zeros((127, 127), dtype=bool)
    for polygon in LAND:
        mask |= polygon_mask(x, y, polygon)
    for polygon in WATER:
        mask &= ~polygon_mask(x, y, polygon)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((1016, 1016), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Validate the files actually written, including the enlargement rule.
    with csv_path.open(newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)
    with Image.open(out / "candidate.png") as original:
        assert original.size == (127, 127)
        actual = np.array(original)
        assert set(np.unique(actual)).issubset({0, 255})
        assert np.array_equal(actual, pixels)
    with Image.open(out / "candidate_8x.png") as scaled:
        assert scaled.size == (1016, 1016)
        scaled_pixels = np.array(scaled)
        assert set(np.unique(scaled_pixels)).issubset({0, 255})
        expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(scaled_pixels, expected)
    print("Validated: 127 x 127 = 16,129 binary point classifications; "
          "127 x 127 PNG; exact nearest-neighbor 1016 x 1016 PNG.")
    print("Method: hand-written approximate polygons from existing knowledge; "
          "no geographic data, map images, or network requests.")

if __name__ == "__main__":
    main()
