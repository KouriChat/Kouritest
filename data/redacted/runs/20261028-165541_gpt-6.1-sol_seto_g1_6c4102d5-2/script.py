def point_in_polygon(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            x = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < x:
                inside = not inside
        j = i
    return inside

def on_island(lon, lat, island):
    cx, cy, rx, ry = island
    return ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2 <= 1.0

def main():
    rows, cols = 64, 253
    step = 2.0 / 63.0
    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for r in range(rows):
        lat = 35.0 - r * step
        for c in range(cols):
            lon = 129.0 + c * step
            land = any(point_in_polygon(lon, lat, p) for p in LAND_POLYGONS)
            if not land:
                land = any(on_island(lon, lat, p) for p in ISLANDS)
            matrix[r, c] = int(land)
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        for row in matrix:
            f.write(",".join(map(str, map(int, row))) + "\n")
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((2024, 512), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

if __name__ == "__main__":
    main()

