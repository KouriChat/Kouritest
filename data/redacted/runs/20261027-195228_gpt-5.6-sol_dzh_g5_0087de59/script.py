import csv
from pathlib import Path

import numpy as np
from PIL import Image


def inside_polygon(lon, lat, polygon):
    inside = False
    previous = polygon[-1]
    for current in polygon:
        x1, y1 = previous
        x2, y2 = current
        if (y1 > lat) != (y2 > lat):
            crossing_lon = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < crossing_lon:
                inside = not inside
        previous = current
    return inside


def main():
    latitudes = [45.0 - 0.2 * row for row in range(71)]
    longitudes = [-9.0 + 0.2 * col for col in range(231)]
    matrix = np.zeros((71, 231), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = any(
                inside_polygon(lon, lat, polygon) for polygon in LAND
            )

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "candidate.csv").open(
        "w", newline="", encoding="ascii"
    ) as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(output_dir / "candidate.png")
    enlarged = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(output_dir / "candidate_8x.png")

    with (output_dir / "candidate.csv").open(
        "r", newline="", encoding="ascii"
    ) as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    assert image.size == (231, 71)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert enlarged.size == (1848, 568)
    assert all(
        enlarged.getpixel((x, y)) == image.getpixel((x // 8, y // 8))
        for y in range(568)
        for x in range(1848)
    )
    print(f"validated {len(rows)}x{len(rows[0])} matrix")


if __name__ == "__main__":
    main()
