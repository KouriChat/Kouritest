def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)
    matrix = LAND.astype(np.uint8)
    assert matrix.shape == (90, 180)
    assert matrix.size == 16200
    assert np.isin(matrix, [0, 1]).all()

    csv_path = output_dir / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(output_dir / "candidate.png")
    enlarged = original.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(output_dir / "candidate_8x.png")

    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16200
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(output_dir / "candidate.png") as image:
        assert image.size == (180, 90)
        raw = np.asarray(image)
        assert set(np.unique(raw)) == {0, 255}
        assert np.array_equal(raw, pixels)
    with Image.open(output_dir / "candidate_8x.png") as image:
        assert image.size == (1440, 720)
        big = np.asarray(image)
        assert set(np.unique(big)) == {0, 255}
        assert np.array_equal(big, raw.repeat(8, axis=0).repeat(8, axis=1))
    print(f"Validated {matrix.shape[0]} x {matrix.shape[1]} = {matrix.size} binary values.")
    print("Validated black/white PNGs: 180x90 and 1440x720; exact nearest-neighbor 8x.")
    print(f"Land points: {matrix.sum()}; handwritten polygon rules: {len(RULES)}.")


if __name__ == "__main__":
    main()
