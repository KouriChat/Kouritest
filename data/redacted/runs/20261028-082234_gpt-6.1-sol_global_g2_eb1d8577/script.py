"""Reconstruct a coarse land mask using only manually recalled geography.

Run from any current directory: python outputs/generate_map.py
Dependencies: numpy, Pillow. No geographic files, network, or reference mask.
All coordinates below are approximate, handwritten longitude/latitude pairs.
Inland lakes are intentionally filled. Floating ice is not included.
"""
from pathlib import Path
import csv
import numpy as np
from PIL import Image

LONS = np.arange(-179, 180, 2, dtype=float)
LATS = np.arange(89, -90, -2, dtype=float)
X, Y = np.meshgrid(LONS, LATS)
LAND = np.zeros((90, 180), dtype=bool)
RULES = []


def polygon(name, coordinates, water=False):
    """Ray casting over handwritten polygons, not independent model judgments."""
    points = [tuple(map(float, pair.split(","))) for pair in coordinates.split()]
    assert len(points) >= 3, name
    mask = np.zeros_like(LAND)
    for shift in (-360, 0, 360):
        xx = X + shift
        inside = np.zeros_like(LAND)
        x1, y1 = points[-1]
        for x2, y2 in points:
            if y1 != y2:
                crosses = (y1 > Y) != (y2 > Y)
                edge_x = (x2 - x1) * (Y - y1) / (y2 - y1) + x1
                inside ^= crosses & (xx < edge_x)
            x1, y1 = x2, y2
        mask |= inside
    if water:
        LAND[mask] = False
    else:
        LAND[mask] = True
    RULES.append((name, len(points), water))


