def inside(lon, lat, polygon):
    """Even-odd point-in-polygon; unwrap vertices relative to query longitude."""
    hit = False
    previous = polygon[-1]
    for current in polygon:
        x1 = ((previous[0] - lon + 180) % 360) - 180
        x2 = ((current[0] - lon + 180) % 360) - 180
        y1, y2 = previous[1], current[1]
        if (y1 > lat) != (y2 > lat):
            cross = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if cross > 0:
                hit = not hit
        previous = current
    return hit

def classify(lon, lat):
    if lat <= -70:
        return 1
    if any(inside(lon, lat, polygon) for polygon in LAND):
        if not any(inside(lon, lat, polygon) for polygon in WATER):
            return 1
    return 0


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    latitudes = range(89, -90, -2)
    longitudes = range(-179, 180, 2)
    matrix = np.array(
        [[classify(lon, lat) for lon in longitudes] for lat in latitudes],
        dtype=np.uint8,
    )
    if matrix.shape != (90, 180):
        raise RuntimeError(f"Unexpected matrix shape: {matrix.shape}")

    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as csv_file:
        writer = csv.writer(csv_file, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Matrix value 1 (land) is white; value 0 (water) is black.
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )

    values, counts = np.unique(matrix, return_counts=True)
    print(f"Matrix: {matrix.shape[0]}x{matrix.shape[1]}, {matrix.size} values")
    print(f"Class counts: {dict(zip(values.tolist(), counts.tolist()))}")
    print("Wrote outputs/candidate.csv, candidate.png, candidate_8x.png")


if __name__ == "__main__":
    main()
