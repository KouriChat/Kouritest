# Emit the pointwise binary mask.  Raster enlargement only replicates
# pixels and does not modify, smooth, or repair the underlying coastline.
out = Path("outputs")
out.mkdir(exist_ok=True)
matrix = land.astype(np.uint8)
with (out / "candidate.csv").open("w", newline="", encoding="utf-8") as f:
    csv.writer(f).writerows(matrix.tolist())

original = Image.fromarray(matrix * 255, mode="L")
original.save(out / "candidate.png")
enlarged = original.resize((2024, 512), resample=Image.Resampling.NEAREST)
enlarged.save(out / "candidate_8x.png")

# Read back the actual deliverables to verify all requested invariants.
with (out / "candidate.csv").open(newline="", encoding="utf-8") as f:
    rows = list(csv.reader(f))
assert len(rows) == 64 and all(len(r) == 253 for r in rows)
assert all(c in ("0", "1") for row in rows for c in row)
assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
with Image.open(out / "candidate.png") as image:
    assert image.size == (253, 64)
    assert set(image.getdata()) <= {0, 255}
with Image.open(out / "candidate_8x.png") as image:
    assert image.size == (2024, 512)
    assert set(image.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(image), np.repeat(
        np.repeat(np.asarray(original), 8, axis=0), 8, axis=1))
print("Validated 64 x 253 = 16192 points; CSV and both monochrome PNGs.")
