LAT = 35.0 - 2.0 * np.arange(64) / 63.0
LON = 129.0 + 8.0 * np.arange(253) / 252.0
X, Y = np.meshgrid(LON, LAT)
land = np.zeros((64, 253), dtype=bool)


def polygon(vertices):
    """Even-odd polygon mask; the classification is at each sampled point."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        crosses = ((y0 > Y) != (y1 > Y))
        xc = (x1 - x0) * (Y - y0) / ((y1 - y0) if y1 != y0 else 1e-20) + x0
        inside ^= crosses & (X < xc)
        x0, y0 = x1, y1
    return inside


def add(vertices):
    land[:] |= polygon(vertices)


def remove(vertices):
    land[:] &= ~polygon(vertices)


def ellipse(x, y, rx, ry, angle=0):
    """Rotate in approximate kilometre coordinates, not unscaled degrees."""
    a = np.deg2rad(angle)
    dx, dy = (X-x)*0.83, Y-y
    u = dx*np.cos(a) + dy*np.sin(a)
    v = -dx*np.sin(a) + dy*np.cos(a)
    return (u/(rx*0.83))**2 + (v/ry)**2 <= 1


def island(x, y, rx, ry, angle=0):
    land[:] |= ellipse(x, y, rx, ry, angle)


