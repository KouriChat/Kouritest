LON, LAT = np.meshgrid(np.arange(-179, 180, 2), np.arange(89, -90, -2))
land = np.zeros((90, 180), dtype=bool)


def polygon(vertices, value=True):
    """Rasterize a hand-written polygon by point-in-polygon, NOT pointwise AI."""
    inside = np.zeros_like(land)
    for (xa, ya), (xb, yb) in zip(vertices, vertices[1:] + vertices[:1]):
        if ya == yb:
            continue
        crossing = ((ya > LAT) != (yb > LAT)) & (
            LON < xa + (LAT - ya) * (xb - xa) / (yb - ya)
        )
        inside ^= crossing
    land[inside] = value


def oval(lon, lat, rx, ry, value=True):
    land[((LON - lon) / rx) ** 2 + ((LAT - lat) / ry) ** 2 <= 1] = value


