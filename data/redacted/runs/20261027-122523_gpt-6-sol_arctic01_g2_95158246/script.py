def decode(data):
    return [[tuple(map(float, pair.split(","))) for pair in line.split()]
            for line in data.strip().splitlines()]

def inside(x, y, poly):
    hit = False
    prev_x, prev_y = poly[-1]
    for curr_x, curr_y in poly:
        if (curr_y > y) != (prev_y > y):
            crossing = curr_x + (y - curr_y) * (prev_x - curr_x) / (prev_y - curr_y)
            if x < crossing:
                hit = not hit
        prev_x, prev_y = curr_x, curr_y
    return hit

def main():
    polygons = decode(LAND) + decode(DEVON)
    matrix = [[int(any(inside(105 - col / 10, 79 - row / 10, poly)
                       for poly in polygons)) for col in range(241)]
              for row in range(61)]
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(matrix)
    image = Image.new("RGB", (241, 61))
    image.putdata([(255 * value,) * 3 for line in matrix for value in line])
    image.save(out / "candidate.png")
    enlarged = image.resize((1928, 488), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    assert len(matrix) == 61 and all(len(r) == 241 and set(r) <= {0, 1} for r in matrix)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert all(enlarged.getpixel((8*x+dx, 8*y+dy)) == image.getpixel((x, y))
               for y in range(61) for x in range(241) for dx in range(8) for dy in range(8))

if __name__ == "__main__":
    main()
