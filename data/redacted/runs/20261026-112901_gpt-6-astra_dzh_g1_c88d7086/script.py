def point_in_polygon(lon, lat, polygon):
    """Ray casting with coastline boundary points included."""
    inside = False
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        cross = (lon - x1) * (y2 - y1) - (lat - y1) * (x2 - x1)
        if abs(cross) < 1e-10 and (
            min(x1, x2) - 1e-10 <= lon <= max(x1, x2) + 1e-10
            and min(y1, y2) - 1e-10 <= lat <= max(y1, y2) + 1e-10
        ):
            return True
        if (y1 > lat) != (y2 > lat):
            crossing_lon = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < crossing_lon:
                inside = not inside
    return inside


def main():
    latitudes = [45.0 - 0.2 * i for i in range(71)]
    longitudes = [-9.0 + 0.2 * j for j in range(231)]
    matrix = np.zeros((71, 231), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(
                any(point_in_polygon(lon, lat, poly) for poly in LAND)
            )

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open(
        "w", newline="", encoding="ascii"
    ) as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())

    original = Image.fromarray(matrix * 255, mode="L")
    original.save(out / "candidate.png")
    enlarged = original.resize((1848, 568), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert original.size == (231, 71) and enlarged.size == (1848, 568)


if __name__ == "__main__":
    main()
