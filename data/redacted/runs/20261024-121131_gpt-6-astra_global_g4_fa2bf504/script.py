LAND = []
WATER = []


def outline(name, coordinates, *, water=False):
    """Add an explicitly hand-written lon,lat polygon."""
    vertices = [
        tuple(map(float, token.split(","))) for token in coordinates.split()
    ]
    if len(vertices) < 3:
        raise ValueError(name)
    (WATER if water else LAND).append((name, vertices))


def inside_polygon(x, y, vertices):
    """Even/odd ray crossing; polygon edges themselves count as inside."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (x - x0) * dy - (y - y0) * dx
        boundary |= (
            (np.abs(cross) < 1e-9)
            & (x >= min(x0, x1) - 1e-10)
            & (x <= max(x0, x1) + 1e-10)
            & (y >= min(y0, y1) - 1e-10)
            & (y <= max(y0, y1) + 1e-10)
        )
        if dy != 0:
            intersects = ((y0 > y) != (y1 > y)) & (
                x < x0 + (y - y0) * dx / dy
            )
            inside ^= intersects
        x0, y0 = x1, y1
    return inside | boundary


