def polygon_mask(xs, ys, vertices):
    """Ray casting with edges included; coordinates are planar lon/lat."""
    inside = np.zeros(xs.shape, dtype=bool)
    boundary = np.zeros(xs.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        on_line = np.abs((xs - ax) * dy - (ys - ay) * dx) < 1e-10
        on_segment = ((xs >= min(ax, bx) - 1e-10) &
                      (xs <= max(ax, bx) + 1e-10) &
                      (ys >= min(ay, by) - 1e-10) &
                      (ys <= max(ay, by) + 1e-10))
        boundary |= on_line & on_segment
        if dy != 0:
            crossing = ((ay > ys) != (by > ys))
            intersection_x = ax + (ys - ay) * dx / dy
            inside ^= crossing & (xs < intersection_x)
        ax, ay = bx, by
    return inside | boundary


def make_matrix():
    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    xs, ys = np.meshgrid(longitudes, latitudes)
    result = np.zeros((90, 180), dtype=np.uint8)
    for name, vertices in POLYGONS:
        if len(vertices) < 3:
            raise ValueError("Invalid polygon: " + name)
        coords = np.asarray(vertices, dtype=float)
        eligible = ((xs >= coords[:, 0].min()) &
                    (xs <= coords[:, 0].max()) &
                    (ys >= coords[:, 1].min()) &
                    (ys <= coords[:, 1].max()))
        if np.any(eligible):
            result[eligible] |= polygon_mask(
                xs[eligible], ys[eligible], vertices).astype(np.uint8)
    return result


def validate_files(directory, expected):
    with (directory / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90, "CSV must have 90 rows"
    assert all(len(row) == 180 for row in rows), "CSV must have 180 columns"
    assert all(v in ("0", "1") for row in rows for v in row)
    loaded = np.asarray(rows, dtype=np.uint8)
    assert loaded.size == 16200 and np.array_equal(loaded, expected)
    with Image.open(directory / "candidate.png") as image:
        assert image.format == "PNG" and image.size == (180, 90)
        assert image.mode == "L"
        original = np.array(image)
    with Image.open(directory / "candidate_8x.png") as image:
        assert image.format == "PNG" and image.size == (1440, 720)
        assert image.mode == "L"
        enlarged = np.array(image)
    assert set(np.unique(original).tolist()) == {0, 255}
    assert set(np.unique(enlarged).tolist()) == {0, 255}
    assert np.array_equal(original, loaded * np.uint8(255))
    nearest = np.repeat(np.repeat(original, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged, nearest), "Not exact nearest-neighbor"
    return {
        "matrix_shape": [90, 180], "valid_values": int(loaded.size),
        "land_samples": int(loaded.sum()),
        "water_samples": int(loaded.size - loaded.sum()),
        "original_size": [180, 90], "enlarged_size": [1440, 720],
        "pixel_values": [0, 255], "exact_nearest_neighbor_8x": True,
        "north_to_south": True, "west_to_east": True,
        "method": "handwritten approximate polygons; computed point-in-polygon",
        "independent_LLM_inference_per_sample": False,
        "external_geographic_data_used": False,
        "accuracy_against_real_coastlines": "not measured",
        "csv_sha256": hashlib.sha256(
            (directory / "candidate.csv").read_bytes()).hexdigest()
    }


def main():
    directory = Path.cwd() / "outputs"
    directory.mkdir(parents=True, exist_ok=True)
    matrix = make_matrix()
    with (directory / "candidate.csv").open(
            "w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(directory / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    original.resize((1440, 720), resample=nearest).save(
        directory / "candidate_8x.png")
    report = validate_files(directory, matrix)
    (directory / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
