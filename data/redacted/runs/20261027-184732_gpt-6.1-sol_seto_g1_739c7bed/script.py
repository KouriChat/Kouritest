def contains(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                inside = not inside
        j = i
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for r in range(64):
        lat = 35.0 - r * (2.0 / 63.0)
        row = []
        for c in range(253):
            lon = 129.0 + c * (8.0 / 252.0)
            row.append(int(any(contains(lon, lat, p) for p in LAND)))
        rows.append(row)

    with (out / "candidate.csv").open("w", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(rows)
    pixels = np.asarray(rows, dtype=np.uint8) * 255
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((2024, 512), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")

    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert sum(map(len, rows)) == 16192 and set(np.unique(pixels)) <= {0, 255}
    with (out / "candidate.csv").open(newline="") as f:
        loaded = list(csv.reader(f))
    assert len(loaded) == 64 and all(len(row) == 253 for row in loaded)
    assert all(v in ("0", "1") for row in loaded for v in row)
    assert Image.open(out / "candidate.png").size == (253, 64)
    assert Image.open(out / "candidate_8x.png").size == (2024, 512)
    assert set(Image.open(out / "candidate.png").getdata()) <= {0, 255}

if __name__ == "__main__":
    main()
