def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    matrix = LAND.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert LAT[0] == 79.0 and LAT[-1] == 73.0
    assert LON[0] == -105.0 and LON[-1] == -81.0

    csv_path = out / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())

    raw_pixels = matrix * np.uint8(255)
    raw = Image.fromarray(raw_pixels)
    raw.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = raw.resize((1928, 488), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Verify files actually written, including every CSV cell and every
    # pixel of the enlarged image; no smoothing or coastline postprocessing.
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(cell in ("0", "1") for row in rows for cell in row)
    reread = np.array(rows, dtype=np.uint8)
    assert np.array_equal(reread, matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.size == (241, 61)
        pixels = np.array(image)
        assert set(np.unique(pixels).tolist()) == {0, 255}
        assert np.array_equal(pixels, raw_pixels)
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1928, 488)
        pixels8 = np.array(image)
        assert set(np.unique(pixels8).tolist()) == {0, 255}
        expected = np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(pixels8, expected)
    report = {
        "method": "handwritten knowledge-only polygons and marine-fjord cuts",
        "independent_point_LM_inference": False,
        "external_geographic_data": False,
        "rows": 61,
        "columns": 241,
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_validated": True,
        "raw_png_size": [241, 61],
        "enlarged_png_size": [1928, 488],
        "pixel_values": [0, 255],
        "nearest_neighbor_exactly_validated": True,
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
