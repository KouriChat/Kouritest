LAT = np.arange(790, 729, -1, dtype=np.int32) / 10.0
LON = np.arange(-1050, -809, dtype=np.int32) / 10.0
X, Y = np.meshgrid(LON, LAT)
LAND = np.zeros(X.shape, dtype=bool)
ISLANDS = []


def inside(vertices):
    """Vectorized point-in-polygon; coordinates are (longitude, latitude)."""
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > Y) != (y1 > Y))
            intercept = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (X < intercept)
        x0, y0 = x1, y1
    return result


def island(name, coast, fjords=()):
    global LAND
    mask = inside(coast)
    for fjord in fjords:
        mask &= ~inside(fjord)
    LAND |= mask
    ISLANDS.append(name)


