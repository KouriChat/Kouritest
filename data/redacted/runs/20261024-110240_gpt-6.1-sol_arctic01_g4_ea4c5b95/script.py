"""Knowledge-only reconstruction; all coast vertices below are hand estimates.

No map, geographical database, network, reference answer, or land-mask package
is used. Point classification is by the explicitly written polygons, not by
14,701 independent language-model judgements. Inland lakes remain land.
Dependencies: Python 3, numpy, Pillow. Run from the desired working directory.
"""
from pathlib import Path
import csv
import json
import numpy as np
