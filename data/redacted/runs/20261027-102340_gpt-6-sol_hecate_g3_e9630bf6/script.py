def parse_shapes(source):
    source = '\n'.join(line.split('#')[0] for line in source.splitlines())
    return [[tuple(map(float, vertex.strip().split(',')))
             for vertex in shape.split(';') if vertex.strip()]
            for shape in source.split('|') if shape.strip()]

def contains(poly, lon, lat):
    inside = False
    for i in range(len(poly)):
        x1, y1 = poly[i - 1]
        x2, y2 = poly[i]
        if (y1 > lat) != (y2 > lat):
            at_x = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon >= at_x:
                inside = not inside
    return inside

