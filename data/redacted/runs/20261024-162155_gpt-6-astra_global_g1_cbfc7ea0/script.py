def polygon(name, text, water=False):
    values = [float(v) for v in text.replace(",", " ").split()]
    assert len(values) >= 6 and len(values) % 2 == 0, name
    vertices = np.array(values, dtype=float).reshape(-1, 2)
    (SEA if water else LAND).append((name, vertices))

