"""Knowledge-only world land mask; no geographic files, services or databases.

All polygon vertices below are handwritten approximations from geographic
knowledge, not measured coastlines. Classification uses polygon membership,
not independent language-model reasoning at each grid point. Inland lakes
are deliberately not cut out. Sea ice is never used as a land criterion.
Dependencies: Python 3, numpy, Pillow. Run from any working directory.
"""
