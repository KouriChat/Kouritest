def contains(lon, lat, polygon):
    # Shift vertices by whole turns so polygons crossing 180 degrees stay local.
    x = polygon[:, 0] + 360.0 * np.round((lon - polygon[:, 0]) / 360.0)
    y = polygon[:, 1]
    inside = False
    j = len(x) - 1
    for i in range(len(x)):
        if (y[i] > lat) != (y[j] > lat):
            cross = (x[j] - x[i]) * (lat - y[i]) / (y[j] - y[i]) + x[i]
            if lon < cross:
                inside = not inside
        j = i
    return inside

