def main():
    # Only the requested point coordinates are evaluated. No area averaging,
    # interpolation, external geography, morphological filtering or smoothing.
    land = np.zeros((71, 231), dtype=bool)
    for name, polygon in LAND_POLYGONS:
        land |= contains(polygon)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert (LATS[0], LATS[-1], LONS[0], LONS[-1]) == (45, 31, -9, 37)
    assert np.allclose(np.diff(LATS), -0.2)
    assert np.allclose(np.diff(LONS), 0.2)

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    raw_path = out / "candidate.png"
    big_path = out / "candidate_8x.png"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    assert image.mode == "L"
    image.save(raw_path, format="PNG")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((1848, 568), resample=nearest)
    enlarged.save(big_path, format="PNG")

    # Validate the saved deliverables, not merely the in-memory objects.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16401
    saved_matrix = np.array(rows, dtype=np.uint8)
    assert np.array_equal(saved_matrix, matrix)
    with Image.open(raw_path) as f:
        assert f.size == (231, 71) and f.mode == "L"
        raw = np.array(f)
    with Image.open(big_path) as f:
        assert f.size == (1848, 568) and f.mode == "L"
        big = np.array(f)
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, pixels)
    repeated = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, repeated)
    report = {
        "method": "handwritten knowledge-only polygons, point-in-polygon union",
        "external_geographic_inputs": False,
        "shape_rows_columns": [71, 231],
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_no_header_no_blanks_binary_only": True,
        "raw_png_width_height": [231, 71],
        "enlarged_png_width_height": [1848, 568],
        "png_values": [0, 255],
        "nearest_neighbor_verified_pixel_by_pixel": True,
        "orientation": "north to south; west to east",
        "dependencies": ["numpy", "Pillow"],
        "accuracy_against_real_map": "not tested; no reference map used",
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False))

if __name__ == "__main__":
    main()
