def contains(vertices):
    """Vectorized even-odd point test, including polygon edges."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        if dy != 0:
            crossing = ((y0 > Y) != (y1 > Y))
            inside ^= crossing & (X < x0 + (Y - y0) * dx / dy)
        cross = (X - x0) * dy - (Y - y0) * dx
        boundary |= (
            (np.abs(cross) < 1e-10)
            & (X >= min(x0, x1) - 1e-10)
            & (X <= max(x0, x1) + 1e-10)
            & (Y >= min(y0, y1) - 1e-10)
            & (Y <= max(y0, y1) + 1e-10)
        )
        x0, y0 = x1, y1
    return inside | boundary

