def inside(x, y, edges):
    """Even-odd ray casting, with a point on the boundary counted as land."""
    hit = False
    for (ax, ay), (bx, by) in edges:
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        if (abs(cross) < 1e-10
                and min(ax, bx) - 1e-10 <= x <= max(ax, bx) + 1e-10
                and min(ay, by) - 1e-10 <= y <= max(ay, by) + 1e-10):
            return True
        if (ay > y) != (by > y):
            intersection = ax + (y - ay) * (bx - ax) / (by - ay)
            if x < intersection:
                hit = not hit
    return hit


def prepare():
    prepared = []
    for name, poly in LAND:
        xs, ys = zip(*poly)
        edges = tuple(zip(poly, poly[1:] + poly[:1]))
        prepared.append((min(xs), max(xs), min(ys), max(ys), edges))
    return prepared


def classify(lon, lat, prepared):
    for xmin, xmax, ymin, ymax, edges in prepared:
        if not ymin <= lat <= ymax:
            continue
        for x in (lon, lon + 360, lon - 360):
            if xmin <= x <= xmax and inside(x, lat, edges):
                return 1
    return 0


