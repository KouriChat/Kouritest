    # Exactly the requested WGS84 angular grid; no projection correction.
    lats = list(range(89, -90, -2))
    lons = list(range(-179, 180, 2))
    prepared = prepare()
    matrix = [[classify(lon, lat, prepared) for lon in lons] for lat in lats]
    assert len(matrix) == 90
    assert all(len(row) == 180 for row in matrix)
    assert sum(map(len, matrix)) == 16200
    assert all(value in (0, 1) for row in matrix for value in row)

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix)

    pixels = bytes(255 * value for row in matrix for value in row)
    original = Image.frombytes("L", (180, 90), pixels)
    original.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    original.resize((1440, 720), resample=nearest).save(out / "candidate_8x.png")

    # Validate saved artifacts, not merely the in-memory construction.
    with csv_path.open(newline="", encoding="ascii") as f:
        saved = list(csv.reader(f))
    assert len(saved) == 90 and all(len(row) == 180 for row in saved)
    assert all(value in {"0", "1"} for row in saved for value in row)
    assert [[int(value) for value in row] for row in saved] == matrix

    with Image.open(out / "candidate.png") as raw:
        raw.load()
        assert raw.size == (180, 90) and raw.mode == "L"
        assert set(raw.tobytes()) == {0, 255}
        assert raw.tobytes() == pixels
    with Image.open(out / "candidate_8x.png") as enlarged:
        enlarged.load()
        assert enlarged.size == (1440, 720) and enlarged.mode == "L"
        assert set(enlarged.tobytes()) == {0, 255}
        large_pixels = enlarged.tobytes()
    for row in range(90):
        source_row = pixels[row * 180:(row + 1) * 180]
        expected = b"".join(bytes([value]) * 8 for value in source_row)
        for dy in range(8):
            offset = (row * 8 + dy) * 1440
            assert large_pixels[offset:offset + 1440] == expected

    land_count = sum(map(sum, matrix))
    report = {
        "method": "handwritten approximate polygons, automatic point-in-polygon",
        "external_geographic_data": False,
        "independent_model_reasoning_per_point": False,
        "rows": 90, "columns": 180, "valid_values": 16200,
        "land": land_count, "water": 16200 - land_count,
        "latitude_order": "89,87,...,-89",
        "longitude_order": "-179,-177,...,179",
        "original_size": [180, 90], "enlarged_size": [1440, 720],
        "pixel_values": [0, 255], "white": "land", "black": "water",
        "scale_factor": 8, "nearest_neighbor_exact_blocks_verified": True,
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


