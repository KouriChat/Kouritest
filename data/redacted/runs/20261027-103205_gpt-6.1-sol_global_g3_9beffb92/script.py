"""World land/water approximation from hand-written geographic knowledge.

No map files, geographic libraries, online services, or reference answers are
used. Every classification is a polygon-rule calculation, NOT an independent
language-model judgement. Inland lakes count as land. Sea ice does not.
Run: python outputs/generate_map.py       Dependency: Pillow
"""
from pathlib import Path
