def contains(lon, lat, polygon):
    """Ray casting after longitude unwrapping around the sample point."""
    pts = []
    for x, y in polygon:
        while x - lon > 180:
            x -= 360
        while x - lon < -180:
            x += 360
        pts.append((x, y))
    inside = False
    j = len(pts) - 1
    for i, (xi, yi) in enumerate(pts):
        xj, yj = pts[j]
        if (yi > lat) != (yj > lat):
            crossing = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing:
                inside = not inside
        j = i
    return inside


def main():
    matrix = []
    for lat in range(89, -90, -2):
        row = []
        for lon in range(-179, 180, 2):
            row.append(int(any(contains(lon, lat, poly)
                               for _, poly in POLYGONS)))
        matrix.append(row)
    assert len(matrix) == 90 and all(len(row) == 180 for row in matrix)
    root = Path.cwd() / 'outputs'
    root.mkdir(parents=True, exist_ok=True)
    with (root / 'candidate.csv').open('w', newline='') as stream:
        csv.writer(stream, lineterminator='\n').writerows(matrix)
    pixels = [255 if value else 0 for row in matrix for value in row]
    image = Image.new('L', (180, 90))
    image.putdata(pixels)
    image.save(root / 'candidate.png')
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        root / 'candidate_8x.png')


if __name__ == '__main__':
    main()
