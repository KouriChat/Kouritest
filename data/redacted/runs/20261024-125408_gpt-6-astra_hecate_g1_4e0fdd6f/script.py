def polygon_mask(vertices):
    """Even/odd point test at the requested coordinates, not pixel areas."""
    inside = np.zeros((N, N), dtype=bool)
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        if y1 != y2:
            crossing = ((y1 > LAT) != (y2 > LAT))
            intercept = x1 + (LAT - y1) * (x2 - x1) / (y2 - y1)
            inside ^= crossing & (LON < intercept)
        x1, y1 = x2, y2
    return inside


