def point_in_polygon(lon, lat, polygon):
    """Ray-crossing point test; boundary points are treated as land."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        dx, dy = xj - xi, yj - yi
        cross = (lon - xi) * dy - (lat - yi) * dx
        if abs(cross) < 1e-10 and min(xi, xj) <= lon <= max(xi, xj) and min(yi, yj) <= lat <= max(yi, yj):
            return True
        if (yi > lat) != (yj > lat):
            if lon < xi + (lat - yi) * dx / dy:
                inside = not inside
        j = i
    return inside
def main():
    latitudes = 23.0 - 0.2 * np.arange(111)
    longitudes = 99.0 + 0.2 * np.arange(141)
    matrix = np.zeros((111, 141), dtype=np.uint8)

    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = any(
                point_in_polygon(float(lon), float(lat), polygon)
                for polygon in LAND_POLYGONS
            )

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        for row in matrix:
            f.write(",".join(str(int(value)) for value in row) + "\n")

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((1128, 888), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
