def contains_points(xs, ys, vertices):
    """Vectorized even-odd ray crossing with explicit on-edge inclusion."""
    inside = np.zeros(xs.shape, dtype=bool)
    edge = np.zeros(xs.shape, dtype=bool)
    x0, y0 = vertices[-1]
    eps = 1e-10
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (xs - x0) * dy - (ys - y0) * dx
        on = ((np.abs(cross) < eps)
              & (xs >= min(x0, x1) - eps) & (xs <= max(x0, x1) + eps)
              & (ys >= min(y0, y1) - eps) & (ys <= max(y0, y1) + eps))
        edge |= on
        if abs(dy) > eps:
            intersection_x = x0 + (ys - y0) * dx / dy
            inside ^= ((y0 > ys) != (y1 > ys)) & (xs < intersection_x)
        x0, y0 = x1, y1
    return inside | edge


def main():
    # Integer-based construction avoids accumulated 0.2-degree rounding drift.
    longitude = np.arange(-45, 186, dtype=np.int64) / 5.0
    latitude = np.arange(225, 154, -1, dtype=np.int64) / 5.0
    xs, ys = np.meshgrid(longitude, latitude)
    land = np.zeros((71, 231), dtype=bool)
    for name, vertices in LAND:
        land |= contains_points(xs, ys, vertices)
    matrix = land.astype(np.uint8)
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / "candidate.png")
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    image.resize((1848, 568), resample=nearest).save(out / "candidate_8x.png")
    # Validate serialized products, including every 8x8 nearest-neighbor block.
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    loaded = np.array(rows, dtype=np.uint8)
    assert loaded.shape == (71, 231) and loaded.size == 16401
    assert np.array_equal(loaded, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (231, 71) and im.mode == "L"
        small = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1848, 568) and im.mode == "L"
        large = np.array(im)
    assert set(np.unique(small).tolist()) <= {0, 255}
    assert set(np.unique(large).tolist()) <= {0, 255}
    assert np.array_equal(small, matrix * 255)
    assert np.array_equal(large, np.repeat(np.repeat(small, 8, 0), 8, 1))
    assert latitude[0] == 45 and latitude[-1] == 31
    assert longitude[0] == -9 and longitude[-1] == 37
    print("Verified: 71 x 231 = 16401 binary values; PNG 231x71; nearest 8x 1848x568.")


