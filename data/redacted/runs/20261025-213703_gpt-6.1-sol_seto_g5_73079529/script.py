lon = 129.0 + np.arange(253, dtype=np.float64) * (2.0 / 63.0)
lat = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((64, 253), dtype=bool)

def polygon(points):
    """Ray-crossing test at the exact sample coordinates, without raster fill."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y0 != y1:
            crosses = (y0 > Y) != (y1 > Y)
            crossing_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (X < crossing_x)
        x0, y0 = x1, y1
    return inside

def add(points):
    land[:] |= polygon(points)

def island(cx, cy, rx, ry, angle=0):
    """Hand-estimated elliptical small-island contour, tested as a polygon."""
    a = np.deg2rad(angle)
    t = np.arange(24) * (2 * np.pi / 24)
    u, v = rx * np.cos(t), ry * np.sin(t)
    add(list(zip(cx + u*np.cos(a)-v*np.sin(a),
                 cy + u*np.sin(a)+v*np.cos(a))))

