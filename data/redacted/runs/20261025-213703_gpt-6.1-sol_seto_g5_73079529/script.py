    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix)).issubset({0, 1})
    with (OUT / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(OUT / "candidate.png")
    enlarged = original.resize((2024, 512), resample=Image.Resampling.NEAREST)
    enlarged.save(OUT / "candidate_8x.png")

    # Validate the actual saved files, including every replicated pixel.
    with (OUT / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(OUT / "candidate.png") as im:
        assert im.size == (253, 64)
        saved = np.array(im)
    with Image.open(OUT / "candidate_8x.png") as im:
        assert im.size == (2024, 512)
        saved8 = np.array(im)
    assert set(np.unique(saved)) == {0, 255}
    assert set(np.unique(saved8)) == {0, 255}
    assert np.array_equal(saved, pixels)
    expected8 = np.repeat(np.repeat(saved, 8, axis=0), 8, axis=1)
    assert np.array_equal(saved8, expected8)
    assert lon[0] == 129 and lon[-1] == 137
    assert lat[0] == 35 and lat[-1] == 33
    print("Validated: 64 x 253 = 16192 binary values; CSV has no header or gaps.")
    print("Validated: PNG 253 x 64; black/white only; exact nearest 8x 2024 x 512.")
    print("Method: hand-estimated geographic polygons and small-island contours.")
    print(f"Land samples: {matrix.sum()}; water samples: {matrix.size-matrix.sum()}.")

