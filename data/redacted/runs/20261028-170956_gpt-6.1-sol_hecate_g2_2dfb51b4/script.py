def inside(lon, lat, poly):
    hit = False
    j = len(poly) - 1
    for i, (x, y) in enumerate(poly):
        px, py = poly[j]
        cross = (lon-x)*(py-y) - (lat-y)*(px-x)
        if abs(cross) < 1e-10 and min(x,px) <= lon <= max(x,px) and min(y,py) <= lat <= max(y,py):
            return True
        if (y > lat) != (py > lat) and lon < (px-x)*(lat-y)/(py-y) + x:
            hit = not hit
        j = i
    return hit

def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    lats, lons = np.linspace(55, 53, 127), np.linspace(-131, -129, 127)
    polys = [MAINLAND, GRAHAM, MORESBY, *ISLANDS]
    data = np.zeros((127, 127), dtype=np.uint8)
    for r, lat in enumerate(lats):
        for c, lon in enumerate(lons):
            data[r, c] = any(inside(float(lon), float(lat), p) for p in polys)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(data.tolist())
    image = Image.fromarray(data * 255).convert("RGB")
    image.save(out / "candidate.png")
    image.resize((1016,1016), Image.Resampling.NEAREST).save(out / "candidate_8x.png")
    assert data.shape == (127,127) and data.size == 16129

if __name__ == "__main__":
    main()
