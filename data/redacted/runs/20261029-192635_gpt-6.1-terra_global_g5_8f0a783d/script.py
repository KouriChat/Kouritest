def inside_polygon(x, y, vertices):
    inside = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crossing = ((ay > y) != (by > y))
            edge_x = ax + (y - ay) * (bx - ax) / (by - ay)
            inside ^= crossing & (x < edge_x)
        ax, ay = bx, by
    return inside


def main():
    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    longitude, latitude = np.meshgrid(np.arange(-179, 180, 2), np.arange(89, -90, -2))
    land = np.zeros((90, 180), dtype=bool)
    for polygon in polygons:
        land |= inside_polygon(longitude, latitude, polygon)
    matrix = land.astype(np.uint8)
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as handle:
        csv.writer(handle).writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    image.save(out / 'candidate.png')
    image.resize((1440, 720), Image.Resampling.NEAREST).save(out / 'candidate_8x.png')
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    assert sum(map(len, rows)) == 16200
    with Image.open(out / 'candidate.png') as original:
        assert original.size == (180, 90)
        pixels = np.array(original)
        assert set(np.unique(pixels)) == {0, 255}
        assert np.array_equal(pixels, matrix * 255)
    with Image.open(out / 'candidate_8x.png') as enlarged:
        assert enlarged.size == (1440, 720)
        large_pixels = np.array(enlarged)
        assert set(np.unique(large_pixels)) == {0, 255}
        assert np.array_equal(large_pixels, np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1))
    print('Validated 90 x 180 = 16200 binary values; 180 x 90 PNG; exact 8x nearest-neighbor PNG.')


if __name__ == '__main__':
    main()
