# Vertex lists are hand-estimated geographical outlines, in (longitude, latitude).
# The point-in-polygon calculation is applied to the 0.2-degree sample points.
def inside(x, y, vertices):
    hit = False
    j = len(vertices) - 1
    for i, (xi, yi) in enumerate(vertices):
        xj, yj = vertices[j]
        if (yi > y) != (yj > y):
            crossing = xi + (y - yi) * (xj - xi) / (yj - yi)
            if x <= crossing:
                hit = not hit
        j = i
    return hit

