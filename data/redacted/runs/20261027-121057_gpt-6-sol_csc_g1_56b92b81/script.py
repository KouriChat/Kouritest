def generate():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    rows = []
    for row in range(111):
        lat = round(23 - row * 0.2, 8)
        rows.append([int(any(inside(round(99 + col*.2, 8), lat, p)
                             for p in polygons)) for col in range(141)])
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(rows)
    im = Image.new("RGB", (141, 111))
    im.putdata([(255,255,255) if v else (0,0,0)
                for row in rows for v in row])
    im.save(out / "candidate.png")
    large = im.resize((1128, 888), Image.Resampling.NEAREST)
    large.save(out / "candidate_8x.png")
    assert len(rows) == 111 and all(len(r) == 141 for r in rows)
    assert {v for r in rows for v in r} == {0, 1}
    assert set(im.getdata()) == {(0,0,0), (255,255,255)}
    assert large.size == (1128, 888)
    assert all(large.getpixel((8*x+dx,8*y+dy)) == im.getpixel((x,y))
               for y in range(111) for x in range(141)
               for dx in range(8) for dy in range(8))
    print("Wrote 111 x 141 CSV and 141 x 111 / 1128 x 888 PNG images.")

if __name__ == "__main__":
    generate()
