import math

def oval(cx, cy, rx, ry, angle=0):
    """Small hand-located islands, approximated by rotated ellipses."""
    a = math.radians(angle)
    ca, sa = math.cos(a), math.sin(a)
    add([(cx + rx*math.cos(t)*ca - ry*math.sin(t)*sa,
          cy + rx*math.cos(t)*sa + ry*math.sin(t)*ca)
         for t in [2*math.pi*k/20 for k in range(20)]])

