# Arrays refer to point coordinates, NOT to area averages of pixel cells.
LON = 129 + np.arange(253, dtype=float)[None, :] / 31.5
LAT = 35 - np.arange(64, dtype=float)[:, None] / 31.5
land = np.zeros((64, 253), dtype=bool)

def polygon(vertices):
    """Paint a hand-sketched island/coast polygon by point-in-polygon."""
    global land
    inside = np.zeros(land.shape, dtype=bool)
    for (x0, y0), (x1, y1) in zip(vertices, vertices[1:] + vertices[:1]):
        if y0 != y1:
            cross = (LAT >= min(y0, y1)) & (LAT < max(y0, y1))
            edge_x = x0 + (LAT - y0) * (x1 - x0) / (y1 - y0)
            inside ^= cross & (LON < edge_x)
    land |= inside

def ellipse(x, y, rx, ry, angle=0):
    """Approximate small offshore islands; angle in degrees, CCW."""
    global land
    a = np.deg2rad(angle)
    dx, dy = LON - x, LAT - y
    u = dx * np.cos(a) + dy * np.sin(a)
    v = -dx * np.sin(a) + dy * np.cos(a)
    land |= (u / rx) ** 2 + (v / ry) ** 2 <= 1

