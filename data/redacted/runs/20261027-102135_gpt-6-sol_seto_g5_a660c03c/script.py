def main():
    directory = Path('outputs')
    directory.mkdir(parents=True, exist_ok=True)
    matrix = land.astype(np.uint8)
    csv_path = directory / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='ascii') as f:
        csv.writer(f, lineterminator='\n').writerows(matrix.tolist())
    pixels = matrix * 255
    image = Image.fromarray(pixels, mode='L').convert('RGB')
    raw_path = directory / 'candidate.png'
    big_path = directory / 'candidate_8x.png'
    image.save(raw_path)
    image.resize((2024, 512), resample=Image.Resampling.NEAREST).save(big_path)

    with csv_path.open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert sum(map(len, rows)) == 16192
    assert all(v in ('0', '1') for row in rows for v in row)
    with Image.open(raw_path) as actual, Image.open(big_path) as enlarged:
        assert actual.size == (253, 64) and enlarged.size == (2024, 512)
        assert set(actual.getdata()) <= {(0, 0, 0), (255, 255, 255)}
        assert set(enlarged.getdata()) <= {(0, 0, 0), (255, 255, 255)}
        assert list(enlarged.getdata()) == list(actual.resize(
            (2024, 512), Image.Resampling.NEAREST).getdata())
    print('Validated: 64 x 253; 16,192 binary samples; PNG 253x64 and 2024x512.')

if __name__ == '__main__':
    main()
