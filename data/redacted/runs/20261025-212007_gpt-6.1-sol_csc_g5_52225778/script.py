def contains_points(vertices, x, y):
    """Vectorized ray crossing; coastline points are assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (x - x0) * dy - (y - y0) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(x0, x1) - 1e-10)
            & (x <= max(x0, x1) + 1e-10)
            & (y >= min(y0, y1) - 1e-10)
            & (y <= max(y0, y1) + 1e-10)
        )
        if abs(dy) > 1e-14:
            intersects = ((y0 > y) != (y1 > y))
            intersection_x = x0 + (y - y0) * dx / dy
            inside ^= intersects & (x < intersection_x)
        x0, y0 = x1, y1
    return inside | boundary


