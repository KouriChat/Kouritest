# Small islands use either short hand-drawn polygons or knowledge-based ellipses.
# The ellipses are vector outlines, not marks painted into the output image.
def oval(name, x, y, rx, ry, angle=0.0):
    t = np.arange(48, dtype=np.float64) * (2 * np.pi / 48)
    a = np.deg2rad(angle)
    dx, dy = rx * np.cos(t), ry * np.sin(t)
    land(name, np.column_stack((x + dx * np.cos(a) - dy * np.sin(a),
                               y + dx * np.sin(a) + dy * np.cos(a))))


