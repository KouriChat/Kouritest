def inside(lon, lat, poly):
    """Ray-crossing point-in-polygon test."""
    hit = False
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if (y1 > lat) != (y0 > lat):
            cross = (x0 - x1) * (lat - y1) / (y0 - y1) + x1
            if lon < cross:
                hit = not hit
        x0, y0 = x1, y1
    return hit


def is_land(lon, lat):
    return any(inside(lon, lat, p) for p in LAND) or any(
        inside(lon, lat, p) for p in ISLANDS
    )


def main():
    # Exactly 64 rows (35N to 33N) by 253 columns (129E to 137E).
    lats = [35.0 - i * (2.0 / 63.0) for i in range(64)]
    lons = [129.0 + j * (8.0 / 252.0) for j in range(253)]
    matrix = np.array([[int(is_land(lon, lat)) for lon in lons]
                       for lat in lats], dtype=np.uint8)

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    # PIL mode 1 is a two-color bitmap: 1/white is land, 0/black is water.
    image = Image.fromarray(matrix * 255, mode="L").convert("1")
    image.save(out / "candidate.png")
    image.resize((2024, 512), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    # Validate every requested artifact before returning.
    assert matrix.shape == (64, 253) and matrix.size == 16192
    assert set(np.unique(matrix)) <= {0, 1}
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64 and all(len(r) == 253 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    assert image.size == (253, 64)
    assert set(image.getdata()) <= {0, 255}
    enlarged = Image.open(out / "candidate_8x.png")
    assert enlarged.size == (2024, 512) and set(enlarged.getdata()) <= {0, 255}
    print("Validated 64x253 CSV, two-color PNG, and nearest-neighbor 8x PNG.")


if __name__ == "__main__":
    main()
