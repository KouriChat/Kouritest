W, H = 253, 64
lon = 129.0 + np.arange(W) * (8.0 / (W - 1))
lat = 35.0 - np.arange(H) * (2.0 / (H - 1))
X, Y = np.meshgrid(lon, lat)
land = np.zeros((H, W), dtype=bool)

def polygon(vertices, water=False):
    """Point-in-polygon on actual sample coordinates (not area coverage)."""
    global land
    inside = np.zeros_like(land)
    for (a, b), (c, d) in zip(vertices, vertices[1:] + vertices[:1]):
        if b == d:
            continue
        crosses = ((b > Y) != (d > Y))
        xcut = a + (Y - b) * (c - a) / (d - b)
        inside ^= crosses & (X < xcut)
    if water:
        land &= ~inside
    else:
        land |= inside

def ellipse(cx, cy, rx, ry, angle=0):
    global land
    t = np.deg2rad(angle)
    u = (X-cx)*np.cos(t) + (Y-cy)*np.sin(t)
    v = -(X-cx)*np.sin(t) + (Y-cy)*np.cos(t)
    land |= (u/rx)**2 + (v/ry)**2 <= 1

