def prepare(shapes):
    return [
        (name, vertices, min(x for x, y in vertices),
         max(x for x, y in vertices), min(y for x, y in vertices),
         max(y for x, y in vertices))
        for name, vertices in shapes
    ]


def in_polygon(x, y, vertices):
    """Even-odd ray casting; a point exactly on a boundary counts as inside."""
    inside = False
    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
        if (abs(cross) < 1e-10
                and min(x1, x2) <= x <= max(x1, x2)
                and min(y1, y2) <= y <= max(y1, y2)):
            return True
        if (y1 > y) != (y2 > y):
            intersection = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < intersection:
                inside = not inside
        x1, y1 = x2, y2
    return inside


def in_shapes(lon, lat, shapes):
    for name, vertices, xmin, xmax, ymin, ymax in shapes:
        if not ymin <= lat <= ymax:
            continue
        for x in (lon, lon + 360, lon - 360):
            if xmin <= x <= xmax and in_polygon(x, lat, vertices):
                return True
    return False


def main():
    latitudes = list(range(89, -90, -2))
    longitudes = list(range(-179, 180, 2))
    land, water = prepare(LAND), prepare(WATER)
    matrix = [
        [int(in_shapes(lon, lat, land) and not in_shapes(lon, lat, water))
         for lon in longitudes]
        for lat in latitudes
    ]
    assert len(matrix) == 90 and all(len(row) == 180 for row in matrix)
    assert sum(map(len, matrix)) == 16200
    assert all(value in (0, 1) for row in matrix for value in row)

    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix)
    pixels = bytes(value * 255 for row in matrix for value in row)
    original = Image.frombytes("L", (180, 90), pixels)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    original.save(out / "candidate.png", format="PNG")
    enlarged.save(out / "candidate_8x.png", format="PNG")

    # Re-open ONLY our generated artifacts, never a map or answer/reference.
    with csv_path.open("r", newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    assert rows == [[str(value) for value in row] for row in matrix]
    with Image.open(out / "candidate.png") as image:
        assert image.size == (180, 90) and image.mode == "L"
        assert set(image.getdata()) == {0, 255}
        assert image.tobytes() == pixels
    expected = b"".join(
        b"".join(bytes([value * 255]) * 8 for value in row) * 8
        for row in matrix
    )
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1440, 720) and image.mode == "L"
        assert set(image.getdata()) == {0, 255}
        assert image.tobytes() == expected, "Not an exact 8x nearest-neighbor image"

    report = {
        "method": "Manually estimated memory-only polygons; automated ray casting",
        "external_geographic_data_used": False,
        "shape": [90, 180], "valid_values": 16200,
        "land_points": sum(map(sum, matrix)),
        "water_points": 16200 - sum(map(sum, matrix)),
        "original_pixels": [180, 90], "enlarged_pixels": [1440, 720],
        "pixel_values": [0, 255], "exact_8x_nearest_neighbor_verified": True,
        "latitude_order": "89,87,...,-89",
        "longitude_order": "-179,-177,...,179",
        "coastline_accuracy": "Approximate; not validated against geographic truth",
    }
    (out / "validation.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False))


