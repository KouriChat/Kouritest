def point_in_polygon(w, n, vertices):
    """Boolean point-in-polygon on the sample coordinates, not cell areas."""
    pts = np.asarray(vertices, dtype=np.float64)
    xmin, xmax = pts[:, 0].min(), pts[:, 0].max()
    ymin, ymax = pts[:, 1].min(), pts[:, 1].max()
    bbox = (w >= xmin) & (w <= xmax) & (n >= ymin) & (n <= ymax)
    if not bbox.any():
        return bbox
    inside = np.zeros(w.shape, dtype=bool)
    for i in range(len(pts)):
        x1, y1 = pts[i - 1]
        x2, y2 = pts[i]
        if y1 == y2:
            continue
        cross = (y1 > n) != (y2 > n)
        edge_x = x1 + (n - y1) * (x2 - x1) / (y2 - y1)
        inside ^= bbox & cross & (w < edge_x)
    return inside

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    west, north = np.meshgrid(
        105.0 - 0.1 * np.arange(241),
        79.0 - 0.1 * np.arange(61),
    )
    land = np.zeros((61, 241), dtype=bool)
    for _, polygon in LAND:
        land |= point_in_polygon(west, north, polygon)
    for _, polygon in WATER_CUTS:
        land &= ~point_in_polygon(west, north, polygon)
    grid = land.astype(np.uint8)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(grid.tolist())
    raw = Image.fromarray(grid * 255, mode="L")
    raw.save(out / "candidate.png")
    large = raw.resize((1928, 488), resample=Image.Resampling.NEAREST)
    large.save(out / "candidate_8x.png")

    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = [[int(v) for v in row] for row in csv.reader(f)]
    assert len(rows) == 61 and all(len(r) == 241 for r in rows)
    assert {v for row in rows for v in row} <= {0, 1}
    assert sum(map(len, rows)) == 14701
    assert raw.size == (241, 61) and large.size == (1928, 488)
    assert set(raw.getdata()) <= {0, 255}
    assert set(large.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(large),
                          np.repeat(np.repeat(np.asarray(raw), 8, axis=0), 8, axis=1))
    print("Validated 61 x 241 = 14701 points; 241 x 61 and 1928 x 488 binary PNGs.")

if __name__ == "__main__":
    main()
