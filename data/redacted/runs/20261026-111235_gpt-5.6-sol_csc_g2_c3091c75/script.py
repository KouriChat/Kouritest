lats = 23.0 - 0.2 * np.arange(111)
lons = 99.0 + 0.2 * np.arange(141)
lon_grid, lat_grid = np.meshgrid(lons, lats)
land = np.zeros((111, 141), dtype=bool)


def add_polygon(points):
    """Mark grid points inside a hand-drawn lon/lat polygon."""
    inside = np.zeros(land.shape, dtype=bool)
    x, y = lon_grid, lat_grid
    j = len(points) - 1
    for i in range(len(points)):
        xi, yi = points[i]
        xj, yj = points[j]
        crosses = ((yi > y) != (yj > y)) & (
            x < (xj - xi) * (y - yi) / ((yj - yi) or 1e-30) + xi
        )
        inside ^= crosses
        j = i
    land[:] |= inside


def add_ellipse(lon, lat, rx, ry, angle=0.0):
    """Add an approximate island; radii and angle are in degrees."""
    a = np.deg2rad(angle)
    dx = lon_grid - lon
    dy = lat_grid - lat
    u = dx * np.cos(a) + dy * np.sin(a)
    v = -dx * np.sin(a) + dy * np.cos(a)
    land[:] |= (u / rx) ** 2 + (v / ry) ** 2 <= 1.0


