LAT = 23 - np.arange(111, dtype=float) * 0.2
LON = 99 + np.arange(141, dtype=float) * 0.2
X, Y = np.meshgrid(LON, LAT)
land = np.zeros((111, 141), dtype=bool)


def polygon(coords):
    """Even/odd point-in-polygon test performed simultaneously for all samples."""
    global land
    inside = np.zeros_like(land)
    for (x0, y0), (x1, y1) in zip(coords, coords[1:] + coords[:1]):
        if y0 == y1:
            continue
        crossing = ((y0 > Y) != (y1 > Y)) & (
            X < x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
        )
        inside ^= crossing
    land |= inside


def island(x, y, rx, ry, tilt=0):
    """Small ellipsoid island/reef with radii measured in degrees."""
    global land
    t = np.deg2rad(tilt)
    xx = (X - x) * np.cos(t) + (Y - y) * np.sin(t)
    yy = -(X - x) * np.sin(t) + (Y - y) * np.cos(t)
    land |= (xx / rx) ** 2 + (yy / ry) ** 2 <= 1.0


