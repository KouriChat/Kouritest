LAT = np.arange(89, -90, -2, dtype=float)
LON = np.arange(-179, 180, 2, dtype=float)
X, Y = np.meshgrid(LON, LAT)
LAND = np.zeros(X.shape, dtype=bool)
RULE_NAMES = []


def polygon(name, text):
    """Union a hand-drawn lon,lat polygon into the sampling mask."""
    points = [tuple(map(float, p.split(","))) for p in text.split()]
    assert len(points) >= 3
    inside = np.zeros(X.shape, dtype=bool)
    border = np.zeros(X.shape, dtype=bool)
    x1, y1 = points[-1]
    for x2, y2 in points:
        dx, dy = x2 - x1, y2 - y1
        cross = (X - x1) * dy - (Y - y1) * dx
        border |= ((np.abs(cross) < 1e-10)
                   & (X >= min(x1, x2)) & (X <= max(x1, x2))
                   & (Y >= min(y1, y2)) & (Y <= max(y1, y2)))
        if dy != 0:
            crossing = ((y1 > Y) != (y2 > Y))
            inside ^= crossing & (X < x1 + (Y - y1) * dx / dy)
        x1, y1 = x2, y2
    LAND[:] |= inside | border
    RULE_NAMES.append(name)


