LAT = np.arange(89, -90, -2, dtype=np.float64)
LON = np.arange(-179, 180, 2, dtype=np.float64)
XX, YY = np.meshgrid(LON, LAT)
land = np.zeros((90, 180), dtype=bool)
rules = []


def polygon(name, text, value=True):
    """Union/subtract a remembered polygon; longitudes may exceed 180."""
    numbers = np.array([float(v) for v in text.split()])
    assert len(numbers) >= 6 and len(numbers) % 2 == 0, name
    vertices = numbers.reshape(-1, 2)
    rules.append((name, vertices, value))
    xmin, ymin = vertices.min(axis=0)
    xmax, ymax = vertices.max(axis=0)
    for shift in (-360.0, 0.0, 360.0):
        x = XX + shift
        active = (x >= xmin) & (x <= xmax) & (YY >= ymin) & (YY <= ymax)
        if not active.any():
            continue
        px, py = x[active], YY[active]
        inside = np.zeros(px.shape, dtype=bool)
        boundary = np.zeros(px.shape, dtype=bool)
        ax, ay = vertices[-1]
        for bx, by in vertices:
            dx, dy = bx - ax, by - ay
            cross = (px - ax) * dy - (py - ay) * dx
            boundary |= ((np.abs(cross) < 1e-9) &
                         (px >= min(ax, bx)) & (px <= max(ax, bx)) &
                         (py >= min(ay, by)) & (py <= max(ay, by)))
            if dy != 0:
                inside ^= ((ay > py) != (by > py)) & (
                    px < ax + (py - ay) * dx / dy)
            ax, ay = bx, by
        selected = np.zeros_like(land)
        selected[active] = inside | boundary
        land[selected] = value


