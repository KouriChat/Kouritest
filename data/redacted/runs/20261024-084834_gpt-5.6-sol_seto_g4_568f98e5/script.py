def inside_poly(x, y, p):
    c = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]; xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            xx = (xj-xi) * (y-yi) / (yj-yi) + xi
            if x < xx:
                c = not c
        j = i
    return c

def ellipse(x, y, cx, cy, rx, ry, ang=0.0):
    a = np.deg2rad(ang)
    u = (x-cx)*np.cos(a) + (y-cy)*np.sin(a)
    v = -(x-cx)*np.sin(a) + (y-cy)*np.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1.0

