def point_on_segment(x, y, a, b, eps=1e-10):
    ax, ay = a
    bx, by = b
    cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
    return (abs(cross) <= eps and min(ax, bx) - eps <= x <= max(ax, bx) + eps
            and min(ay, by) - eps <= y <= max(ay, by) + eps)

def inside_polygon(x, y, polygon):
    inside = False
    for i, a in enumerate(polygon):
        b = polygon[(i + 1) % len(polygon)]
        if point_on_segment(x, y, a, b):
            return True
        x1, y1 = a
        x2, y2 = b
        if (y1 > y) != (y2 > y):
            if x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
                inside = not inside
    return inside

def is_land(lon, lat):
    return any(inside_polygon(lon, lat, poly) for poly in POLYGONS)

matrix = np.zeros((ROWS, COLS), dtype=np.uint8)
for row in range(ROWS):
    lat = LAT_TOP - row * STEP
    for col in range(COLS):
        lon = LON_LEFT + col * STEP
        matrix[row, col] = int(is_land(lon, lat))

