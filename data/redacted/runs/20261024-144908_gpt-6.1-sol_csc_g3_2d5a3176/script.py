# Only land outlines are unioned. Inland lakes remain land by the definition
# of this experiment; bays, straits and the open sea are outside polygons.
def inside_polygon(x, y, polygon):
    """Even-odd ray casting; points on an edge are assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = polygon[-1]
    eps = 1e-11
    for bx, by in polygon:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= eps)
            & (x >= min(ax, bx) - eps)
            & (x <= max(ax, bx) + eps)
            & (y >= min(ay, by) - eps)
            & (y <= max(ay, by) + eps)
        )
        if abs(dy) > eps:
            crossing = (ay > y) != (by > y)
            intersection_x = ax + (y - ay) * dx / dy
            inside ^= crossing & (x < intersection_x)
        ax, ay = bx, by
    return inside | boundary


def make_matrix():
    # Integer fifth-degrees avoid accumulation in floating-point arange.
    longitude = (495 + np.arange(141, dtype=np.int64)) / 5.0
    latitude = (115 - np.arange(111, dtype=np.int64)) / 5.0
    xx, yy = np.meshgrid(longitude, latitude)
    x, y = xx.ravel(), yy.ravel()
    result = np.zeros(x.size, dtype=bool)
    for name, polygon in POLYGONS:
        assert np.isfinite(polygon).all(), name
        low, high = polygon.min(axis=0), polygon.max(axis=0)
        use = (
            (~result) & (x >= low[0] - 1e-11)
            & (x <= high[0] + 1e-11) & (y >= low[1] - 1e-11)
            & (y <= high[1] + 1e-11)
        )
        if use.any():
            result[use] |= inside_polygon(x[use], y[use], polygon)
    return result.astype(np.uint8).reshape(111, 141)


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    matrix = make_matrix()
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert np.isin(matrix, [0, 1]).all()
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
