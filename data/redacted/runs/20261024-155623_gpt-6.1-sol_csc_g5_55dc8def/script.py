LONS = (990 + 2 * np.arange(141)) / 10.0
LATS = (230 - 2 * np.arange(111)) / 10.0
X, Y = np.meshgrid(LONS, LATS)
land = np.zeros(X.shape, dtype=bool)

def polygon(vertices):
    """Union a hand-drawn land polygon into the point-sampled mask."""
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > Y) != (y1 > Y))
            edge_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (X < edge_x)
        x0, y0 = x1, y1
    land[:] |= inside

def island(cx, cy, rx, ry, angle=0):
    """Small approximate island outline, with radii in degrees."""
    t = np.linspace(0, 2 * np.pi, 25)[:-1]
    a = np.deg2rad(angle)
    dx, dy = rx * np.cos(t), ry * np.sin(t)
    polygon(list(zip(cx + dx*np.cos(a) - dy*np.sin(a),
                     cy + dx*np.sin(a) + dy*np.cos(a))))

