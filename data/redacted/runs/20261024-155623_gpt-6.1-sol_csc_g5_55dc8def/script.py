"""Knowledge-only coastline reconstruction; no external geographic inputs.
Run: python outputs/generate_map.py
Requires numpy and Pillow. Coordinates below are hand-written approximations.
Classification is polygon membership, not independent reasoning per point.
"""
from pathlib import Path
