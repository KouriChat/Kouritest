def inside_polygon(xx, yy, poly):
    """Ray-crossing point-in-polygon; xx and yy can be full numpy arrays."""
    hit = np.zeros(xx.shape, dtype=bool)
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        if y0 != y1:
            crossing = ((y0 > yy) != (y1 > yy))
            edge_x = (x1-x0) * (yy-y0) / (y1-y0) + x0
            hit ^= crossing & (xx < edge_x)
        x0, y0 = x1, y1
    return hit


def build():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    # Exact endpoints, i.e. spacing 2 / 126 degrees; rows run north to south.
    latitude = np.linspace(55, 53, 127)
    longitude = np.linspace(-131, -129, 127)
    lon, lat = np.meshgrid(longitude, latitude)

    land = inside_polygon(lon, lat, mainland)
    for shape in island_shapes:
        land |= inside_polygon(lon, lat, vertices(shape))
    for inlet in watercuts:
        land &= ~inside_polygon(lon, lat, vertices(inlet))
    matrix = land.astype(np.uint8)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(matrix.tolist())

    raw = Image.fromarray(matrix * 255, mode="L")
    raw.save(out / "candidate.png")
    expanded = raw.resize((1016, 1016), resample=Image.Resampling.NEAREST)
    expanded.save(out / "candidate_8x.png")

    # Reopen generated artifacts and verify every requested property.
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        data = [row for row in csv.reader(f)]
    assert len(data) == 127 and all(len(row) == 127 for row in data)
    assert all(value in ("0", "1") for row in data for value in row)
    assert np.array_equal(np.asarray(data, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as check:
        small = np.asarray(check)
        assert check.size == (127, 127) and set(np.unique(small)) <= {0, 255}
    with Image.open(out / "candidate_8x.png") as check:
        large = np.asarray(check)
        assert check.size == (1016, 1016) and set(np.unique(large)) <= {0, 255}
        assert np.array_equal(large, np.repeat(np.repeat(small, 8, axis=0), 8, axis=1))
    print(f"Validated {matrix.size} samples; land {int(matrix.sum())}, water {int(matrix.size - matrix.sum())}")


if __name__ == "__main__":
    build()
