ROWS, COLS = 64, 253
STEP = 2.0 / 63.0
longitude = 129.0 + np.arange(COLS) * STEP
latitude = 35.0 - np.arange(ROWS) * STEP
X, Y = np.meshgrid(longitude, latitude)
land = np.zeros((ROWS, COLS), dtype=np.uint8)


def polygon(vertices, value=1):
    """Even-odd containment evaluated at the actual WGS84 sampling points."""
    inside = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if by != ay:
            crosses = (ay > Y) != (by > Y)
            intercept = ax + (Y - ay) * (bx - ax) / (by - ay)
            inside ^= crosses & (X < intercept)
        ax, ay = bx, by
    land[inside] = value


