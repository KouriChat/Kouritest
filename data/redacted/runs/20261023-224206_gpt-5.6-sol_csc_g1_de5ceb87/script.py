def inside(x, y, p):
    """Even/odd point in polygon, with boundary points treated as land."""
    hit = False
    n = len(p)
    for i in range(n):
        ax, ay = p[i]
        bx, by = p[(i + 1) % n]
        cross = (x-ax)*(by-ay) - (y-ay)*(bx-ax)
        if abs(cross) < 1e-9 and min(ax,bx)-1e-9 <= x <= max(ax,bx)+1e-9 \
                and min(ay,by)-1e-9 <= y <= max(ay,by)+1e-9:
            return True
        if (ay > y) != (by > y):
            xx = ax + (y-ay) * (bx-ax) / (by-ay)
            if x < xx:
                hit = not hit
    return hit

def ellipse(x, y, cx, cy, rx, ry, angle=0):
    a = math.radians(angle)
    u = (x-cx)*math.cos(a) + (y-cy)*math.sin(a)
    v = -(x-cx)*math.sin(a) + (y-cy)*math.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1.0

