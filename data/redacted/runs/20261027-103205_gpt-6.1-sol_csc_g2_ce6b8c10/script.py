def classify_points(longitudes, latitudes):
    """Union of memory-authored polygons; coastline points count as land."""
    xx, yy = np.meshgrid(longitudes, latitudes)
    result = np.zeros(xx.shape, dtype=np.uint8)
    for name, vertices in POLYGONS:
        vertices = np.asarray(vertices, dtype=np.float64)
        xmin, ymin = vertices.min(axis=0)
        xmax, ymax = vertices.max(axis=0)
        selected = ((xx >= xmin - 1e-10) & (xx <= xmax + 1e-10)
                    & (yy >= ymin - 1e-10) & (yy <= ymax + 1e-10))
        if not selected.any():
            continue
        x, y = xx[selected], yy[selected]
        inside = np.zeros(x.shape, dtype=bool)
        boundary = np.zeros(x.shape, dtype=bool)
        previous = vertices[-1]
        for current in vertices:
            x1, y1 = previous
            x2, y2 = current
            dx, dy = x2 - x1, y2 - y1
            if dy != 0:
                crossing = ((y1 > y) != (y2 > y))
                intercept = x1 + (y - y1) * dx / dy
                inside ^= crossing & (x < intercept)
            cross_product = (x - x1) * dy - (y - y1) * dx
            boundary |= ((np.abs(cross_product) <= 1e-11)
                         & (x >= min(x1, x2) - 1e-11)
                         & (x <= max(x1, x2) + 1e-11)
                         & (y >= min(y1, y2) - 1e-11)
                         & (y <= max(y1, y2) + 1e-11))
            previous = current
        result[selected] |= (inside | boundary).astype(np.uint8)
    return result

