# Smaller islands: remembered centers and approximate angular half-extents.
# Rotated ellipses are still fixed hand-authored geographic rules.
def island(name, lon, lat, a, b, angle=0):
    theta = np.linspace(0, 2 * np.pi, 48, endpoint=False)
    phi = np.deg2rad(angle)
    u, v = a * np.cos(theta), b * np.sin(theta)
    points = np.column_stack((lon + u*np.cos(phi) - v*np.sin(phi),
                              lat + u*np.sin(phi) + v*np.cos(phi)))
    POLYGONS.append((name, points.tolist()))

