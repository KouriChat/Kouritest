def contains(poly, x, y):
    """Even/odd ray test on coordinate points; coast-boundary points are land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = poly[-1]
    for x1, y1 in poly:
        dx, dy = x1 - x0, y1 - y0
        if dy != 0:
            crosses = (y0 > y) != (y1 > y)
            intersection = x0 + (y - y0) * dx / dy
            inside ^= crosses & (x < intersection)
        cross = (x - x0) * dy - (y - y0) * dx
        on_segment = (
            (np.abs(cross) <= 1e-10)
            & (x >= min(x0, x1) - 1e-10)
            & (x <= max(x0, x1) + 1e-10)
            & (y >= min(y0, y1) - 1e-10)
            & (y <= max(y0, y1) + 1e-10)
        )
        boundary |= on_segment
        x0, y0 = x1, y1
    return inside | boundary

