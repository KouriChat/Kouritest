"""Knowledge-only, hand-drawn approximation; no geographic inputs are read.

Coordinates below are (longitude, latitude), WGS84 degrees.  Polygon inclusion
and narrow, variable-width inlet rules classify points, not pixel areas.
Dependencies: numpy, Pillow. Run from any current working directory.
"""
from pathlib import Path
