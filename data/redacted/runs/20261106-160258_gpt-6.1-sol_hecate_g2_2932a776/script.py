N = 127
lon = -131.0 + np.arange(N, dtype=float) * (2.0 / 126.0)
lat = 55.0 - np.arange(N, dtype=float) * (2.0 / 126.0)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((N, N), dtype=bool)


def polygon(points):
    inside = np.zeros_like(land)
    ax, ay = points[-1]
    for bx, by in points:
        if by != ay:
            cross = ((ay > Y) != (by > Y))
            edge_x = ax + (Y - ay) * (bx - ax) / (by - ay)
            inside ^= cross & (X < edge_x)
        ax, ay = bx, by
    return inside


def add(points):
    land[:] |= polygon(points)


def water(points):
    land[:] &= ~polygon(points)


def inlet(points, widths):
    """Widths are half-widths in latitude degrees; longitude scaled by 0.59."""
    for (ax, ay), (bx, by), wa, wb in zip(
            points[:-1], points[1:], widths[:-1], widths[1:]):
        dx, dy = (bx - ax) * .59, by - ay
        px, py = (X - ax) * .59, Y - ay
        t = np.clip((px * dx + py * dy) / (dx * dx + dy * dy), 0, 1)
        d2 = (px - t * dx) ** 2 + (py - t * dy) ** 2
        land[d2 <= (wa + t * (wb - wa)) ** 2] = False


