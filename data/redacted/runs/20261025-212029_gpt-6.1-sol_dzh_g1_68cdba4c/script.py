def points_in_polygon(x, y, polygon):
    """Even/odd ray crossings, with points on the hand-drawn boundary on land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = polygon[-1]
    for bx, by in polygon:
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        if abs(dy) > 1e-15:
            crosses = (ay > y) != (by > y)
            intersection_x = ax + (y - ay) * dx / dy
            inside ^= crosses & (x < intersection_x)
        ax, ay = bx, by
    return inside | boundary


def generate():
    longitude = (-90 + 2 * np.arange(231, dtype=np.int32)) / 10.0
    latitude = (450 - 2 * np.arange(71, dtype=np.int32)) / 10.0
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((71, 231), dtype=bool)
    for polygon in POLYGONS:
        # Bounding-box screening only speeds up the exact point-in-polygon test.
        possible = (
            (x >= polygon[:, 0].min() - 1e-10)
            & (x <= polygon[:, 0].max() + 1e-10)
            & (y >= polygon[:, 1].min() - 1e-10)
            & (y <= polygon[:, 1].max() + 1e-10)
        )
        if possible.any():
            land[possible] |= points_in_polygon(x[possible], y[possible], polygon)
    return land.astype(np.uint8)


