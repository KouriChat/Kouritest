# Approximate exposed reef rims: outer minus inner marine lagoon.
REEF_RIMS = [
    ("Scarborough", 117.77, 15.15, .085, .075, .064, .052),
    ("Pratas reef", 116.82, 20.7, .115, .10, .094, .081),
    ("Bombay reef", 112.53, 16.03, .035, .025, .026, .016),
    ("Mischief reef", 115.53, 9.9, .055, .040, .041, .028),
    ("Subi reef", 114.08, 10.92, .040, .025, .029, .015),
    ("Commodore reef", 115.22, 8.37, .032, .024, .022, .015),
]



def point_in_polygon(x, y, vertices):
    """Vectorized point rule, not cell coverage or independent LLM judgments."""
    inside = np.zeros(x.shape, dtype=bool)
    on_edge = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        if dy != 0:
            crossing = ((ay > y) != (by > y))
            x_crossing = ax + (y - ay) * dx / dy
            inside ^= crossing & (x < x_crossing)
        if dx != 0 or dy != 0:
            on_edge |= (
                (np.abs(dx * (y - ay) - dy * (x - ax)) <= 1e-10)
                & (x >= min(ax, bx) - 1e-10)
                & (x <= max(ax, bx) + 1e-10)
                & (y >= min(ay, by) - 1e-10)
                & (y <= max(ay, by) + 1e-10)
            )
        ax, ay = bx, by
    return inside | on_edge


def generate():
    longitude = 99 + np.arange(141, dtype=np.float64) / 5
    latitude = 23 - np.arange(111, dtype=np.float64) / 5
    x, y = np.meshgrid(longitude, latitude)
    land = np.zeros((111, 141), dtype=bool)
    for name, vertices in POLYGONS:
        land |= point_in_polygon(x, y, vertices)
    for name, cx, cy, rx, ry, ix, iy in REEF_RIMS:
        outer = ((x-cx)/rx)**2 + ((y-cy)/ry)**2
        inner = ((x-cx)/ix)**2 + ((y-cy)/iy)**2
        land |= (outer <= 1 + 1e-12) & (inner >= 1 - 1e-12)
    # No lake holes: inland lakes are land under the requested definition.
    return land.astype(np.uint8)


