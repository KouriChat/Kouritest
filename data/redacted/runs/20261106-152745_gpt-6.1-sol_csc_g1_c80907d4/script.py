POLYGONS = []


def add(name, coordinates):
    points = [tuple(map(float, p.split(","))) for p in coordinates.split()]
    assert len(points) >= 3, name
    POLYGONS.append((name, points))


def ellipse(name, lon, lat, rx, ry, angle=0):
    # Small-island approximations, specified here rather than queried.
    t = np.linspace(0, 2 * np.pi, 33)[:-1]
    a = np.deg2rad(angle)
    dx, dy = rx * np.cos(t), ry * np.sin(t)
    points = list(zip(lon + dx*np.cos(a) - dy*np.sin(a),
                      lat + dx*np.sin(a) + dy*np.cos(a)))
    POLYGONS.append((name, points))


