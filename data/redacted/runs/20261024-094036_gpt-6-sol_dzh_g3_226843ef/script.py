def generate():
    latitudes = 45.0 - .2 * np.arange(71)
    longitudes = -9.0 + .2 * np.arange(231)
    result = np.zeros((71, 231), dtype=np.uint8)
    # Scan each hand-drawn coastline polygon. Crossings are paired and the
    # individual sampled POINT, never any grid cell's area, determines its bit.
    for polygon in (europe_west, balkans, anatolia, africa, *islands):
        for i, latitude in enumerate(latitudes):
            crossings = []
            last_x, last_y = polygon[-1]
            for curr_x, curr_y in polygon:
                if (last_y > latitude) != (curr_y > latitude):
                    cut = last_x + (latitude - last_y) * (
                        curr_x - last_x) / (curr_y - last_y)
                    crossings.append(cut)
                last_x, last_y = curr_x, curr_y
            crossings.sort()
            for left, right in zip(crossings[::2], crossings[1::2]):
                result[i, (longitudes >= left) & (longitudes < right)] = 1
    return result


def main():
    matrix = generate()
    dest = Path("outputs")
    dest.mkdir(parents=True, exist_ok=True)
    csv_path = dest / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        writer = csv.writer(handle)
        writer.writerows(matrix.tolist())
    raw = Image.fromarray(matrix * 255, "L")
    raw.save(dest / "candidate.png")
    enlarged = raw.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(dest / "candidate_8x.png")
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix)).issubset({0, 1})
    with csv_path.open(newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert set(raw.getdata()) <= {0, 255}
    assert set(enlarged.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(enlarged)[::8, ::8], np.asarray(raw))
    assert np.array_equal(np.asarray(enlarged),
                          np.repeat(np.repeat(np.asarray(raw), 8, axis=0),
                                    8, axis=1))


if __name__ == "__main__":
    main()
