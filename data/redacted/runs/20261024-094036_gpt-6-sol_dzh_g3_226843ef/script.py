def inside(x, y, poly):
    """Odd/even ray crossing against a polygon of (longitude, latitude) pairs."""
    hit = False
    prev_x, prev_y = poly[-1]
    for cur_x, cur_y in poly:
        if ((cur_y > y) != (prev_y > y)):
            edge_x = cur_x + (y - cur_y) * (prev_x - cur_x) / (prev_y - cur_y)
            if x < edge_x:
                hit = not hit
        prev_x, prev_y = cur_x, cur_y
    return hit


