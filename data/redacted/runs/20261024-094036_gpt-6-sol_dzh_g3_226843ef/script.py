import math


def oval(lon, lat, rx, ry, theta=0):
    """A coarse manually positioned ellipse, theta in degrees."""
    a = math.radians(theta)
    ca, sa = math.cos(a), math.sin(a)
    coords = []
    for k in range(16):
        t = 2 * math.pi * k / 16
        xx, yy = rx * math.cos(t), ry * math.sin(t)
        coords.append((lon + xx * ca - yy * sa, lat + xx * sa + yy * ca))
    islands.append(coords)


