    matrix = land.astype(np.uint8)
    assert matrix.shape == (64, 253)
    assert matrix.size == 16192
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert LAT[0] == 35.0 and LAT[-1] == 33.0
    assert LON[0] == 129.0 and LON[-1] == 137.0

    csv_path = OUT / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((2024, 512), resample=nearest)
    original.save(OUT / "candidate.png", format="PNG")
    enlarged.save(OUT / "candidate_8x.png", format="PNG")

    # Read back only our own generated outputs, never any geographic input.
    with csv_path.open("r", encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16192
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)

    with Image.open(OUT / "candidate.png") as im:
        assert im.size == (253, 64)
        assert im.mode == "L"
        small = np.array(im)
    with Image.open(OUT / "candidate_8x.png") as im:
        assert im.size == (2024, 512)
