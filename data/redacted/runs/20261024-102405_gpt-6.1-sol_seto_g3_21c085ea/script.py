LAT = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
LON = 129.0 + np.arange(253, dtype=np.float64) * (2.0 / 63.0)
X, Y = np.meshgrid(LON, LAT)
land = np.zeros((64, 253), dtype=bool)

def polygon(text):
    """Ray crossing at exact sample coordinates; text is lon,lat pairs."""
    vertices = [tuple(map(float, t.split(","))) for t in text.split()]
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            cross = ((y0 > Y) != (y1 > Y))
            xx = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= cross & (X < xx)
        x0, y0 = x1, y1
    return inside

def add(text):
    global land
    land |= polygon(text)

def remove(text):
    global land
    land &= ~polygon(text)

def ellipse(cx, cy, rx, ry, angle=0):
    global land
    a = np.deg2rad(angle)
    dx, dy = X-cx, Y-cy
    u, v = dx*np.cos(a)+dy*np.sin(a), -dx*np.sin(a)+dy*np.cos(a)
    land |= (u/rx)**2 + (v/ry)**2 <= 1

