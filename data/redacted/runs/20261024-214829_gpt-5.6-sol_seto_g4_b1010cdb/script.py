X, Y = np.meshgrid(xs, ys)
land = np.zeros((H, W), dtype=bool)

def poly(points):
    """Return point-in-polygon mask (boundary choice is immaterial here)."""
    p = np.asarray(points, float)
    inside = np.zeros(X.shape, dtype=bool)
    xj, yj = p[-1]
    for xi, yi in p:
        cross = ((yi > Y) != (yj > Y))
        xcut = (xj-xi) * (Y-yi) / ((yj-yi) if yj != yi else 1e-30) + xi
        inside ^= cross & (X < xcut)
        xj, yj = xi, yi
    return inside

def add_poly(points):
    global land
    land |= poly(points)

def cut_poly(points):
    global land
    land &= ~poly(points)

def ellipse(cx, cy, rx, ry, angle=0.0):
    a = np.deg2rad(angle)
    u = (X-cx)*np.cos(a) + (Y-cy)*np.sin(a)
    v = -(X-cx)*np.sin(a) + (Y-cy)*np.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1.0

def add_ellipse(cx, cy, rx, ry, angle=0.0):
    global land
    land |= ellipse(cx, cy, rx, ry, angle)

