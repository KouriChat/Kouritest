def inside(west, north, vertices):
    """Even-odd point-in-polygon test on the longitude/latitude plane."""
    hit = False
    previous = vertices[-1]
    for current in vertices:
        x1, y1 = previous
        x2, y2 = current
        if (y1 > north) != (y2 > north):
            boundary = x1 + (north - y1) * (x2 - x1) / (y2 - y1)
            if west < boundary:
                hit = not hit
        previous = current
    return hit

def land(west, north):
    return int(any(inside(west, north, outline) for outline in islands.values())
               and not any(inside(west, north, inlet)
                           for inlet in water_inlets.values()))

def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    matrix = [[land(105 - col / 10, 79 - row / 10)
               for col in range(241)] for row in range(61)]
    with (output / "candidate.csv").open("w", newline="", encoding="ascii") as file:
        csv.writer(file, lineterminator="\n").writerows(matrix)
    image = Image.new("RGB", (241, 61))
    image.putdata([(255 * cell,) * 3 for row in matrix for cell in row])
    image.save(output / "candidate.png")
    enlarged = image.resize((1928, 488), Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")
    assert len(matrix) == 61 and all(len(row) == 241 for row in matrix)
    assert {value for row in matrix for value in row} <= {0, 1}
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert enlarged.size == (1928, 488)
    assert all(enlarged.getpixel((8 * x + dx, 8 * y + dy))
               == image.getpixel((x, y))
               for y in range(61) for x in range(241)
               for dx in range(8) for dy in range(8))

if __name__ == "__main__":
    main()
