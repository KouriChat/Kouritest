def classify(lat, lon):
    land = any(inside(lat, lon, polygon) for polygon in POLYGONS)
    if land and any(inside(lat, lon, lake) for lake in LAKES):
        return 0
    return int(land)


def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    lats = range(89, -90, -2)
    lons = range(-179, 180, 2)
    matrix = np.array(
        [[classify(lat, lon) for lon in lons] for lat in lats],
        dtype=np.uint8,
    )
    with (output / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        for row in matrix:
            f.write(",".join(map(str, row)) + "\n")
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(
        output / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
