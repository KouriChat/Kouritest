def inside_polygon(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    return any(inside_polygon(lon, lat, polygon) for polygon in LAND)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    matrix = np.array(
        [[1 if is_land(lon, lat) else 0 for lon in LONS] for lat in LATS],
        dtype=np.uint8,
    )
    if matrix.shape != (71, 231) or matrix.size != 16401:
        raise AssertionError(f"unexpected matrix shape: {matrix.shape}")

    csv_path = OUT / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(OUT / "candidate.png")
    image.resize((1848, 568), resample=Image.Resampling.NEAREST).save(
        OUT / "candidate_8x.png"
    )

    rows = list(csv.reader(csv_path.open("r", newline="", encoding="ascii")))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(Image.open(OUT / "candidate.png")), matrix * 255)
    enlarged = np.asarray(Image.open(OUT / "candidate_8x.png"))
    assert enlarged.shape == (568, 1848)
    assert set(np.unique(enlarged)) == {0, 255}
    assert np.array_equal(enlarged, np.repeat(np.repeat(matrix * 255, 8, 0), 8, 1))
    print("Validated: 71x231 values, binary CSV/PNGs, exact nearest-neighbor 8x.")


if __name__ == "__main__":
    main()
