LONS = np.round(-9 + np.arange(231) * 0.2, 8)
LATS = np.round(45 - np.arange(71) * 0.2, 8)
X, Y = np.meshgrid(LONS, LATS)
land = np.ones(X.shape, dtype=np.uint8)


def inside(vertices):
    """Vectorized even-odd polygon test, independently at each sample point."""
    result = np.zeros(X.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crosses = (ay > Y) != (by > Y)
            edge_x = (bx - ax) * (Y - ay) / (by - ay) + ax
            result ^= crosses & (X < edge_x)
        ax, ay = bx, by
    return result


def water(vertices):
    land[inside(vertices)] = 0


def island(vertices):
    land[inside(vertices)] = 1


