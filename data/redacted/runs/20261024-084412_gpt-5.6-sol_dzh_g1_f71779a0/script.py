# Hand-written geographic reconstruction: no files or geographic services are read.
xs = np.round(-9.0 + .2*np.arange(231), 10)
ys = np.round(45.0 - .2*np.arange(71), 10)
X, Y = np.meshgrid(xs, ys)
land = np.zeros(X.shape, dtype=bool)

def poly(points):
    """Union a polygon into the land mask (vectorized even/odd point test)."""
    global land
    q = np.zeros(X.shape, dtype=bool)
    xj, yj = points[-1]
    for xi, yi in points:
        hit = ((yi > Y) != (yj > Y)) & (
            X < (xj-xi)*(Y-yi)/(yj-yi + 1e-30) + xi)
        q ^= hit
        xj, yj = xi, yi
    land |= q

def ellipse(cx, cy, rx, ry, angle=0):
    global land
    a = np.deg2rad(angle)
    u = (X-cx)*np.cos(a) + (Y-cy)*np.sin(a)
    v = -(X-cx)*np.sin(a) + (Y-cy)*np.cos(a)
    land |= (u/rx)**2 + (v/ry)**2 <= 1

