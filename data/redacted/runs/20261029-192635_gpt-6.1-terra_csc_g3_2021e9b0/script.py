def inside(x, y, poly):
    result = False
    prev = poly[-1]
    for cur in poly:
        x1, y1 = prev
        x2, y2 = cur
        if (y1 > y) != (y2 > y) and x < x1 + (y-y1)*(x2-x1)/(y2-y1):
            result = not result
        prev = cur
    return result

def land(x, y):
    return int(any(inside(x, y, p) for p in polygons) or
               any(((x-a)/rx)**2 + ((y-b)/ry)**2 <= 1 for a,b,rx,ry in islets))

