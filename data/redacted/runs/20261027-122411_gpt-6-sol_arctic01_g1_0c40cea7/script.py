def inside(x, y, polygon):
    """Ray crossing test with longitude represented by positive degrees west."""
    contained = False
    previous = polygon[-1]
    for current in polygon:
        x0, y0 = previous
        x1, y1 = current
        if (y0 > y) != (y1 > y):
            if x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
                contained = not contained
        previous = current
    return contained

def land(west, north):
    found = any(inside(west, north, coast) for coast in ISLANDS.values())
    if found and any(inside(west, north, channel) for channel in CHANNELS):
        found = False
    if not found:
        for x, y, rx, ry in SMALL_ISLANDS:
            if ((west - x) / rx) ** 2 + ((north - y) / ry) ** 2 <= 1:
                found = True
                break
    return int(found)

def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    rows = [[land(105 - col / 10, 79 - row / 10)
             for col in range(241)] for row in range(61)]
    with (out / "candidate.csv").open("w", newline="", encoding="utf-8") as handle:
        csv.writer(handle).writerows(rows)
    image = Image.new("RGB", (241, 61))
    image.putdata([(255, 255, 255) if value else (0, 0, 0)
                   for row in rows for value in row])
    image.save(out / "candidate.png")
    image.resize((1928, 488), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")
    assert len(rows) == 61 and all(len(row) == 241 for row in rows)
    assert all(value in (0, 1) for row in rows for value in row)

if __name__ == "__main__":
    main()
