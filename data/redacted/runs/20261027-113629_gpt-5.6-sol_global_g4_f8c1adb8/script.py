def inside(x, y, q):
    hit = False
    x0, y0 = q[-1]
    for x1, y1 in q:
        if (y1 > y) != (y0 > y):
            cut = x1 + (y-y1) * (x0-x1) / (y0-y1)
            if x < cut:
                hit = not hit
        x0, y0 = x1, y1
    return hit

def antarctic_coast(lon):
    # Piecewise approximation keeps the Ross/Weddell seas water and peninsula land.
    knots = [(-180,-78),(-160,-78),(-145,-75),(-120,-73),(-90,-72),
             (-75,-68),(-65,-63),(-57,-64),(-50,-74),(-25,-73),
             (0,-70),(25,-69),(50,-67),(80,-66),(110,-66),
             (140,-67),(160,-73),(180,-78)]
    for (a,ya),(b,yb) in zip(knots, knots[1:]):
        if a <= lon <= b:
            return ya + (yb-ya)*(lon-a)/(b-a)
    return -78

def land(lon, lat):
    if lat <= antarctic_coast(lon):
        return 1
    return int(any(inside(lon, lat, q) for q in P))

lats = list(range(89, -90, -2))
lons = list(range(-179, 180, 2))
matrix = np.array([[land(x, y) for x in lons] for y in lats], dtype=np.uint8)

out = Path("outputs")
