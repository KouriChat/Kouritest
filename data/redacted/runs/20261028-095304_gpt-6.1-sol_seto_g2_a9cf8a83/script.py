def inside_polygon(lon, lat, polygon):
    """Vectorized ray crossing; decisions use the sample point itself."""
    inside = np.zeros(lon.shape, dtype=bool)
    previous = polygon[-1]
    for current in polygon:
        x0, y0 = previous
        x1, y1 = current
        if y0 != y1:
            intersects_row = (y0 > lat) != (y1 > lat)
            crossing_lon = x0 + (lat - y0) * (x1 - x0) / (y1 - y0)
            inside ^= intersects_row & (lon < crossing_lon)
        previous = current
    return inside


