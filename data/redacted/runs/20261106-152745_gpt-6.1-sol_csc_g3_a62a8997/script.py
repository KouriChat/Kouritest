def contains(x, y, vertices):
    """Ray-crossing point test; a point on a polygon boundary is land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    previous = vertices[-1]
    for current in vertices:
        ax, ay = previous
        bx, by = current
        dx, dy = bx - ax, by - ay
        cross = (x - ax) * dy - (y - ay) * dx
        boundary |= ((np.abs(cross) <= 1e-10)
                     & (x >= min(ax, bx) - 1e-10)
                     & (x <= max(ax, bx) + 1e-10)
                     & (y >= min(ay, by) - 1e-10)
                     & (y <= max(ay, by) + 1e-10))
        if dy != 0:
            crosses = (ay > y) != (by > y)
            inside ^= crosses & (x < ax + (y - ay) * dx / dy)
        previous = current
    return inside | boundary


def main():
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    longitude = np.arange(495, 636, dtype=np.int32) / 5.0
    latitude = np.arange(115, 4, -1, dtype=np.int32) / 5.0
    x, y = np.meshgrid(longitude, latitude)
    matrix = np.zeros((111, 141), dtype=np.uint8)
    for name, vertices in POLYGONS:
        v = np.asarray(vertices)
        mask = ((x >= v[:, 0].min() - 1e-10)
                & (x <= v[:, 0].max() + 1e-10)
                & (y >= v[:, 1].min() - 1e-10)
                & (y <= v[:, 1].max() + 1e-10))
        matrix[mask] |= contains(x[mask], y[mask], vertices).astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
