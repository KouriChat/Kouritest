def polygon(name, text, water=False):
    """Store a manually specified polygon; never read geographic files."""
    points = [tuple(map(float, pair.split(','))) for pair in text.split()]
    assert len(points) >= 3 and all(len(p) == 2 for p in points)
    (SEA_CUTOUTS if water else OUTLINES).append((name, points))

def ellipse(name, x, y, rx, ry, angle=0):
    """Small islands approximated by a rotated 32-vertex outline."""
    t = np.arange(32) * (2 * np.pi / 32)
    a = np.deg2rad(angle)
    dx, dy = rx * np.cos(t), ry * np.sin(t)
    pts = list(zip(x + dx*np.cos(a) - dy*np.sin(a),
                   y + dx*np.sin(a) + dy*np.cos(a)))
    OUTLINES.append((name, pts))

def contains(points):
    """Vectorized even-odd point test, evaluated at sampling coordinates."""
    inside = np.zeros(X.shape, dtype=bool)
    xj, yj = points[-1]
    for xi, yi in points:
        if yi != yj:
            crosses = (yi > Y) != (yj > Y)
            intercept = xi + (Y - yi) * (xj - xi) / (yj - yi)
            inside ^= crosses & (X < intercept)
        xj, yj = xi, yi
    return inside

