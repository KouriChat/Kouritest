def contains(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    return any(contains(lon, lat, poly) for poly in LAND_POLYGONS) and not any(
        contains(lon, lat, poly) for poly in WATER_POLYGONS
    )

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    matrix = np.array(
        [[int(is_land(int(lon), int(lat))) for lon in longitudes]
         for lat in latitudes],
        dtype=np.uint8,
    )
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )

    assert matrix.shape == (90, 180)
    assert int(matrix.sum() + (matrix == 0).sum()) == 16200
    assert set(image.getdata()) == {0, 255}


if __name__ == "__main__":
    main()
