def on_segment(x, y, a, b):
    (x1, y1), (x2, y2) = a, b
    cross = (x-x1)*(y2-y1) - (y-y1)*(x2-x1)
    return abs(cross) < 1e-9 and min(x1,x2) <= x <= max(x1,x2) and min(y1,y2) <= y <= max(y1,y2)

def in_poly(x, y, poly):
    inside = False
    j = len(poly) - 1
    for i in range(len(poly)):
        a, b = poly[j], poly[i]
        if on_segment(x, y, a, b):
            return True
        xi, yi = b
        xj, yj = a
        if (yi > y) != (yj > y):
            cross_x = (xj-xi) * (y-yi) / (yj-yi) + xi
            if x < cross_x:
                inside = not inside
        j = i
    return inside

def in_any_polygon(x, y, collection):
    # ±360 also permits a hand-drawn polygon to straddle the date line.
    return any(in_poly(xx, y, p) for p in collection for xx in (x, x-360, x+360))

def in_any_ellipse(x, y, collection):
    for cx, cy, rx, ry in collection:
        dx = min(abs(x-cx), abs(x-cx-360), abs(x-cx+360))
        if (dx/rx)**2 + ((y-cy)/ry)**2 <= 1:
            return True
    return False

def is_land(lon, lat):
    land = in_any_polygon(lon, lat, polys) or in_any_ellipse(lon, lat, ellipses)
    cut = in_any_polygon(lon, lat, water_polys) or in_any_ellipse(lon, lat, water_ellipses)
    return int(land and not cut)

