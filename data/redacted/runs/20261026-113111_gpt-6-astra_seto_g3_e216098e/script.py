def point_in_polygon(lon, lat, polygon):
    """Ray-casting point-in-polygon test."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing_lon = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing_lon:
                inside = not inside
        j = i
    return inside

def ellipse_polygon(cx, cy, rx, ry, vertices=16):
    return [
        (
            cx + rx * math.cos(2.0 * math.pi * k / vertices),
            cy + ry * math.sin(2.0 * math.pi * k / vertices),
        )
        for k in range(vertices)
    ]

def main():
    islands = [ellipse_polygon(*item) for item in ISLAND_ELLIPSES]
    polygons = LAND_POLYGONS + islands
    matrix = np.zeros((ROWS, COLS), dtype=np.uint8)
    for row in range(ROWS):
        lat = LAT_TOP - row * LAT_STEP
        for col in range(COLS):
            lon = LON_LEFT + col * LON_STEP
            matrix[row, col] = any(
                point_in_polygon(lon, lat, polygon)
                for polygon in polygons
            )
    out_dir = Path("outputs")
    out_dir.mkdir(parents=True, exist_ok=True)

    with (out_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as f:
        for row in matrix:
            f.write(",".join(str(int(value)) for value in row) + "\n")

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out_dir / "candidate.png")
    enlarged = image.resize(
        (COLS * 8, ROWS * 8),
        Image.Resampling.NEAREST,
    )
    enlarged.save(out_dir / "candidate_8x.png")

if __name__ == "__main__":
    main()
