def in_polygon(lon, lat, vertices):
    inside = False
    for i, (ax, ay) in enumerate(vertices):
        bx, by = vertices[(i + 1) % len(vertices)]
        cross = (lon - ax) * (by - ay) - (lat - ay) * (bx - ax)
        if (abs(cross) < 1e-10 and min(ax, bx) <= lon <= max(ax, bx)
                and min(ay, by) <= lat <= max(ay, by)):
            return True
        if (ay > lat) != (by > lat):
            intersection = ax + (lat - ay) * (bx - ax) / (by - ay)
            if lon < intersection:
                inside = not inside
    return inside


def land(lon, lat):
    if any(in_polygon(lon, lat, outline) for outline in polygons):
        return 1
    for cx, cy, rx, ry in islands:
        if ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2 <= 1:
            return 1
    return 0


def main():
    out = Path("outputs")
    out.mkdir(exist_ok=True)
    matrix = [[land(99 + col / 5, 23 - row / 5)
               for col in range(141)] for row in range(111)]
    assert len(matrix) == 111
    assert all(len(row) == 141 and set(row) <= {0, 1} for row in matrix)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as file:
        csv.writer(file, lineterminator="\n").writerows(matrix)
    image = Image.new("L", (141, 111))
    image.putdata([255 * cell for row in matrix for cell in row])
    image.save(out / "candidate.png")
    enlarged = image.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    with (out / "candidate.csv").open(newline="", encoding="ascii") as file:
        saved = list(csv.reader(file))
    assert len(saved) == 111 and all(
        len(row) == 141 and set(row) <= {"0", "1"} for row in saved)
    assert set(image.getdata()) <= {0, 255}
    assert set(enlarged.getdata()) <= {0, 255}
    assert all(enlarged.getpixel((x * 8 + dx, y * 8 + dy))
               == image.getpixel((x, y))
               for y in range(111) for x in range(141)
               for dy in range(8) for dx in range(8))
    print("Validated: 111 x 141 = 15651 cells; binary PNGs; 8x nearest-neighbor.")


if __name__ == "__main__":
    main()
