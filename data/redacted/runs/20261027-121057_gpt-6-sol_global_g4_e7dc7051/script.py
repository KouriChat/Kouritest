lon, lat = np.meshgrid(np.arange(-179, 180, 2), np.arange(89, -90, -2))
land = np.zeros((90, 180), dtype=bool)

def contains(coords):
    """Even-odd ray test on all the sample coordinates."""
    x, y = coords[::2], coords[1::2]
    inside = np.zeros_like(land)
    for i in range(len(x)):
        j = (i - 1) % len(x)
        if y[i] != y[j]:
            edge = x[i] + (lat - y[i]) * (x[j] - x[i]) / (y[j] - y[i])
            inside ^= ((y[i] > lat) != (y[j] > lat)) & (lon < edge)
    return inside

for line in POLYGONS.splitlines():
    if line and not line.startswith("#"):
        vertices = [float(v) for v in line.split()]
        assert len(vertices) >= 6 and len(vertices) % 2 == 0
        land |= contains(vertices)

