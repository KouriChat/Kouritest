# The Gulf of Corinth enters far into the Greek mainland. At this grid
# spacing the narrow Corinth isthmus is kept by ending the gulf before 23 E.
corinth_gulf = [
    (21.8, 38.3), (22.18, 38.36), (22.55, 38.36),
    (22.87, 38.07), (22.86, 37.99), (22.5, 38.1),
    (22.09, 38.2), (21.8, 38.3),
]


def land_at(x, y):
    solid = inside(x, y, europe) or inside(x, y, africa) or inside(x, y, asia)
    if solid and (inside(x, y, black_sea) or inside(x, y, marmara)
                  or inside(x, y, corinth_gulf)):
        solid = False
    if not solid:
        solid = any(inside(x, y, shape) for shape in islands)
    if not solid:
        solid = any(((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1
                    for cx, cy, rx, ry in ellipses)
    return int(solid)


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = [[land_at(-9 + col / 5, 45 - row / 5)
               for col in range(231)] for row in range(71)]
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as stream:
        csv.writer(stream).writerows(matrix)

    im = Image.new("L", (231, 71))
    im.putdata([255 * value for row in matrix for value in row])
    im.save(out / "candidate.png")
    enlarged = im.resize((1848, 568), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    assert len(matrix) == 71 and all(len(row) == 231 for row in matrix)
    assert sum(len(row) for row in matrix) == 16401
    assert {value for row in matrix for value in row} == {0, 1}
    with (out / "candidate.csv").open(newline="", encoding="ascii") as stream:
        recorded = [list(map(int, row)) for row in csv.reader(stream)]
    assert recorded == matrix
    with Image.open(out / "candidate.png") as raw, \
         Image.open(out / "candidate_8x.png") as large:
        assert raw.size == (231, 71) and large.size == (1848, 568)
        assert set(raw.getdata()) == {0, 255}
        assert set(large.getdata()) == {0, 255}
        assert list(large.getdata()) == list(
            raw.resize((1848, 568), Image.Resampling.NEAREST).getdata())
    print("Validated 71 x 231 samples, monochrome PNGs, and 8x nearest-neighbor enlargement")


if __name__ == "__main__":
    main()
