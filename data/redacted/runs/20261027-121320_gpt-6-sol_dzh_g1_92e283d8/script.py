def inside(x, y, vertices):
    """Even/odd polygon test; the endpoints belong to the polygon."""
    hit = False
    previous = vertices[-1]
    for current in vertices:
        xa, ya = previous
        xb, yb = current
        cross = (xb - xa) * (y - ya) - (yb - ya) * (x - xa)
        if abs(cross) < 1e-10 and min(xa, xb) <= x <= max(xa, xb) and min(ya, yb) <= y <= max(ya, yb):
            return True
        if (ya > y) != (yb > y):
            boundary = xa + (xb - xa) * (y - ya) / (yb - ya)
            if x < boundary:
                hit = not hit
        previous = current
    return hit


