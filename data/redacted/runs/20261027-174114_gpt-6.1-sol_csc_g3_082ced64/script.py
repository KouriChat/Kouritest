def polygon_mask(longitude, latitude, vertices):
    """Vectorized ray crossing, with coastline points assigned to land."""
    inside = np.zeros(longitude.shape, dtype=bool)
    boundary = np.zeros(longitude.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (longitude - ax) * dy - (latitude - ay) * dx
        on_segment = (
            (np.abs(cross) <= 1e-10)
            & (longitude >= min(ax, bx) - 1e-10)
            & (longitude <= max(ax, bx) + 1e-10)
            & (latitude >= min(ay, by) - 1e-10)
            & (latitude <= max(ay, by) + 1e-10)
        )
        boundary |= on_segment
        if abs(dy) > 1e-14:
            crossing = (ay > latitude) != (by > latitude)
            intersection = ax + (latitude - ay) * dx / dy
            inside ^= crossing & (longitude < intersection)
        ax, ay = bx, by
    return inside | boundary


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    # Integer construction ensures 111 north-to-south rows and 141 columns.
    latitudes = np.arange(115, 4, -1, dtype=np.int32) / 5.0
    longitudes = np.arange(495, 636, dtype=np.int32) / 5.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    mask = np.zeros((111, 141), dtype=bool)
    for _, vertices in POLYGONS:
        mask |= polygon_mask(longitude, latitude, vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert set(np.unique(matrix)) == {0, 1}
    assert (latitudes[0], latitudes[-1]) == (23.0, 1.0)
    assert (longitudes[0], longitudes[-1]) == (99.0, 127.0)

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle, lineterminator="\n").writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((1128, 888), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Check the files actually written, including every replicated pixel.
    with csv_path.open(newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in {"0", "1"} for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)
    with Image.open(out / "candidate.png") as image:
        assert image.size == (141, 111)
        raw = np.array(image)
    with Image.open(out / "candidate_8x.png") as image:
        assert image.size == (1128, 888)
        scaled = np.array(image)
    assert set(np.unique(raw)) == {0, 255}
    assert set(np.unique(scaled)) == {0, 255}
    assert np.array_equal(raw, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(scaled, expected)
    report = {
        "method": "memory-based handwritten polygons; point-in-polygon union",
        "rows": 111,
        "columns": 141,
        "valid_values": int(matrix.size),
        "land_points": int(matrix.sum()),
        "water_points": int(matrix.size - matrix.sum()),
        "csv_binary_complete": True,
        "original_size": [141, 111],
        "enlarged_size": [1128, 888],
        "only_black_white": True,
        "nearest_neighbor_verified_pixel_by_pixel": True,
    }
    (out / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


