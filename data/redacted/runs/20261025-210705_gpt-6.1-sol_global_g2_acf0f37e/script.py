def point_in_polygon(xs, ys, vertices):
    """Even/odd ray casting, with boundary points counted as land."""
    inside = np.zeros(xs.shape, dtype=bool)
    boundary = np.zeros(xs.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        dx, dy = bx - ax, by - ay
        cross = (xs - ax) * dy - (ys - ay) * dx
        boundary |= (
            (np.abs(cross) <= 1e-9)
            & (xs >= min(ax, bx) - 1e-10)
            & (xs <= max(ax, bx) + 1e-10)
            & (ys >= min(ay, by) - 1e-10)
            & (ys <= max(ay, by) + 1e-10)
        )
        if dy != 0:
            crossing = ((ay > ys) != (by > ys))
            intercept = ax + (ys - ay) * dx / dy
            inside ^= crossing & (xs < intercept)
        ax, ay = bx, by
    return inside | boundary


def generate_matrix():
    latitudes = 89 - 2 * np.arange(90, dtype=np.int16)
    longitudes = -179 + 2 * np.arange(180, dtype=np.int16)
    xx, yy = np.meshgrid(longitudes.astype(float), latitudes.astype(float))
    result = np.zeros((90, 180), dtype=bool)
    for name, vertices in POLYGONS:
        assert len(vertices) >= 3, name
        v = np.asarray(vertices, dtype=float)
        assert np.all(np.isfinite(v)), name
        assert np.all((v[:, 1] >= -90) & (v[:, 1] <= 90)), name
        xmin, ymin = v.min(axis=0)
        xmax, ymax = v.max(axis=0)
        # Some recalled outlines explicitly continue east through longitude
        # 180. Equivalent longitude copies handle the antimeridian, without
        # smoothing, dilation, filling holes, or any later geographic edits.
        for shift in (0, 360, -360):
            shifted = xx + shift
            box = (
                (shifted >= xmin) & (shifted <= xmax)
                & (yy >= ymin) & (yy <= ymax)
            )
            if np.any(box):
                result[box] |= point_in_polygon(
                    shifted[box], yy[box], vertices
                )
    return result.astype(np.uint8)


