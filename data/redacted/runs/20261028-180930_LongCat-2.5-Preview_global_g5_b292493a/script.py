def in_poly(lon, lat, poly):
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > lat) != (yj > lat):
            xint = xi + (lat - yi) * (xj - xi) / (yj - yi)
            if lon < xint:
                inside = not inside
        j = i
    return inside


def in_poly_wrap(lon, lat, poly):
    return (in_poly(lon, lat, poly)
            or in_poly(lon + 360.0, lat, poly)
            or in_poly(lon - 360.0, lat, poly))


def any_poly(lon, lat, polys):
    for p in polys:
        if in_poly_wrap(lon, lat, p):
            return True
    return False


