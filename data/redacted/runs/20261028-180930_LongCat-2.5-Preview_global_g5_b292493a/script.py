def antarctic_edge(lon):
    """Latitude of the Antarctic coastline at a given longitude."""
    xs = [p[0] for p in ANTARCTIC]
    ys = [p[1] for p in ANTARCTIC]
    if lon <= xs[0] or lon >= xs[-1]:
        return ys[0]
    for i in range(len(xs) - 1):
        if xs[i] <= lon <= xs[i + 1]:
            t = (lon - xs[i]) / (xs[i + 1] - xs[i])
            return ys[i] + t * (ys[i + 1] - ys[i])
    return ys[-1]


def build_matrix():
    grid = np.zeros((90, 180), dtype=np.uint8)
    for r, lat in enumerate(LATS):
        for c, lon in enumerate(LONS):
            v = 1 if any_poly(lon, lat, LAND_POLYS) else 0
            if lat <= antarctic_edge(lon):
                v = 1
            if any_poly(lon, lat, WATER_POLYS):
                v = 0
            grid[r, c] = v
    return grid


def main():
    os.makedirs("outputs", exist_ok=True)
    grid = build_matrix()
    assert grid.shape == (90, 180)
    assert grid.size == 16200
    assert set(np.unique(grid).tolist()) <= {0, 1}

    with open("outputs/candidate.csv", "w", encoding="ascii", newline="\n") as f:
        for row in grid:
            f.write(",".join(str(int(v)) for v in row) + "\n")

    img = Image.fromarray((grid * 255).astype(np.uint8), mode="L")
    img.save("outputs/candidate.png")
    img.resize((1440, 720), Image.NEAREST).save("outputs/candidate_8x.png")

    print("shape", grid.shape, "land cells", int(grid.sum()),
          "water cells", int(grid.size - grid.sum()))


if __name__ == "__main__":
    main()
