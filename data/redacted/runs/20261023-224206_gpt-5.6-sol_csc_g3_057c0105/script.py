def inside_poly(x, y, p):
    """Odd/even point-in-polygon test, with polygon edges counted as land."""
    hit = False
    n = len(p)
    for i in range(n):
        x1, y1 = p[i]
        x2, y2 = p[(i + 1) % n]
        dx, dy = x2 - x1, y2 - y1
        cross = (x - x1) * dy - (y - y1) * dx
        if abs(cross) < 1e-10 and min(x1, x2)-1e-10 <= x <= max(x1, x2)+1e-10 and min(y1, y2)-1e-10 <= y <= max(y1, y2)+1e-10:
            return True
        if ((y1 > y) != (y2 > y)):
            xx = x1 + (y-y1)*dx/dy
            if x <= xx:
                hit = not hit
    return hit


