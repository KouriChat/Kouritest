def is_land(x, y):
    for p in polys:
        if inside_poly(x, y, p):
            return 1
    for cx, cy, rx, ry in ellipses:
        if ((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1.0:
            return 1
    for cx, cy, r in reefs:
        # longitude scaling is immaterial at this resolution and latitude.
        if (x-cx)**2 + (y-cy)**2 <= r*r:
            return 1
    return 0


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lons = [round(99.0 + .2*i, 10) for i in range(141)]
    lats = [round(23.0 - .2*j, 10) for j in range(111)]
    matrix = np.array([[is_land(x, y) for x in lons] for y in lats],
                      dtype=np.uint8)

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f).writerows(matrix.tolist())

    raw = Image.fromarray(matrix * np.uint8(255), mode="L")
    raw.save(out / "candidate.png")
    large = raw.resize((1128, 888), resample=Image.Resampling.NEAREST)
    large.save(out / "candidate_8x.png")

    # Self-check all requested structural properties, including exact NN blocks.
    assert matrix.shape == (111, 141)
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert raw.size == (141, 111) and set(raw.getdata()) <= {0, 255}
    assert large.size == (1128, 888) and set(large.getdata()) <= {0, 255}
    enlarged = np.asarray(large)
    assert np.array_equal(enlarged, np.repeat(np.repeat(
        np.asarray(raw), 8, axis=0), 8, axis=1))
    print("validated:", matrix.shape, matrix.size, "points;",
          int(matrix.sum()), "land points")


if __name__ == "__main__":
    main()
