def inside(lon, lat, polygon):
    hit = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross:
                hit = not hit
        j = i
    return hit

def is_land(lon, lat):
    return int(any(inside(lon, lat, p) for p in LAND))

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lats = [45.0 - 0.2 * r for r in range(71)]
    lons = [-9.0 + 0.2 * c for c in range(231)]
    matrix = np.array([[is_land(x, y) for x in lons] for y in lats],
                      dtype=np.uint8)
    with (out / "candidate.csv").open("w", newline="") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = np.where(matrix == 1, 255, 0).astype(np.uint8)
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    image.resize((1848, 568), Image.Resampling.NEAREST).save(
        out / "candidate_8x.png")
    assert matrix.shape == (71, 231) and matrix.size == 16401

if __name__ == "__main__":
    main()
