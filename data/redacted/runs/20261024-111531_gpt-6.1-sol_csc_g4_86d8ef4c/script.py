def polygon_points(x, y, vertices):
    """Vectorized ray crossing; boundary points are taken as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        if by != ay:
            inside ^= ((ay > y) != (by > y)) & (
                x < ax + (y - ay) * (bx - ax) / (by - ay)
            )
        ax, ay = bx, by
    return inside | boundary


def generate():
    # Integer construction avoids cumulative stepping drift.
    lats = (115 - np.arange(111)) / 5.0
    lons = (495 + np.arange(141)) / 5.0
    x, y = np.meshgrid(lons, lats)
    land = np.zeros((111, 141), dtype=bool)
    for name, vertices in POLYGONS:
        vx, vy = np.asarray(vertices).T
        selection = (
            (x >= vx.min() - 1e-10) & (x <= vx.max() + 1e-10)
            & (y >= vy.min() - 1e-10) & (y <= vy.max() + 1e-10)
        )
        land[selection] |= polygon_points(x[selection], y[selection], vertices)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert set(np.unique(matrix)) <= {0, 1}
    assert (lats[0], lats[-1], lons[0], lons[-1]) == (23, 1, 99, 127)
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    np.savetxt(out / "candidate.csv", matrix, fmt="%d", delimiter=",")
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((1128, 888), resample=nearest)
    enlarged.save(out / "candidate_8x.png")
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111
    assert all(len(row) == 141 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as original:
        assert original.size == (141, 111) and original.mode == "L"
        assert set(np.unique(np.asarray(original))) == {0, 255}
        assert np.array_equal(np.asarray(original), pixels)
    expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
    with Image.open(out / "candidate_8x.png") as zoom:
        assert zoom.size == (1128, 888) and zoom.mode == "L"
        assert set(np.unique(np.asarray(zoom))) == {0, 255}
        assert np.array_equal(np.asarray(zoom), expected)
    print("Validated: 111x141 = 15651 binary values; CSV complete; "
          "141x111 and 1128x888 black/white PNGs; exact nearest-neighbor 8x.")
    print(f"Land: {int(matrix.sum())}; water: {int(matrix.size-matrix.sum())}")


