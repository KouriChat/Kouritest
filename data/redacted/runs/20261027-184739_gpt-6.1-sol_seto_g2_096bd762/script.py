longitudes = [129.0 + j * (8.0 / 252.0) for j in range(253)]
matrix = np.zeros((64, 253), dtype=np.uint8)

for row, lat in enumerate(latitudes):
    for col, lon in enumerate(longitudes):
        matrix[row, col] = any(contains(lon, lat, polygon) for polygon in LAND)

