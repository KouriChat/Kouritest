LAT = np.arange(89, -90, -2)
LON = np.arange(-179, 180, 2)
XX, YY = np.meshgrid(LON, LAT)
LAND = np.zeros((90, 180), dtype=bool)
OUTLINES = []


def polygon(name, text, water=False):
    """Register a memory-drawn polygon; longitude precedes latitude."""
    points = [tuple(map(float, item.split(","))) for item in text.split()]
    OUTLINES.append((name, points, water))


def rasterize(points):
    # Ray casting evaluated at precisely the requested sample coordinates.
    # Also include points that lie exactly on a hand-drawn boundary.
    inside = np.zeros(XX.shape, dtype=bool)
    boundary = inside.copy()
    x0, y0 = points[-1]
    for x1, y1 in points:
        dx, dy = x1 - x0, y1 - y0
        if dy != 0:
            crosses = (y0 > YY) != (y1 > YY)
            xcross = x0 + (YY - y0) * dx / dy
            inside ^= crosses & (XX < xcross)
        cross = (XX - x0) * dy - (YY - y0) * dx
        on = (np.abs(cross) < 1e-9)
        on &= (XX >= min(x0, x1)) & (XX <= max(x0, x1))
        on &= (YY >= min(y0, y1)) & (YY <= max(y0, y1))
        boundary |= on
        x0, y0 = x1, y1
    return inside | boundary


