def main():
    for _, points, water in OUTLINES:
        if not water:
            LAND[:] |= rasterize(points)
    for _, points, water in OUTLINES:
        if water:
            LAND[:] &= ~rasterize(points)
    matrix = LAND.astype(np.uint8)
    assert matrix.shape == (90, 180)
    assert matrix.size == 16200
    assert np.isin(matrix, [0, 1]).all()
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(out / "candidate.png")
    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST
    enlarged = original.resize((1440, 720), resample=nearest)
    enlarged.save(out / "candidate_8x.png")
    # Validate the actual on-disk deliverables, including every enlarged pixel.
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    restored = np.array(rows, dtype=np.uint8)
    assert restored.size == 16200
    assert np.array_equal(restored, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (180, 90)
        assert im.mode == "L"
        raw = np.array(im)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1440, 720)
        assert im.mode == "L"
        big = np.array(im)
    assert set(np.unique(raw)).issubset({0, 255})
    assert set(np.unique(big)).issubset({0, 255})
    assert np.array_equal(raw, restored * np.uint8(255))
    assert np.array_equal(big, np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1))
    assert LAT.tolist() == list(range(89, -90, -2))
    assert LON.tolist() == list(range(-179, 180, 2))
    print("Validated: 90 x 180 = 16,200 binary labels; north-to-south rows.")
    print("PNG: 180 x 90; 8x PNG: 1440 x 720; black/white only; exact nearest neighbor.")
    print("Method: hand-written memory-only polygons, automatically rasterized.")
    print(f"Land samples: {matrix.sum()} / {matrix.size}")


if __name__ == "__main__":
    main()
