def in_polygon(x, y, vertices):
    """向量化射线判定；返回每个采样点是否在手写多边形内。"""
    inside = np.zeros(x.shape, dtype=bool)
    x1, y1 = vertices[-1]

    for x2, y2 in vertices:
        if y1 != y2:
            crosses = (y1 > y) != (y2 > y)
            boundary_x = (x2 - x1) * (y - y1) / (y2 - y1) + x1
            inside ^= crosses & (x < boundary_x)
        x1, y1 = x2, y2

    return inside


def in_ellipse(x, y, cx, cy, rx, ry, angle):
    theta = np.deg2rad(angle)
    dx = x - cx
    dy = y - cy
    u = dx * np.cos(theta) + dy * np.sin(theta)
    v = -dx * np.sin(theta) + dy * np.cos(theta)
    return (u / rx) ** 2 + (v / ry) ** 2 <= 1


def main():
    longitude = 129.0 + np.arange(253) * (2.0 / 63.0)
    latitude = 35.0 - np.arange(64) * (2.0 / 63.0)
    x, y = np.meshgrid(longitude, latitude)

    land = np.zeros((64, 253), dtype=bool)
    for coast in COASTS:
        land |= in_polygon(x, y, coast)
    for island in ISLANDS:
        land |= in_ellipse(x, y, *island)

    matrix = land.astype(np.uint8)
    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)

    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as file:
        csv.writer(file).writerows(matrix.tolist())

    # mode L 中的 0、255 分别表示黑、白；nearest 保留原像素。
    original = Image.fromarray(matrix * 255, mode="L")
    original.save(output / "candidate.png")
    enlarged = original.resize((2024, 512), resample=Image.Resampling.NEAREST)
    enlarged.save(output / "candidate_8x.png")

    assert matrix.shape == (64, 253)
    assert matrix.size == 16192
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    with csv_path.open("r", encoding="utf-8", newline="") as file:
        rows = list(csv.reader(file))
    assert len(rows) == 64
    assert all(len(row) == 253 and set(row) <= {"0", "1"} for row in rows)
    assert original.size == (253, 64)
    assert enlarged.size == (2024, 512)
    assert set(original.getdata()) <= {0, 255}
    assert set(enlarged.getdata()) <= {0, 255}
    assert np.array_equal(
        np.asarray(enlarged),
        np.repeat(np.repeat(np.asarray(original), 8, axis=0), 8, axis=1),
    )

    print("已生成 outputs/candidate.csv、candidate.png、candidate_8x.png")


if __name__ == "__main__":
    main()
