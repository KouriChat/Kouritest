def polygon_mask(vertices, longitude, latitude):
    """Vectorized ray crossing, with polygon-edge points included."""
    p = np.asarray(vertices, dtype=np.float64)
    assert p.shape[0] >= 3 and p.shape[1] == 2
    assert np.isfinite(p).all()
    eligible = (
        (longitude >= p[:, 0].min() - 1e-10)
        & (longitude <= p[:, 0].max() + 1e-10)
        & (latitude >= p[:, 1].min() - 1e-10)
        & (latitude <= p[:, 1].max() + 1e-10)
    )
    mask = np.zeros(longitude.shape, dtype=bool)
    if not eligible.any():
        return mask
    x, y = longitude[eligible], latitude[eligible]
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x1, y1 = p[-1]
    for x2, y2 in p:
        dx, dy = x2 - x1, y2 - y1
        cross = (x - x1) * dy - (y - y1) * dx
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(x1, x2) - 1e-10)
            & (x <= max(x1, x2) + 1e-10)
            & (y >= min(y1, y2) - 1e-10)
            & (y <= max(y1, y2) + 1e-10)
        )
        if dy != 0:
            inside ^= ((y1 > y) != (y2 > y)) & (
                x < x1 + (y - y1) * dx / dy
            )
        x1, y1 = x2, y2
    mask[eligible] = inside | boundary
    return mask
def main():
    # Integer arithmetic fixes the requested coordinates and ordering exactly.
    latitudes = (450 - 2 * np.arange(71, dtype=np.int64)) / 10.0
    longitudes = (-90 + 2 * np.arange(231, dtype=np.int64)) / 10.0
    longitude, latitude = np.meshgrid(longitudes, latitudes)
    assert latitudes[0] == 45 and latitudes[-1] == 31
    assert longitudes[0] == -9 and longitudes[-1] == 37
    assert longitude.shape == latitude.shape == (71, 231)

    # Only the 16,401 requested points are classified. Polygon vertices outside
    # the frame merely close contours; no out-of-frame samples are generated.
    land_mask = np.zeros((71, 231), dtype=bool)
    for _, outline in LAND:
        land_mask |= polygon_mask(outline, longitude, latitude)
    for _, outline in WATER:
        land_mask &= ~polygon_mask(outline, longitude, latitude)
    for _, outline in ISLANDS:
        land_mask |= polygon_mask(outline, longitude, latitude)
    matrix = land_mask.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()

