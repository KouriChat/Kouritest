# Polygon coordinates are approximate (longitude, latitude) vertices recalled
# from geography. A single point-in-polygon test is applied to every grid cell.
xs = np.arange(-179, 180, 2, dtype=float)
ys = np.arange(89, -90, -2, dtype=float)
X, Y = np.meshgrid(xs, ys)
mask = np.zeros((90, 180), dtype=bool)

def polygon(points):
    p = np.asarray(points, dtype=float)
    x = X
    if np.max(p[:, 0]) > 180:
        x = np.where(X < 0, X + 360, X)
    elif np.min(p[:, 0]) < -180:
        x = np.where(X > 0, X - 360, X)
    inside = np.zeros_like(mask)
    for (x0, y0), (x1, y1) in zip(p, np.roll(p, -1, axis=0)):
        if y0 == y1:
            continue
        inside ^= ((y0 > Y) != (y1 > Y)) & (
            x < x0 + (Y - y0) * (x1 - x0) / (y1 - y0))
    return inside

def land(points):
    global mask
    mask |= polygon(points)

def sea(points):
    global mask
    mask &= ~polygon(points)

