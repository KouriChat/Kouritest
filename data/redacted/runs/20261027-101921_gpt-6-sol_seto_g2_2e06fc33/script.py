OUTLINES = (HONSHU, EAST_ISE, KYUSHU, SHIKOKU, *ISLANDS)
BOUNDED_OUTLINES = [
    (min(p[0] for p in outline), max(p[0] for p in outline),
     min(p[1] for p in outline), max(p[1] for p in outline), outline)
    for outline in OUTLINES
]


def is_land(longitude, latitude):
    for west, east, south, north, outline in BOUNDED_OUTLINES:
        if west <= longitude <= east and south <= latitude <= north:
            if polygon_contains(longitude, latitude, outline):
                return 1
    for center_x, center_y, rx, ry in SMALL_ISLANDS:
        dx = (longitude - center_x) / rx
        dy = (latitude - center_y) / ry
        if dx * dx + dy * dy <= 1.0:
            return 1
    return 0


def main():
    destination = Path('outputs')
    destination.mkdir(parents=True, exist_ok=True)
    height, width = 64, 253
    matrix = [
        [is_land(129 + col * (2 / 63), 35 - row * (2 / 63))
         for col in range(width)]
        for row in range(height)
    ]
    assert len(matrix) == 64 and all(len(row) == 253 for row in matrix)
    assert all(value in (0, 1) for row in matrix for value in row)

    with (destination / 'candidate.csv').open('w', newline='', encoding='ascii') as csv_file:
        csv.writer(csv_file).writerows(matrix)

    raw = Image.new('L', (width, height))
    raw.putdata([255 * value for row in matrix for value in row])
    raw.save(destination / 'candidate.png')
    upscaled = raw.resize((width * 8, height * 8), resample=Image.Resampling.NEAREST)
    upscaled.save(destination / 'candidate_8x.png')

    with (destination / 'candidate.csv').open('r', newline='', encoding='ascii') as csv_file:
        written = list(csv.reader(csv_file))
    assert len(written) == 64
    assert all(len(row) == 253 and set(row) <= {'0', '1'} for row in written)
    assert sum(map(len, written)) == 16192
    with Image.open(destination / 'candidate.png') as check_raw, \
         Image.open(destination / 'candidate_8x.png') as check_big:
        assert check_raw.size == (253, 64) and check_big.size == (2024, 512)
        assert set(check_raw.getdata()) <= {0, 255}
        assert set(check_big.getdata()) <= {0, 255}
        assert list(check_big.getdata()) == list(
            check_raw.resize((2024, 512), Image.Resampling.NEAREST).getdata()
        )
    print('Validated: 64 x 253 = 16192 points, binary CSV/PNGs, nearest-neighbor 8x.')


if __name__ == '__main__':
    main()
