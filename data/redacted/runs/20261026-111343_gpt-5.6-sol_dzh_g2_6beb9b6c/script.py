def on_segment(lon, lat, a, b):
    cross = (lon - a[0]) * (b[1] - a[1]) - (lat - a[1]) * (b[0] - a[0])
    if abs(cross) > 1e-9:
        return False
    return (min(a[0], b[0]) - 1e-9 <= lon <= max(a[0], b[0]) + 1e-9 and
            min(a[1], b[1]) - 1e-9 <= lat <= max(a[1], b[1]) + 1e-9)


def inside(lon, lat, ring):
    hit = False
    for i, a in enumerate(ring):
        b = ring[(i + 1) % len(ring)]
        if on_segment(lon, lat, a, b):
            return True
        if (a[1] > lat) != (b[1] > lat):
            crossing = (b[0] - a[0]) * (lat - a[1]) / (b[1] - a[1]) + a[0]
            if lon < crossing:
                hit = not hit
    return hit


def is_land(lon, lat):
    return any(inside(lon, lat, ring) for ring in LAND) or any(
        inside(lon, lat, ring) for ring in ISLANDS
    )


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    lons = [WEST + STEP * col for col in range(COLS)]
    lats = [NORTH - STEP * row for row in range(ROWS)]
    matrix = np.fromiter(
        (int(is_land(lon, lat)) for lat in lats for lon in lons),
        dtype=np.uint8,
        count=ROWS * COLS,
    ).reshape((ROWS, COLS))

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(np.where(matrix == 1, 255, 0).astype(np.uint8), mode="L")
    image.save(out / "candidate.png")
    enlarged = image.resize((COLS * 8, ROWS * 8), Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix)) <= {0, 1}
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71 and all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert image.size == (231, 71) and set(image.getdata()) <= {0, 255}
    assert enlarged.size == (1848, 568)
    assert enlarged.resize(image.size, Image.Resampling.NEAREST).tobytes() == image.tobytes()


if __name__ == "__main__":
    main()
