def inside_poly(x, y, p):
    """Boundary-inclusive ray casting, adequate for the hand-drawn polygons."""
    hit = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]; xj, yj = p[j]
        dx, dy = xj-xi, yj-yi
        cross = (x-xi)*dy - (y-yi)*dx
        if abs(cross) < 1e-10 and min(xi,xj)-1e-10 <= x <= max(xi,xj)+1e-10 \
                and min(yi,yj)-1e-10 <= y <= max(yi,yj)+1e-10:
            return True
        if (yi > y) != (yj > y):
            cut = xi + (y-yi)*(xj-xi)/(yj-yi)
            if x < cut:
                hit = not hit
        j = i
    return hit

def paint_poly(a, p, value=1):
    xmin, xmax = min(q[0] for q in p), max(q[0] for q in p)
    ymin, ymax = min(q[1] for q in p), max(q[1] for q in p)
    for r, y in enumerate(LATS):
        if ymin-1e-9 <= y <= ymax+1e-9:
            for c, x in enumerate(LONS):
                if xmin-1e-9 <= x <= xmax+1e-9 and inside_poly(x, y, p):
                    a[r,c] = value

def paint_ellipse(a, cx, cy, rx, ry, value=1):
    for r,y in enumerate(LATS):
        for c,x in enumerate(LONS):
            if ((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1.0+1e-10:
                a[r,c] = value

