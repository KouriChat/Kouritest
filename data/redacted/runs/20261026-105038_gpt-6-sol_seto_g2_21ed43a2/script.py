def on_segment(x, y, a, b, eps=1e-10):
    cross = (x - a[0]) * (b[1] - a[1]) - (y - a[1]) * (b[0] - a[0])
    if abs(cross) > eps:
        return False
    return (
        min(a[0], b[0]) - eps <= x <= max(a[0], b[0]) + eps
        and min(a[1], b[1]) - eps <= y <= max(a[1], b[1]) + eps
    )


def inside_polygon(x, y, poly):
    inside = False
    n = len(poly)
    for i in range(n):
        a, b = poly[i], poly[(i + 1) % n]
        if on_segment(x, y, a, b):
            return True
        if (a[1] > y) != (b[1] > y):
            crossing_x = a[0] + (y - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
            if x < crossing_x:
                inside = not inside
    return inside


def main():
    rows, cols = 64, 253
    step = 2.0 / 63.0
    matrix = np.zeros((rows, cols), dtype=np.uint8)

    bounded = []
    for poly in LAND:
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        bounded.append((poly, min(xs), max(xs), min(ys), max(ys)))

    for r in range(rows):
        lat = 35.0 - r * step
        for c in range(cols):
            lon = 129.0 + c * step
            for poly, min_x, max_x, min_y, max_y in bounded:
                if min_x <= lon <= max_x and min_y <= lat <= max_y:
                    if inside_polygon(lon, lat, poly):
                        matrix[r, c] = 1
                        break

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        for row in matrix:
            f.write(",".join(str(int(v)) for v in row) + "\n")

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out / "candidate.png")
    image.resize((cols * 8, rows * 8), resample=Image.Resampling.NEAREST).save(
        out / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
