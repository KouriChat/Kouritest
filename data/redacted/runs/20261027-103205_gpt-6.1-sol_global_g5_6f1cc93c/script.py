LONS = np.arange(-179, 180, 2, dtype=np.float64)
LATS = np.arange(89, -90, -2, dtype=np.float64)
X, Y = np.meshgrid(LONS, LATS)
LAND = np.zeros((90, 180), dtype=bool)
POLYGONS = []


def add(name, points):
    """Record a hand-authored polygon; points are (longitude, latitude)."""
    if name != 'Eurasia':
        POLYGONS.append((name, points))


def contains(points):
    """Vectorized ray casting, with boundary points included and seam wrapping."""
    p = np.asarray(points, dtype=np.float64)
    center = (p[:, 0].min() + p[:, 0].max()) / 2
    x = (X - center + 180) % 360 - 180 + center
    inside = np.zeros(X.shape, dtype=bool)
    edge = np.zeros(X.shape, dtype=bool)
    ax, ay = p[-1]
    for bx, by in p:
        if by != ay:
            crossing = ((ay > Y) != (by > Y))
            intercept = ax + (Y - ay) * (bx - ax) / (by - ay)
            inside ^= crossing & (x < intercept)
        cross = (x - ax) * (by - ay) - (Y - ay) * (bx - ax)
        edge |= ((np.abs(cross) < 1e-9)
                 & (x >= min(ax, bx) - 1e-9) & (x <= max(ax, bx) + 1e-9)
                 & (Y >= min(ay, by) - 1e-9) & (Y <= max(ay, by) + 1e-9))
        ax, ay = bx, by
    return inside | edge


