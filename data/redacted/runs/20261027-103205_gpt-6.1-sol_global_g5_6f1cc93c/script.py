"""Generate an approximate world land mask from hand-written, remembered outlines.

No map, geographic database, reference answer, network, or image model is used.
The classifications are polygon-rule computations, NOT independent LLM judgments.
Inland lakes remain land; connected seas and floating Antarctic shelves are water.
Dependencies: Python 3, numpy, Pillow. Run from any working directory.
"""
