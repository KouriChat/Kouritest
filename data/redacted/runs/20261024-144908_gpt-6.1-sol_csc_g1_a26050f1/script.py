# A reef rim is land; its open seawater lagoon is not filled as land.
# These, like every coastline above, are uncertain hand-written estimates.
REEFS = [
    ("Pratas",
     points("116.68,20.7 116.72,20.77 116.85,20.79 116.96,20.71 116.94,20.62 116.82,20.59 116.72,20.62"),
     points("116.74,20.7 116.78,20.75 116.86,20.75 116.92,20.7 116.9,20.65 116.8,20.63 116.76,20.66")),
    ("Scarborough",
     points("117.74,15.1 117.76,15.2 117.84,15.22 117.86,15.14 117.8,15.07"),
     points("117.76,15.12 117.79,15.18 117.82,15.19 117.84,15.14 117.8,15.1")),
]
def contains_polygon(poly, xx, yy):
    """Ray crossing at the coordinate itself; coastline points count as land."""
    inside = np.zeros(xx.shape, dtype=bool)
    boundary = np.zeros(xx.shape, dtype=bool)
    x0, y0 = poly[-1]
    eps = 1e-10
    for x1, y1 in poly:
        dx, dy = x1 - x0, y1 - y0
        if dy != 0:
            crosses = (yy > y0) != (yy > y1)
            x_crossing = x0 + (yy - y0) * dx / dy
            inside ^= crosses & (xx < x_crossing)
        on_line = np.abs((xx - x0) * dy - (yy - y0) * dx) <= eps
        on_segment = (
            (xx >= min(x0, x1) - eps)
            & (xx <= max(x0, x1) + eps)
            & (yy >= min(y0, y1) - eps)
            & (yy <= max(y0, y1) + eps)
        )
        boundary |= on_line & on_segment
        x0, y0 = x1, y1
    return inside | boundary


def make_matrix():
    # Integer arithmetic defines the requested decimal-degree sampling lattice.
    longitudes = (990 + 2 * np.arange(141)) / 10.0
    latitudes = (230 - 2 * np.arange(111)) / 10.0
    assert longitudes[0] == 99 and longitudes[-1] == 127
    assert latitudes[0] == 23 and latitudes[-1] == 1
    xx, yy = np.meshgrid(longitudes, latitudes)
    land = np.zeros(xx.shape, dtype=bool)
    for name, poly in POLYGONS:
        land |= contains_polygon(poly, xx, yy)
    for name, outer, lagoon in REEFS:
        land |= contains_polygon(outer, xx, yy) & ~contains_polygon(lagoon, xx, yy)
    # No inland-lake holes are cut: inland lakes belong to class 1.
    matrix = land.astype(np.uint8)
    assert matrix.shape == (111, 141) and matrix.size == 15651
    assert set(np.unique(matrix).tolist()) == {0, 1}
    return matrix


def write_outputs(matrix, out):
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", encoding="ascii", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    raw = Image.fromarray(matrix * np.uint8(255))
    raw.save(out / "candidate.png", format="PNG")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    big = raw.resize((1128, 888), resample=nearest)
    big.save(out / "candidate_8x.png", format="PNG")
def validate_outputs(matrix, out):
    with (out / "candidate.csv").open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 111, "CSV row count"
    assert all(len(row) == 141 for row in rows), "CSV column count"
    assert sum(map(len, rows)) == 15651, "CSV sample count"
    assert all(value in {"0", "1"} for row in rows for value in row)
    loaded = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(loaded, matrix), "CSV must preserve the matrix"
    with Image.open(out / "candidate.png") as raw:
        assert raw.size == (141, 111) and raw.mode == "L"
        raw_pixels = np.asarray(raw).copy()
    with Image.open(out / "candidate_8x.png") as big:
        assert big.size == (1128, 888) and big.mode == "L"
        big_pixels = np.asarray(big).copy()
    assert set(np.unique(raw_pixels).tolist()) == {0, 255}
    assert set(np.unique(big_pixels).tolist()) == {0, 255}
    assert np.array_equal(raw_pixels, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(big_pixels, expected), "Must be exact nearest-neighbor"
    assert np.array_equal(big_pixels[::8, ::8], raw_pixels)
    return {
        "shape": list(matrix.shape),
        "valid_values": int(matrix.size),
        "land": int(matrix.sum()),
        "water": int(matrix.size - matrix.sum()),
        "raw_png": [141, 111],
        "enlarged_png": [1128, 888],
        "binary_images": True,
        "exact_nearest_neighbor_8x": True,
    }


def main():
    output_directory = Path.cwd() / "outputs"
    matrix = make_matrix()
    write_outputs(matrix, output_directory)
    print(validate_outputs(matrix, output_directory))


if __name__ == "__main__":
    main()
