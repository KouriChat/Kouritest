def is_land(lon, lat):
    # 大陆先按外轮廓判断，再减去与海洋连通的入口。
    mainland = in_polygon(lon, lat, MAINLAND)

    if mainland:
        for water_polygon in MAINLAND_WATER_CUTS:
            if in_polygon(lon, lat, water_polygon):
                mainland = False
                break

    if mainland:
        return True

    # 大岛规则。
    for polygon in ISLAND_POLYGONS:
        if in_polygon(lon, lat, polygon):
            return True

    # 小岛、礁石和礁盘规则。
    for cx, cy, rx, ry, angle in SMALL_ISLANDS:
        if in_rotated_ellipse(lon, lat, cx, cy, rx, ry, angle):
            return True

    return False


def validate_csv(path):
    with path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))

    assert len(rows) == 127, f"CSV 行数错误：{len(rows)}"

    count = 0
    for row_number, row in enumerate(rows, start=1):
        assert len(row) == 127, (
            f"CSV 第 {row_number} 行列数错误：{len(row)}"
        )
        assert all(value in {"0", "1"} for value in row), (
            f"CSV 第 {row_number} 行含有非 0/1 值"
        )
        count += len(row)

    assert count == 16129


def validate_images(original_path, enlarged_path, matrix):
    with Image.open(original_path) as image:
        original = np.asarray(image.convert("L"))
        assert image.size == (127, 127)
        assert original.shape == (127, 127)
        assert set(np.unique(original)).issubset({0, 255})
        assert np.array_equal(original, matrix * 255)

    with Image.open(enlarged_path) as image:
        enlarged = np.asarray(image.convert("L"))
        assert image.size == (1016, 1016)
        assert enlarged.shape == (1016, 1016)
        assert set(np.unique(enlarged)).issubset({0, 255})

    expected = np.repeat(
        np.repeat(matrix * 255, 8, axis=0),
        8,
        axis=1,
    )
    assert np.array_equal(enlarged, expected)

    # 逐块确认每个原像素恰好扩展成 8×8 同色块。
    blocks = enlarged.reshape(127, 8, 127, 8)
    assert np.all(blocks == blocks[:, :1, :, :1])


def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "candidate.csv"
    original_path = output_dir / "candidate.png"
    enlarged_path = output_dir / "candidate_8x.png"

    # 纬度自北向南；经度自西向东。
    latitudes = np.linspace(55.0, 53.0, 127)
    longitudes = np.linspace(-131.0, -129.0, 127)

    matrix = np.zeros((127, 127), dtype=np.uint8)

    for row, lat in enumerate(latitudes):
        for column, lon in enumerate(longitudes):
            matrix[row, column] = 1 if is_land(
                float(lon), float(lat)
            ) else 0

    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert set(np.unique(matrix)).issubset({0, 1})

    # 无表头 CSV。
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 白色为陆地，黑色为水域。
    original_pixels = matrix * np.uint8(255)
    Image.fromarray(original_pixels, mode="L").save(original_path)

    # 直接按数组重复实现最近邻 8 倍放大，不进行插值或平滑。
    enlarged_pixels = np.repeat(
        np.repeat(original_pixels, 8, axis=0),
        8,
        axis=1,
    )
    Image.fromarray(enlarged_pixels, mode="L").save(enlarged_path)

    validate_csv(csv_path)
    validate_images(original_path, enlarged_path, matrix)

    print("Generated and validated:")
    print(f"  {csv_path}")
    print(f"  {original_path}")
    print(f"  {enlarged_path}")
    print(f"  matrix: {matrix.shape[0]} x {matrix.shape[1]}")
    print(f"  values: {matrix.size}")
    print(f"  land samples: {int(matrix.sum())}")
