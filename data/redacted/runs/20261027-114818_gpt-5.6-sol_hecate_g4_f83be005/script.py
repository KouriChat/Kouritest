# ============================================================
# 基本几何判断
# 坐标顺序统一为 (经度, 纬度)。
# 多边形边界上的点按陆地处理。
# ============================================================

EPS = 1.0e-10


def point_on_segment(x, y, x1, y1, x2, y2):
    dx = x2 - x1
    dy = y2 - y1
    cross = (x - x1) * dy - (y - y1) * dx

    if abs(cross) > EPS * max(1.0, abs(dx), abs(dy)):
        return False

    return (
        min(x1, x2) - EPS <= x <= max(x1, x2) + EPS
        and min(y1, y2) - EPS <= y <= max(y1, y2) + EPS
    )


def in_polygon(x, y, polygon):
    inside = False
    n = len(polygon)

    for i in range(n):
        x1, y1 = polygon[i]
        x2, y2 = polygon[(i + 1) % n]

        if point_on_segment(x, y, x1, y1, x2, y2):
            return True

        if (y1 > y) != (y2 > y):
            crossing_x = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < crossing_x:
                inside = not inside

    return inside


def in_rotated_ellipse(x, y, cx, cy, rx, ry, angle_deg=0.0):
    angle = math.radians(angle_deg)
    ca = math.cos(angle)
    sa = math.sin(angle)

    dx = x - cx
    dy = y - cy

    # 把采样点反向旋转到椭圆局部坐标。
    u = ca * dx + sa * dy
    v = -sa * dx + ca * dy

    return (u / rx) ** 2 + (v / ry) ** 2 <= 1.0 + EPS


