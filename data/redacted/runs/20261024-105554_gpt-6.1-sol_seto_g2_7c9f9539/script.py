ROWS, COLS = 64, 253
lon = 129.0 + np.arange(COLS, dtype=np.float64) * (2.0 / 63.0)
lat = 35.0 - np.arange(ROWS, dtype=np.float64) * (2.0 / 63.0)
X, Y = np.meshgrid(lon, lat)
land = np.zeros((ROWS, COLS), dtype=bool)
features = []


def polygon_mask(vertices):
    inside = np.zeros_like(land)
    for a, b in zip(vertices, vertices[1:] + vertices[:1]):
        x1, y1 = a
        x2, y2 = b
        if y1 == y2:
            continue
        crossing = ((y1 > Y) != (y2 > Y))
        edge_x = x1 + (Y - y1) * (x2 - x1) / (y2 - y1)
        inside ^= crossing & (X < edge_x)
    return inside


def shape(name, text, water=False):
    values = [float(v) for v in text.replace(",", " ").split()]
    assert len(values) >= 6 and len(values) % 2 == 0
    vertices = list(zip(values[0::2], values[1::2]))
    mask = polygon_mask(vertices)
    if water:
        land[mask] = False
    else:
        land[mask] = True
    features.append((name, vertices, water))


