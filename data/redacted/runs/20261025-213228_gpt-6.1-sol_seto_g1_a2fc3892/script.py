LAND = []
WATER = []

def polygon(name, text, water=False):
    points = [tuple(map(float, p.split(","))) for p in text.split()]
    assert len(points) >= 3, name
    (WATER if water else LAND).append((name, points))

def island(name, x, y, rx, ry, angle=0):
    # Small islands are approximated by explicitly parameterized ellipses.
    a = math.radians(angle)
    points = []
    for t in np.linspace(0, 2 * math.pi, 25)[:-1]:
        u, v = rx * math.cos(t), ry * math.sin(t)
        points.append((x + u*math.cos(a)-v*math.sin(a),
                       y + u*math.sin(a)+v*math.cos(a)))
    LAND.append((name, points))

