def contains(points):
    """Ray crossing, evaluated at the sample point (not cell coverage)."""
    result = np.zeros(X.shape, dtype=bool)
    ax, ay = points[-1]
    for bx, by in points:
        if by != ay:
            crossing = ((ay > Y) != (by > Y))
            cut_x = ax + (Y - ay) * ((bx - ax) / (by - ay))
            result ^= crossing & (X < cut_x)
        ax, ay = bx, by
    return result

