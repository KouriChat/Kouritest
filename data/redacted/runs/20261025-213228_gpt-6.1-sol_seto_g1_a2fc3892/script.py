    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(output / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = original.resize((COLS * 8, ROWS * 8), resample=nearest)
    enlarged.save(output / "candidate_8x.png")

    # Verify actual files, dimensions, values and every replicated pixel block.
    with csv_path.open("r", newline="", encoding="ascii") as f:
        records = list(csv.reader(f))
    assert len(records) == ROWS
    assert all(len(row) == COLS for row in records)
    assert all(value in ("0", "1") for row in records for value in row)
    restored = np.array(records, dtype=np.uint8)
    assert restored.shape == (64, 253) and restored.size == 16192
    assert np.array_equal(restored, matrix)
    with Image.open(output / "candidate.png") as image:
        assert image.size == (253, 64)
        raw = np.asarray(image)
        assert set(np.unique(raw).tolist()) <= {0, 255}
        assert np.array_equal(raw, pixels)
    with Image.open(output / "candidate_8x.png") as image:
        assert image.size == (2024, 512)
        big = np.asarray(image)
        assert set(np.unique(big).tolist()) <= {0, 255}
        expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
        assert np.array_equal(big, expected), "Not exact nearest-neighbor 8x"
    print("Validated: 64x253 = 16192 binary samples; PNGs 253x64 and 2024x512.")

