W, H = 231, 71
LON, LAT = np.meshgrid(-9.0 + np.arange(W) * .2, 45.0 - np.arange(H) * .2)
land = np.ones((H, W), dtype=bool)


def paint(vertices, is_land):
    """Even-odd point-in-polygon, evaluated directly at the sampled points."""
    global land
    inside = np.zeros((H, W), dtype=bool)
    for (ax, ay), (bx, by) in zip(vertices, vertices[1:] + vertices[:1]):
        if ay == by:
            continue
        crossed = ((ay > LAT) != (by > LAT)) & (LON < (bx-ax)*(LAT-ay)/(by-ay) + ax)
        inside ^= crossed
    land[inside] = is_land


