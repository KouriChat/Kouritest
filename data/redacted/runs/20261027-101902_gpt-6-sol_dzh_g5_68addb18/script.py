def export():
    directory = Path.cwd() / 'outputs'
    directory.mkdir(parents=True, exist_ok=True)
    values = land.astype(np.uint8)
    assert values.shape == (71, 231) and values.size == 16401
    with (directory / 'candidate.csv').open('w', newline='', encoding='ascii') as file:
        writer = csv.writer(file)
        writer.writerows(values.tolist())
    image = Image.fromarray(values * 255, mode='L')
    image.save(directory / 'candidate.png')
    enlarged = image.resize((1848, 568), Image.Resampling.NEAREST)
    enlarged.save(directory / 'candidate_8x.png')

    with (directory / 'candidate.csv').open(newline='', encoding='ascii') as file:
        rows = list(csv.reader(file))
    assert len(rows) == H and all(len(row) == W for row in rows)
    assert all(v in ('0', '1') for row in rows for v in row)
    assert image.size == (231, 71) and enlarged.size == (1848, 568)
    original = np.asarray(Image.open(directory / 'candidate.png'))
    zoom = np.asarray(Image.open(directory / 'candidate_8x.png'))
    assert set(np.unique(original)).issubset({0, 255})
    assert set(np.unique(zoom)).issubset({0, 255})
    assert np.array_equal(zoom, np.repeat(np.repeat(original, 8, 0), 8, 1))
    print('Wrote outputs/candidate.csv, outputs/candidate.png, '
          'outputs/candidate_8x.png: 71 x 231 points, nearest-neighbor 8x.')


if __name__ == '__main__':
    export()
