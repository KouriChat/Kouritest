def oval(cx, cy, rx, ry, deg=0):
    """Add a small memory-placed island via rotated point-ellipse rule."""
    a = np.deg2rad(deg)
    dx, dy = LON-cx, LAT-cy
    u, v = dx*np.cos(a)+dy*np.sin(a), -dx*np.sin(a)+dy*np.cos(a)
    land[(u/rx)**2+(v/ry)**2 <= 1] = True


