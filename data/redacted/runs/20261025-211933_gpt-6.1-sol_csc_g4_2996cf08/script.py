def inside_polygon(x, y, vertices):
    """Vectorized even/odd ray casting, evaluated at each point itself."""
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            cross_x = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= ((y0 > y) != (y1 > y)) & (x < cross_x)
        x0, y0 = x1, y1
    return inside

def generate():
    # Integer arithmetic first avoids accumulated coordinate-step error.
    latitudes = (115 - np.arange(111)) / 5
    longitudes = (495 + np.arange(141)) / 5
    x, y = np.meshgrid(longitudes, latitudes)
    result = np.zeros((111, 141), dtype=np.uint8)
    for _, vertices in POLYGONS:
        result[inside_polygon(x, y, vertices)] = 1
    return result
