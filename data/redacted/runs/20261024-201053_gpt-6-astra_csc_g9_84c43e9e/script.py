def polygon(name, vertices):
    """Ray casting, including boundary points, using remembered vertices."""
    vertices = np.asarray(vertices, dtype=float)
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        cross = (X - x0) * dy - (Y - y0) * dx
        on = (np.abs(cross) < 1e-10)
        on &= (X >= min(x0, x1) - 1e-10)
        on &= (X <= max(x0, x1) + 1e-10)
        on &= (Y >= min(y0, y1) - 1e-10)
        on &= (Y <= max(y0, y1) + 1e-10)
        boundary |= on
        if dy != 0:
            hit = ((y0 > Y) != (y1 > Y))
            hit &= X < x0 + (Y - y0) * dx / dy
            inside ^= hit
        x0, y0 = x1, y1
    land[:] |= inside | boundary
    rules.append(name)


def oval(name, lon, lat, rx, ry, angle=0.0):
    """Small island approximation; radii are angular, not pixel sizes."""
    a = np.deg2rad(angle)
    u = (X - lon) * np.cos(a) + (Y - lat) * np.sin(a)
    v = -(X - lon) * np.sin(a) + (Y - lat) * np.cos(a)
    land[:] |= (u / rx) ** 2 + (v / ry) ** 2 <= 1.0
    rules.append(name)

