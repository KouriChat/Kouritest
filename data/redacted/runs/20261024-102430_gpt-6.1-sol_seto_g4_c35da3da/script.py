X, Y = np.meshgrid(LONGITUDES, LATITUDES)
LAND_POLYGONS = []
WATER_POLYGONS = []


def coordinates(text):
    return [tuple(map(float, item.split(","))) for item in text.split()]


def land(text):
    LAND_POLYGONS.append(coordinates(text))


def water(text):
    WATER_POLYGONS.append(coordinates(text))


def ellipse(lon, lat, rx, ry, angle=0):
    """Hand-estimated small island, not a queried geographic primitive."""
    t = np.arange(32) * (2 * np.pi / 32)
    a = np.deg2rad(angle)
    u, v = rx * np.cos(t), ry * np.sin(t)
    LAND_POLYGONS.append(list(zip(lon + u*np.cos(a) - v*np.sin(a),
                                  lat + u*np.sin(a) + v*np.cos(a))))


def inside(vertices):
    result = np.zeros(X.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crossing = ((y0 > Y) != (y1 > Y))
            cut = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (X < cut)
        x0, y0 = x1, y1
    return result


