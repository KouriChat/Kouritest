def contains(lon, lat, polygon):
    """Return whether a point lies inside a polygon using ray casting."""
    inside = False
    x1, y1 = polygon[-1]
    for x2, y2 in polygon:
        if (y1 > lat) != (y2 > lat):
            crossing_lon = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < crossing_lon:
                inside = not inside
        x1, y1 = x2, y2
    return inside


def main():
    lats = 45.0 - 0.2 * np.arange(71)
    lons = -9.0 + 0.2 * np.arange(231)
    matrix = np.zeros((71, 231), dtype=np.uint8)

    for row, lat in enumerate(lats):
        for col, lon in enumerate(lons):
            matrix[row, col] = any(
                contains(float(lon), float(lat), polygon)
                for polygon in LAND
            )

    output = Path("outputs")
    output.mkdir(parents=True, exist_ok=True)
    np.savetxt(output / "candidate.csv", matrix, fmt="%d", delimiter=",")

    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(output / "candidate.png")
    image.resize((1848, 568), Image.Resampling.NEAREST).save(
        output / "candidate_8x.png"
    )

    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix)).issubset({0, 1})
    assert image.size == (231, 71)
    assert Image.open(output / "candidate_8x.png").size == (1848, 568)


if __name__ == "__main__":
    main()
