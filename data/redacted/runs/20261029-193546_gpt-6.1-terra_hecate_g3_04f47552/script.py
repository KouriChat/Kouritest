def inside(x, y, polygon):
    result = False
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        if (y0 > y) != (y1 > y):
            if x < x0 + (x1 - x0) * (y - y0) / (y1 - y0):
                result = not result
        x0, y0 = x1, y1
    return result


def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    matrix = [[int(any(inside(-131 + 2 * col / 126, 55 - 2 * row / 126, p)
                       for p in LAND)) for col in range(127)] for row in range(127)]
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f).writerows(matrix)
    image = Image.new('L', (127, 127))
    image.putdata([255 * value for row in matrix for value in row])
    image.save(out / 'candidate.png')
    image.resize((1016, 1016), Image.Resampling.NEAREST).save(out / 'candidate_8x.png')
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127 and all(len(row) == 127 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    original = Image.open(out / 'candidate.png')
    enlarged = Image.open(out / 'candidate_8x.png')
    assert original.size == (127, 127) and enlarged.size == (1016, 1016)
    assert set(original.getdata()) <= {0, 255} and set(enlarged.getdata()) <= {0, 255}
    assert enlarged.tobytes() == original.resize((1016, 1016), Image.Resampling.NEAREST).tobytes()
    print('Validated 127 x 127 = 16129 points and both PNGs.')


if __name__ == '__main__':
    main()
