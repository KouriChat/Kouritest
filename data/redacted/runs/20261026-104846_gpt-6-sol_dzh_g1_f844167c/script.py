def point_in_polygon(lon, lat, polygon):
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            cross_x = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < cross_x:
                inside = not inside
        j = i
    return inside

def is_land(lon, lat):
    if any(point_in_polygon(lon, lat, polygon) for polygon in POLYGONS):
        return True
    for cx, cy, rx, ry in ISLANDS:
        if ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2 <= 1.0:
            return True
    return False

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    matrix = np.zeros((71, 231), dtype=np.uint8)
    for row, lat in enumerate(LATITUDES):
        for col, lon in enumerate(LONGITUDES):
            matrix[row, col] = int(is_land(float(lon), float(lat)))
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert np.isin(matrix, (0, 1)).all()
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(out / "candidate.png")
    enlarged = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")
    assert enlarged.size == (1848, 568)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    with (out / "candidate.csv").open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 71 and all(
        len(r) == 231 and set(r) <= {"0", "1"} for r in rows
    )

if __name__ == "__main__":
    main()
