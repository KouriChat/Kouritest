def polygon_mask(lons, lats, vertices):
    """Even/odd ray casting, with points on a rule boundary treated as land."""
    lo = vertices.min(axis=0)
    hi = vertices.max(axis=0)
    center = (lo[0] + hi[0]) / 2
    x = lons + 360 * np.round((center - lons) / 360)
    selected = ((x >= lo[0]) & (x <= hi[0]) &
                (lats >= lo[1]) & (lats <= hi[1]))
    result = np.zeros(lons.shape, dtype=bool)
    if not selected.any():
        return result
    px, py = x[selected], lats[selected]
    inside = np.zeros(px.shape, dtype=bool)
    boundary = np.zeros(px.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        cross = (px - ax) * (by - ay) - (py - ay) * (bx - ax)
        boundary |= ((np.abs(cross) < 1e-10) &
                     (px >= min(ax, bx) - 1e-10) &
                     (px <= max(ax, bx) + 1e-10) &
                     (py >= min(ay, by) - 1e-10) &
                     (py <= max(ay, by) + 1e-10))
        if by != ay:
            cut = ax + (py - ay) * (bx - ax) / (by - ay)
            inside ^= ((ay > py) != (by > py)) & (px < cut)
        ax, ay = bx, by
    result[selected] = inside | boundary
    return result

def main():
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    latitudes = np.arange(89, -90, -2, dtype=float)
    longitudes = np.arange(-179, 180, 2, dtype=float)
    lons, lats = np.meshgrid(longitudes, latitudes)
    assert lons.shape == lats.shape == (90, 180)
    assert (lats[0, 0], lons[0, 0]) == (89, -179)
    assert (lats[-1, -1], lons[-1, -1]) == (-89, 179)
    mask = np.zeros((90, 180), dtype=bool)
    for name, vertices in POLYGONS:
        mask |= polygon_mask(lons, lats, vertices)
    matrix = mask.astype(np.uint8)
    assert matrix.shape == (90, 180) and matrix.size == 16200
    assert set(np.unique(matrix).tolist()) == {0, 1}

    csv_path = output / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as stream:
        csv.writer(stream, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    image.save(output / "candidate.png")
    nearest = Image.Resampling.NEAREST
    image.resize((1440, 720), resample=nearest).save(
        output / "candidate_8x.png")

    # Reopen our own results, not geographic reference material.
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(map(len, rows)) == 16200
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(output / "candidate.png") as original:
        assert original.size == (180, 90) and original.mode == "L"
        small = np.asarray(original).copy()
    with Image.open(output / "candidate_8x.png") as enlarged:
        assert enlarged.size == (1440, 720) and enlarged.mode == "L"
        big = np.asarray(enlarged).copy()
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(small, pixels)
    assert np.array_equal(big, small.repeat(8, axis=0).repeat(8, axis=1))
    print("Validated: 90x180 CSV, 16200 binary judgments; "
          "180x90 black/white PNG; exact nearest-neighbor 1440x720 PNG.")
    print(f"Land: {int(matrix.sum())}; water: {int(matrix.size-matrix.sum())}.")
    print("Method: hand-written knowledge-only polygons; numpy ray casting. "
          "Dependencies: numpy, Pillow; no downloads or external map inputs.")

