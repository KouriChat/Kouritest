def contains(vertices, w, n):
    """Vectorized even-odd point-in-polygon at WGS84 sample *points*."""
    inside = np.zeros(w.shape, dtype=bool)
    for (x1, y1), (x2, y2) in zip(vertices, vertices[1:] + vertices[:1]):
        if y1 == y2:
            continue
        cross = (y1 > n) != (y2 > n)
        xcross = x1 + (n - y1) * (x2 - x1) / (y2 - y1)
        inside ^= cross & (w < xcross)
    return inside

def generate():
    # Array columns descend in degrees WEST: 105 W -> 81 W.
    west, north = np.meshgrid(105 - np.arange(241) / 10,
                              79 - np.arange(61) / 10)
    land = np.zeros((61, 241), dtype=bool)
    for shape in LAND:
        land |= contains(shape, west, north)
    for shape in SEA:
        land &= ~contains(shape, west, north)
    values = land.astype(np.uint8)

    output = Path('outputs')
    output.mkdir(parents=True, exist_ok=True)
    with (output / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f).writerows(values.tolist())
    # No smoothing: one source pixel per sample, and exact integer expansion.
    image = Image.fromarray(values * 255, 'L').convert('RGB')
    image.save(output / 'candidate.png')
    enlarged = image.resize((1928, 488), Image.Resampling.NEAREST)
    enlarged.save(output / 'candidate_8x.png')

    with (output / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61 and all(len(r) == 241 for r in rows)
    assert all(cell in ('0', '1') for row in rows for cell in row)
    assert image.size == (241, 61) and enlarged.size == (1928, 488)
    assert set(image.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert set(enlarged.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    assert np.array_equal(np.asarray(enlarged)[::8, ::8], np.asarray(image))
    assert np.array_equal(np.asarray(enlarged),
                          np.repeat(np.repeat(np.asarray(image), 8, axis=0),
                                    8, axis=1))
    print(f'Validated: {values.shape}, {values.size} points; '
          f'{int(values.sum())} land, {int((1-values).sum())} water.')

if __name__ == '__main__':
    generate()
