def oval(w, n, rx, ry, bearing=0, count=36):
    """Draw an approximate islet, with deterministic non-circular shoreline."""
    a = math.radians(bearing)
    shape = []
    for j in range(count):
        t = j * 2 * math.pi / count
        r = 1 + .065 * math.sin(5*t + w) + .043 * math.sin(9*t + n)
        u, v = rx * r * math.cos(t), ry * r * math.sin(t)
        shape.append((w + u*math.cos(a)-v*math.sin(a),
                      n + u*math.sin(a)+v*math.cos(a)))
    island(*shape)

