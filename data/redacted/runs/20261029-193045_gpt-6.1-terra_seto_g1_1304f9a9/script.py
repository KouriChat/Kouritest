# The smaller islands are deliberately represented by compact hand-written
# ellipses.  The scale factors below are in degrees, not pixels.
import math

def island(cx, cy, rx, ry, n=12, phase=0.0):
    return [(cx + rx * math.cos(phase + 2 * math.pi * k / n),
             cy + ry * math.sin(phase + 2 * math.pi * k / n))
            for k in range(n)]

