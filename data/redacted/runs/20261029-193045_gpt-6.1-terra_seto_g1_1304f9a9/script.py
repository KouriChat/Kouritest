# Hand-estimated longitude, latitude outlines; no external geographic data.
def inside(x, y, polygon):
    result = False
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        if (y1 > y) != (y0 > y):
            if x < (x0 - x1) * (y - y1) / (y0 - y1) + x1:
                result = not result
        x0, y0 = x1, y1
    return result

