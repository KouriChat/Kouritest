LON0, LON1 = 129.0, 137.0
LAT0, LAT1 = 35.0, 33.0
WIDTH, HEIGHT = 253, 64

def land(lon, lat):
    return any(inside(lon, lat, p) for p in polygons)

matrix = []
for row in range(HEIGHT):
    lat = LAT0 - (LAT0 - LAT1) * row / (HEIGHT - 1)
    values = []
    for col in range(WIDTH):
        lon = LON0 + (LON1 - LON0) * col / (WIDTH - 1)
        values.append(1 if land(lon, lat) else 0)
    matrix.append(values)

