LON, LAT = np.meshgrid(129 + np.arange(253) * (2 / 63),
                       35 - np.arange(64) * (2 / 63))
land = np.zeros((64, 253), dtype=bool)

def polygon(vertices):
    """Ray casting at the sample coordinates, not cell-area classification."""
    inside = np.zeros(LON.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y0 != y1:
            crossing = ((y0 > LAT) != (y1 > LAT))
            edge_x = x0 + (LAT - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (LON < edge_x)
        x0, y0 = x1, y1
    return inside

def add(vertices):
    land[:] |= polygon(vertices)

def water(vertices):
    land[:] &= ~polygon(vertices)

def island(cx, cy, rx, ry, angle=0, n=16):
    """Hand-estimated elliptical outline for very small islands."""
    t = np.arange(n) * 2 * np.pi / n
    a = np.deg2rad(angle)
    x, y = rx * np.cos(t), ry * np.sin(t)
    add(list(zip(cx + x*np.cos(a) - y*np.sin(a),
                 cy + x*np.sin(a) + y*np.cos(a))))

