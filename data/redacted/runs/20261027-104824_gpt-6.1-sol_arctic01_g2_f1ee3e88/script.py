def polygon_mask(points, west, north):
    """Vectorized ray casting at points, not cell-area majority voting.

    Boundary ties use the ray-casting half-open convention. There is no
    external coastline, geospatial package, or per-point model invocation.
    """
    inside = np.zeros(west.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y1 != y0:
            crosses = (y0 > north) != (y1 > north)
            intersection = x0 + (north - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (west < intersection)
        x0, y0 = x1, y1
    return inside


def generate():
    # Integer tenths avoid cumulative floating-point stepping errors.
    north_values = (790 - np.arange(61, dtype=np.int64)) / 10.0
    west_values = (1050 - np.arange(241, dtype=np.int64)) / 10.0
    west, north = np.meshgrid(west_values, north_values)
    land = np.zeros((61, 241), dtype=bool)
    for name, points in LAND:
        land |= polygon_mask(points, west, north)
    for name, points in WATER:
        land &= ~polygon_mask(points, west, north)
    # The hand-written polygons represent land envelopes: inland lakes are
    # not removed. Floating sea ice is not represented as land.
    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert north_values[0] == 79 and north_values[-1] == 73
    assert west_values[0] == 105 and west_values[-1] == 81

    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f, lineterminator='\n').writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / 'candidate.png')
    nearest = getattr(Image, 'Resampling', Image).NEAREST
    enlarged = original.resize((1928, 488), resample=nearest)
    enlarged.save(out / 'candidate_8x.png')

    # Read back only our own generated artifacts; never input map data.
    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    assert sum(map(len, rows)) == 14701
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / 'candidate.png') as saved:
        assert saved.size == (241, 61) and saved.mode == 'L'
        raw = np.asarray(saved).copy()
    with Image.open(out / 'candidate_8x.png') as saved:
        assert saved.size == (1928, 488) and saved.mode == 'L'
        big = np.asarray(saved).copy()
    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, pixels)
    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected), 'Nearest-neighbor verification failed'
    print('Verified: 61 x 241 = 14,701 binary samples; CSV has no header or blanks.')
    print('Verified: black/white PNGs, 241 x 61 and exact 8x nearest-neighbor 1928 x 488.')
    print('Method: hand-written approximate polygons, vectorized point-in-polygon tests.')
    print('Land samples:', int(matrix.sum()), '; water samples:', int(matrix.size-matrix.sum()))
    return matrix


if __name__ == '__main__':
    generate()
