    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Integer construction avoids cumulative stepping errors.
    longitude = np.arange(-45, 186, dtype=np.int32) / 5.0
    latitude = np.arange(225, 154, -1, dtype=np.int32) / 5.0
    x, y = np.meshgrid(longitude, latitude)
