def inside_polygon(x, y, vertices):
    """Vectorized ray casting, with points on the boundary counted as land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        boundary |= (
            (np.abs(cross) <= 1e-10)
            & (x >= min(ax, bx) - 1e-10)
            & (x <= max(ax, bx) + 1e-10)
            & (y >= min(ay, by) - 1e-10)
            & (y <= max(ay, by) + 1e-10)
        )
        if by != ay:
            crosses = ((ay > y) != (by > y))
            intersection_x = ax + (y - ay) * (bx - ax) / (by - ay)
            inside ^= crosses & (x < intersection_x)
        ax, ay = bx, by
    return inside | boundary


