# Hand-drawn geographic model.  Every vertex below is an approximate
# (longitude, latitude) pair, written from memory rather than map data.
def poly(*pts):
    return list(pts)

def inside(x, y, p):
    hit = False
    x0, y0 = p[-1]
    for x1, y1 in p:
        if ((y1 > y) != (y0 > y)):
            xx = x1 + (y-y1) * (x0-x1) / (y0-y1)
            if x <= xx:
                hit = not hit
        x0, y0 = x1, y1
    return hit

