def classify(lon, lat):
    # Union of hand-drawn land polygons, followed by marine-inlet subtraction.
    if not any(inside(lon, lat, p) for p in land):
        return 0
    if any(inside(lon, lat, p) for p in water_cuts):
        return 0
    return 1

N = 127
lats = np.linspace(55.0, 53.0, N)
lons = np.linspace(-131.0, -129.0, N)
matrix = np.empty((N, N), dtype=np.uint8)
for r, lat in enumerate(lats):
    for c, lon in enumerate(lons):
        matrix[r, c] = classify(float(lon), float(lat))

out = Path("outputs")
out.mkdir(parents=True, exist_ok=True)
with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
    csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

raw = matrix * np.uint8(255)
