WIDTH, HEIGHT = 231, 71
XS = -9.0 + np.arange(WIDTH) * 0.2
YS = 45.0 - np.arange(HEIGHT) * 0.2
LAND = np.zeros((HEIGHT, WIDTH), dtype=bool)


def paint(vertices, is_land=True):
    """Vectorized even/odd point-in-polygon on the prescribed point grid."""
    polygon = np.asarray(vertices, dtype=float)
    x0, y0 = polygon[-1]
    mask = np.zeros_like(LAND)
    for x1, y1 in polygon:
        rows = (YS >= min(y0, y1)) & (YS < max(y0, y1))
        if y1 != y0 and rows.any():
            intercept = x0 + (YS[rows] - y0) * (x1 - x0) / (y1 - y0)
            mask[rows] ^= XS[None, :] < intercept[:, None]
        x0, y0 = x1, y1
    LAND[mask] = is_land


def ellipse(lon, lat, rx, ry, angle=0, is_land=True):
    """Small hand-specified islands: rotated angular ellipses."""
    radians = np.deg2rad(angle)
    u = (XS[None, :] - lon) * np.cos(radians) + (YS[:, None] - lat) * np.sin(radians)
    v = -(XS[None, :] - lon) * np.sin(radians) + (YS[:, None] - lat) * np.cos(radians)
    LAND[(u / rx) ** 2 + (v / ry) ** 2 <= 1] = is_land


