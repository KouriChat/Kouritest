def contains(vertices, x, y):
    """Vectorized ray crossing at the sample points, not raster area voting."""
    inside = np.zeros(x.shape, dtype=bool)
    x0,y0 = vertices[-1]
    for x1,y1 in vertices:
        if y1 != y0:
            cross = ((y0 > y) != (y1 > y))
            edge_x = x0 + (y-y0)*(x1-x0)/(y1-y0)
            inside ^= cross & (x < edge_x)
        x0,y0 = x1,y1
    return inside

def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    # Exact interval 2/63 degrees in both axes.
    lons = 129 + np.arange(253, dtype=float)*2/63
    lats = 35 - np.arange(64, dtype=float)*2/63
    x,y = np.meshgrid(lons,lats)
    land = np.zeros((64,253),dtype=bool)
    for vertices in POLYGONS:
        land |= contains(vertices,x,y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (64,253) and matrix.size == 16192
    assert np.isin(matrix,[0,1]).all()
    csv_path = out/"candidate.csv"
    with csv_path.open("w",newline="",encoding="ascii") as f:
        csv.writer(f,lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix*255)
    image.save(out/"candidate.png")
    enlarged = image.resize((2024,512),resample=Image.Resampling.NEAREST)
    enlarged.save(out/"candidate_8x.png")
    with csv_path.open(newline="",encoding="ascii") as f:
        rows=list(csv.reader(f))
    assert len(rows)==64
    assert all(len(row)==253 for row in rows)
    assert all(v in ("0","1") for row in rows for v in row)
    raw=np.asarray(Image.open(out/"candidate.png"))
    big=np.asarray(Image.open(out/"candidate_8x.png"))
    assert raw.shape==(64,253) and big.shape==(512,2024)
    assert set(np.unique(raw)).issubset({0,255})
    assert set(np.unique(big)).issubset({0,255})
    assert np.array_equal(big,np.repeat(np.repeat(raw,8,axis=0),8,axis=1))
    print("Validated: 64 x 253 = 16192 binary samples; PNG 253x64; nearest 8x 2024x512.")

if __name__ == "__main__":
    main()
