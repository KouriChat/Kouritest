def write_outputs(mask):
    if mask.shape != (71, 231):
        raise RuntimeError(f"unexpected matrix shape: {mask.shape}")
    if not np.isin(mask, (0, 1)).all():
        raise RuntimeError("matrix contains a value other than 0 or 1")

    with (OUT / "candidate.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerows(mask.tolist())

    # PIL mode 1 is avoided here so the source PNG is explicitly 8-bit
    # black/white and its pixel values can be checked without palette rules.
    source = Image.fromarray(np.where(mask == 1, 255, 0).astype(np.uint8),
                             mode="L")
    source.save(OUT / "candidate.png")
    enlarged = source.resize((231 * 8, 71 * 8), Image.Resampling.NEAREST)
    enlarged.save(OUT / "candidate_8x.png")

def main():
    mask = make_land()
    apply_seas(mask)
    add_islands(mask)
    write_outputs(mask)
    print(f"wrote {mask.shape[0]}x{mask.shape[1]} matrix "
          f"({mask.size} points)")

if __name__ == "__main__":
    main()
