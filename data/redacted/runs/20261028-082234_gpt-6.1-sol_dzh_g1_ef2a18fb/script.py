def inside(x, y, poly):
    """Even-odd point-in-polygon test for a hand-written coastline."""
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        cross = ((yi > y) != (yj > y))
        if cross and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit

def polygon(mask, poly):
    for r, lat in enumerate(lats):
        for c, lon in enumerate(lons):
            if inside(lon, lat, poly):
                mask[r, c] = 1

def add_polygons(mask, polygons):
    for poly in polygons:
        polygon(mask, poly)

