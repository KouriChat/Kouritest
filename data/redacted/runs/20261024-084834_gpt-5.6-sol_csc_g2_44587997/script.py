def is_land(x, y):
    land = any(in_poly(x, y, p) for p in polygons)
    if not land:
        land = any(ellipse(x, y, *e) for e in ellipses)
    if land and any(in_poly(x, y, h) for h in water_holes):
        land = False
    return land


def main():
    lons = [99.0 + .2*i for i in range(141)]
    lats = [23.0 - .2*i for i in range(111)]
    a = np.fromiter((int(is_land(x, y)) for y in lats for x in lons),
                    dtype=np.uint8, count=111*141).reshape(111, 141)

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out/"candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(a.tolist())

    raw = Image.fromarray(a*255, mode="L")
    raw.save(out/"candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    big = raw.resize((1128, 888), resample=nearest)
    big.save(out/"candidate_8x.png")

    # Required integrity checks, including an exact nearest-neighbour test.
    assert a.shape == (111, 141) and set(np.unique(a)) <= {0, 1}
    assert raw.size == (141, 111) and set(raw.getdata()) <= {0, 255}
    assert big.size == (1128, 888) and set(big.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(big), np.repeat(np.repeat(
        np.asarray(raw), 8, axis=0), 8, axis=1))
    with (out/"candidate.csv").open(encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111 and all(len(r) == 141 for r in rows)
    assert all(v in ("0", "1") for r in rows for v in r)
    print("validated: 111x141 CSV; 141x111 and 1128x888 binary PNGs")


if __name__ == "__main__":
    main()
