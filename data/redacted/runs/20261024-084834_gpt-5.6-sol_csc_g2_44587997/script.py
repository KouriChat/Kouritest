def in_poly(x, y, p):
    """Even/odd point-in-polygon test, with polygon boundary counted as land."""
    inside = False
    j = len(p) - 1
    for i, (xi, yi) in enumerate(p):
        xj, yj = p[j]
        dx, dy = xj - xi, yj - yi
        cross = (x-xi)*dy - (y-yi)*dx
        if abs(cross) < 1e-10 and min(xi,xj)-1e-10 <= x <= max(xi,xj)+1e-10 \
                and min(yi,yj)-1e-10 <= y <= max(yi,yj)+1e-10:
            return True
        if (yi > y) != (yj > y):
            cut = xi + (y-yi)*dx/dy
            if x < cut:
                inside = not inside
        j = i
    return inside


def ellipse(x, y, cx, cy, rx, ry, angle=0):
    a = math.radians(angle)
    u = (x-cx)*math.cos(a) + (y-cy)*math.sin(a)
    v = -(x-cx)*math.sin(a) + (y-cy)*math.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1.0 + 1e-12


