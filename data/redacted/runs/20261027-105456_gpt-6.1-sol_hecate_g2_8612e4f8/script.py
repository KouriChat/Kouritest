def channel(name, vertices, half_width_km):
    """Water rule: distance to a hand-estimated fjord centerline."""
    px, py = WEST * 65.4, NORTH * 111.2
    for (aw, an), (bw, bn) in zip(vertices, vertices[1:]):
        ax, ay, bx, by = aw*65.4, an*111.2, bw*65.4, bn*111.2
        dx, dy = bx-ax, by-ay
        t = np.clip(((px-ax)*dx+(py-ay)*dy)/(dx*dx+dy*dy), 0., 1.)
        distance2 = (px-ax-t*dx)**2 + (py-ay-t*dy)**2
        LAND[:] &= distance2 > half_width_km**2


