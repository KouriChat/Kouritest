"""Knowledge-only, hand-drawn approximation: no geographic files or services.

All vertices below are estimates from geographic memory, NOT surveyed coasts.
Coordinates in the handwritten tables are (degrees WEST, degrees NORTH).
Each output is a point-in-polygon classification, not independent LLM inference
at each point and not an area-averaged rasterization. Inland lakes stay land.
Run: python outputs/generate_map.py   Dependencies: numpy, Pillow.
"""
from pathlib import Path
import csv
import numpy as np
from PIL import Image

N = 127
WEST, NORTH = np.meshgrid(np.linspace(131., 129., N),
                          np.linspace(55., 53., N))
LAND = np.zeros((N, N), dtype=bool)


def inside(vertices):
    """Even/odd polygon test at the actual sampling coordinates."""
    result = np.zeros_like(LAND)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crossing = ((ay > NORTH) != (by > NORTH))
            intersection = ax + (NORTH - ay) * (bx - ax) / (by - ay)
            result ^= crossing & (WEST < intersection)
        ax, ay = bx, by
    return result


def land(name, vertices):
    LAND[:] |= inside(vertices)


def water(name, vertices):
    LAND[:] &= ~inside(vertices)


