def export_and_verify():
    """Write the sampled matrix directly, without smoothing or pixel edits."""
    output = Path.cwd() / 'outputs'
    output.mkdir(parents=True, exist_ok=True)
    matrix = LAND.astype(np.uint8)
    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert set(np.unique(matrix)) == {0, 1}
    assert (WEST[0, 0], WEST[0, -1]) == (131., 129.)
    assert (NORTH[0, 0], NORTH[-1, 0]) == (55., 53.)

    csv_path = output / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='ascii') as stream:
        writer = csv.writer(stream, lineterminator='\n')
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    resampling = getattr(Image, 'Resampling', Image)
    enlarged = original.resize((1016, 1016), resampling.NEAREST)
    original.save(output / 'candidate.png')
    enlarged.save(output / 'candidate_8x.png')

    # Verify the actual files, not merely the arrays before serialization.
    with csv_path.open('r', newline='', encoding='ascii') as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    assert sum(map(len, rows)) == 16129
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)

    with Image.open(output / 'candidate.png') as loaded:
        loaded.load()
        assert loaded.format == 'PNG' and loaded.size == (127, 127)
        actual_small = np.asarray(loaded)
        assert set(np.unique(actual_small)) == {0, 255}
        assert np.array_equal(actual_small, pixels)
    with Image.open(output / 'candidate_8x.png') as loaded:
        loaded.load()
        assert loaded.format == 'PNG' and loaded.size == (1016, 1016)
        actual_large = np.asarray(loaded)
        assert set(np.unique(actual_large)) == {0, 255}
        expected_large = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(actual_large, expected_large)

