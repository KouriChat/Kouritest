def in_ellipse(x, y, e):
    cx, cy, rx, ry, a = e
    ca, sa = math.cos(a), math.sin(a)
    dx, dy = x-cx, y-cy
    u = dx*ca + dy*sa
    v = -dx*sa + dy*ca
    return (u/rx)**2 + (v/ry)**2 <= 1.0 + 1e-12


def is_land(lon, lat):
    # This is a rule evaluation against hand-written outlines, not 16,401
    # independent language-model judgements.
    for p in POLYS:
        if in_poly(lon, lat, p):
            return 1
    for e in ELLIPSES:
        if in_ellipse(lon, lat, e):
            return 1
    return 0


def main():
    lons = [-9.0 + 0.2*i for i in range(231)]
    lats = [45.0 - 0.2*j for j in range(71)]
    matrix = np.array([[is_land(x, y) for x in lons] for y in lats],
                      dtype=np.uint8)

    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels, mode="L")
    image.save(out / "candidate.png")
    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST
    enlarged = image.resize((1848, 568), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Required integrity checks.
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert set(np.unique(matrix).tolist()) <= {0, 1}
    assert image.size == (231, 71) and enlarged.size == (1848, 568)
    assert set(image.getdata()) <= {0, 255}
    assert set(enlarged.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(enlarged), np.repeat(np.repeat(
        np.asarray(image), 8, axis=0), 8, axis=1))


if __name__ == "__main__":
    main()
