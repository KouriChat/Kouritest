def inside(lon, lat, poly):
    hit = False
    for i, (x1, y1) in enumerate(poly):
        x2, y2 = poly[(i + 1) % len(poly)]
        cross = (lon-x1)*(y2-y1) - (lat-y1)*(x2-x1)
        if abs(cross) < 1e-12 and min(x1,x2) <= lon <= max(x1,x2) and min(y1,y2) <= lat <= max(y1,y2):
            return True
        if (y1 > lat) != (y2 > lat):
            if lon < x1 + (lat-y1)*(x2-x1)/(y2-y1):
                hit = not hit
    return hit


def main():
    os.makedirs("outputs", exist_ok=True)
    matrix = np.zeros((ROWS, COLS), dtype=np.uint8)
    for r in range(ROWS):
        lat = NORTH - r * STEP
        for c in range(COLS):
            lon = WEST + c * STEP
            matrix[r, c] = any(inside(lon, lat, poly) for poly in LAND)
    with open("outputs/candidate.csv", "w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L")
    image.save("outputs/candidate.png")
    big = image.resize((1016, 1016), Image.Resampling.NEAREST)
    big.save("outputs/candidate_8x.png")
    assert matrix.shape == (127,127) and matrix.size == 16129
    assert set(np.unique(matrix)) <= {0,1}
    assert image.size == (127,127) and set(image.getdata()) <= {0,255}
    assert big.size == (1016,1016)
    for r in range(127):
        for c in range(127):
            assert big.getpixel((c*8,r*8)) == image.getpixel((c,r))
    print("Validated 16,129 samples; output images are 127 and 1016 pixels.")


if __name__ == "__main__":
    main()
