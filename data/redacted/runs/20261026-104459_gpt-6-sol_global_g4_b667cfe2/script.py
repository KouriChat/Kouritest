def inside_polygon(x, y, vertices):
    """Vectorized ray crossing, with each vertex expressed as lon/lat."""
    inside = np.zeros(x.shape, dtype=bool)
    j = len(vertices) - 1
    for i, (xi, yi) in enumerate(vertices):
        xj, yj = vertices[j]
        crosses = (yi > y) != (yj > y)
        edge_x = (xj - xi) * (y - yi) / ((yj - yi) + 1e-15) + xi
        inside ^= crosses & (x < edge_x)
        j = i
    return inside

def make_mask():
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    lon, lat = np.meshgrid(longitudes, latitudes)
    land = np.zeros(lon.shape, dtype=bool)
    for polygon in POLYGONS:
        land |= inside_polygon(lon, lat, polygon)
    # Approximate major inland lakes as water; Antarctic ice remains land.
    lakes = [
        (-87.5, 47.5, 1.7, 3.8), (-84, 45.5, 1.5, 2.5),
        (-81.5, 44.5, 1.0, 2.0), (-78.5, 43.5, 0.8, 1.5),
        (-82.5, 17.5, 0.7, 1.2), (33, 0, 3.5, 2.0),
        (34, -1, 2.4, 1.5), (29, -12, 1.7, 5.0),
        (110, 45, 1.6, 4.0), (48, 41, 0.8, 2.0),
        (59, 45, 2.0, 3.5), (51, 40, 2.0, 3.0),
    ]
    for cx, cy, rx, ry in lakes:
        land &= (((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2) > 1
    return land.astype(np.uint8)

def main():
    mask = make_mask()
    if mask.shape != (90, 180) or mask.size != 16200:
        raise RuntimeError("unexpected mask dimensions")
    np.savetxt(OUT / "candidate.csv", mask, fmt="%d", delimiter=",")
    # 1 -> white land, 0 -> black water.
    image = Image.fromarray(mask * 255, mode="L").convert("RGB")
    image.save(OUT / "candidate.png")
    image.resize((1440, 720), Image.Resampling.NEAREST).save(OUT / "candidate_8x.png")

if __name__ == "__main__":
    main()
