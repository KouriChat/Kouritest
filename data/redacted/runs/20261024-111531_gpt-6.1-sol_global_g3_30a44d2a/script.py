"""Memory-only world land/water reconstruction.

Run: python outputs/generate_map.py
Dependency: Pillow (pip install Pillow).
All geographic rules below are handwritten approximations from prior knowledge.
No maps, geographic datasets, network requests, or reference labels are read.
The classifier is polygon membership, NOT independent reasoning at each cell.
Lakes are intentionally not removed. Sea ice is not included as land.
"""
