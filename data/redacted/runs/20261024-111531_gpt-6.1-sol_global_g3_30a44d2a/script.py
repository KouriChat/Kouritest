POLYGONS = []


def land(name, coordinates):
    """Register a hand-written closed polygon; coordinates are longitude,latitude."""
    points = [tuple(map(float, pair.split(",")))
              for pair in coordinates.split()]
    assert len(points) >= 3 and all(len(p) == 2 for p in points), name
    POLYGONS.append((name, points))


def contains(x, y, points):
    inside = False
    ax, ay = points[-1]
    for bx, by in points:
        # Treat a sampling point on a polygon boundary as land.
        cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
        if abs(cross) < 1e-10 and min(ax, bx) <= x <= max(ax, bx) \
                and min(ay, by) <= y <= max(ay, by):
            return True
        if (ay > y) != (by > y):
            hit = ax + (y - ay) * (bx - ax) / (by - ay)
            if x < hit:
                inside = not inside
        ax, ay = bx, by
    return inside


