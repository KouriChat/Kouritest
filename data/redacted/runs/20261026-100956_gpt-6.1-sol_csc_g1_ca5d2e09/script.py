def inside_polygon(lon, lat, polygon):
    """Ray-crossing point-in-polygon test."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing_x = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing_x:
                inside = not inside
        j = i
    return inside

def classify(lon, lat):
    if any(inside_polygon(lon, lat, poly) for poly in POLYGONS):
        return 1
    for cx, cy, radius in ISLANDS:
        dx = (lon - cx) * np.cos(np.deg2rad(lat))
        if dx * dx + (lat - cy) ** 2 <= radius * radius:
            return 1
    return 0

def main():
    latitudes = 23.0 - 0.2 * np.arange(111)
    longitudes = 99.0 + 0.2 * np.arange(141)
    matrix = np.zeros((111, 141), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = classify(float(lon), float(lat))

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "candidate.csv").open("w", newline="") as file:
        writer = csv.writer(file, lineterminator="\n")
        writer.writerows(matrix.tolist())

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")
    image.resize((1128, 888), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )

    assert matrix.shape == (111, 141)
    assert matrix.size == 15651 and set(np.unique(matrix)) <= {0, 1}
    with (output_dir / "candidate.csv").open(newline="") as file:
        rows = list(csv.reader(file))
    assert len(rows) == 111 and all(len(row) == 141 for row in rows)
    assert all(v in {"0", "1"} for row in rows for v in row)
    assert image.size == (141, 111)
    assert set(image.getdata()) <= {0, 255}
    enlarged = Image.open(output_dir / "candidate_8x.png")
    expected = image.resize((1128, 888), resample=Image.Resampling.NEAREST)
    assert enlarged.size == (1128, 888)
    assert list(enlarged.getdata()) == list(expected.getdata())

if __name__ == "__main__":
    main()
