def inside(x, y, polygon):
    """Even-odd rule; each input is a longitude, latitude pair."""
    hit = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > y) != (yj > y):
            crossing = xi + (y - yi) * (xj - xi) / (yj - yi)
            if x < crossing:
                hit = not hit
        j = i
    return hit


