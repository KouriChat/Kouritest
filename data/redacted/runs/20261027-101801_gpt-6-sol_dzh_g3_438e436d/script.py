def on_ellipse(x, y, ellipse):
    cx, cy, rx, ry, angle = ellipse
    a = radians(angle)
    dx, dy = x - cx, y - cy
    u, v = dx * cos(a) + dy * sin(a), -dx * sin(a) + dy * cos(a)
    return (u / rx) ** 2 + (v / ry) ** 2 <= 1


land_polygons = [europe, africa_levant, anatolia, crimea] + islands


def is_land(lon, lat):
    return int(any(inside(lon, lat, poly) for poly in land_polygons) or
               any(on_ellipse(lon, lat, e) for e in small_islands))


def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    # Integers avoid drift; 45 - row/5 N, -9 + column/5 E.
    matrix = [[is_land(-9 + col / 5, 45 - row / 5)
               for col in range(231)] for row in range(71)]
    with (out / 'candidate.csv').open('w', encoding='utf-8', newline='') as f:
        csv.writer(f).writerows(matrix)

    img = Image.new('L', (231, 71))
    img.putdata([255 * cell for row in matrix for cell in row])
    img.save(out / 'candidate.png')
    large = img.resize((1848, 568), resample=Image.Resampling.NEAREST)
    large.save(out / 'candidate_8x.png')
    assert len(matrix) == 71 and all(len(row) == 231 for row in matrix)
    assert {v for row in matrix for v in row} <= {0, 1}
    assert set(img.getdata()) <= {0, 255}
    assert large.size == (1848, 568)
    assert all(large.getpixel((8 * x + dx, 8 * y + dy)) == img.getpixel((x, y))
               for y in range(71) for x in range(231)
               for dx in range(8) for dy in range(8))


if __name__ == '__main__':
    main()
