def in_poly(lon, lat, poly):
    n = len(poly); inside = False; j = n - 1
    for i in range(n):
        xi, yi = poly[i]; xj, yj = poly[j]
        if ((yi > lat) != (yj > lat)) and (lon < (xj-xi)*(lat-yi)/(yj-yi)+xi):
            inside = not inside
        j = i
    return inside

def build_matrix():
    rows, cols = 61, 241
    M = np.zeros((rows, cols), dtype=np.uint8)
    for r in range(rows):
        lat = 79.0 - 0.1*r
        for c in range(cols):
            lon = -105.0 + 0.1*c
            M[r, c] = 1 if any(in_poly(lon, lat, p) for p in ISLANDS) else 0
    return M

def main():
    os.makedirs("outputs", exist_ok=True)
    M = build_matrix()
    assert M.shape == (61, 241)
    np.savetxt("outputs/candidate.csv", M, fmt="%d", delimiter=",")
    img = Image.fromarray(np.where(M == 1, 255, 0).astype(np.uint8), mode="L")
    img.save("outputs/candidate.png")
    big = img.resize((241*8, 61*8), Image.NEAREST)
    big.save("outputs/candidate_8x.png")
    print("ok", M.shape, int(M.sum()))

if __name__ == "__main__":
    main()
