def in_polygon(x, y, vertices):
    inside = False
    xa, ya = vertices[-1]
    for xb, yb in vertices:
        if (ya > y) != (yb > y):
            cross = xa + (y - ya) * (xb - xa) / (yb - ya)
            if x < cross:
                inside = not inside
        xa, ya = xb, yb
    return inside

def ellipse(cx, cy, rx, ry, n=28):
    import math
    return tuple((cx + rx*math.cos(i*2*math.pi/n),
                  cy + ry*math.sin(i*2*math.pi/n)) for i in range(n))

