def rasterize():
    longs = np.arange(-179, 180, 2)
    lats = np.arange(89, -90, -2)
    result = np.zeros((90, 180), dtype=np.uint8)
    # Test grid-cell centers against the remembered, hand-entered outlines.
    # Coarse polygon masks are the actual point-wise classification method.
    for value, polygons in ((1, LAND), (0, WATER)):
        for vertices in polygons:
            minx = min(p[0] for p in vertices)
            maxx = max(p[0] for p in vertices)
            miny = min(p[1] for p in vertices)
            maxy = max(p[1] for p in vertices)
            cols = np.flatnonzero((longs >= minx) & (longs <= maxx))
            rows = np.flatnonzero((lats >= miny) & (lats <= maxy))
            for r in rows:
                for c in cols:
                    if in_polygon(float(longs[c]), float(lats[r]), vertices):
                        result[r, c] = value
    return result

def main():
    destination = Path("outputs")
    destination.mkdir(exist_ok=True, parents=True)
    grid = rasterize()
    with (destination / "candidate.csv").open("w", newline="", encoding="ascii") as file:
        csv.writer(file).writerows(grid.tolist())
    raw = Image.fromarray(grid * 255, mode="L")
    raw.save(destination / "candidate.png")
    nearest = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    large = raw.resize((1440, 720), resample=nearest)
    large.save(destination / "candidate_8x.png")
    assert grid.shape == (90, 180) and grid.size == 16200
    assert set(np.unique(grid)).issubset({0, 1})
    assert raw.size == (180, 90) and large.size == (1440, 720)
    assert set(raw.getdata()) <= {0, 255} and set(large.getdata()) <= {0, 255}
    assert np.array_equal(np.asarray(large), np.repeat(np.repeat(
        np.asarray(raw), 8, axis=0), 8, axis=1))
    print("Validated 90x180 grid and 180x90 / nearest-neighbor 1440x720 black-white PNGs.")

if __name__ == "__main__":
    main()
