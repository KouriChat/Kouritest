X, Y = np.meshgrid(lon, lat)
land = np.zeros(X.shape, dtype=bool)

def polygon(text, value=True):
    """Ray crossing at sample POINTS, not pixel-area coverage."""
    global land
    a = np.array([float(v) for v in text.split()]).reshape(-1, 2)
    inside = np.zeros(X.shape, dtype=bool)
    x0, y0 = a[-1]
    for x1, y1 in a:
        if y0 != y1:
            cross = ((y0 > Y) != (y1 > Y))
            xx = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= cross & (X < xx)
        x0, y0 = x1, y1
    land[inside] = value

def oval(cx, cy, rx, ry, angle=0, value=True):
    """Small islands approximated by rotated ellipses in degree space."""
    global land
    t = math.radians(angle)
    dx, dy = X-cx, Y-cy
    u, v = dx*math.cos(t)+dy*math.sin(t), -dx*math.sin(t)+dy*math.cos(t)
    land[(u/rx)**2+(v/ry)**2 <= 1] = value

