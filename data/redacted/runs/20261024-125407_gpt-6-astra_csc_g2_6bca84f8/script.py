"""Knowledge-only approximate South China Sea land mask; no geographic inputs.
Dependencies: numpy, Pillow. Run from the working directory.
Coordinates below are hand-written approximations, not independent point inference.
Inland lakes are deliberately not subtracted from the land polygons.
"""
from pathlib import Path
import csv
import numpy as np
from PIL import Image

LON, LAT = np.meshgrid(99.0 + np.arange(141) / 5,
                       23.0 - np.arange(111) / 5)
land = np.zeros((111, 141), dtype=bool)

def vertices(text):
    return [tuple(map(float, pair.split(","))) for pair in text.split()]

def polygon(text):
    """Vectorized ray crossing at the sample points, not cell-area voting."""
    pts = vertices(text)
    inside = np.zeros_like(land)
    x0, y0 = pts[-1]
    for x1, y1 in pts:
        if y1 != y0:
            crossing = ((y0 > LAT) != (y1 > LAT))
            cut = x0 + (LAT - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crossing & (LON < cut)
        x0, y0 = x1, y1
    land[:] |= inside

