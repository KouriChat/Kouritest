def point_in_polygon(lon, lat, polygon):
    """Ray-crossing point test; boundary points count as land."""
    inside = False
    n = len(polygon)
    for i in range(n):
        x1, y1 = polygon[i]
        x2, y2 = polygon[(i + 1) % n]

        cross = (lon - x1) * (y2 - y1) - (lat - y1) * (x2 - x1)
        if abs(cross) < 1e-10:
            if (min(x1, x2) - 1e-10 <= lon <= max(x1, x2) + 1e-10
                    and min(y1, y2) - 1e-10 <= lat <= max(y1, y2) + 1e-10):
                return True

        if (y1 > lat) != (y2 > lat):
            crossing_lon = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < crossing_lon:
                inside = not inside
    return inside


def build_matrix():
    matrix = np.zeros((HEIGHT, WIDTH), dtype=np.uint8)
    for row in range(HEIGHT):
        lat = LAT_MAX - row * STEP
        for col in range(WIDTH):
            lon = LON_MIN + col * STEP
            if any(point_in_polygon(lon, lat, polygon) for polygon in POLYGONS):
                matrix[row, col] = 1
    return matrix


def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    matrix = build_matrix()
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert np.isin(matrix, (0, 1)).all()

    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 1 is white land; 0 is black water.
    pixels = matrix * 255
    image = Image.fromarray(pixels, mode="L").convert("RGB")
    assert image.size == (141, 111)
    assert set(image.getdata()).issubset({(0, 0, 0), (255, 255, 255)})
    image.save(output_dir / "candidate.png")

    enlarged = image.resize((141 * 8, 111 * 8), resample=Image.Resampling.NEAREST)
    assert enlarged.size == (1128, 888)
    enlarged.save(output_dir / "candidate_8x.png")


if __name__ == "__main__":
    main()
