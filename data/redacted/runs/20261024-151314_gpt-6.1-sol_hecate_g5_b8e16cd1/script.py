def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    assert matrix.shape == (127, 127) and matrix.size == 16129
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert west[0] == 131 and west[-1] == 129
    assert north[0] == 55 and north[-1] == 53

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    original.resize((1016, 1016), resample=nearest).save(
        out / "candidate_8x.png"
    )

    # Reopen only this script's own outputs; no external geographic inputs.
    with (out / "candidate.csv").open(encoding="ascii", newline="") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    roundtrip = np.asarray(rows, dtype=np.uint8)
    assert roundtrip.size == 16129 and np.array_equal(roundtrip, matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (127, 127) and im.mode == "L"
        small = np.asarray(im).copy()
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1016, 1016) and im.mode == "L"
        large = np.asarray(im).copy()
    assert set(np.unique(small).tolist()) == {0, 255}
    assert set(np.unique(large).tolist()) == {0, 255}
    assert np.array_equal(small, pixels)
    expected = np.repeat(np.repeat(small, 8, axis=0), 8, axis=1)
    assert np.array_equal(large, expected), "Not an exact nearest-neighbor image"
    print("Validated: 127x127, 16,129 binary point classifications; "
          "127x127 and 1016x1016 black/white PNGs; exact nearest-neighbor 8x.")
    print(f"Land points: {int(matrix.sum())}; "
          f"water points: {int(matrix.size - matrix.sum())}.")

if __name__ == "__main__":
    main()
