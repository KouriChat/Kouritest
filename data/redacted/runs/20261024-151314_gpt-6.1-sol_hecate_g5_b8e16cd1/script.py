def channel(points, half_width_km):
    """Subtract a hand-estimated marine channel, using local flat geometry."""
    radius = half_width_km / 111.2
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        dx, dy = (x1 - x0) * 0.585, y1 - y0
        px, py = (X - x0) * 0.585, Y - y0
        t = np.clip((px * dx + py * dy) / (dx * dx + dy * dy), 0, 1)
        land[:] &= (px - t * dx)**2 + (py - t * dy)**2 > radius**2

