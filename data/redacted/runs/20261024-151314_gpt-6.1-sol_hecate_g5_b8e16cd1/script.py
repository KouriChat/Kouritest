X, Y = np.meshgrid(west, north)
land = np.zeros((N, N), dtype=bool)

def inside(vertices):
    result = np.zeros((N, N), dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crossing = (y1 > Y) != (y0 > Y)
            hit_x = x0 + (Y - y0) * (x1 - x0) / (y1 - y0)
            result ^= crossing & (X < hit_x)
        x0, y0 = x1, y1
    return result

def add(vertices):
    land[:] |= inside(vertices)

def water(vertices):
    land[:] &= ~inside(vertices)

