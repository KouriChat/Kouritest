def contains(vertices, x, y):
    """Vectorized ray casting: evaluate the actual point, not a cell majority."""
    inside = np.zeros(x.shape, dtype=bool)
    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crosses = ((ay > y) != (by > y))
            edge_x = ax + (y - ay) * (bx - ax) / (by - ay)
            inside ^= crosses & (x < edge_x)
        ax, ay = bx, by
    return inside

def generate():
    # Exact rational-grid formulas, rather than the rounded example labels.
    longitude = 129.0 + np.arange(253, dtype=np.float64) * (2.0 / 63.0)
    latitude = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
    x, y = np.meshgrid(longitude, latitude)
    result = np.zeros((64, 253), dtype=bool)
    for vertices in LAND:
        result |= contains(vertices, x, y)
    for vertices in WATER:
        result &= ~contains(vertices, x, y)
    return result.astype(np.uint8)
