def ellipse(lon, lat, rx, ry, angle=0.0, n=24):
    """Hand-positioned elliptical island, rx/ry in degrees, angle in degrees."""
    t = np.arange(n) * (2 * np.pi / n)
    a = np.deg2rad(angle)
    x, y = rx * np.cos(t), ry * np.sin(t)
    LAND.append(list(zip(lon + x*np.cos(a) - y*np.sin(a),
                         lat + x*np.sin(a) + y*np.cos(a))))

