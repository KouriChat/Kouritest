longitudes = np.array([99.0 + .2*j for j in range(141)])[None, :]
latitudes = np.array([23.0 - .2*i for i in range(111)])[:, None]
xx, yy = np.broadcast_arrays(longitudes, latitudes)
land = np.zeros((111, 141), dtype=bool)

for vertices in polygons:
    inside = np.zeros((111, 141), dtype=bool)
    for (xa, ya), (xb, yb) in zip(vertices, vertices[1:] + vertices[:1]):
        if ya == yb:
            continue
        crossing = (ya > yy) != (yb > yy)
        x_intersection = xa + (yy - ya) * (xb - xa) / (yb - ya)
        inside ^= crossing & (xx < x_intersection)
    land |= inside

for cx, cy, rx, ry in ellipses:
    land |= ((xx-cx)/rx)**2 + ((yy-cy)/ry)**2 <= 1

pixels = np.where(land, 255, 0).astype(np.uint8)
