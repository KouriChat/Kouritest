def contains(points, x, y):
    """Vectorized ray crossing for the sample points, never pixel area voting."""
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = points[-1]
    for x1, y1 in points:
        if y1 != y0:
            crosses = (y1 > y) != (y0 > y)
            intersection = (x0 - x1) * (y - y1) / (y0 - y1) + x1
            inside ^= crosses & (x < intersection)
        x0, y0 = x1, y1
    return inside


def main():
    out = Path.cwd() / "outputs"
    out.mkdir(parents=True, exist_ok=True)
    lon = 129.0 + np.arange(253, dtype=float) * (2.0 / 63.0)
    lat = 35.0 - np.arange(64, dtype=float) * (2.0 / 63.0)
    x, y = np.meshgrid(lon, lat)
    land = np.zeros((64, 253), dtype=bool)
    for outline in LAND:
        land |= contains(outline, x, y)
    for outline in WATER:
        land &= ~contains(outline, x, y)
    matrix = land.astype(np.uint8)
    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())
    pixels = matrix * 255
    image = Image.fromarray(pixels)
    image.save(out / "candidate.png")
    nearest = getattr(Image, "Resampling", Image).NEAREST
    enlarged = image.resize((2024, 512), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 64
    assert all(len(row) == 253 for row in rows)
    assert sum(len(row) for row in rows) == 16192
    assert all(v in ("0", "1") for row in rows for v in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (253, 64)
        original = np.asarray(im)
        assert set(np.unique(original)).issubset({0, 255})
        assert np.array_equal(original, pixels)
    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (2024, 512)
        large = np.asarray(im)
        assert set(np.unique(large)).issubset({0, 255})
        assert np.array_equal(large, original.repeat(8, 0).repeat(8, 1))
    assert lon[0] == 129 and lon[-1] == 137
    assert lat[0] == 35 and lat[-1] == 33
    print("Validated: 64x253 = 16192 binary values; PNG 253x64; "
          "nearest-neighbor PNG 2024x512; black/white only.")


if __name__ == "__main__":
    main()
