def point_on_segment(x, y, x1, y1, x2, y2):
    cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
    if abs(cross) > 1e-10:
        return False
    return (
        min(x1, x2) - 1e-10 <= x <= max(x1, x2) + 1e-10
        and min(y1, y2) - 1e-10 <= y <= max(y1, y2) + 1e-10
    )


def inside_polygon(lon, lat, polygon):
    inside = False
    for i, (x1, y1) in enumerate(polygon):
        x2, y2 = polygon[(i + 1) % len(polygon)]
        if point_on_segment(lon, lat, x1, y1, x2, y2):
            return True
        if (y1 > lat) != (y2 > lat):
            crossing_lon = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < crossing_lon:
                inside = not inside
    return inside


def is_land(lon, lat):
    return int(any(inside_polygon(lon, lat, p) for p in POLYGONS))


def main():
    lats = 45.0 - 0.2 * np.arange(71)
    lons = -9.0 + 0.2 * np.arange(231)
    matrix = np.zeros((71, 231), dtype=np.uint8)
    for row, lat in enumerate(lats):
        for col, lon in enumerate(lons):
            matrix[row, col] = is_land(float(lon), float(lat))

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as csv_file:
        for row in matrix:
            csv_file.write(",".join(str(int(v)) for v in row) + "\n")

    image = Image.fromarray(matrix * np.uint8(255), mode="L")
    image.save(output_dir / "candidate.png")
    enlarged = image.resize((1848, 568), resample=Image.Resampling.NEAREST)
    enlarged.save(output_dir / "candidate_8x.png")

    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert set(np.unique(matrix)).issubset({0, 1})
    assert image.size == (231, 71)
    assert enlarged.size == (1848, 568)
    assert set(image.getdata()).issubset({0, 255})


if __name__ == "__main__":
    main()
