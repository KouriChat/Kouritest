def points_in_polygon(west, north, polygon):
    """Ray crossing at the sampled point (not cell-area sampling)."""
    inside = np.zeros(west.shape, dtype=bool)
    px, py = polygon[-1]
    for qx, qy in polygon:
        if (qy > py):  # oriented edge direction does not affect crossings
            ya, yb, xa, xb = py, qy, px, qx
        else:
            ya, yb, xa, xb = qy, py, qx, px
        if yb != ya:
            crossed = (north >= ya) & (north < yb)
            boundary = px + (north - py) * (qx - px) / (qy - py)
            inside ^= crossed & (west < boundary)
        px, py = qx, qy
    return inside


def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    # Integer indexing avoids floating point stepping inaccuracies.
    west = (1050 - np.arange(241)[None, :]) / 10.0
    north = (790 - np.arange(61)[:, None]) / 10.0
    west, north = np.broadcast_arrays(west, north)
    land = np.zeros((61, 241), dtype=bool)
    for _, outline in ISLANDS:
        land |= points_in_polygon(west, north, outline)
    matrix = land.astype(np.uint8)

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f)
        writer.writerows(matrix.tolist())

    original = Image.fromarray(matrix * np.uint8(255), mode="L")
    original.save(out / "candidate.png")
    enlarged = original.resize((1928, 488), resample=Image.Resampling.NEAREST)
    enlarged.save(out / "candidate_8x.png")

    with csv_path.open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert matrix.shape == (61, 241) and matrix.size == 14701
    assert len(rows) == 61 and all(
        len(row) == 241 and all(value in ("0", "1") for value in row)
        for row in rows
    )
    assert np.array_equal(np.array(rows, dtype=np.uint8), matrix)
    with Image.open(out / "candidate.png") as img:
        small = np.asarray(img.convert("L"))
        assert img.size == (241, 61) and set(np.unique(small)) <= {0, 255}
    with Image.open(out / "candidate_8x.png") as img:
        big = np.asarray(img.convert("L"))
        assert img.size == (1928, 488) and set(np.unique(big)) <= {0, 255}
    assert np.array_equal(big, np.repeat(np.repeat(small, 8, 0), 8, 1))
    print(f"Validated 61 x 241 = {matrix.size} samples; "
          f"land {int(matrix.sum())}, water {matrix.size - int(matrix.sum())}.")


if __name__ == "__main__":
    main()
