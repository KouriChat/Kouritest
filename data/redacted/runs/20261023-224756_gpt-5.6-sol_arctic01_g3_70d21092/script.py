# Coordinates below are hand-authored approximations (west longitude, latitude).
# They deliberately encode only the requested window.
def inside_poly(w, y, p):
    inside = False
    j = len(p) - 1
    for i in range(len(p)):
        xi, yi = p[i]
        xj, yj = p[j]
        if ((yi > y) != (yj > y)):
            xcut = (xj-xi) * (y-yi) / (yj-yi) + xi
            if w < xcut:
                inside = not inside
        j = i
    return inside

def ellipse(w, y, cx, cy, rx, ry, angle=0):
    a = math.radians(angle)
    dx, dy = w-cx, y-cy
    u = dx*math.cos(a) + dy*math.sin(a)
    v = -dx*math.sin(a) + dy*math.cos(a)
    return (u/rx)**2 + (v/ry)**2 <= 1

