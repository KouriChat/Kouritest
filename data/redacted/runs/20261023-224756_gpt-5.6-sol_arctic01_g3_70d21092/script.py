def is_land(w, y):
    land = any(inside_poly(w, y, p) for p in polys)
    if not land:
        land = any(ellipse(w, y, *e) for e in ellipses)
    if land and any(inside_poly(w, y, p) for p in cuts):
        land = False
    return 1 if land else 0

def build():
    # Integer construction avoids cumulative stepping error.
    a = np.zeros((61, 241), dtype=np.uint8)
    for r in range(61):
        lat = (790-r) / 10.0
        for c in range(241):
            west_lon = (1050-c) / 10.0
            a[r, c] = is_land(west_lon, lat)
    return a

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    a = build()

    with (out / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(a.tolist())

    raw = (a * 255).astype(np.uint8)
    Image.fromarray(raw, mode="L").save(out / "candidate.png")
    enlarged = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    Image.fromarray(enlarged, mode="L").save(out / "candidate_8x.png")

    # Fail loudly if any delivery invariant was accidentally violated.
    assert a.shape == (61, 241) and a.size == 14701
    assert set(np.unique(a)).issubset({0, 1})
    with (out / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 61 and all(len(row) == 241 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)
    with Image.open(out / "candidate.png") as im:
        assert im.size == (241, 61) and set(im.getdata()).issubset({0, 255})
    with Image.open(out / "candidate_8x.png") as im:
        big = np.asarray(im)
        assert im.size == (1928, 488)
        assert set(np.unique(big)).issubset({0, 255})
        assert np.array_equal(big, np.repeat(np.repeat(raw, 8, 0), 8, 1))
    print("validated: 61x241 values; PNG 241x61; nearest 8x PNG 1928x488")

if __name__ == "__main__":
    main()
