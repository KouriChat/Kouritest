def in_polygon(x, y, p):
    inside = False
    j = len(p) - 1
    for i, (xi, yi) in enumerate(p):
        xj, yj = p[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def ellipse(x, y, cx, cy, rx, ry, angle=0):
    from math import cos, sin, radians
    a = radians(angle)
    u, v = x - cx, y - cy
    return ((u * cos(a) + v * sin(a)) / rx) ** 2 + ((v * cos(a) - u * sin(a)) / ry) ** 2 <= 1


