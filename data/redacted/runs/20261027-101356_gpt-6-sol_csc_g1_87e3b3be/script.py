def is_land(x, y):
    if any(in_polygon(x, y, shape) for shape in polygons):
        return 1
    return int(any(ellipse(x, y, *island) for island in small_islands))


def main():
    out = Path('outputs')
    out.mkdir(exist_ok=True)
    matrix = np.array([[is_land(99 + c / 5, 23 - r / 5)
                        for c in range(141)] for r in range(111)], dtype=np.uint8)
    assert matrix.shape == (111, 141)
    assert np.isin(matrix, (0, 1)).all() and matrix.size == 15651

    with (out / 'candidate.csv').open('w', newline='', encoding='ascii') as f:
        csv.writer(f).writerows(matrix.tolist())

    original = Image.fromarray(matrix * 255, mode='L').convert('RGB')
    original.save(out / 'candidate.png')
    enlarged = original.resize((1128, 888), resample=Image.Resampling.NEAREST)
    enlarged.save(out / 'candidate_8x.png')

    with (out / 'candidate.csv').open(newline='', encoding='ascii') as f:
        rows = list(csv.reader(f))
    assert len(rows) == 111 and all(len(row) == 141 for row in rows)
    assert all(value in ('0', '1') for row in rows for value in row)
    with Image.open(out / 'candidate.png') as im:
        assert im.size == (141, 111) and set(im.getdata()) <= {(0, 0, 0), (255, 255, 255)}
    with Image.open(out / 'candidate_8x.png') as im:
        assert im.size == (1128, 888)
        assert set(im.getdata()) <= {(0, 0, 0), (255, 255, 255)}
        assert np.array_equal(np.asarray(im), np.repeat(np.repeat(np.asarray(original), 8, axis=0), 8, axis=1))
    print('Validated 111x141 matrix, binary PNGs, and nearest-neighbor 8x image.')


if __name__ == '__main__':
    main()
