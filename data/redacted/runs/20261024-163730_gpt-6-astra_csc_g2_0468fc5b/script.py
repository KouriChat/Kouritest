LON, LAT = np.meshgrid(99 + np.arange(141) / 5,
                       23 - np.arange(111) / 5)
land = np.zeros((111, 141), dtype=bool)

def polygon(coords):
    """Union a hand-estimated land polygon into the point-sampled mask."""
    points = np.asarray(coords, dtype=float)
    inside = np.zeros(LON.shape, dtype=bool)
    boundary = np.zeros(LON.shape, dtype=bool)
    for (ax, ay), (bx, by) in zip(points, np.roll(points, -1, axis=0)):
        dx, dy = bx - ax, by - ay
        cross = (LON - ax) * dy - (LAT - ay) * dx
        boundary |= ((np.abs(cross) < 1e-10) &
                     (LON >= min(ax, bx) - 1e-10) &
                     (LON <= max(ax, bx) + 1e-10) &
                     (LAT >= min(ay, by) - 1e-10) &
                     (LAT <= max(ay, by) + 1e-10))
        if dy != 0:
            inside ^= (((ay > LAT) != (by > LAT)) &
                       (LON < ax + (LAT - ay) * dx / dy))
    land[:] |= inside | boundary

