def path(s):
    return [tuple(map(float, word.split(":"))) for word in s.split()]


def inside(x, y, vertices):
    """Even-odd polygon test; points on a vertex are assigned arbitrarily."""
    found = False
    px, py = vertices[-1]
    for qx, qy in vertices:
        if ((qy > y) != (py > y)):
            cut = (px - qx) * (y - qy) / (py - qy) + qx
            if x < cut:
                found = not found
        px, py = qx, qy
    return found


