def classify(lon, lat):
    if inside(lon, lat, EUROPE) or inside(lon, lat, AFRICA):
        return 1
    if inside(lon, lat, ASIA):
        return 1
    return int(any(inside(lon, lat, island) for island in ISLANDS))

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)
    grid = np.array([
        [classify(-9 + col * 0.2, 45 - row * 0.2)
         for col in range(231)]
        for row in range(71)
    ], dtype=np.uint8)
    assert grid.shape == (71, 231) and grid.size == 16401
    assert np.all((grid == 0) | (grid == 1))

    csv_file = out / "candidate.csv"
    with csv_file.open("w", newline="", encoding="utf-8") as file:
        csv.writer(file).writerows(grid.tolist())

    image = Image.fromarray(grid * 255, "L")
    nn = Image.Resampling.NEAREST if hasattr(Image, "Resampling") else Image.NEAREST
    magnified = image.resize((1848, 568), resample=nn)
    image.save(out / "candidate.png")
    magnified.save(out / "candidate_8x.png")

    with csv_file.open(newline="", encoding="utf-8") as file:
        rows = list(csv.reader(file))
    assert len(rows) == 71
    assert all(len(row) == 231 and set(row) <= {"0", "1"} for row in rows)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), grid)
    assert image.size == (231, 71) and magnified.size == (1848, 568)
    assert set(image.getdata()) <= {0, 255}
    assert set(magnified.getdata()) <= {0, 255}
    assert np.array_equal(
        np.asarray(magnified),
        np.repeat(np.repeat(np.asarray(image), 8, axis=0), 8, axis=1),
    )
    print("Validated 71x231 CSV, binary PNG and 8x nearest-neighbor PNG.")


if __name__ == "__main__":
    main()
