def contains_polygon(longitudes, latitudes, vertices):
    """Even/odd crossing test, evaluated at the point, not the cell area."""
    result = np.zeros(longitudes.shape, dtype=bool)
    prev_x, prev_y = vertices[-1]
    for next_x, next_y in vertices:
        if prev_y != next_y:
            crossing = ((prev_y > latitudes) != (next_y > latitudes))
            boundary_x = prev_x + (latitudes - prev_y) * (
                (next_x - prev_x) / (next_y - prev_y)
            )
            result ^= crossing & (longitudes < boundary_x)
        prev_x, prev_y = next_x, next_y
    return result


