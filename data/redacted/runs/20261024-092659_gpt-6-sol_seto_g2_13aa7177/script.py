    for polygon in polygons:
        land |= contains_polygon(longitudes, latitudes, polygon)
    for longitude, latitude, rlon, rlat, angle in islets:
        radians = math.radians(angle)
        dx, dy = longitudes - longitude, latitudes - latitude
        aligned_x = dx * math.cos(radians) + dy * math.sin(radians)
        aligned_y = -dx * math.sin(radians) + dy * math.cos(radians)
        land |= (aligned_x / rlon) ** 2 + (aligned_y / rlat) ** 2 <= 1

    matrix = land.astype(np.uint8)
    output = Path.cwd() / "outputs"
    output.mkdir(parents=True, exist_ok=True)
    csv_path = output / "candidate.csv"
    png_path = output / "candidate.png"
    large_path = output / "candidate_8x.png"
    with csv_path.open("w", newline="", encoding="ascii") as handle:
        csv.writer(handle).writerows(matrix.tolist())
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(png_path)
    image.resize((2024, 512), resample=Image.Resampling.NEAREST).save(large_path)

    # Validate the actual saved products and exact nearest-neighbor mapping.
    with csv_path.open(newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 64 and all(len(row) == 253 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(png_path) as saved, Image.open(large_path) as enlarged:
        small_pixels = np.asarray(saved.convert("L"))
        large_pixels = np.asarray(enlarged.convert("L"))
        assert saved.size == (253, 64) and enlarged.size == (2024, 512)
        assert set(np.unique(small_pixels)) <= {0, 255}
        assert set(np.unique(large_pixels)) <= {0, 255}
        assert np.array_equal(small_pixels, matrix * 255)
        assert np.array_equal(
            large_pixels, np.repeat(np.repeat(small_pixels, 8, axis=0), 8, axis=1)
        )
    print(f"Validated {matrix.size} samples; {matrix.sum()} land, "
          f"{matrix.size - matrix.sum()} water; outputs in {output}")


