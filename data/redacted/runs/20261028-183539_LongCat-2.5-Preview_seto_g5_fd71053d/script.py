def inside(poly, lon, lat):
    n = len(poly)
    if n < 3:
        return False
    x, y = lon, lat
    c = False
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y):
            xt = xi + (y - yi) * (xj - xi) / (yj - yi)
            if x < xt:
                c = not c
        j = i
    return c

