def is_land(lon, lat):
    for _, poly in POLY:
        if inside(poly, lon, lat):
            for _, wpoly in WATER:
                if inside(wpoly, lon, lat):
                    return False
            return True
    return False

mat = np.zeros((NLAT, NLON), dtype=np.uint8)
for i, lat in enumerate(LATS):
    for j, lon in enumerate(LONS):
        mat[i, j] = 1 if is_land(lon, lat) else 0

os.makedirs("outputs", exist_ok=True)
with open("outputs/candidate.csv", "w") as f:
    for i in range(NLAT):
        f.write(",".join(str(int(v)) for v in mat[i]) + "\n")

