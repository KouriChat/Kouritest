def is_land(x, y):
    # The tuple form is used for small, approximate island ellipses.
    answer = False
    for shape in LAND:
        if isinstance(shape, tuple):
            cx, cy, rx, ry = shape
            answer = answer or ellipse(x, y, cx, cy, rx, ry)
        else:
            answer = answer or inside(x, y, shape)
    if answer:
        for shape in HOLES:
            if inside(x, y, shape):
                return False
    return bool(answer)

def main():
    os.makedirs("outputs", exist_ok=True)
    rows = []
    for r in range(H):
        lat = 89 - 2 * r
        row = [1 if is_land(-179 + 2 * c, lat) else 0 for c in range(W)]
        rows.append(row)

    assert len(rows) == 90 and all(len(row) == 180 for row in rows)
    assert all(v in (0, 1) for row in rows for v in row)
    with open("outputs/candidate.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(rows)

    # A grayscale array gives exactly two colors: 0=black water, 255=white land.
    image = Image.fromarray(np.asarray(rows, dtype=np.uint8) * 255, mode="L")
    assert image.size == (180, 90)
    image.save("outputs/candidate.png")
    enlarged = image.resize((1440, 720), Image.Resampling.NEAREST)
    enlarged.save("outputs/candidate_8x.png")

    # Runtime checks required by the experiment.
    with Image.open("outputs/candidate.png") as check:
        assert check.size == (180, 90)
        assert set(check.getdata()) <= {0, 255}
    with Image.open("outputs/candidate_8x.png") as check:
        assert check.size == (1440, 720)
        assert set(check.getdata()) <= {0, 255}
    print("generated 90x180 matrix and two-color PNGs")

if __name__ == "__main__":
    main()
