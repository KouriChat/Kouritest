"""Knowledge-only hand-drawn approximate Mediterranean land mask.

Vertices are (longitude, latitude), in WGS84 degrees. All the boundaries below
are drawn from memory; no cartographic files or network access are involved.
The vectorised point-in-polygon test is a point test, not an area average.
"""
import csv
