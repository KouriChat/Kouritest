xs = -9.0 + np.arange(231) * 0.2
ys = 45.0 - np.arange(71) * 0.2
X, Y = np.meshgrid(xs, ys)
land = np.zeros((71, 231), dtype=bool)


def polygon(points):
    """Even-odd point-in-polygon; boundary points can go either way."""
    inside = np.zeros_like(land)
    ax, ay = points[-1]
    for bx, by in points:
        if ay != by:
            crossed = ((ay > Y) != (by > Y)) & (
                X < (bx - ax) * (Y - ay) / (by - ay) + ax
            )
            inside ^= crossed
        ax, ay = bx, by
    return inside


def add(points):
    land[:] |= polygon(points)


def cut(points):
    land[:] &= ~polygon(points)


