def points_inside(vertices, x, y):
    """Even/odd ray casting with exact-edge points assigned to land."""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        dx, dy = x1 - x0, y1 - y0
        crosses = (y0 > y) != (y1 > y)
        if dy != 0:
            edge_x = x0 + (y - y0) * dx / dy
            inside ^= crosses & (x < edge_x)
        cross_product = (x - x0) * dy - (y - y0) * dx
        boundary |= (
            (np.abs(cross_product) <= 1e-10)
            & (x >= min(x0, x1) - 1e-12)
            & (x <= max(x0, x1) + 1e-12)
            & (y >= min(y0, y1) - 1e-12)
            & (y <= max(y0, y1) + 1e-12)
        )
        x0, y0 = x1, y1
    return inside | boundary


def main():
    # Integer-based construction prevents cumulative coordinate-step errors.
    longitudes = (np.arange(231, dtype=np.float64) - 45) / 5
    latitudes = (225 - np.arange(71, dtype=np.float64)) / 5
    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((71, 231), dtype=bool)
    for vertices in POLYGONS:
        land |= points_inside(vertices, x, y)
    matrix = land.astype(np.uint8)
    assert matrix.shape == (71, 231) and matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()
    assert (longitudes[0], longitudes[-1]) == (-9, 37)
    assert (latitudes[0], latitudes[-1]) == (45, 31)

    out = Path.cwd() / 'outputs'
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / 'candidate.csv'
    with csv_path.open('w', newline='', encoding='utf-8') as handle:
        csv.writer(handle, lineterminator='\n').writerows(matrix.tolist())
    image = Image.fromarray(matrix * np.uint8(255))
    nearest = getattr(Image, 'Resampling', Image).NEAREST
    enlarged = image.resize((1848, 568), resample=nearest)
    image.save(out / 'candidate.png')
    enlarged.save(out / 'candidate_8x.png')

    # Validate the saved artifacts themselves, not just the in-memory objects.
    with csv_path.open(newline='', encoding='utf-8') as handle:
        rows = list(csv.reader(handle))
    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in {'0', '1'} for row in rows for value in row)
    assert sum(map(len, rows)) == 16401
    assert np.array_equal(np.asarray(rows, dtype=np.uint8), matrix)
    with Image.open(out / 'candidate.png') as saved:
        assert saved.size == (231, 71)
        raw_pixels = np.array(saved)
    with Image.open(out / 'candidate_8x.png') as saved:
        assert saved.size == (1848, 568)
        big_pixels = np.array(saved)
    assert set(np.unique(raw_pixels).tolist()) == {0, 255}
    assert set(np.unique(big_pixels).tolist()) == {0, 255}
    assert np.array_equal(raw_pixels, matrix * np.uint8(255))
    expected = np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(big_pixels, expected), 'Not exact nearest-neighbor 8x'
    print(json.dumps({
        'validation': 'passed', 'matrix_shape': list(matrix.shape),
        'valid_values': int(matrix.size), 'land_points': int(matrix.sum()),
        'water_points': int(matrix.size - matrix.sum()),
        'raw_png_size': [231, 71], 'enlarged_png_size': [1848, 568],
        'png_values': [0, 255], 'exact_nearest_neighbor_8x': True,
        'method': 'hand-written memory-only polygons; point-in-polygon union',
        'polygon_count': len(POLYGONS)
    }, ensure_ascii=False))


if __name__ == '__main__':
    main()
