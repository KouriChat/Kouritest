"""Memory-only approximate world land reconstruction.

Dependencies: Python 3, numpy, Pillow. Run from any working directory.
No maps, geographic datasets, network access or external inputs are used.
All geographic rules below were handwritten from existing geographic knowledge.
Classification is polygon rasterization, NOT independent reasoning at each point.
Lakes are deliberately not subtracted; ocean gulfs/straits remain water.
Floating ice shelves are excluded approximately at their grounding lines.
"""
