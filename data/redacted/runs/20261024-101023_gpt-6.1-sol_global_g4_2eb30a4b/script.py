LATITUDES = np.arange(89, -90, -2, dtype=np.int16)
LONGITUDES = np.arange(-179, 180, 2, dtype=np.int16)
X, Y = np.meshgrid(LONGITUDES.astype(float), LATITUDES.astype(float))
LAND = np.zeros((90, 180), dtype=bool)
RULES = []


def polygon_mask(text):
    vertices = [tuple(map(float, p.split(","))) for p in text.split()]
    if len(vertices) < 3:
        raise ValueError("A polygon needs at least three vertices")
    result = np.zeros_like(LAND)
    # Longitude shifts also cover polygons crossing the antimeridian.
    for shift in (0, -360, 360):
        xx = X + shift
        hit = np.zeros_like(LAND)
        on_edge = np.zeros_like(LAND)
        ax, ay = vertices[-1]
        for bx, by in vertices:
            crossing = ((ay > Y) != (by > Y))
            if by != ay:
                cut_x = ax + (Y - ay) * (bx - ax) / (by - ay)
                hit ^= crossing & (xx < cut_x)
            cross = (xx - ax) * (by - ay) - (Y - ay) * (bx - ax)
            on_edge |= ((np.abs(cross) < 1e-9)
                        & (xx >= min(ax, bx)) & (xx <= max(ax, bx))
                        & (Y >= min(ay, by)) & (Y <= max(ay, by)))
            ax, ay = bx, by
        result |= hit | on_edge
    return result


def add(name, text):
    LAND[:] |= polygon_mask(text)
    RULES.append(("land", name))


def subtract(name, text):
    LAND[:] &= ~polygon_mask(text)
    RULES.append(("ocean", name))


