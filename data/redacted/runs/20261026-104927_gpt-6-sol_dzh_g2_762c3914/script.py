def point_on_segment(px, py, ax, ay, bx, by, eps=1e-10):
    cross = (px - ax) * (by - ay) - (py - ay) * (bx - ax)
    if abs(cross) > eps:
        return False
    return (min(ax, bx) - eps <= px <= max(ax, bx) + eps and
            min(ay, by) - eps <= py <= max(ay, by) + eps)


def point_in_polygon(lon, lat, polygon):
    inside = False
    for i, (ax, ay) in enumerate(polygon):
        bx, by = polygon[(i + 1) % len(polygon)]
        if point_on_segment(lon, lat, ax, ay, bx, by):
            return True
        if (ay > lat) != (by > lat):
            crossing_lon = ax + (lat - ay) * (bx - ax) / (by - ay)
            if lon < crossing_lon:
                inside = not inside
    return inside


def classify(lon, lat):
    return int(any(point_in_polygon(lon, lat, polygon)
                   for polygon in ALL_POLYGONS))


def generate_matrix():
    latitudes = [45.0 - 0.2 * i for i in range(71)]
    longitudes = [-9.0 + 0.2 * j for j in range(231)]
    matrix = np.zeros((71, 231), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = classify(lon, lat)
    return matrix


