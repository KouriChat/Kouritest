WEST = 105.0 - np.arange(241, dtype=np.float64) / 10
NORTH = 79.0 - np.arange(61, dtype=np.float64) / 10
X, Y = np.meshgrid(WEST, NORTH)
LAND = []
SEA = []

def land(name, vertices):
    LAND.append((name, vertices))

