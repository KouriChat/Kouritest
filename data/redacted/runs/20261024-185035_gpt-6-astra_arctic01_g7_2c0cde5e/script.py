"""Knowledge-only approximation of the Canadian Arctic Archipelago.

No map files, geographic databases, network access, or reference labels.
All coast vertices below were manually estimated from geographic knowledge.
Coordinates in the rules are (degrees WEST, degrees NORTH).
The classification is polygon membership, not independent point reasoning.
Land polygons include inland lakes and land ice; sea ice remains water.
Run: python outputs/generate_map.py
Dependencies: numpy, Pillow.
"""
