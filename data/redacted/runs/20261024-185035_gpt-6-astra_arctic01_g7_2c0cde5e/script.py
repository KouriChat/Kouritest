def contains(vertices):
    """Vectorized ray crossing at the exact sample coordinates."""
    inside = np.zeros(X.shape, dtype=bool)
    boundary = np.zeros(X.shape, dtype=bool)
    xa, ya = vertices[-1]
    for xb, yb in vertices:
        dx, dy = xb - xa, yb - ya
        cross = (X - xa) * dy - (Y - ya) * dx
        on_segment = (
            (np.abs(cross) < 1e-10)
            & (X >= min(xa, xb) - 1e-10)
            & (X <= max(xa, xb) + 1e-10)
            & (Y >= min(ya, yb) - 1e-10)
            & (Y <= max(ya, yb) + 1e-10)
        )
        boundary |= on_segment
        if dy != 0:
            crossing = ((ya > Y) != (yb > Y))
            intersection = xa + (Y - ya) * dx / dy
            inside ^= crossing & (X < intersection)
        xa, ya = xb, yb
    return inside | boundary

