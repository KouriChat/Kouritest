def point_in_polygon(x, y, polygon):
    inside = False
    n = len(polygon)
    j = n - 1
    for i in range(n):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        crosses = ((yi > y) != (yj > y))
        if crosses:
            x_intersection = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < x_intersection:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    for polygon in POLYGONS:
        if point_in_polygon(lon, lat, polygon):
            return 1
    for polygon in ISLANDS:
        if point_in_polygon(lon, lat, polygon):
            return 1
    return 0


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    longitudes = list(range(-179, 180, 2))
    latitudes = list(range(89, -90, -2))

    matrix = np.zeros((90, 180), dtype=np.uint8)

    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = is_land(lon, lat)

    assert matrix.shape == (90, 180)
    assert matrix.size == 16200
    assert set(np.unique(matrix)).issubset({0, 1})

    csv_path = output_dir / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        for row in matrix:
            writer.writerow([int(value) for value in row])

    # White = land, black = water.
    image_array = np.where(matrix == 1, 255, 0).astype(np.uint8)
    image = Image.fromarray(image_array, mode="L")

    assert image.size == (180, 90)
    assert set(image.getdata()).issubset({0, 255})

    raw_path = output_dir / "candidate.png"
    image.save(raw_path, format="PNG")

    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    assert enlarged.size == (1440, 720)
    assert set(enlarged.getdata()).issubset({0, 255})

    enlarged_path = output_dir / "candidate_8x.png"
    enlarged.save(enlarged_path, format="PNG")

    print(f"CSV: {csv_path}")
    print(f"Raw PNG: {raw_path}")
    print(f"Nearest-neighbor PNG: {enlarged_path}")
    print(f"Matrix shape: {matrix.shape}")
    print(f"Valid values: {matrix.size}")
    print(f"Land cells: {int(matrix.sum())}")
    print(f"Water cells: {int(matrix.size - matrix.sum())}")


if __name__ == "__main__":
    main()
