def point_in_polygon(x, y, polygon):
    """Ray-casting test; points exactly on a segment count as land."""
    inside = False
    n = len(polygon)
    for i in range(n):
        x1, y1 = polygon[i]
        x2, y2 = polygon[(i + 1) % n]

        cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
        if abs(cross) < 1e-10 and min(x1, x2) - 1e-10 <= x <= max(x1, x2) + 1e-10:
            if min(y1, y2) - 1e-10 <= y <= max(y1, y2) + 1e-10:
                return True

        if (y1 > y) != (y2 > y):
            crossing_x = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < crossing_x:
                inside = not inside
    return inside


def main():
    longitudes = np.round(np.arange(WEST, EAST + STEP / 2, STEP), 10)
    latitudes = np.round(np.arange(NORTH, SOUTH - STEP / 2, -STEP), 10)
    matrix = np.zeros((len(latitudes), len(longitudes)), dtype=np.uint8)

    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = int(
                any(point_in_polygon(lon, lat, polygon)
                    for polygon in LAND_POLYGONS)
            )

    if matrix.shape != (71, 231):
        raise ValueError(f"Unexpected matrix shape: {matrix.shape}")

    os.makedirs("outputs", exist_ok=True)
    with open("outputs/candidate.csv", "w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Matrix value 1 is white land; 0 is black water.
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save("outputs/candidate.png")

    enlarged = image.resize(
        (image.width * SCALE, image.height * SCALE),
        resample=Image.Resampling.NEAREST,
    )
    enlarged.save("outputs/candidate_8x.png")


if __name__ == "__main__":
    main()
