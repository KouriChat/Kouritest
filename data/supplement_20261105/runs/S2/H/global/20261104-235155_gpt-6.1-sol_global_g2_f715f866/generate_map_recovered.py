def contains(lon, lat, polygon):
    """Return whether a point lies inside a polygon using ray casting."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing_lon = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing_lon:
                inside = not inside
        j = i
    return inside


def classify(lon, lat):
    if any(contains(lon, lat, polygon) for polygon in WATER_POLYGONS):
        return 0
    return int(any(contains(lon, lat, polygon) for polygon in LAND_POLYGONS))


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    latitudes = range(89, -90, -2)
    longitudes = range(-179, 180, 2)
    matrix = np.array(
        [[classify(lon, lat) for lon in longitudes] for lat in latitudes],
        dtype=np.uint8,
    )

    assert matrix.shape == (90, 180)
    assert int(matrix.size) == 16200
    assert np.isin(matrix, (0, 1)).all()

    with (output_dir / "candidate.csv").open("w", encoding="ascii", newline="") as f:
        for row in matrix:
            f.write(",".join(map(str, row.tolist())) + "\n")

    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
