def point_in_polygon(lon, lat, polygon):
    """Ray-casting point-in-polygon test."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        crosses = (yi > lat) != (yj > lat)
        if crosses:
            x_intersection = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < x_intersection:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    land = any(point_in_polygon(lon, lat, p) for p in LAND_POLYGONS)
    if land and any(point_in_polygon(lon, lat, p) for p in WATER_POLYGONS):
        return False
    return land


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    latitudes = np.arange(89, -90, -2, dtype=int)
    longitudes = np.arange(-179, 180, 2, dtype=int)

    matrix = np.zeros((90, 180), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = 1 if is_land(float(lon), float(lat)) else 0

    # Headerless CSV; each row contains exactly 180 binary values.
    np.savetxt(output_dir / "candidate.csv", matrix, fmt="%d", delimiter=",")

    # Black water (0), white land (255); row 0 is northernmost.
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
