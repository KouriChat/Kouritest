def point_on_segment(x, y, x1, y1, x2, y2, eps=1e-10):
    cross = (x - x1) * (y2 - y1) - (y - y1) * (x2 - x1)
    if abs(cross) > eps:
        return False
    return (
        min(x1, x2) - eps <= x <= max(x1, x2) + eps
        and min(y1, y2) - eps <= y <= max(y1, y2) + eps
    )


def point_in_polygon(lon, lat, polygon):
    inside = False
    for i in range(len(polygon) - 1):
        x1, y1 = polygon[i]
        x2, y2 = polygon[i + 1]

        if point_on_segment(lon, lat, x1, y1, x2, y2):
            return True

        if (y1 > lat) != (y2 > lat):
            crossing_lon = x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
            if lon < crossing_lon:
                inside = not inside

    return inside


def is_land(lon, lat):
    return any(point_in_polygon(lon, lat, polygon) for polygon in LAND_POLYGONS)


def main():
    latitudes = [23.0 - 0.2 * i for i in range(111)]
    longitudes = [99.0 + 0.2 * j for j in range(141)]

    matrix = np.zeros((111, 141), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = 1 if is_land(lon, lat) else 0

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 0 -> 黑色水域，1 -> 白色陆地
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")

    enlarged = image.resize((141 * 8, 111 * 8), resample=Image.Resampling.NEAREST)
    enlarged.save(output_dir / "candidate_8x.png")

    # 对输出尺寸和矩阵内容做基本校验
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert set(np.unique(matrix)).issubset({0, 1})
    assert image.size == (141, 111)
    assert set(image.getdata()).issubset({0, 255})
    assert enlarged.size == (1128, 888)


if __name__ == "__main__":
    main()
