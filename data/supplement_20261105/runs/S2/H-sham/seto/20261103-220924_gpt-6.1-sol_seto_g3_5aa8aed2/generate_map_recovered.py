def point_in_polygon(lon, lat, polygon):
    """射线法判断点是否位于多边形内。"""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        crosses = (yi > lat) != (yj > lat)
        if crosses:
            x_cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < x_cross:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    land = any(point_in_polygon(lon, lat, p) for p in LAND_POLYGONS)
    if not land:
        return False

    if any(point_in_polygon(lon, lat, p) for p in WATER_POLYGONS):
        # 志摩半岛内的水域扣除优先；岛屿会在下方重新添加。
        return False

    return True


def main():
    lons = LON_MIN + np.arange(WIDTH, dtype=np.float64) * STEP
    lats = LAT_MAX - np.arange(HEIGHT, dtype=np.float64) * STEP

    matrix = np.zeros((HEIGHT, WIDTH), dtype=np.uint8)
    for row, lat in enumerate(lats):
        for col, lon in enumerate(lons):
            matrix[row, col] = 1 if is_land(float(lon), float(lat)) else 0

    # 岛屿在水域扣除之后重新判定，避免湾区掩膜吞掉岛屿。
    for row, lat in enumerate(lats):
        for col, lon in enumerate(lons):
            if any(point_in_polygon(float(lon), float(lat), p)
                   for p in LAND_POLYGONS[8:]):
                matrix[row, col] = 1

    out_dir = Path("outputs")
    out_dir.mkdir(parents=True, exist_ok=True)

    csv_path = out_dir / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as f:
        for row in matrix:
            f.write(",".join(str(int(value)) for value in row) + "\n")

    # Pillow 的 L 模式：0 为黑色水域，255 为白色陆地。
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out_dir / "candidate.png")
    enlarged = image.resize((WIDTH * 8, HEIGHT * 8), resample=Image.Resampling.NEAREST)
    enlarged.save(out_dir / "candidate_8x.png")

    # 对输出形状、值域、CSV 和图片进行基本校验。
    assert matrix.shape == (64, 253)
    assert matrix.size == 16192
    assert set(np.unique(matrix).tolist()) <= {0, 1}

    lines = csv_path.read_text(encoding="ascii").splitlines()
    assert len(lines) == 64
    assert all(len(line.split(",")) == 253 for line in lines)
    assert all(value in {"0", "1"} for line in lines for value in line.split(","))

    assert image.size == (253, 64)
    assert set(image.getdata()) <= {0, 255}
    assert enlarged.size == (2024, 512)
    assert set(enlarged.getdata()) <= {0, 255}

    print(f"Generated {matrix.shape[0]} x {matrix.shape[1]} matrix ({matrix.size} values)")
    print(f"CSV: {csv_path}")
    print(f"PNG: {out_dir / 'candidate.png'} ({WIDTH} x {HEIGHT})")
    print(f"8x PNG: {out_dir / 'candidate_8x.png'} ({WIDTH * 8} x {HEIGHT * 8})")


if __name__ == "__main__":
    main()
