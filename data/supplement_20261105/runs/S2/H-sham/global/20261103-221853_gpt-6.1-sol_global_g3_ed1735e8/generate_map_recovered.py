def point_in_polygon(lon, lat, polygon):
    """Ray-casting point-in-polygon test."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing_lon = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing_lon:
                inside = not inside
        j = i
    return inside


def is_land(lon, lat):
    land = any(point_in_polygon(lon, lat, p) for p in LAND_POLYGONS)
    if land and any(point_in_polygon(lon, lat, p) for p in LAKE_POLYGONS):
        return 0
    return int(land)


def main():
    out_dir = Path("outputs")
    out_dir.mkdir(parents=True, exist_ok=True)

    latitudes = range(89, -90, -2)
    longitudes = range(-179, 180, 2)
    matrix = np.array(
        [[is_land(lon, lat) for lon in longitudes] for lat in latitudes],
        dtype=np.uint8,
    )

    if matrix.shape != (90, 180) or matrix.size != 16200:
        raise RuntimeError(f"Unexpected matrix shape: {matrix.shape}")
    if not np.isin(matrix, (0, 1)).all():
        raise RuntimeError("Matrix contains values other than 0 and 1")

    with (out_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Land is white (255), water is black (0).
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(out_dir / "candidate.png")

    enlarged = image.resize((1440, 720), resample=Image.Resampling.NEAREST)
    enlarged.save(out_dir / "candidate_8x.png")

    # Reopen outputs to verify dimensions and palette.
    with (out_dir / "candidate.csv").open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    if len(rows) != 90 or any(len(row) != 180 for row in rows):
        raise RuntimeError("CSV dimensions are not 90x180")
    if any(value not in {"0", "1"} for row in rows for value in row):
        raise RuntimeError("CSV contains an invalid value")

    original = Image.open(out_dir / "candidate.png")
    scaled = Image.open(out_dir / "candidate_8x.png")
    if original.size != (180, 90) or scaled.size != (1440, 720):
        raise RuntimeError("Unexpected PNG dimensions")
    if not set(original.getdata()).issubset({0, 255}):
        raise RuntimeError("Original image is not strictly black and white")
    if scaled.resize((180, 90), Image.Resampling.NEAREST).tobytes() != original.tobytes():
        raise RuntimeError("Enlarged image does not preserve nearest-neighbor pixels")

    print("Validated 90x180 matrix (16,200 values), black/white PNGs, and 8x nearest-neighbor output.")


if __name__ == "__main__":
    main()
