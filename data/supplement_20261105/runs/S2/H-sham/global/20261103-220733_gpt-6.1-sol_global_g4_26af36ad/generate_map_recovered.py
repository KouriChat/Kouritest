def points_in_polygon(lon_grid, lat_grid, polygon):
    """Return a mask for grid points inside a polygon using ray casting."""
    x = lon_grid
    y = lat_grid
    inside = np.zeros(x.shape, dtype=bool)

    for i in range(len(polygon)):
        x1, y1 = polygon[i]
        x2, y2 = polygon[(i + 1) % len(polygon)]
        crosses = (y1 > y) != (y2 > y)
        denominator = y2 - y1
        if denominator != 0:
            x_intersection = (x2 - x1) * (y - y1) / denominator + x1
            inside ^= crosses & (x < x_intersection)

    return inside


def main():
    latitudes = np.arange(89, -90, -2, dtype=np.float64)
    longitudes = np.arange(-179, 180, 2, dtype=np.float64)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)

    land = np.zeros((90, 180), dtype=bool)
    for polygon in POLYGONS:
        land |= points_in_polygon(lon_grid, lat_grid, polygon)

    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    with (output_dir / "candidate.csv").open("w", newline="") as csv_file:
        writer = csv.writer(csv_file, lineterminator="\n")
        writer.writerows(land.astype(np.uint8).tolist())

    # Mode "L": land is white (255), water is black (0).
    image = Image.fromarray(land.astype(np.uint8) * 255, mode="L")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
