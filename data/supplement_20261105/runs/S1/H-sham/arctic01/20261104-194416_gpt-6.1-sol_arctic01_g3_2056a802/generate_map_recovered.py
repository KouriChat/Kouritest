def point_in_polygon(x, y, vertices):
    """
    射线交点奇偶法，直接判断每个经纬度采样点。
    陆地外轮廓边界计为陆地；扣除海水轮廓时，其边界计为水域。
    不涉及格子面积、邻点投票、插值或图像后处理。
    """
    points = tuple(vertices)
    if len(points) < 3:
        raise ValueError("Each polygon must have at least three vertices.")

    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    tolerance = 1.0e-10

    for (x0, y0), (x1, y1) in zip(
        points, points[1:] + points[:1]
    ):
        dx = x1 - x0
        dy = y1 - y0

        if abs(dx) + abs(dy) < tolerance:
            continue

        cross_product = (x - x0) * dy - (y - y0) * dx
        on_segment = (
            (np.abs(cross_product) <= tolerance)
            & (x >= min(x0, x1) - tolerance)
            & (x <= max(x0, x1) + tolerance)
            & (y >= min(y0, y1) - tolerance)
            & (y <= max(y0, y1) + tolerance)
        )
        boundary |= on_segment

        if abs(dy) > tolerance:
            crosses_row = (y0 > y) != (y1 > y)
            intersection_x = x0 + (y - y0) * dx / dy
            inside ^= crosses_row & (x < intersection_x)

    return inside | boundary


def generate_matrix():
    # 整数刻度除以 10，避免反复累加 0.1 导致坐标漂移。
    latitudes = (790 - np.arange(61, dtype=np.int32)) / 10.0
    longitudes = (-1050 + np.arange(241, dtype=np.int32)) / 10.0
    longitude_grid, latitude_grid = np.meshgrid(longitudes, latitudes)

    assert latitudes.shape == (61,)
    assert longitudes.shape == (241,)
    assert latitudes[0] == 79.0 and latitudes[-1] == 73.0
    assert longitudes[0] == -105.0 and longitudes[-1] == -81.0
    assert longitude_grid.shape == latitude_grid.shape == (61, 241)

    names = [name for name, _ in LAND_POLYGONS]
    assert len(names) == len(set(names)), "Duplicate island names."
    assert set(MARINE_CUTS).issubset(set(names))

    land = np.zeros((61, 241), dtype=bool)

    for name, coastline in LAND_POLYGONS:
        island = point_in_polygon(
            longitude_grid, latitude_grid, coastline
        )
        for marine_polygon in MARINE_CUTS.get(name, []):
            island &= ~point_in_polygon(
                longitude_grid, latitude_grid, marine_polygon
            )
        land |= island

    matrix = land.astype(np.uint8)

    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, [0, 1]).all()
    return matrix


def write_outputs(matrix, output_dir):
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "candidate.csv"
    png_path = output_dir / "candidate.png"
    enlarged_path = output_dir / "candidate_8x.png"

    with csv_path.open("w", encoding="ascii", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 严格逐点映射：0 -> 黑色 0，1 -> 白色 255。
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    assert original.mode == "L"
    assert original.size == (241, 61)
    original.save(png_path, format="PNG")

    resampling = getattr(Image, "Resampling", Image)
    enlarged = original.resize(
        (241 * 8, 61 * 8),
        resample=resampling.NEAREST,
    )
    enlarged.save(enlarged_path, format="PNG")

    return csv_path, png_path, enlarged_path


def verify_outputs(matrix, csv_path, png_path, enlarged_path):
    # 以下只回读本脚本刚写出的结果，不读取任何外部地图或答案。
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))

    assert len(rows) == 61, "CSV must contain exactly 61 rows."
    assert all(len(row) == 241 for row in rows), (
        "Every CSV row must contain exactly 241 values."
    )
    assert all(
        value in ("0", "1")
        for row in rows
        for value in row
    ), "CSV must contain only literal 0 and 1, with no blanks."

    csv_matrix = np.array(
        [[int(value) for value in row] for row in rows],
        dtype=np.uint8,
    )
    assert csv_matrix.shape == (61, 241)
    assert csv_matrix.size == 14701
    assert np.array_equal(csv_matrix, matrix)

    expected_pixels = matrix * np.uint8(255)

    with Image.open(png_path) as image:
        assert image.format == "PNG"
        assert image.mode == "L"
        assert image.size == (241, 61)
        original_pixels = np.array(image)

    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, expected_pixels)

    with Image.open(enlarged_path) as image:
        assert image.format == "PNG"
        assert image.mode == "L"
        assert image.size == (1928, 488)
        enlarged_pixels = np.array(image)

    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}

    # 每个源像素必须恰好复制为一个同色 8×8 块。
    expected_enlarged = np.repeat(
        np.repeat(expected_pixels, 8, axis=0),
        8,
        axis=1,
    )
    assert enlarged_pixels.shape == (488, 1928)
    assert np.array_equal(enlarged_pixels, expected_enlarged), (
        "The enlarged PNG must be an exact nearest-neighbor 8x enlargement."
    )

    # 再检查行列方向及最近邻采样对应关系。
    assert np.array_equal(
        enlarged_pixels[0::8, 0::8],
        original_pixels,
    )

    land_count = int(matrix.sum())
    water_count = int(matrix.size - land_count)
    assert land_count + water_count == 14701

    print("Validation passed.")
    print("Matrix: 61 rows x 241 columns = 14,701 valid binary values.")
    print("Order: north to south, west to east.")
    print(f"Land points: {land_count}; water points: {water_count}.")
    print("Original PNG: 241 x 61; colors: black and white only.")
    print("Enlarged PNG: 1928 x 488; exact nearest-neighbor 8x.")
    print(f"CSV: {csv_path}")
    print(f"Original PNG: {png_path}")
    print(f"Enlarged PNG: {enlarged_path}")


def main():
    matrix = generate_matrix()
    output_dir = Path.cwd() / "outputs"
    paths = write_outputs(matrix, output_dir)
    verify_outputs(matrix, *paths)


if __name__ == "__main__":
    main()
