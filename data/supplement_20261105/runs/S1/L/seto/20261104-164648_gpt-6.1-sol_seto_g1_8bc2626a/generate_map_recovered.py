def points_in_polygon(xs, ys, vertices):
    """
    向右射线奇偶规则，直接判断采样坐标点。
    不做像元面积平均、不做多数表决、不做轮廓修补。
    """
    inside = np.zeros(xs.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crosses = (y0 > ys) != (y1 > ys)
            x_intersection = x0 + (ys - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (xs < x_intersection)
        x0, y0 = x1, y1
    return inside


def generate_matrix():
    # 使用精确的 2/63 度间隔，而非题目示例中的舍入坐标。
    longitudes = 129.0 + np.arange(253, dtype=np.float64) * (2.0 / 63.0)
    latitudes = 35.0 - np.arange(64, dtype=np.float64) * (2.0 / 63.0)
    xs, ys = np.meshgrid(longitudes, latitudes)

    result = np.zeros((64, 253), dtype=bool)
    for polygon in LAND_POLYGONS:
        result |= points_in_polygon(xs, ys, polygon)
    for polygon in WATER_POLYGONS:
        result &= ~points_in_polygon(xs, ys, polygon)

    assert longitudes[0] == 129.0
    assert longitudes[-1] == 137.0
    assert latitudes[0] == 35.0
    assert latitudes[-1] == 33.0
    return result.astype(np.uint8)


