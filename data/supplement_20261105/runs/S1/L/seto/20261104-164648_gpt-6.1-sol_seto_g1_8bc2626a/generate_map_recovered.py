def island(cx, cy, rx, ry, angle=0.0, n=24):
    """手写中心、半轴和方向的椭圆形近似岛屿。"""
    a = math.radians(angle)
    ca, sa = math.cos(a), math.sin(a)
    points = []
    for k in range(n):
        t = 2.0 * math.pi * k / n
        u, v = rx * math.cos(t), ry * math.sin(t)
        points.append((cx + ca*u - sa*v, cy + sa*u + ca*v))
    land(points)


