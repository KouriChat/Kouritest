# 其余能凭记忆定位的岛屿。使用手写椭圆近似轮廓，
# 并用与其他多边形相同的点判据计算。
def ellipse(name, lon, lat, radius_lon, radius_lat, count=24):
    angles = np.arange(count) * (2.0 * np.pi / count)
    vertices = [
        (lon + radius_lon * np.cos(a),
         lat + radius_lat * np.sin(a))
        for a in angles
    ]
    add(name, vertices)


