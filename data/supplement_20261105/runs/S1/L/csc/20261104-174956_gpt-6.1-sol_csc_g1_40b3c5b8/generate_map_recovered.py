def points_in_polygon(x, y, vertices):
    """射线法批量点判定；边界上的点归入陆地。"""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    eps = 1e-10

    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        dx = x2 - x1
        dy = y2 - y1

        cross = (x - x1) * dy - (y - y1) * dx
        on_segment = (
            (np.abs(cross) <= eps)
            & (x >= min(x1, x2) - eps)
            & (x <= max(x1, x2) + eps)
            & (y >= min(y1, y2) - eps)
            & (y <= max(y1, y2) + eps)
        )
        boundary |= on_segment

        if dy != 0:
            crosses_y = (y1 > y) != (y2 > y)
            intersection_x = x1 + (y - y1) * dx / dy
            inside ^= crosses_y & (x < intersection_x)

        x1, y1 = x2, y2

    return inside | boundary


def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    # 用整数刻度构建坐标，避免累加 0.2 导致步长漂移。
    latitudes = np.arange(115, 4, -1, dtype=np.int64) / 5.0
    longitudes = np.arange(495, 636, dtype=np.int64) / 5.0
    assert len(latitudes) == 111
    assert len(longitudes) == 141
    assert latitudes[0] == 23.0 and latitudes[-1] == 1.0
    assert longitudes[0] == 99.0 and longitudes[-1] == 127.0

    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((111, 141), dtype=bool)

    for _, polygon in POLYGONS:
        land |= points_in_polygon(x, y, polygon)

    # 内陆湖泊按任务定义仍为陆地，因此不挖除湖泊。
    matrix = land.astype(np.uint8)
    assert matrix.shape == (111, 141)
    assert matrix.size == 15651
    assert np.isin(matrix, [0, 1]).all()

    csv_path = output_dir / "candidate.csv"
    with csv_path.open("w", encoding="ascii", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

