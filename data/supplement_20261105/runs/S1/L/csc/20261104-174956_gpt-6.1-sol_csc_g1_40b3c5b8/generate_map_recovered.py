# 仅在点确实进入所写的小轮廓时计陆地；不将整个群岛海域填成陆地。
def add_ellipse(name, cx, cy, rx, ry, vertices=16):
    angles = np.arange(vertices, dtype=float) * (2 * np.pi / vertices)
    add(name, [
        (cx + rx * np.cos(a), cy + ry * np.sin(a))
        for a in angles
    ])


