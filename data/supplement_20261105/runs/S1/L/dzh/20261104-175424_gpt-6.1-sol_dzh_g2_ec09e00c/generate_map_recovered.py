def points_in_polygon(x, y, vertices):
    """射线法批量判断点是否在多边形内，不做格子面积平均。"""
    inside = np.zeros(x.shape, dtype=bool)
    xj, yj = vertices[-1]
    for xi, yi in vertices:
        if yi != yj:
            crossing = ((yi > y) != (yj > y))
            x_intersection = xi + (y - yi) * (xj - xi) / (yj - yi)
            inside ^= crossing & (x < x_intersection)
        xj, yj = xi, yi
    return inside


def main():
    # 用整数刻度构造采样坐标，避免浮点累加导致行列数量变化。
    longitudes = np.arange(-45, 186, dtype=np.int64) / 5.0
    latitudes = np.arange(225, 154, -1, dtype=np.int64) / 5.0
    assert longitudes.size == 231
    assert latitudes.size == 71
    assert longitudes[0] == -9 and longitudes[-1] == 37
    assert latitudes[0] == 45 and latitudes[-1] == 31

    x, y = np.meshgrid(longitudes, latitudes)
    land = np.zeros((71, 231), dtype=bool)
    for polygon in LAND:
        land |= points_in_polygon(x, y, polygon)
    matrix = land.astype(np.uint8)

    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert np.isin(matrix, [0, 1]).all()

