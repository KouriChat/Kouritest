    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "candidate.csv"
    original_path = output_dir / "candidate.png"
    enlarged_path = output_dir / "candidate_8x.png"

    matrix = make_matrix()

    with csv_path.open("w", newline="", encoding="ascii") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 行方向直接对应北→南，列方向直接对应西→东。
    # 陆地 1 → 白色 255；水域 0 → 黑色 0。
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(original_path, format="PNG")

    # 兼容较新和较旧的 Pillow 版本。
    nearest = (
        Image.Resampling.NEAREST
        if hasattr(Image, "Resampling")
        else Image.NEAREST
    )
    enlarged = original.resize((1848, 568), resample=nearest)
    enlarged.save(enlarged_path, format="PNG")

    verify_outputs(matrix, csv_path, original_path, enlarged_path)
    for path in (csv_path, original_path, enlarged_path):
        print(path)


