def points_in_polygon(x, y, vertices):
    """射线法，直接判断采样点；没有格子面积平均或多数表决。"""
    inside = np.zeros(x.shape, dtype=bool)
    xj, yj = vertices[-1]
    for xi, yi in vertices:
        if yi != yj:
            crosses = (yi > y) != (yj > y)
            intersection_x = xi + (y - yi) * (xj - xi) / (yj - yi)
            inside ^= crosses & (x < intersection_x)
        xj, yj = xi, yi
    return inside


def make_matrix():
    # 整数生成坐标，避免浮点 arange 的端点或行列数量误差。
    longitude = np.arange(-90, 371, 2, dtype=np.int32) / 10.0
    latitude = np.arange(450, 309, -2, dtype=np.int32) / 10.0
    x, y = np.meshgrid(longitude, latitude)

    assert longitude.shape == (231,)
    assert latitude.shape == (71,)
    assert longitude[0] == -9 and longitude[-1] == 37
    assert latitude[0] == 45 and latitude[-1] == 31

    land = points_in_polygon(x, y, EURASIA)
    land |= points_in_polygon(x, y, AFRICA)

    for sea in (BLACK_SEA, MARMARA, DARDANELLES, BOSPHORUS):
        land &= ~points_in_polygon(x, y, sea)

    # 岛屿最后加入，允许海域扣除轮廓内部存在岛屿。
    for island in ISLANDS:
        land |= points_in_polygon(x, y, island)

    return land.astype(np.uint8)


def verify_outputs(matrix, csv_path, original_path, enlarged_path):
    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert np.isin(matrix, (0, 1)).all()

    with csv_path.open("r", newline="", encoding="ascii") as handle:
        rows = list(csv.reader(handle))

    assert len(rows) == 71
    assert all(len(row) == 231 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)

    loaded = np.array([[int(value) for value in row] for row in rows],
                      dtype=np.uint8)
    assert np.array_equal(loaded, matrix)

    with Image.open(original_path) as image:
        assert image.format == "PNG"
        assert image.mode == "L"
        assert image.size == (231, 71)
        original = np.asarray(image).copy()

    with Image.open(enlarged_path) as image:
        assert image.format == "PNG"
        assert image.mode == "L"
        assert image.size == (1848, 568)
        enlarged = np.asarray(image).copy()

    assert set(np.unique(original).tolist()) == {0, 255}
    assert set(np.unique(enlarged).tolist()) == {0, 255}
    assert np.array_equal(original, matrix * np.uint8(255))

    # 逐像素验证：每个原像素恰好对应一个 8×8 的同色块。
    expected = np.repeat(np.repeat(original, 8, axis=0), 8, axis=1)
    assert np.array_equal(enlarged, expected)

    print("验证通过：71×231 = 16401 个有效二值采样点；CSV 无表头、无空缺。")
    print("验证通过：原图 231×71；放大图 1848×568；仅黑白；严格最近邻放大。")
    print(f"陆地点数：{int(matrix.sum())}")
    print(f"水域点数：{int(matrix.size - matrix.sum())}")


