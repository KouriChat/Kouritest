def inside_polygon(x, y, vertices):
    """向量化奇偶射线法；x、y 为相同形状的采样网格。"""
    inside = np.zeros(x.shape, dtype=bool)
    x0, y0 = vertices[-1]
    for x1, y1 in vertices:
        if y1 != y0:
            crosses = ((y0 > y) != (y1 > y))
            intersection_x = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            inside ^= crosses & (x < intersection_x)
        x0, y0 = x1, y1
    return inside


