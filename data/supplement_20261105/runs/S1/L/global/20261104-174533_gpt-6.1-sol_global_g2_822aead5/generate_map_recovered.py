def inside_polygon(x, y, polygon):
    """Vectorized even-odd point-in-polygon classification."""
    result = np.zeros(x.shape, dtype=bool)
    xj, yj = polygon[-1]
    for xi, yi in polygon:
        if yi != yj:
            cross = ((yi > y) != (yj > y))
            x_intersection = (xj - xi) * (y - yi) / (yj - yi) + xi
            result ^= cross & (x < x_intersection)
        xj, yj = xi, yi
    return result

def main():
    out = Path("outputs")
    out.mkdir(parents=True, exist_ok=True)

    latitudes = np.arange(89, -90, -2, dtype=np.int16)
    longitudes = np.arange(-179, 180, 2, dtype=np.int16)
    lon, lat = np.meshgrid(longitudes, latitudes)
    land = np.zeros((90, 180), dtype=bool)

    for polygon in LAND:
        land |= inside_polygon(lon, lat, polygon)
    for polygon in WATER:
        land &= ~inside_polygon(lon, lat, polygon)

    matrix = land.astype(np.uint8)
    assert matrix.shape == (90, 180)
    assert matrix.size == 16200
    assert np.isin(matrix, [0, 1]).all()

    csv_path = out / "candidate.csv"
    with csv_path.open("w", newline="", encoding="ascii") as f:
        csv.writer(f, lineterminator="\n").writerows(matrix.tolist())

    raw = Image.fromarray(matrix * 255)
    raw.save(out / "candidate.png")
    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST
    enlarged = raw.resize((1440, 720), resample=nearest)
    enlarged.save(out / "candidate_8x.png")

    # Validate the actual saved CSV and PNG files.
    with csv_path.open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    assert len(rows) == 90
    assert all(len(row) == 180 for row in rows)
    assert all(v in ("0", "1") for row in rows for v in row)

    with Image.open(out / "candidate.png") as im:
        assert im.size == (180, 90)
        pixels = np.array(im)
        assert set(np.unique(pixels).tolist()) <= {0, 255}
        assert np.array_equal(pixels, matrix * 255)

    with Image.open(out / "candidate_8x.png") as im:
        assert im.size == (1440, 720)
        big_pixels = np.array(im)
        assert set(np.unique(big_pixels).tolist()) <= {0, 255}
        expected = np.repeat(np.repeat(pixels, 8, axis=0), 8, axis=1)
        assert np.array_equal(big_pixels, expected)

    print("Validated: 90 x 180 = 16,200 binary classifications.")
    print("Validated: black/white PNGs, 180 x 90 and 1440 x 720.")
    print("Validated: enlarged image is an exact nearest-neighbor 8x copy.")
    print("Land samples:", int(matrix.sum()))
    for name in ("candidate.csv", "candidate.png", "candidate_8x.png"):
        print(out / name)

if __name__ == "__main__":
    main()
