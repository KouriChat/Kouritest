def points_in_polygon(x, y, vertices):
    """射线法，矢量化判断；边界点归入该多边形。"""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    eps = 1e-11

    for i, (ax, ay) in enumerate(vertices):
        bx, by = vertices[(i + 1) % len(vertices)]
        dx, dy = bx - ax, by - ay

        cross = (x - ax) * dy - (y - ay) * dx
        on_segment = (
            (np.abs(cross) <= eps)
            & (x >= min(ax, bx) - eps)
            & (x <= max(ax, bx) + eps)
            & (y >= min(ay, by) - eps)
            & (y <= max(ay, by) + eps)
        )
        boundary |= on_segment

        if ay != by:
            crosses = (ay > y) != (by > y)
            intersection_x = ax + (y - ay) * dx / dy
            inside ^= crosses & (x < intersection_x)

    return inside | boundary


def create_matrix():
    # 使用精确的 2/126 度步长，题目中的小数坐标仅视为展示舍入。
    latitudes = 55.0 - np.arange(127, dtype=np.float64) * (2.0 / 126.0)
    longitudes = -131.0 + np.arange(127, dtype=np.float64) * (2.0 / 126.0)
    longitude_grid, latitude_grid = np.meshgrid(longitudes, latitudes)

    land = np.zeros((127, 127), dtype=bool)
    for polygon in LAND.values():
        land |= points_in_polygon(longitude_grid, latitude_grid, polygon)

    # 显式水道优先；压在水道边界的点在此近似中取水域。
    for polygon in WATER.values():
        land &= ~points_in_polygon(longitude_grid, latitude_grid, polygon)

    matrix = land.astype(np.uint8)
    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()
    assert latitudes[0] == 55.0 and latitudes[-1] == 53.0
    assert longitudes[0] == -131.0 and longitudes[-1] == -129.0
    return matrix


def verify_outputs(output_dir, matrix):
    csv_path = output_dir / "candidate.csv"
    with csv_path.open("r", encoding="ascii", newline="") as stream:
        rows = list(csv.reader(stream))

    assert len(rows) == 127, "CSV 行数错误"
    assert all(len(row) == 127 for row in rows), "CSV 列数错误"
    assert all(value in ("0", "1") for row in rows for value in row), \
        "CSV 存在非二值或空缺"
    restored = np.array(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix), "CSV 与矩阵不一致"

    with Image.open(output_dir / "candidate.png") as image:
        assert image.size == (127, 127), "原图尺寸错误"
        original_pixels = np.array(image.convert("L"))

    with Image.open(output_dir / "candidate_8x.png") as image:
        assert image.size == (1016, 1016), "放大图尺寸错误"
        enlarged_pixels = np.array(image.convert("L"))

    assert set(np.unique(original_pixels)).issubset({0, 255})
    assert set(np.unique(enlarged_pixels)).issubset({0, 255})
    assert np.array_equal(original_pixels, matrix * 255)

    expected_enlargement = np.repeat(
        np.repeat(original_pixels, 8, axis=0), 8, axis=1
    )
    assert np.array_equal(enlarged_pixels, expected_enlargement), \
        "放大结果不是严格的 8 倍最近邻复制"

    print("验证通过：127×127，共 16,129 个有效二值采样点。")
    print("CSV：127 行，每行 127 个值，无表头、无空缺。")
    print("PNG：仅含黑白；原图 127×127，放大图 1016×1016。")
    print("最近邻验证：每个原始像素严格复制为 8×8 像素块。")
    print(f"陆地点：{int(matrix.sum())}；水域点：{int(matrix.size - matrix.sum())}")


def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    matrix = create_matrix()
    with (output_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 数组行序直接对应北到南，列序直接对应西到东。
    # 灰度值：陆地 255（白），水域 0（黑）。
    original = Image.fromarray(matrix * np.uint8(255))
    original.save(output_dir / "candidate.png")

    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST

    enlarged = original.resize((1016, 1016), resample=nearest)
    enlarged.save(output_dir / "candidate_8x.png")

    verify_outputs(output_dir, matrix)
    for name in ("candidate.csv", "candidate.png", "candidate_8x.png"):
        print(output_dir / name)


if __name__ == "__main__":
    main()
