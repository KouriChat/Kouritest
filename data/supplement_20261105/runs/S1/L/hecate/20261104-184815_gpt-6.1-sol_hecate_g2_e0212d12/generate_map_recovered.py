def generate_matrix():
    land = np.zeros((N, N), dtype=bool)

    for vertices in LAND.values():
        land |= polygon_mask(vertices)

    for lon, lat, rx, ry in SMALL_ISLANDS:
        land |= ((X - lon) / rx) ** 2 + ((Y - lat) / ry) ** 2 <= 1.0

    for points, half_width_km in CHANNELS:
        land &= ~channel_mask(points, half_width_km)

    return land.astype(np.uint8)


def write_and_validate(matrix):
    OUT.mkdir(parents=True, exist_ok=True)

    csv_path = OUT / "candidate.csv"
    raw_path = OUT / "candidate.png"
    enlarged_path = OUT / "candidate_8x.png"

    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert np.isin(matrix, [0, 1]).all()
    assert lats[0] == 55.0 and lats[-1] == 53.0
    assert lons[0] == -131.0 and lons[-1] == -129.0

    with csv_path.open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 直接逐点映射：陆地为 255，水域为 0。
    pixels = matrix * np.uint8(255)
    image = Image.fromarray(pixels)
    assert image.mode == "L"
    image.save(raw_path)

    # 兼容不同 Pillow 版本。
    resampling = getattr(Image, "Resampling", Image)
    enlarged = image.resize((1016, 1016), resample=resampling.NEAREST)
    enlarged.save(enlarged_path)

    # 回读 CSV，检查实际写出的文件。
    with csv_path.open("r", newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))

    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)

    recovered = np.array(
        [[int(value) for value in row] for row in rows],
        dtype=np.uint8,
    )
    assert np.array_equal(recovered, matrix)

    # 回读 PNG，验证尺寸、颜色及逐像素最近邻复制。
    with Image.open(raw_path) as im:
        assert im.size == (127, 127)
        assert im.mode == "L"
        raw = np.asarray(im).copy()

    with Image.open(enlarged_path) as im:
        assert im.size == (1016, 1016)
        assert im.mode == "L"
        big = np.asarray(im).copy()

    assert set(np.unique(raw).tolist()) == {0, 255}
    assert set(np.unique(big).tolist()) == {0, 255}
    assert np.array_equal(raw, pixels)

    expected = np.repeat(np.repeat(raw, 8, axis=0), 8, axis=1)
    assert np.array_equal(big, expected)

    print("验证通过：127 × 127，共 16,129 个有效二值采样点。")
    print("CSV：127 行，每行 127 个 0/1，无表头、无空缺。")
    print("PNG：仅黑白；原图 127×127；放大图 1016×1016。")
    print("最近邻验证：每个原始像素精确复制为 8×8 像素块。")
    print(f"陆地点：{int(matrix.sum())}")
    print(f"水域点：{int(matrix.size - matrix.sum())}")
    for path in (csv_path, raw_path, enlarged_path):
        print(path.as_posix())


if __name__ == "__main__":
    write_and_validate(generate_matrix())
