# 知识近似实验：
# 所有轮廓坐标均为凭已有地理知识手写的近似值。
# 不读取外部地图、地理数据或标准答案，不执行网络请求。
# 坐标顺序始终为 (经度, 纬度)，西经使用负数。
# 内陆湖泊按陆地处理，因此不从陆地多边形内扣除湖泊。

N = 127
OUT = Path("outputs")

lons = np.linspace(-131.0, -129.0, N)
lats = np.linspace(55.0, 53.0, N)
X, Y = np.meshgrid(lons, lats)


def polygon_mask(vertices):
    """射线法判断每个采样点是否在手写多边形内。"""
    inside = np.zeros(X.shape, dtype=bool)
    for i, (x1, y1) in enumerate(vertices):
        x2, y2 = vertices[(i + 1) % len(vertices)]
        if y1 == y2:
            continue
        crossing = (y1 > Y) != (y2 > Y)
        intersect_x = x1 + (Y - y1) * (x2 - x1) / (y2 - y1)
        inside ^= crossing & (X < intersect_x)
    return inside


def channel_mask(points, half_width_km):
    """以手写折线和近似半宽定义海水通道；使用局部平面距离。"""
    # 在该纬度附近，每经度约 65 km，每纬度约 111.2 km。
    px = X * 65.0
    py = Y * 111.2
    result = np.zeros(X.shape, dtype=bool)
    for (lon1, lat1), (lon2, lat2) in zip(points[:-1], points[1:]):
        ax, ay = lon1 * 65.0, lat1 * 111.2
        bx, by = lon2 * 65.0, lat2 * 111.2
        dx, dy = bx - ax, by - ay
        denominator = dx * dx + dy * dy
        if denominator == 0:
            distance2 = (px - ax) ** 2 + (py - ay) ** 2
        else:
            t = np.clip(
                ((px - ax) * dx + (py - ay) * dy) / denominator,
                0.0,
                1.0,
            )
            distance2 = (px - ax - t * dx) ** 2 + (
                py - ay - t * dy
            ) ** 2
        result |= distance2 <= half_width_km ** 2
    return result


