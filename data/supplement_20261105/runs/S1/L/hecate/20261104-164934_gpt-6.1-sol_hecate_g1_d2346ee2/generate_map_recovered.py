def points_in_polygon(lon_grid, lat_grid, vertices):
    """向量化射线交叉法；边界上的极少数点允许任一侧取舍。"""
    inside = np.zeros(lon_grid.shape, dtype=bool)
    x_previous, y_previous = vertices[-1]

    for x_current, y_current in vertices:
        if y_current != y_previous:
            crosses_latitude = (
                (y_current > lat_grid) != (y_previous > lat_grid)
            )
            intersection_lon = (
                x_current
                + (lat_grid - y_current)
                * (x_previous - x_current)
                / (y_previous - y_current)
            )
            inside ^= crosses_latitude & (lon_grid < intersection_lon)
        x_previous, y_previous = x_current, y_current

    return inside


def main():
    out_dir = Path.cwd() / "outputs"
    out_dir.mkdir(parents=True, exist_ok=True)

    # 使用题目给定的精确步长，不使用示例中四舍五入后的坐标。
    indices = np.arange(127, dtype=np.float64)
    latitudes = 55.0 - indices * (2.0 / 126.0)
    longitudes = -131.0 + indices * (2.0 / 126.0)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)

    land = np.zeros((127, 127), dtype=bool)

    land_polygons = [
        NORTHERN_MAINLAND,
        EASTERN_MAINLAND,
        *ISLANDS.values(),
    ]
    for polygon in land_polygons:
        land |= points_in_polygon(lon_grid, lat_grid, polygon)

    for polygon in WATER_CUTS.values():
        land &= ~points_in_polygon(lon_grid, lat_grid, polygon)

    matrix = land.astype(np.uint8)

    csv_path = out_dir / "candidate.csv"
    raw_path = out_dir / "candidate.png"
    enlarged_path = out_dir / "candidate_8x.png"

    with csv_path.open("w", newline="", encoding="ascii") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 每个采样值直接对应一个像素；不插值、不修补。
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(raw_path)

    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST

    enlarged = original.resize((1016, 1016), resample=nearest)
    enlarged.save(enlarged_path)

    # 验证矩阵和坐标方向。
    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert np.isin(matrix, (0, 1)).all()
    assert latitudes[0] == 55.0 and latitudes[-1] == 53.0
    assert longitudes[0] == -131.0 and longitudes[-1] == -129.0
    assert np.all(np.diff(latitudes) < 0)
    assert np.all(np.diff(longitudes) > 0)

    # 从实际写出的 CSV 回读验证。
    with csv_path.open("r", newline="", encoding="ascii") as stream:
        rows = list(csv.reader(stream))
    assert len(rows) == 127
    assert all(len(row) == 127 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    recovered = np.array(rows, dtype=np.uint8)
    assert np.array_equal(recovered, matrix)

    # 从实际写出的 PNG 回读验证。
    with Image.open(raw_path) as image:
        assert image.size == (127, 127)
        raw_pixels = np.array(image)
    with Image.open(enlarged_path) as image:
        assert image.size == (1016, 1016)
        large_pixels = np.array(image)

    assert raw_pixels.ndim == 2
    assert large_pixels.ndim == 2
    assert set(np.unique(raw_pixels).tolist()) == {0, 255}
    assert set(np.unique(large_pixels).tolist()) == {0, 255}
    assert np.array_equal(raw_pixels, pixels)

    # 独立用逐行逐列重复构造最近邻应有结果，验证每个 8×8 像素块。
    expected_large = np.repeat(np.repeat(raw_pixels, 8, axis=0), 8, axis=1)
    assert np.array_equal(large_pixels, expected_large)

    print("验证通过：127×127，共 16,129 个有效采样值。")
    print("CSV：127 行，每行 127 个值，仅含 0/1，无空缺。")
    print("PNG：127×127，仅含黑白；白色为陆地，黑色为水域。")
    print("放大 PNG：1016×1016，已验证为严格的 8 倍最近邻放大。")
    print(f"陆地点数：{int(matrix.sum())}")
    print(f"水域点数：{int(matrix.size - matrix.sum())}")
    for path in (csv_path, raw_path, enlarged_path):
        print(path)


if __name__ == "__main__":
    main()
