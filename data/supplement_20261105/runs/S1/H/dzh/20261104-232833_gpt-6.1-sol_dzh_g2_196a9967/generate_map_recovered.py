def point_on_segment(x, y, ax, ay, bx, by):
    """判断点是否落在多边形边界线段上。"""
    cross = (x - ax) * (by - ay) - (y - ay) * (bx - ax)
    if abs(cross) > 1e-10:
        return False
    return (
        min(ax, bx) - 1e-10 <= x <= max(ax, bx) + 1e-10
        and min(ay, by) - 1e-10 <= y <= max(ay, by) + 1e-10
    )


def inside_polygon(lon, lat, polygon):
    """射线法点判据；恰落边界时按陆地处理。"""
    inside = False
    n = len(polygon)
    for i in range(n):
        ax, ay = polygon[i]
        bx, by = polygon[(i + 1) % n]

        if point_on_segment(lon, lat, ax, ay, bx, by):
            return True

        if (ay > lat) != (by > lat):
            crossing_lon = ax + (lat - ay) * (bx - ax) / (by - ay)
            if lon < crossing_lon:
                inside = not inside
    return inside


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    rows = 71
    cols = 231
    latitudes = [45.0 - 0.2 * r for r in range(rows)]
    longitudes = [-9.0 + 0.2 * c for c in range(cols)]

    matrix = np.zeros((rows, cols), dtype=np.uint8)
    for r, lat in enumerate(latitudes):
        for c, lon in enumerate(longitudes):
            if any(inside_polygon(lon, lat, poly) for poly in LAND_POLYGONS):
                matrix[r, c] = 1

    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 值 1 显示为白色，值 0 显示为黑色。
    image = Image.fromarray(matrix * 255, mode="L")
    image.save(output_dir / "candidate.png")

    enlarged = image.resize((cols * 8, rows * 8), resample=Image.Resampling.NEAREST)
    enlarged.save(output_dir / "candidate_8x.png")

    assert matrix.shape == (71, 231)
    assert matrix.size == 16401
    assert set(np.unique(matrix)).issubset({0, 1})
    assert image.size == (231, 71)
    assert enlarged.size == (1848, 568)
    assert set(image.getdata()).issubset({0, 255})

    print("Created outputs/candidate.csv: 71 rows x 231 values")
    print("Created outputs/candidate.png: 231 x 71, black and white")
    print("Created outputs/candidate_8x.png: 1848 x 568, nearest-neighbor")


if __name__ == "__main__":
    main()
