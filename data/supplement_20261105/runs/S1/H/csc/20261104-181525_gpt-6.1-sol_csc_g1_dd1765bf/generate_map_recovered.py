    output_dir.mkdir(parents=True, exist_ok=True)

    matrix, latitudes, longitudes = generate_matrix()

    with (output_dir / "candidate.csv").open(
        "w", encoding="ascii", newline=""
    ) as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 数组第 0 行为 23N，第 0 列为 99E。
    # 不作转置、翻转、插值、平滑或海岸线修补。
    pixels = matrix * np.uint8(255)
    original_image = Image.fromarray(pixels)
    original_image.save(output_dir / "candidate.png", format="PNG")

    # 兼容不同版本 Pillow。
