# 所有地理轮廓均凭已有知识手工近似编写。
# 坐标顺序统一为：经度、纬度，单位为 WGS84 十进制度。
# 多边形内部（包括内陆湖泊）按陆地处理。
# 小岛和礁盘仅在手写轮廓或规则覆盖采样点时记为陆地；
# 不将附近海域、整个群岛范围或整个海上浅滩自动算作陆地。
#
# 不读取外部地理文件，不下载数据，不调用海陆判断库。
# 部分多边形顶点位于采样框外，只用于封闭轮廓；
# 实际仅计算指定框内的 111 × 141 个采样点。

POLYGONS = []


def polygon(name, text):
    values = np.array(
        [float(token) for token in text.split()], dtype=np.float64
    )
    if len(values) % 2:
        raise ValueError(f"{name}: 坐标数量不是偶数")
    vertices = values.reshape(-1, 2)
    if len(vertices) < 3:
        raise ValueError(f"{name}: 多边形顶点不足")
    POLYGONS.append((name, vertices))


