def points_in_polygon(x, y, vertices):
    """射线法批量判断坐标点是否在多边形内，边界点按陆地处理。"""
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)
    tolerance = 1e-10

    previous = vertices[-1]
    for current in vertices:
        ax, ay = previous
        bx, by = current
        dx = bx - ax
        dy = by - ay

        # 仅在非水平边上计算射线交点，避免除以零。
        if dy != 0.0:
            crosses_row = (ay > y) != (by > y)
            intersection_x = ax + dx * (y - ay) / dy
            inside ^= crosses_row & (x < intersection_x)

        cross_product = (x - ax) * dy - (y - ay) * dx
        on_segment = (
            (np.abs(cross_product) <= tolerance)
            & (x >= min(ax, bx) - tolerance)
            & (x <= max(ax, bx) + tolerance)
            & (y >= min(ay, by) - tolerance)
            & (y <= max(ay, by) + tolerance)
        )
        boundary |= on_segment
        previous = current

    return inside | boundary


def generate_matrix():
    # 用整数索引除以 5，避免累加 0.2 引入累计误差。
    latitudes = 23.0 - np.arange(111, dtype=np.float64) / 5.0
    longitudes = 99.0 + np.arange(141, dtype=np.float64) / 5.0
    longitude_grid, latitude_grid = np.meshgrid(longitudes, latitudes)

    land = np.zeros((111, 141), dtype=bool)

    for _, vertices in POLYGONS:
        land |= points_in_polygon(
            longitude_grid, latitude_grid, vertices
        )

    for _, center_lon, center_lat, radius_lon, radius_lat in ELLIPSES:
        ellipse_value = (
            ((longitude_grid - center_lon) / radius_lon) ** 2
            + ((latitude_grid - center_lat) / radius_lat) ** 2
        )
        land |= ellipse_value <= 1.0 + 1e-12

    return land.astype(np.uint8), latitudes, longitudes


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


