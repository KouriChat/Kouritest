# ----------------------------------------------------------------------
# 点判据：射线法，并将恰好位于多边形边界上的点归入多边形。
# 对海洋切口，其边界随后按水域处理。
# ----------------------------------------------------------------------

def points_in_polygon(x, y, vertices):
    """
    对数组 x、y 中的每一个坐标点进行点在多边形内判断。
    不计算像素面积比例，不做多数表决，不做邻域平滑。
    """
    polygon = np.asarray(vertices, dtype=np.float64)
    inside = np.zeros(x.shape, dtype=bool)
    boundary = np.zeros(x.shape, dtype=bool)

    tolerance = 1e-11
    x1, y1 = polygon[-1]

    for x2, y2 in polygon:
        dx = x2 - x1
        dy = y2 - y1

        # 检查点是否在线段上。
        cross = (x - x1) * dy - (y - y1) * dx
        within_bounds = (
            (x >= min(x1, x2) - tolerance)
            & (x <= max(x1, x2) + tolerance)
            & (y >= min(y1, y2) - tolerance)
            & (y <= max(y1, y2) + tolerance)
        )
        boundary |= (np.abs(cross) <= tolerance) & within_bounds

        # 半开区间的水平射线交点规则，避免重复计算顶点。
        if y1 != y2:
            straddles = (y1 > y) != (y2 > y)
            crossing_x = x1 + (y - y1) * dx / dy
            inside ^= straddles & (x < crossing_x)

        x1, y1 = x2, y2

    return inside | boundary


def generate_matrix():
    # 精确按照端点与等间隔生成，而非使用题目中截短的小数。
    longitudes = -131.0 + np.arange(127, dtype=np.float64) * (2.0 / 126.0)
    latitudes = 55.0 - np.arange(127, dtype=np.float64) * (2.0 / 126.0)

    # 明确固定四个端点，避免浮点尾差影响文件说明。
    longitudes[0], longitudes[-1] = -131.0, -129.0
    latitudes[0], latitudes[-1] = 55.0, 53.0

    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)
    land = np.zeros((127, 127), dtype=bool)

    for _name, outline, inlets in FEATURES:
        feature_land = points_in_polygon(lon_grid, lat_grid, outline)
        for inlet in inlets:
            feature_land &= ~points_in_polygon(lon_grid, lat_grid, inlet)
        land |= feature_land

    return land.astype(np.uint8)


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def validate_outputs(matrix, csv_path, image_path, enlarged_path):
    require(matrix.shape == (127, 127), "矩阵形状不是 127×127")
    require(matrix.size == 16129, "矩阵有效值数量不是 16,129")
    require(
        np.all((matrix == 0) | (matrix == 1)),
        "矩阵包含 0/1 之外的值",
    )

    # 重新读取刚写出的 CSV；不读取任何外部地图或答案。
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))

    require(len(rows) == 127, "CSV 行数不是 127")
    require(all(len(row) == 127 for row in rows), "CSV 列数不一致")
    require(
        all(value in ("0", "1") for row in rows for value in row),
        "CSV 包含空缺或 0/1 之外的值",
    )
    require(
        sum(len(row) for row in rows) == 16129,
        "CSV 有效值总数错误",
    )

    restored_matrix = np.asarray(
        [[int(value) for value in row] for row in rows],
        dtype=np.uint8,
    )
    require(
        np.array_equal(restored_matrix, matrix),
        "CSV 与内存矩阵不一致",
    )

    with Image.open(image_path) as image:
        require(image.format == "PNG", "原始图片格式不是 PNG")
        require(image.size == (127, 127), "原始 PNG 尺寸错误")
        require(image.mode == "L", "原始 PNG 模式错误")
        original_pixels = np.asarray(image).copy()

    with Image.open(enlarged_path) as image:
        require(image.format == "PNG", "放大图片格式不是 PNG")
        require(image.size == (1016, 1016), "放大 PNG 尺寸错误")
        require(image.mode == "L", "放大 PNG 模式错误")
        enlarged_pixels = np.asarray(image).copy()

    for label, pixels in (
        ("原始 PNG", original_pixels),
        ("放大 PNG", enlarged_pixels),
    ):
        require(
            set(np.unique(pixels).tolist()) == {0, 255},
            label + " 未恰好包含黑色和白色",
        )

    require(
        np.array_equal(original_pixels, matrix * np.uint8(255)),
        "原始图片不符合白=陆地、黑=水域的直接转换规则",
    )

    # 逐像素验证：每个原像素必须对应完全相同的 8×8 像素块。
    expected_enlarged = np.repeat(
        np.repeat(original_pixels, 8, axis=0), 8, axis=1
    )
    require(
        np.array_equal(enlarged_pixels, expected_enlarged),
        "放大图片不符合严格的 8 倍最近邻复制",
    )


def main():
    output_directory = Path.cwd() / "outputs"
    output_directory.mkdir(parents=True, exist_ok=True)

    csv_path = output_directory / "candidate.csv"
    image_path = output_directory / "candidate.png"
    enlarged_path = output_directory / "candidate_8x.png"

    matrix = generate_matrix()

    with csv_path.open("w", encoding="ascii", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 矩阵直接映射为灰度：0 -> 黑色，1 -> 白色。
    # 行列顺序已为北到南、西到东，不翻转、不平滑、不修补。
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    original.save(image_path, format="PNG")

    # Pillow 新旧版本兼容；两种写法均明确使用最近邻。
    if hasattr(Image, "Resampling"):
        nearest = Image.Resampling.NEAREST
    else:
        nearest = Image.NEAREST

    enlarged = original.resize((1016, 1016), resample=nearest)
    enlarged.save(enlarged_path, format="PNG")

    validate_outputs(matrix, csv_path, image_path, enlarged_path)

    print("验证通过：127×127，共 16,129 个有效的 0/1 值。")
    print("CSV：127 行，每行 127 列，无表头、无空缺。")
    print("原始 PNG：127×127，仅黑白，白=陆地、黑=水域。")
    print("放大 PNG：1016×1016，严格最近邻放大 8 倍。")
    print("方向：第 1 行 55N，最后一行 53N；")
    print("      第 1 列 131W，最后一列 129W。")
    print("方法：手写知识近似轮廓 + 对各采样点进行多边形包含计算。")
    print("未使用真实地图、外部地理数据或标准答案。")
    print("输出文件：")
    for path in (csv_path, image_path, enlarged_path):
        print("  " + str(path))


if __name__ == "__main__":
    main()
