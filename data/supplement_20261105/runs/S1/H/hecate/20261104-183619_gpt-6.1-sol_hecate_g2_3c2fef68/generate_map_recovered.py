def polygon(text):
    """解析手写轮廓。每对数依次为：经度、纬度。"""
    coordinates = []
    for token in text.split():
        lon, lat = token.split(",")
        coordinates.append((float(lon), float(lat)))
    if len(coordinates) < 3:
        raise ValueError("多边形至少需要三个顶点")
    return np.asarray(coordinates, dtype=np.float64)


