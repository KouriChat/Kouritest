def points_in_polygon(lon_grid, lat_grid, vertices):
    """
    在原始采样坐标上使用射线法判断点是否落入多边形。
    恰好在边上的点视为落入；水域多边形的边界最终优先记为水域。
    不插值、不平均、不处理像素邻域。
    """
    inside = np.zeros(lon_grid.shape, dtype=bool)
    on_boundary = np.zeros(lon_grid.shape, dtype=bool)
    tolerance = 1.0e-11

    x1, y1 = vertices[-1]
    for x2, y2 in vertices:
        dx = x2 - x1
        dy = y2 - y1

        cross = (lon_grid - x1) * dy - (lat_grid - y1) * dx
        within_segment_box = (
            (lon_grid >= min(x1, x2) - tolerance)
            & (lon_grid <= max(x1, x2) + tolerance)
            & (lat_grid >= min(y1, y2) - tolerance)
            & (lat_grid <= max(y1, y2) + tolerance)
        )
        on_boundary |= (
            np.abs(cross) <= tolerance
        ) & within_segment_box

        if dy != 0.0:
            crosses_row = (y1 > lat_grid) != (y2 > lat_grid)
            intersection_lon = (
                x1 + (lat_grid - y1) * dx / dy
            )
            inside ^= crosses_row & (lon_grid < intersection_lon)

        x1, y1 = x2, y2

    return inside | on_boundary


def build_matrix():
    # 精确采用两个端点之间的等距采样，而非使用题面四舍五入的示例。
    latitudes = np.linspace(55.0, 53.0, N, dtype=np.float64)
    longitudes = np.linspace(-131.0, -129.0, N, dtype=np.float64)
    lon_grid, lat_grid = np.meshgrid(longitudes, latitudes)

    land = np.zeros((N, N), dtype=bool)
    for _, vertices in LAND_POLYGONS:
        land |= points_in_polygon(lon_grid, lat_grid, vertices)

    for _, vertices in WATER_POLYGONS:
        land &= ~points_in_polygon(lon_grid, lat_grid, vertices)

    matrix = land.astype(np.uint8)

    assert matrix.shape == (127, 127)
    assert matrix.size == 16129
    assert set(np.unique(matrix).tolist()) == {0, 1}
    assert latitudes[0] == 55.0 and latitudes[-1] == 53.0
    assert longitudes[0] == -131.0 and longitudes[-1] == -129.0

    return matrix


