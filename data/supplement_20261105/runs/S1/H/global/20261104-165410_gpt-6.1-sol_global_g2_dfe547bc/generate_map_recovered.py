def point_in_polygon(lon, lat, polygon):
    """Ray-casting point-in-polygon test."""
    inside = False
    x1, y1 = polygon[-1]
    for x2, y2 in polygon:
        if (y1 > lat) != (y2 > lat):
            crossing_x = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < crossing_x:
                inside = not inside
        x1, y1 = x2, y2
    return inside


def is_land(lon, lat):
    # The Arctic Ocean remains water; northern mainland outlines are polygons.
    return any(point_in_polygon(lon, lat, polygon) for polygon in LAND_POLYGONS)


def main():
    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    latitudes = range(89, -90, -2)
    longitudes = range(-179, 180, 2)
    matrix = np.zeros((90, 180), dtype=np.uint8)

    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = 1 if is_land(lon, lat) else 0

    with (output_dir / "candidate.csv").open("w", newline="") as csv_file:
        writer = csv.writer(csv_file, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Convert 1=land to white and 0=water to black.
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )


if __name__ == "__main__":
    main()
