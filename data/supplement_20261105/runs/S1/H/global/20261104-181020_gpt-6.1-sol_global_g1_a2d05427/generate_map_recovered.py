def point_in_polygon(lon, lat, polygon):
    """Ray-casting point-in-polygon test."""
    inside = False
    j = len(polygon) - 1
    for i, (xi, yi) in enumerate(polygon):
        xj, yj = polygon[j]
        if (yi > lat) != (yj > lat):
            crossing_lon = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < crossing_lon:
                inside = not inside
        j = i
    return inside

def is_land(lon, lat):
    # Continental Antarctica is land; the surrounding ocean and sea ice remain water.
    if lat <= -72:
        return True
    return any(point_in_polygon(lon, lat, polygon) for polygon in POLYGONS)

def main():
    latitudes = np.arange(89, -90, -2, dtype=int)
    longitudes = np.arange(-179, 180, 2, dtype=int)

    matrix = np.zeros((90, 180), dtype=np.uint8)
    for row, lat in enumerate(latitudes):
        for col, lon in enumerate(longitudes):
            matrix[row, col] = 1 if is_land(int(lon), int(lat)) else 0

    output_dir = Path("outputs")
    output_dir.mkdir(parents=True, exist_ok=True)

    with (output_dir / "candidate.csv").open("w", newline="", encoding="ascii") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # Matrix value 1 is white land; value 0 is black water.
    image = Image.fromarray(matrix * 255, mode="L").convert("RGB")
    image.save(output_dir / "candidate.png")
    image.resize((1440, 720), resample=Image.Resampling.NEAREST).save(
        output_dir / "candidate_8x.png"
    )

if __name__ == "__main__":
    main()
