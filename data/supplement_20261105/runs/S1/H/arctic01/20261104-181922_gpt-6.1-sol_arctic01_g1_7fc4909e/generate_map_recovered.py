def polygon_contains_points(west, north, vertices):
    """向量化射线法；点恰在近似轮廓上时归入多边形。"""
    result = np.zeros(west.shape, dtype=bool)
    boundary = np.zeros(west.shape, dtype=bool)
    x0, y0 = vertices[-1]
    eps = 1e-10

    for x1, y1 in vertices:
        dx = x1 - x0
        dy = y1 - y0

        cross = (west - x0) * dy - (north - y0) * dx
        within_box = (
            (west >= min(x0, x1) - eps)
            & (west <= max(x0, x1) + eps)
            & (north >= min(y0, y1) - eps)
            & (north <= max(y0, y1) + eps)
        )
        boundary |= (np.abs(cross) <= eps) & within_box

        if dy != 0:
            crosses_row = (y0 > north) != (y1 > north)
            intersection_x = x0 + (north - y0) * dx / dy
            result ^= crosses_row & (west < intersection_x)

        x0, y0 = x1, y1

    return result | boundary


def build_matrix():
    # 通过整数十分之一度构造坐标，避免 arange 的端点数量问题。
    latitude_tenths = np.arange(790, 729, -1, dtype=np.int32)
    longitude_tenths = np.arange(-1050, -809, 1, dtype=np.int32)

    latitudes = latitude_tenths / 10.0
    longitudes = longitude_tenths / 10.0
    longitude_grid, latitude_grid = np.meshgrid(longitudes, latitudes)
    west_grid = -longitude_grid

    assert latitudes.shape == (61,)
    assert longitudes.shape == (241,)
    assert latitudes[0] == 79.0 and latitudes[-1] == 73.0
    assert longitudes[0] == -105.0 and longitudes[-1] == -81.0

    land = np.zeros((61, 241), dtype=bool)
    for vertices in LAND.values():
        land |= polygon_contains_points(west_grid, latitude_grid, vertices)

    for vertices in SEA_CUTS.values():
        land &= ~polygon_contains_points(west_grid, latitude_grid, vertices)

    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, (0, 1)).all()
    return matrix


def main():
    output_dir = Path.cwd() / "outputs"
    output_dir.mkdir(parents=True, exist_ok=True)

    matrix = build_matrix()

    csv_path = output_dir / "candidate.csv"
    original_path = output_dir / "candidate.png"
    enlarged_path = output_dir / "candidate_8x.png"

    with csv_path.open("w", encoding="ascii", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    # 每个采样点直接对应一个像素；不插值、不平滑、不修改矩阵。
    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    assert original.mode == "L"
    original.save(original_path, format="PNG")

    try:
        nearest = Image.Resampling.NEAREST
    except AttributeError:
        nearest = Image.NEAREST

    enlarged = original.resize((1928, 488), resample=nearest)
    enlarged.save(enlarged_path, format="PNG")

    # 重新读取实际写出的 CSV，验证行列数、取值和完整性。
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))

    assert len(rows) == 61
    assert all(len(row) == 241 for row in rows)
    assert all(value in ("0", "1") for row in rows for value in row)
    assert sum(len(row) for row in rows) == 14701
    restored = np.asarray(rows, dtype=np.uint8)
    assert np.array_equal(restored, matrix)

    # 重新读取 PNG，验证尺寸、黑白取值及逐像素最近邻复制关系。
    with Image.open(original_path) as image:
        image.load()
        assert image.size == (241, 61)
        assert image.mode == "L"
        original_saved = np.asarray(image).copy()

    with Image.open(enlarged_path) as image:
        image.load()
        assert image.size == (1928, 488)
        assert image.mode == "L"
        enlarged_saved = np.asarray(image).copy()

    assert set(np.unique(original_saved).tolist()) == {0, 255}
    assert set(np.unique(enlarged_saved).tolist()) == {0, 255}
    assert np.array_equal(original_saved, pixels)

    expected_enlarged = np.repeat(
        np.repeat(original_saved, 8, axis=0), 8, axis=1
    )
    assert np.array_equal(enlarged_saved, expected_enlarged)

