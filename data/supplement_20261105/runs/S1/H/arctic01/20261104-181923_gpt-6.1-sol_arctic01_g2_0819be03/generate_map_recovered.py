def points_in_polygon(x, y, vertices):
    """
    向量化射线法，只判断采样点本身。

    海岸线上的点由射线法的半开边规则确定归属。
    不计算像素覆盖面积，不进行邻点投票或图像修补。
    """
    vertices = np.asarray(vertices, dtype=np.float64)
    if vertices.ndim != 2 or vertices.shape[1] != 2:
        raise ValueError("多边形顶点必须是二维坐标")
    if len(vertices) < 3 or not np.isfinite(vertices).all():
        raise ValueError("无效多边形")

    result = np.zeros(x.shape, dtype=bool)
    xmin, ymin = vertices.min(axis=0)
    xmax, ymax = vertices.max(axis=0)
    selected = (x >= xmin) & (x <= xmax) & (y >= ymin) & (y <= ymax)

    if not selected.any():
        return result

    px = x[selected]
    py = y[selected]
    inside = np.zeros(px.shape, dtype=bool)

    ax, ay = vertices[-1]
    for bx, by in vertices:
        if ay != by:
            crosses_y = (ay > py) != (by > py)
            intersection_x = ax + (py - ay) * (bx - ax) / (by - ay)
            inside ^= crosses_y & (px < intersection_x)
        ax, ay = bx, by

    result[selected] = inside
    return result


def generate_matrix():
    # 先用整数生成坐标，避免浮点步进导致行列数量错误。
    # 第一行 79 N，末行 73 N；第一列 105 W，末列 81 W。
    latitudes = np.arange(790, 729, -1, dtype=np.int32) / 10.0
    west_longitudes = np.arange(1050, 809, -1, dtype=np.int32) / 10.0

    assert latitudes.shape == (61,)
    assert west_longitudes.shape == (241,)
    assert latitudes[0] == 79.0 and latitudes[-1] == 73.0
    assert west_longitudes[0] == 105.0 and west_longitudes[-1] == 81.0

    west_grid, latitude_grid = np.meshgrid(west_longitudes, latitudes)
    land = np.zeros((61, 241), dtype=bool)

    for vertices in LAND_POLYGONS.values():
        land |= points_in_polygon(west_grid, latitude_grid, vertices)

    for vertices in WATER_POLYGONS.values():
        land &= ~points_in_polygon(west_grid, latitude_grid, vertices)

    matrix = land.astype(np.uint8)
    assert matrix.shape == (61, 241)
    assert matrix.size == 14701
    assert np.isin(matrix, [0, 1]).all()
    return matrix


def write_outputs(matrix, output_dir):
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "candidate.csv"
    png_path = output_dir / "candidate.png"
    enlarged_path = output_dir / "candidate_8x.png"

    with csv_path.open("w", encoding="ascii", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerows(matrix.tolist())

    pixels = matrix * np.uint8(255)
    original = Image.fromarray(pixels)
    assert original.mode == "L"
    original.save(png_path, format="PNG")

    # 对完整矩阵直接最近邻放大；不平滑、不重画海岸线。
    if hasattr(Image, "Resampling"):
        nearest = Image.Resampling.NEAREST
    else:
        nearest = Image.NEAREST
    enlarged = original.resize((1928, 488), resample=nearest)
    enlarged.save(enlarged_path, format="PNG")

    return csv_path, png_path, enlarged_path


def verify_outputs(matrix, csv_path, png_path, enlarged_path):
    with csv_path.open("r", encoding="ascii", newline="") as handle:
        rows = list(csv.reader(handle))

    assert len(rows) == 61, "CSV 行数必须为 61"
    assert all(len(row) == 241 for row in rows), "CSV 每行必须为 241 列"
    assert all(value in ("0", "1") for row in rows for value in row), (
        "CSV 仅允许含有 0 和 1，不能有空缺"
    )

    restored = np.asarray(rows, dtype=np.uint8)
    assert restored.size == 14701
    assert np.array_equal(restored, matrix)

    with Image.open(png_path) as image:
        image.load()
        assert image.size == (241, 61)
        assert image.mode == "L"
        original_pixels = np.array(image)

    with Image.open(enlarged_path) as image:
        image.load()
        assert image.size == (1928, 488)
        assert image.mode == "L"
        enlarged_pixels = np.array(image)

    assert set(np.unique(original_pixels).tolist()) == {0, 255}
    assert set(np.unique(enlarged_pixels).tolist()) == {0, 255}
    assert np.array_equal(original_pixels, matrix * np.uint8(255))

    expected = np.repeat(np.repeat(original_pixels, 8, axis=0), 8, axis=1)
    assert expected.shape == (488, 1928)
    assert np.array_equal(enlarged_pixels, expected), (
        "放大图必须与每个原始像素重复为 8×8 像素块的结果完全一致"
    )

    # 每一个放大后的像素块都必须保持原始采样值。
    blocks = enlarged_pixels.reshape(61, 8, 241, 8)
    assert np.all(blocks == original_pixels[:, None, :, None])

    return int(matrix.sum()), int(matrix.size - matrix.sum())


def main():
    matrix = generate_matrix()
    paths = write_outputs(matrix, Path.cwd() / "outputs")
    land_count, water_count = verify_outputs(matrix, *paths)

    print("完成：61 行 × 241 列，共 14,701 个有效采样值。")
    print(f"陆地：{land_count}；水域：{water_count}。")
    print("CSV：无表头，仅含 0/1，无空缺。")
    print("原始 PNG：241×61，仅含黑色与白色。")
    print("放大 PNG：1928×488，已逐像素验证为最近邻放大 8 倍。")
    for path in paths:
        print(path)


if __name__ == "__main__":
    main()
